# -*- coding: utf-8 -*-
"""ChatBI · 会话态与指代消解（A-1 多轮追问）

要解决的问题：现在的问数页**每一问都是孤儿**。用户问完「八月份不合格率最高的
三家厂商」，紧接着打「那上个月呢」——系统会当成一个全新问题，答一句
「需要明确具体指标」。而真人对话里，第二句的**全部信息量都在上文里**。

🔴 为什么不能只靠模型自己记住：`/ask` 是无状态的，每次都是全新一次调用，
   模型看不到任何上文。不把上文喂进去，「那上个月呢」在它眼里就是一句残缺的话。

## 三条设计纪律

1. **不新建槽位，让模型输出「完整意图」。**
   曾经想加一个 `{"继承":"上一轮"}` 槽位，代价是：模型多一个格子要填，
   而填错格子的代价在包 4 已经量化过了（T17 就是把分组名填进了查询类型）。
   改成：把上一轮的问题 + 最终意图放进提示词，要求模型**追问时也输出完整意图**
   （沿用来的条件一并写全）。模型仍然只输出一种东西，出错面不增加。

2. **服务端只做兜底，不做「猜」。**
   兜底条件是**确定的**：本轮意图**自己立不起来**（既没有指标、也没有基础查询、
   也没有场景）→ 才拿上一轮当基底。能自己立起来的（哪怕只有 `{"澄清":...}`）
   一律不被改写 —— 否则「换个话题」会被上一轮的指标污染，
   而这**不会报错**，只会答出一个上下文正确、语义错误的结果。

3. **继承必须说出来。**
   `{"时间":"上月"}` 被沿用在哪一轮，用户必须看得见。静默继承与「用户没提时间」
   在结果里长得一模一样，而两者的含义完全不同（前者=限定在上月，后者=全区间）。
   所以每次继承都产出 `沿用` 列表，随应答一起显示。

## 只记「有意图」的轮次

上一轮是拒答 / 元问题 / 澄清且无意图 → **不记**。记了会让下一轮继承一堆空槽位，
表现为「追问后答了个全区间的东西」——同样是静默错误。

## 过期与容量

会话表是**进程内内存**的（重启即失，这没问题：会话本来就是短生命周期的）。
但内存必须有上限：满了按最近使用淘汰，过期（默认 30 分钟）惰性清理 ——
不清理的后果是长期跑的服务慢慢涨到吃满内存，而现象只是「越用越慢」。
"""

import os
import threading
import time

# 会话保留时长与同时活跃数（都可用环境变量覆盖，自检要用短的 TTL 造过期）
有效期秒 = int(os.environ.get("CHATBI_SESSION_TTL") or 1800)
最多会话 = int(os.environ.get("CHATBI_SESSION_MAX") or 200)

# ASCII 环境变量名 —— bash 标识符不允许中文（已踩过，见 意图解析.py 注释）
关会话 = bool(os.environ.get("CHATBI_NO_SESSION"))

_表 = {}                                                 # 会话id -> {"轮次": [...], "更新": 时间戳}
_锁 = threading.Lock()

# 可观测计数：不做这个，「会话功能没生效」和「用户压根没用会话」长得一样（§9.5）
计数 = {"新建": 0, "命中": 0, "继承": 0, "淘汰": 0, "过期": 0}


def 新id():
    """给前端用（前端自己也可以生成）。**只含 ASCII**：它会进 localStorage 与请求体，
    带中文的 id 在 URL / 日志 / 跨语言边界上会各踩一次编码坑。"""
    return "s%08x%06x" % (int(time.time()) & 0xFFFFFFFF, id(object()) & 0xFFFFFF)


def _现在():
    return time.time()


def _清过期(现在=None):
    """惰性清理。调用方持锁。"""
    现在 = 现在 or _现在()
    死 = [k for k, v in _表.items() if 现在 - v["更新"] > 有效期秒]
    for k in 死:
        _表.pop(k, None)
    计数["过期"] += len(死)
    return len(死)


def _淘汰():
    """超容量时按最近使用淘汰。调用方持锁。"""
    while len(_表) > 最多会话:
        最旧 = min(_表, key=lambda k: _表[k]["更新"])
        _表.pop(最旧, None)
        计数["淘汰"] += 1


def 取(会话id):
    """拿一个会话的轮次列表副本。没有就返回空列表（**不报错** ——
    前端第一次带 id 来时表里必然没有，那是正常路径，不是异常）。"""
    if not 会话id:
        return []
    with _锁:
        _清过期()
        v = _表.get(str(会话id))
        if not v:
            return []
        计数["命中"] += 1
        v["更新"] = _现在()
        return [dict(x) for x in v["轮次"]]


def 记(会话id, 问题, 意图, 类型, 应答摘要=None):
    """追加一轮。**意图为空时不记**（见模块头：拒答/元问题/无意图的澄清没有可继承的东西）。

    返回实际记下的轮次条数变化（0 = 没记）。
    """
    if not 会话id or not 意图:
        return 0
    if 关会话:
        return 0
    with _锁:
        _清过期()
        v = _表.get(str(会话id))
        if v is None:
            v = {"轮次": [], "更新": _现在()}
            _表[str(会话id)] = v
            计数["新建"] += 1
        v["轮次"].append({
            "问题": str(问题 or ""),
            "意图": 意图,
            "类型": 类型,
            "摘要": 应答摘要,
            "时间": _现在(),
        })
        v["轮次"] = v["轮次"][-6:]                       # 只留最近 6 轮：再多也没人看
        v["更新"] = _现在()
        _淘汰()
        return len(v["轮次"])


def 上一轮(会话id):
    """最近一轮。没有就返回 None。"""
    轮 = 取(会话id)
    return 轮[-1] if 轮 else None


def 清空(会话id=None):
    """清掉一个或全部。前端开新会话时用。"""
    with _锁:
        if 会话id is None:
            数 = len(_表)
            _表.clear()
            return 数
        return 1 if _表.pop(str(会话id), None) else 0


# ============================ 上下文拼装 ============================

def 上下文提示(会话id, 最多轮=2):
    """给模型看的【对话上文】区块。返回 (文本, 沿用的上一轮意图 or None)。

    🔴 这里**只放已经归一过的意图**，不放模型的原始 JSON 原文 ——
       原始输出里有被丢弃的越界槽位（校验归一里记着「已忽略无法识别的槽位」），
       把它喂回模型等于把已经扔掉的垃圾再捡回来当范例。
    """
    if 关会话 or not 会话id:
        return None, None
    轮 = 取(会话id)
    if not 轮:
        return None, None

    import json
    近 = 轮[-最多轮:]
    行 = ["【对话上文】（只用于理解「那 / 它 / 换成 / 呢」这类指代；"
          "本轮若提出新的指标或对象，一律以本轮问句为准）"]
    for x in 近[:-1]:
        行.append("用户：%s" % x["问题"])
        行.append("（系统理解为：%s）" % json.dumps(x["意图"], ensure_ascii=False))
    上 = 近[-1]
    行.append("上一轮用户问：%s" % 上["问题"])
    行.append("上一轮系统理解为：%s" % json.dumps(上["意图"], ensure_ascii=False))
    行.append("🔴 如果本轮是**追问或指代**（「那上个月呢」「换成宁波恒力」「它供什么料」），"
              "请输出**完整**意图 —— 把沿用自上一轮的指标 / 维度 / 过滤也一并写全，"
              "只把用户这次**明确改掉**的条件换成新值。")
    行.append("🔴 如果本轮是一个**新的问题**（换了指标或换了对象），"
              "就按新问题独立输出，**不要**带上上一轮的指标。")
    return "\n".join(行), 上["意图"]


# ============================ 确定性兜底 ============================

def 能自立(意图):
    """本轮意图能不能自己站住。**只有这三样之一才算**（见模块头纪律 2）。

    注意：`{"澄清":"..."}` 不算自立 —— 追问「那上个月呢」时，模型看不见上文
    就会回一句澄清，那正是要靠兜底救回来的情况。
    """
    if not isinstance(意图, dict):
        return False
    return bool(意图.get("指标") or 意图.get("基础查询") or 意图.get("场景"))


# 兜底时可以沿用的槽位。**澄清**不在其中（它不是条件，是结论）。
可沿用槽位 = ("指标", "维度", "过滤", "时间", "排序", "限制", "聚合后过滤")


def 兜底合并(上一轮意图, 本轮意图):
    """上一轮做基底 + 本轮覆盖。返回 (合并后意图, 沿用说明列表)。

    🔴 合并规则是**确定的**，不做任何推测：
       · 本轮给了的槽位（非空）→ 覆盖
       · 本轮没给的 → 沿用上一轮
       · 「维度」是**替换**不是并集 —— 用户说「各物料呢」是要换维度看，
         并集会让它变成「按供应商×物料」的交叉表，行数爆炸且答非所问
       · 「排序」「限制」本轮若是显式给了 `null`/空 → 沿用（用户没说=不变）
    """
    if not isinstance(上一轮意图, dict) or not isinstance(本轮意图, dict):
        return 本轮意图, []
    出 = dict(本轮意图)
    出.pop("澄清", None)                                  # 兜底成功就不再是澄清
    沿用 = []
    for k in 可沿用槽位:
        if k == "澄清":
            continue
        本轮值 = 本轮意图.get(k)
        空 = 本轮值 is None or 本轮值 == "" or 本轮值 == [] or 本轮值 == {}
        if not 空:
            continue                                      # 本轮给了 → 以本轮为准
        上值 = 上一轮意图.get(k)
        if 上值 is None or 上值 == "" or 上值 == [] or 上值 == {}:
            continue
        出[k] = 上值
        沿用.append(k)
    return 出, 沿用


def 沿用说明(沿用, 意图):
    """把「沿用了什么」说成人话 —— 必须随答案显示（纪律 3）。"""
    if not 沿用:
        return None
    片段 = []
    for k in 沿用:
        v = 意图.get(k)
        if k == "指标":
            片段.append("指标「%s」" % v)
        elif k == "维度":
            片段.append("维度「%s」" % "×".join(map(str, v)))
        elif k == "过滤":
            片段.append("筛选「%s」" % "、".join(
                str(x.get("值")) for x in v if isinstance(x, dict)))
        elif k == "时间":
            t = v[1] if isinstance(v, list) and len(v) > 1 else v
            片段.append("时间「%s」" % t)
        else:
            片段.append(k)
    return "本次追问沿用了上一轮的：" + "、".join(片段) + "（如需换掉，请在新问题里说明）"


# 「锚点」槽位：决定这一问到底在问什么。**只报这三个** ——
# 维度 / 排序 / 限制 / 过滤 在追问里被改掉是常态（「那换成各物料呢」），
# 每轮都报「沿用了上一轮的排序」纯属噪声，会把真正要说的那句话淹掉。
锚点槽位 = ("指标", "基础查询", "场景")


def 靠上文补全(上轮意图, 问句, 本轮意图, 别名=None):
    """模型**自己**带着上文把追问补全了 → 也要如实报出来。返回沿用槽位列表。

    与 `兜底合并` 的分工（**两条路径都必须报**）：
      · `兜底合并`：模型**没**补出来（本轮意图立不起来）→ 系统拿上一轮当基底补
      · 本函数  ：模型**已经**补出来了（本轮意图能自立）→ 系统只做**如实披露**

    🔴 只报兜底那一条的后果（实测踩到）：模型带着上下文提示词通常**能**自己补全，
       于是 `已承接上一轮` 恒为 False、「本次追问沿用了上一轮的…」恒为空 ——
       前端那个承接提示 UI 元素**在最常见的情况下永远不亮**，等于没做。
       现象上还很像「会话没生效」，会把人送去查会话表（而会话表是好的）。

    🔴 判据刻意**保守**，只认字面：
       本轮问句里出现了该锚点的名字（含别名）→ 认为用户自己说了 → 不报；
       本轮问句里没有、而上一轮有且本轮没换掉 → 才算靠上文补来的。
       代价：同义改写（「不合格率」被说成「次品率」）会**漏报**。
       理由：漏报 = 少说一句「沿用了 X」，答案照样对；
             误报 = 说了一句假话（用户明明自己说了，系统却说「我替你补的」）。
       **保守方向的错是安全的，激进方向的错不是**（与拒答同一条纪律）。
    """
    if not isinstance(上轮意图, dict) or not isinstance(本轮意图, dict):
        return []
    问 = str(问句 or "")
    别名 = 别名 or {}
    沿用 = []
    for k in 锚点槽位:
        本 = 本轮意图.get(k)
        if not 本 or 本 != 上轮意图.get(k):
            # 本轮没有这个锚点，或本轮把它**换成了别的** —— 后者是本轮自己的主张，
            # 不是承接（承接的定义就是「本轮没说、从上一轮拿」）。
            continue
        候选 = [str(本)]
        if k == "指标":
            候选 += [str(x) for x in (别名.get(str(本)) or [])]
        if any(词 and 词 in 问 for 词 in 候选):
            continue                                      # 用户自己说了 → 不算承接
        沿用.append(k)
    return 沿用


# ============================ 状态 ============================

def 统计():
    with _锁:
        活 = len(_表)
        轮次 = sum(len(v["轮次"]) for v in _表.values())
    return {"会话数": 活, "轮次": 轮次, "有效期秒": 有效期秒, "上限": 最多会话,
            "已关闭": 关会话, **计数}
