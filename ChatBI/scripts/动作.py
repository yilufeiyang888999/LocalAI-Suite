# 所有动作函数都接受这三个「公共参数」；其余按各动作自己的声明收。
公共参数 = ("依据", "问题", "时间戳")


def _摘要(参数):
    """参数摘要 —— 依据可能是一整个结果集，审计里只留**形状**，不留全文。

    留形状（几列几行、来源问题）就够回答审计要问的两件事：
    「这次拿的是什么数据」「后面那张单据是不是拿这个数据做的」。
    """
    出 = {}
    for k, v in (参数 or {}).items():
        if k == "依据":
            if isinstance(v, dict):
                出["依据"] = {"类型": v.get("类型"), "列": len(v.get("列") or []),
                              "行": len(v.get("行") or []),
                              "来源问题": str(v.get("问题") or "")[:60]}
            elif v is None:
                出["依据"] = None
            else:
                出["依据"] = "（文本 %d 字）" % len(str(v))
        else:
            出[k] = None if v is None else str(v)[:80]
    return 出


def 调用(动作名, 角色=None, 依据切题=None, **参数):
    """编排层的调用入口 —— 也是**权限与审计的唯一必经关口**。

    三件事必须都在这里做，不能分散到调用方：

    1. **参数过滤**：`供应商=/物料=/依据=` 统一传时，不收该参数的函数会直接
       `TypeError: got an unexpected keyword argument`（实测）。参数名是动作表的
       **契约**，而「调用方记得传什么」是不可靠的（加一个动作就会被漏掉）。
    2. **权限检查**：越权**硬拒** —— 不调函数、不落盘、不静默降级。
       放在这里而不是编排层：只要有人能拿到 `动作.调用`，这一关就绕不过去。
    3. **审计留痕**：允许与拒绝**都要记**。「谁在什么时候被拒过」本身就是
       审计要回答的问题 —— 只记成功的审计，看不出有人在试探。

    返回结构里带 `被拒` 键，让上游能区分「权限不足」与「参数没填对」——
    这两者的下一步完全不同（前者要换人，后者要补参数）。
    """
    规 = 动作表.get(动作名)
    if 规 is None:
        # 未知动作也是安全事件：可能是模型乱造工具名，也可能是有人在探测边界。
        审计.记({"角色": 角色 if 角色 is not None else "（内部）",
                 "动作名": 动作名, "参数": _摘要(参数), "允许": False,
                 "被拒": True, "拒绝理由": "不存在的动作", "落盘": False})
        return {"错误": "没有这个动作：%s（可用：%s）"
                        % (动作名, "、".join(动作表))}

    # ---- 权限关口 ----
    可以吗, 理由 = 权限.检查(角色, 动作名, 参数)
    if not 可以吗:
        审计.记({"角色": 角色, "动作名": 动作名, "参数": _摘要(参数),
                 "依据切题": 依据切题, "允许": False, "被拒": True,
                 "拒绝理由": 理由, "落盘": False})
        return {"动作": 动作名, "错误": "权限不足：%s" % 理由,
                "被拒": True, "拒绝理由": 理由}

    # ---- 放行：过滤参数 → 调函数 ----
    允许参数 = set(规.get("参数") or {}) | set(公共参数)
    收下 = {k: v for k, v in 参数.items() if k in 允许参数}
    出 = 规["函数"](**收下)

    审计.记({"角色": 角色 if 角色 is not None else "（内部）",
             "动作名": 动作名, "参数": _摘要(参数), "依据切题": 依据切题,
             "允许": True, "被拒": False,
             "产物": 出.get("路径"), "落盘": bool(出.get("路径")),
             "错误": 出.get("错误")})
    return 出


def 动作清单():
    return [{"动作": k, "用途": v["用途"], "参数": v["参数"]}
            for k, v in 动作表.items()]


# ============================ CLI ============================

def 主():
    sys.stdout.reconfigure(errors="replace")
    参 = argparse.ArgumentParser(description="ChatBI 动作链路（包 5）")
    参.add_argument("--动作", help="动作名：%s" % "、".join(动作表))
    参.add_argument("--供应商")
    参.add_argument("--物料")
    参.add_argument("--依据", help="依据 JSON（含 列/行/口径）或一段文字")
    参.add_argument("--角色", help="以某角色身份调用；缺省 = 内部直调（不检查权限）")
    参.add_argument("--清单", action="store_true", help="列出可用动作")
    参.add_argument("--产物目录", action="store_true", help="打印产物目录并列出已有产物")
    参 = 参.parse_args()

    if 参.清单:
        for x in 动作清单():
            print("· %s —— %s" % (x["动作"], x["用途"]))
            for k, v in (x["参数"] or {}).items():
                print("    参数 %s：%s" % (k, v))
        return 0
    if 参.产物目录:
        print(产物目录)
        if os.path.isdir(产物目录):
            for 名 in sorted(os.listdir(产物目录)):
                print("  %s" % 名)
        else:
            print("  （还没有产物）")
        return 0
    if not 参.动作:
        参.print_help()
        return 2

    依据 = None
    if 参.依据:
        try:
            依据 = json.loads(参.依据)
        except ValueError:
            依据 = 参.依据
    出 = 调用(参.动作, 角色=参.角色, 供应商=参.供应商, 物料=参.物料, 依据=依据)
    if 出.get("错误"):
        print("%s %s" % ("🚫 被拒：" if 出.get("被拒") else "🔴", 出["错误"]))
        return 1
    print("✅ %s → %s" % (出["摘要"], 出["路径"]))
    return 0


if __name__ == "__main__":
    raise SystemExit(主())
