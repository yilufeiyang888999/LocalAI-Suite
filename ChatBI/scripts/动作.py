# ============================ 依据渲染 ============================

def _格(值):
    """表格单元格 → 纯文本。换行/竖线会破坏 markdown 表，先拍平。"""
    return re.sub(r"\s+", " ", str("" if 值 is None else 值)).replace("|", "／").strip()


def 渲染依据(依据, 最多行=20):
    """把「依据」渲染成 markdown 片段。依据可以是：
      · ChatBI 的应答 dict（有 列 / 行 / 口径）
      · 纯文本（RAG 的答案、或人写的一段话）
      · None（没有依据 —— 单据里要**明写**「未附依据」，不能默默留空）
    """
    if 依据 is None or 依据 == "" or 依据 == []:
        return "（本次未附依据数据）", 0
    if isinstance(依据, str):
        return 依据.strip(), 0
    if isinstance(依据, dict):
        类型 = 依据.get("类型")
        # 🔴 依据不一定是一张表 —— 上游（问数）也可能是「澄清 / 拒答 / 元问题」。
        #    这些必须**明写进单据**：单据上写「（无数据）」比写一张空表更危险，
        #    因为看上去像「查过了、就是没有」。真实原因是「没查成」。
        if 类型 in ("澄清", "拒答", "元问题", "拒绝", "错误"):
            名 = {"澄清": "依据查询缺条件（未执行）",
                  "拒答": "依据查询超出本库数据范围",
                  "元问题": "依据查询返回的是元信息、不是业务数据",
                  "拒绝": "依据查询被只读护栏拒绝",
                  "错误": "依据查询出错"}.get(类型, 类型)
            说明 = (依据.get("澄清") or 依据.get("拒答") or 依据.get("错误")
                    or ((依据.get("回答") or "")[:200]))
            return "⚠️ %s：%s" % (名, 说明), 0
        列 = 依据.get("列") or []
        行 = 依据.get("行") or []
        口径 = str(依据.get("口径") or "").strip()
        来源问题 = str(依据.get("问题") or "").strip()
        块 = []
        if 来源问题:
            块.append("> 数据取自查询：「%s」" % 来源问题)
        if 口径:
            块.append("> %s" % 口径)
        if 列 and 行:
            块.append("")
            块.append("| " + " | ".join(_格(x) for x in 列) + " |")
            块.append("|" + "|".join([" --- "] * len(列)) + "|")
            for r in 行[:最多行]:
                块.append("| " + " | ".join(_格(x) for x in r) + " |")
            if len(行) > 最多行:
                块.append("")
                块.append("（共 %d 行，此处列前 %d 行）" % (len(行), 最多行))
        elif 行 is not None and not 行:
            块.append("")
            块.append("（查询返回 0 行 —— **没有命中记录**，请先确认筛选条件）")
        else:
            块.append(json.dumps(依据, ensure_ascii=False)[:600])
        return "\n".join(块).strip(), len(行 or [])
    return str(依据), 0


def _编号(时间戳=None):
    时间戳 = 时间戳 or time.strftime("%Y%m%d-%H%M%S")
    return str(时间戳)


def _落盘(文件名, 正文, 时间戳=None):
    """写产物。返回绝对路径。目录不存在就建（只建自己的 outbox/）。"""
    全 = os.path.normpath(os.path.join(产物目录, 文件名))
    # 🔴 越界护栏：正常拼出来一定在 产物目录 里；越过说明文件名被污染（如含 ../）。
    #    这类事在「动作」层必须拦 —— 越界写文件是这一层唯一的高危动作。
    根 = os.path.normpath(产物目录) + os.sep
    if not os.path.normpath(全).startswith(根):
        raise ValueError("产物路径越界（只允许写 %s）：%s" % (产物目录, 文件名))
    os.makedirs(产物目录, exist_ok=True)
    with open(全, "w", encoding="utf-8", newline="") as 句柄:
        句柄.write(正文)
    return 全


