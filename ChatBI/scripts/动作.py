def 导出异常台账(依据=None, 问题=None, 时间戳=None):
    """异常台账（CSV）。依据的「列 / 行」直接落成 CSV —— 留痕用，不做二次加工。"""
    列 = []
    行 = []
    if isinstance(依据, dict):
        列 = list(依据.get("列") or [])
        行 = list(依据.get("行") or [])
    编号 = _编号(时间戳)
    缓冲 = io.StringIO()
    # 🔴 `newline=""` + utf-8-sig：给 WPS / Excel 直接双击打开用（BOM 让中文不乱码）。
    #    这是「信创办公软件兼容」那条线踩过的坑，这里按同一纪律处理。
    写 = csv.writer(缓冲, lineterminator="\r\n")           # RFC 4180
    if 列:
        写.writerow(["单据编号", *列, "生成时间"])
        for r in 行:
            写.writerow([编号, *[_格(x) for x in r], time.strftime("%Y-%m-%d %H:%M")])
    else:
        写.writerow(["单据编号", "说明", "生成时间"])
        写.writerow([编号, "本次导出没有附带结构化数据（依据为空或为非表格结果）",
                     time.strftime("%Y-%m-%d %H:%M")])
    全 = _落盘("异常台账-%s.csv" % 编号, "\ufeff" + 缓冲.getvalue(), 时间戳)
    return {"动作": "导出异常台账", "单据": "异常台账", "对象": "",
            "路径": 全, "文件名": os.path.basename(全),
            "摘要": "异常台账 CSV（%d 行 × %d 列）" % (len(行), len(列)),
            "正文": 缓冲.getvalue()}


