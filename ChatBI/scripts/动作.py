# -*- coding: utf-8 -*-
"""ChatBI · 动作链路（包 5）—— 把「数据事实」落成可执行的业务单据草稿。

定位：作品二的第一版定位是「采购到料检验异常处理 Agent」，后升级为
      「制造业经营分析 Agent」。升级后前两条链路（问制度 / 问数字）都是**只读**的，
      动作链路就是「从分析走到处置」的那一步 ——
      用户看到数字之后的下一个动作通常是：发通知、提申请、留台账。

🔴 两条纪律（都是踩过才写的）

  1. **单据正文一律模板拼，绝不调模型。**
     单据是要发出去、给对方签字的。数字必须与查询结果**逐字一致** ——
     这正是作品一「引用忠实度」与作品二「口径错」在动作层的延续：
     模型可以决定「生成哪种单据、填哪个对象」，**不允许出现在正文里**。
     缺依据时宁可不生成（返回「缺依据」让编排层去补），也不凭印象编一个数。
     ⚠️ 判据：同一个依据跑两次，产出的正文必须逐字节相同（`_自检-幂等` 覆盖）。

  2. **业务库永远只读，产物只写自己的目录。**
     部署时业务库往往挂在只读共享上，能不能写、写哪里是部署问题，不是业务问题。
     包 6 的权限白名单就挂在这一层：**白名单外的路径一律拒绝**。

  3. **权限与审计都收在 `调用()` 一个关口上**（包 6）。
     权限管「谁能发起动作」，审计管「每次调用都留痕」——
     两件事放在同一个函数里，拿到 `动作.调用` 就绕不过去。
     分散到各调用方 = 加一条新链路就漏一处（「调用方记得」不可靠）。
     **越权是硬拒**：不调函数、不落盘、不静默降级。

三类单据，对应到料检验异常的三条处置路径：

  | 动作 | 对谁 | 依据 | 产出 |
  |---|---|---|---|
  | 生成质量整改通知 | 供应商 | 该供应商的不良率 / 不合格批次 | `outbox/质量整改通知-*.md` |
  | 生成补货申请单   | 物料   | 低于安全库存的物料与缺口     | `outbox/补货申请单-*.md`   |
  | 导出异常台账     | 留痕   | 异常明细                     | `outbox/异常台账-*.csv`    |
"""

