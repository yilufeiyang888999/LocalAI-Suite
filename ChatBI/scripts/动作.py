_抬头 = "**%s** —— 制造业经营分析助手（演示库，非生产数据）\n\n单据编号：%s\n生成时间：%s\n"


def 生成质量整改通知(供应商=None, 依据=None, 问题=None, 时间戳=None):
    """对供应商发质量整改通知。缺供应商名 → 不生成（返回错误，让编排层去补）。"""
