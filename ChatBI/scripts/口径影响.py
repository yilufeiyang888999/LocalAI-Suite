def 打一份(定义, 变更, 写文件=True):
    if not (变更.get("关键词") or 变更.get("对象")):
        print("  🔴 %s 关键词与对象都空 —— 影响面为 0 是**假**的，先补关键词"
              % 变更.get("编号"))
    面 = 算影响面(定义, 变更)
    print()
    print("─" * 74)
    print("【%s】%s · %s" % (面["编号"], 变更.get("对象"), 变更.get("类型")))
    print("  关键词：%s" % ("、".join(面["关键词"]) or "**空（危险）**"))
    print("  %s" % 面["判别"])
    print("  语义层引用 %d 处 ｜ 题集命中 %d 条 ｜ 历史问法疑似 %d 条"
          % (len(面["语义层引用"]), len(面["题集命中"]), len(面["日志疑似"])))
    for x in 面["题集命中"][:8]:
        print("    %s %s [%s] %s  ← %s" % (x["级别"], x["编号"], x["命中位置"],
                                         x["问题"][:34], "、".join(x["命中词"])))
    if 写文件:
        路径 = os.path.join(项目目录, "eval", "口径变更影响-%s.md" % 面["编号"])
        with open(路径, "w", encoding="utf-8") as 句柄:
            句柄.write(渲染md(变更, 面))
        print("  → %s" % 路径)
    return 面


