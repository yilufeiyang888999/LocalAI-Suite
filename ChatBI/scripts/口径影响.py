# -*- coding: utf-8 -*-
"""ChatBI · A-5 口径变更影响面

要解决的问题：改一处口径，**扩散到哪**是看不出来的。
`指标口径定义-v1.0.yaml` 是本项目唯一的语义事实来源 —— 它同时喂给：
  · 意图解析的提示词（槽位清单从它生成）
  · 语义层渲染（SQL 从它拼）
  · 场景模板（多跳问题的 SQL 直接写在里面）
  · 50 题评测集与 40 题盲测集（金标准按它写）
  · 对账索引（校验-语义层.py 拿它对账）
改一个度量表达式，受影响的是**上面全部**。而改完不重跑评测，
「口径变了但评测还是绿的」会被读成「改得没问题」—— 那是把**陈旧**当**通过**。

🔴 本工具的判据是「能区分『扫到了』与『没扫』」：
   · 关键词为空 → **明确报警**。空关键词扫什么都返回 0，而 0 和「确实没有引用」
     长得一模一样 —— 这正是本项目最怕的那类形态（§9.5）。
   · 必须带**反例判据**：用一个绝不存在的词跑一遍，结果必须是 0。

## 分级（决定要不要重跑评测）

| 级别 | 命中位置 | 含义 | 动作 |
|---|---|---|---|
| 🔴 高 | 评测题 / 盲测题的**期望意图**（结构化） | 这道题的口径直接改了 | 必须重跑该题 |
| 🟠 中 | 评测题的**标准 SQL** 或**问题文本** | 金标准或问法涉及 | 建议重跑该题 |
| 🟡 低 | 语义层内部的引用（指标 / 场景 SQL / 实体别名） | 扩散源 | 逐个看，可能要改 |
| ⚪ 参考 | 历史问数日志里的问句 | 用户真问过 | 参考（文本匹配，会误报） |

⚠️ 历史日志是**问句文本匹配**。日志里没记 SQL / 意图（记的是问句 + 类型 + 口径），
   所以「日志命中」只能算疑似，不能算确定受影响 —— 报告里必须这么写，
   否则会拿「可能相关」当「已核对」。
"""

