# ============================ 变更台账 ============================

def 载入变更():
    if not os.path.exists(变更文件):
        raise SystemExit("🔴 变更台账不存在：%s" % 变更文件)
    try:
        with open(变更文件, encoding="utf-8") as 句柄:
            return json.load(句柄)
    except ValueError as 错:
        raise SystemExit("🔴 变更台账不是合法 JSON：%s" % 错) from None


def 自查(记录):
    """台账**自身**的一致性检查。返回问题列表（空 = 干净）。

    🔴 为什么必须有：台账是手写的。编号写重了、关键词忘了填、变更前后写成一模一样 ——
       一个都不报错，只是「影响面永远是空的」或者「两条变更互相覆盖」。
       配置错了却表现为「正常」，是本项目最难查的一类问题（见 权限.校验配置）。
    """
    问题 = []
    看到 = set()
    for i, 条 in enumerate(记录.get("变更") or []):
        编号 = 条.get("编号")
        在哪 = 编号 or "第 %d 条（连编号都没有）" % (i + 1)
        if not 编号:
            问题.append("%s：缺「编号」" % 在哪)
        elif 编号 in 看到:
            问题.append("%s：编号重复" % 编号)
        else:
            看到.add(编号)
        if not (条.get("关键词") or []):
            # 关键词是影响面的**唯一输入**。空关键词 = 什么都扫不到，且不报错。
            问题.append("%s：关键词为空 —— 影响面会永远是空的，这不是「没影响」" % 在哪)
        for 必 in ("日期", "类型", "对象", "变更前", "变更后", "原因"):
            if not str(条.get(必) or "").strip():
                问题.append("%s：缺「%s」" % (在哪, 必))
        前, 后 = str(条.get("变更前") or "").strip(), str(条.get("变更后") or "").strip()
        if 前 and 后 and 前 == 后:
            问题.append("%s：变更前后一样 —— 记了个恒等变更，看不出改了什么" % 在哪)
        d = str(条.get("日期") or "")
        if d and not re.match(r"^\d{4}-\d{2}-\d{2}$", d):
            问题.append("%s：日期「%s」不是 YYYY-MM-DD" % (在哪, d))
    return 问题


def 补关键词(定义, 变更):
    """关键词**自动补全**：对象若是一个指标名，把它的别名一起算进来。

    为什么要补：用户写台账时只会写「来料不良率」，但题集里写的是「不合格率」
    （实测 T01 就是这种问法）—— 不补的话那条题扫不到，而报告看起来是干净的。
    """
    词, 见 = [], set()

    def 加(x):
        x = str(x or "").strip()
        if x and x not in 见:
            见.add(x)
            词.append(x)

    for w in (变更.get("关键词") or []):
        加(w)
    对象 = str(变更.get("对象") or "").strip()
    加(对象)
    for 指 in (定义.get("指标") or []):
        if 指.get("名称") == 对象:
            for a in (指.get("别名") or []):
                加(a)
            度 = 指.get("度量") or {}
            加(度.get("别名"))
            加(指.get("主表"))
            加(指.get("时间字段"))
    return 词


# ============================ 扫引用 ============================

def 找引用(节点, 关键词, 路径="", 出=None):
    """递归走整个语义层，记下**每个命中的路径**（不是只记「命中过」）。

    路径要可读才可操作：`指标[来料不良率].度量.表达式` 能直接定位到要改的那一行。
    """
    if 出 is None:
        出 = []
    if isinstance(节点, dict):
        for k, v in 节点.items():
            找引用(v, 关键词, ("%s.%s" % (路径, k)) if 路径 else str(k), 出)
    elif isinstance(节点, list):
        for i, v in enumerate(节点):
            标 = i
            if isinstance(v, dict) and v.get("名称"):
                标 = v["名称"]
            找引用(v, 关键词, "%s[%s]" % (路径, 标), 出)
    elif isinstance(节点, str):
        中 = [w for w in 关键词 if w in 节点]
        if 中:
            出.append({"路径": 路径, "命中": 中, "片段": 节点[:110]})
    return 出


def 扫题集(关键词):
    """扫全部评测集。返回 [{文件, 编号, 问题, 级别, 命中位置, 命中词}]。

    命中位置分三档，因为**期望意图命中**与**问题文本命中**的确定性完全不同：
    前者是结构化的（这道题的口径就是它），后者可能只是问句里恰好出现了那个词。
    """
    出 = []
    for 路径 in sorted(glob.glob(题集通配)):
        名 = os.path.basename(路径)
        try:
            with open(路径, encoding="utf-8") as 句柄:
                数据 = json.load(句柄)
        except (OSError, ValueError) as 错:
            出.append({"文件": 名, "编号": "（读不了）", "问题": str(错)[:60],
                       "级别": "🟡 低", "命中位置": "文件读取失败", "命中词": []})
            continue
        for 题 in (数据.get("题目") or []):
            编号 = 题.get("编号") or "?"
            问题 = str(题.get("问题") or "")
            意图 = 题.get("期望意图")
            SQL = str(题.get("标准SQL") or "")
            命中位置, 级别, 词 = None, None, []
            if isinstance(意图, dict):
                文本 = json.dumps(意图, ensure_ascii=False)
                词 = [w for w in 关键词 if w in 文本]
                if 词:
                    命中位置, 级别 = "期望意图", "🔴 高"
            if 命中位置 is None:
                词 = [w for w in 关键词 if w in SQL]
                if 词:
                    命中位置, 级别 = "标准 SQL", "🟠 中"
            if 命中位置 is None:
                词 = [w for w in 关键词 if w in 问题]
                if 词:
                    命中位置, 级别 = "问题文本", "🟠 中"
            if 命中位置 is None:
                continue
            出.append({"文件": 名, "编号": 编号, "问题": 问题,
                       "级别": 级别, "命中位置": 命中位置, "命中词": 词})
    return 出


def 扫日志(关键词, 最多=400):
    """扫历史问数日志里的问句。**只记疑似**（见模块头警告）。"""
    出 = []
    for 路径 in sorted(glob.glob(os.path.join(日志目录, "问数-*.log"))):
        名 = os.path.basename(路径)
        try:
            with open(路径, encoding="utf-8", errors="replace") as 句柄:
                行集 = 句柄.readlines()
        except OSError:
            continue
        for 行 in 行集:
            命 = 问句行.match(行)
            if not 命:
                continue
            问句 = 命.group(2).strip()
            词 = [w for w in 关键词 if w in 问句]
            if 词:
                出.append({"文件": 名, "时间": 命.group(1), "问题": 问句,
                           "类型": 命.group(3), "命中词": 词})
    # 同一句可能被问过很多次 —— 去重，但保留次数（次数说明这条问法有多常用）
    聚 = {}
    for x in 出:
        聚.setdefault(x["问题"], {"问题": x["问题"], "次数": 0,
                               "类型": x["类型"], "命中词": x["命中词"]})
        聚[x["问题"]]["次数"] += 1
    排 = sorted(聚.values(), key=lambda x: -x["次数"])
    return 排[:最多]


# ============================ 影响面 ============================

def 算影响面(定义, 变更):
    词 = 补关键词(定义, 变更)
    面 = {
        "编号": 变更.get("编号"),
        "对象": 变更.get("对象"),
        "关键词": 词,
        "关键词为空": not 词,
        "语义层引用": 找引用(定义, 词) if 词 else [],
        "题集命中": 扫题集(词) if 词 else [],
        "日志疑似": 扫日志(词) if 词 else [],
        "算于": time.strftime("%Y-%m-%d %H:%M:%S"),
    }
    高 = [x for x in 面["题集命中"] if x["级别"] == "🔴 高"]
    中 = [x for x in 面["题集命中"] if x["级别"] == "🟠 中"]
    # 🔴 高 与 🟠 中**分开存**：把「口径被直接改了」和「金标准恰好涉及」混在一个清单里，
    #    会让人以为 40 题都得逐题重跑 —— 判据就退化成了一张没人看的清单。
    面["高风险题"] = sorted({x["编号"] for x in 高})
    面["中风险题"] = sorted({x["编号"] for x in 中})
    面["需重跑"] = sorted(set(面["高风险题"]) | set(面["中风险题"]))
    面["判别"] = ("🔴 必须重跑 %d 题（期望意图里就是这个口径）" % len(面["高风险题"]) if 高 else
               ("🟠 建议重跑 %d 题（金标准或问法涉及）" % len(面["中风险题"]) if 中 else
                "✅ 没有题集命中 —— 但语义层引用仍要看"))
    return 面


def 渲染md(变更, 面):
    行 = []
    行.append("# 口径变更影响面 · %s" % 变更.get("编号"))
    行.append("")
    行.append("| 项 | 内容 |")
    行.append("|---|---|")
    for k in ("日期", "类型", "对象", "字段", "状态", "来源"):
        if 变更.get(k):
            行.append("| %s | %s |" % (k, str(变更[k]).replace("|", "\\|")))
    行.append("")
    行.append("**变更前**：%s" % 变更.get("变更前", ""))
    行.append("")
    行.append("**变更后**：%s" % 变更.get("变更后", ""))
    行.append("")
    行.append("**原因**：%s" % 变更.get("原因", ""))
    行.append("")
    行.append("## 扫描关键词")
    行.append("")
    行.append("`%s`" % "`、`".join(面["关键词"]) if 面["关键词"] else "（**空** —— 扫不到任何东西，先补关键词）")
    行.append("")
    行.append("## 判别：%s" % 面["判别"])
    行.append("")
    if 面["题集命中"]:
        if 面["高风险题"]:
            行.append("**🔴 必须重跑**（期望意图里就是这个口径）：%s"
                      % "、".join(面["高风险题"]))
            行.append("")
        if 面["中风险题"]:
            行.append("**🟠 建议重跑**（金标准 SQL 或问法文本涉及）：%s"
                      % "、".join(面["中风险题"]))
            行.append("")
        行.append("| 题集 | 编号 | 级别 | 命中位置 | 命中词 | 问题 |")
        行.append("|---|---|---|---|---|---|")
        for x in 面["题集命中"]:
            行.append("| %s | %s | %s | %s | %s | %s |"
                      % (x["文件"], x["编号"], x["级别"][:2], x["命中位置"],
                         "、".join(x["命中词"]), x["问题"][:40]))
        行.append("")
    else:
        行.append("没有评测题命中。⚠️ 这只说明**题集里没有这个词**，不等于「改了没影响」——")
        行.append("语义层的引用（下面）才是改动真正扩散的地方。")
        行.append("")
    行.append("## 语义层引用（改动扩散源）")
    行.append("")
    if 面["语义层引用"]:
        行.append("| 路径 | 命中词 | 命中内容 |")
        行.append("|---|---|---|")
        for x in 面["语义层引用"][:60]:
            行.append("| `%s` | %s | %s |"
                      % (x["路径"], "、".join(x["命中"]),
                         x["片段"].replace("|", "\\|").replace("\n", " ")[:80]))
        if len(面["语义层引用"]) > 60:
            行.append("")
            行.append("（共 %d 处，只列前 60）" % len(面["语义层引用"]))
    else:
        行.append("（无）")
    行.append("")
    行.append("## 历史问法（疑似，非确定）")
    行.append("")
    行.append("⚠️ 日志只记问句文本、没记 SQL 与意图，所以这一节是**文本匹配的疑似清单**，")
    行.append("不能当「已核对」。要看确定的影响，看上面的题集与语义层引用。")
    行.append("")
    if 面["日志疑似"]:
        行.append("| 问过次数 | 问句 | 类型 | 命中词 |")
        行.append("|---|---|---|---|")
        for x in 面["日志疑似"][:25]:
            行.append("| %d | %s | %s | %s |"
                      % (x["次数"], x["问题"][:44], x["类型"], "、".join(x["命中词"])))
    else:
        行.append("（无）")
    行.append("")
    行.append("---")
    行.append("")
    行.append("算于 %s ｜ 由 scripts/口径影响.py 生成" % 面["算于"])
    return "\n".join(行) + "\n"


