# -*- coding: utf-8 -*-
"""ChatBI · 意图缓存（B-2）—— 同一句问话不重复问模型

整条链上只有一步要调模型（中文问句 → 槽位），而它是最慢的一步。
实际使用中**同一句问话会被反复问到**：用户重问、页面刷新、多人问同一句、
以及评测跑多轮。这些都不该各花一次模型时间。

## 三条纪律

1. **只缓存成功。**
   被阻断的意图是「**已验证不可用**」的 —— 缓存它等于把一次模型抖动永久固化，
   而且下一次看起来「还是同样的澄清」，没人知道那是缓存。
   命中次数会涨，模型却再没被问过。

2. **提示词或解析规则一改，旧缓存必须作废。**
   key 用「规范化问句 + 上文」，值里另外存一份**提示指纹**。
   指纹 = hash(整段提示词 || **解析规则版本**)。
   指纹不符 → 当作没命中、重新问模型。
   🔴 少了这道闸，A-4 改完提示词跑重测会**全部命中旧缓存**，
   得到一组「改进前后完全一样」的数字 —— 而它不报错，只是白跑一趟。
   🔴 「解析规则版本」那半是同一个坑的另一半：`意图解析.校验归一` 里有
   **不改提示词**的规则（问句字面规则）—— 只按提示词作废的话，改了规则、
   旧缓存照样命中，而结果看起来完全正常。**改规则必须 bump 它**，
   自检有一条断言盯着「规则签名 ⊂ 规则版本」。

3. **带上下文的追问另算一个 key。**
   「那上个月呢」在有上文和没下文时是两个完全不同的问题，
   共用 key 会让追问命中单轮的答案（**答的不是那个问题**）。

## 开关

`CHATBI_NO_INTENT_CACHE=1` 关掉。**评测必须关** ——
缓存的命中会把「模型实测表现」变成「历史表现」，两者混在一起就没法解释数字。
⚠️ **但不要从外部给自检全局设这个开关**：`自检-B档` 有一节要**开着**缓存测命中，
它自己按「临时设 1 → 试 → 恢复原值」来做；外部先设了 1，就把它的「原值」也顶成 1
→ 后面「存得进」那节全挂（实测踩过：`AttributeError: 'NoneType' object has no attribute 'get'`，
很容易误读成代码回归）。**自检的开关交给自检自己管。**
`关缓存()` 是**函数**而不是模块常量：谁先 import 谁后设环境变量不该影响结果
（评测脚本在文件头 import，常量在那一刻就定死了 —— 这个顺序问题踩过）。
"""

import hashlib
import json
import os
import re
import sys
import threading
import time

本目录 = os.path.dirname(os.path.abspath(__file__))
项目目录 = os.path.dirname(本目录)

缓存目录 = os.environ.get("CHATBI_CACHE_DIR") or os.path.join(项目目录, "logs")
缓存文件 = os.path.join(缓存目录, "意图缓存.json")

最多条目 = int(os.environ.get("CHATBI_CACHE_MAX") or 500)

_锁 = threading.RLock()
_表 = None
_记 = {"命中": 0, "未命中": 0, "存入": 0, "指纹不符": 0, "淘汰": 0,
      "写盘": 0, "读盘": 0, "写失败": 0, "失败不缓存": 0}
_最后错 = {"写": None}


def 关缓存():
    """每次读环境变量 —— 见模块头最后一段。"""
    return bool(os.environ.get("CHATBI_NO_INTENT_CACHE"))


_空白 = re.compile(r"\s+")


def 规范化(问句):
    """只做**无损**的规范化：首尾空白、全角空格、连续空白。
    不做去标点 / 去语气词 —— 那些会改变问句含义，而这是一份**答案**缓存，
    不是一份「相似问句」缓存。改错了的表现是「答的不是问的那句」，且不报错。"""
    s = str(问句 or "").replace("\u3000", " ")
    return _空白.sub(" ", s).strip()


def 键(问句, 上下文=None):
    """key = 规范化问句 + 上文 + **生成端身份** + **解析规则版本**。上文进 key 见模块头纪律 3。

    🔴 生成端身份（2026-10-15 夜补，一次真实事故）：
    这份缓存存的是「**某个模型**对某句话的解析结果」，所以 key 里必须有「哪个模型」。
    原来没有 → 同一句话无论谁来解析都命中同一条 → 实测后果见 `生成端身份()` docstring：
    微调 lab 四轮对照里 31/40 题**根本没调模型**，四轮结果逐字相同，
    被读成「微调没效果」并写进了报告；生产上则是「换了模型还在用旧模型的意图」。

    🔴 解析规则版本（2026-10-17 挪进来）：规则变了，旧意图就**不再是同一份答案**
    （哪怕模型和提示词都没变）。原来它混在 `提示指纹()` 里，副作用是
    **任何规则改动都会让「两轮可比性令牌」变红**，而提示词逐字未变 ——
    工具只能报「换了提示词」，这是假警，还会把人引去查提示词。
    现在：**可比性**归 `提示指纹()`（只看提示词），**作废**归这里（key 变 = 不命中）。
    """
    原 = (规范化(问句) + "\x00" + (上下文 or "")
          + "\x00" + 生成端身份()
          + "\x00" + 解析规则版本).encode("utf-8")
    return hashlib.sha1(原).hexdigest()[:20]


# 🔴 解析规则版本 —— 见模块头纪律 2 的下半段。
#    它覆盖**不改提示词**的那类解析规则（当前是 `意图解析.问句要枚举`，
#    以及 2026-10-17 新增的「场景必须含」「过滤字段值必须有问句依据」两条）。
#    改任何这类判据 → bump 这里，并把 `意图解析.问句规则签名` 一起改
#    （自检断言 `问句规则签名 in 解析规则版本`；只改一处 → 自检红，不许静默漂移）。
#    r3：C12 场景门槛 + 基础查询过滤依据（2026-10-17）
#    r4：拒答层的「模糊问项」（指代不明 / 标准不明 → 澄清，2026-10-17）
#        ⚠️ 它不产生意图缓存，**也要进这个版本** —— 这个字段还被写进评测产物，
#        用来给两次跑动的数字差异归因。规则变了而版本没变，差异会被误归成
#        「模型波动」，然后有人去查模型、查采样参数，全是白跑。
#    r5：分组聚合目标「对到简称」也算命中（T44「检验判定」→「检验判定分布」，2026-10-17）
#    r6：方向兜底（模型答不出时按 YAML 方向表补指标 + 实体过滤）+ 实体名不接受「精确」（2026-10-17）
#    r7：实体「去地名前缀」重试（0 命中时剥开头 2~3 字再查，须唯一命中，2026-10-17 M12）
#        ⚠️ 它**改了过滤值**（「东莞恒力」→「恒力」）却没动提示词 ⇒ 只看提示指纹
#        会判成「同一口径」，实际查的东西变了 —— 必须落在这个版本里。
解析规则版本 = "r8:问句枚举:v1+场景门槛:v1+过滤依据:v1+分组简称:v1+方向兜底:v1+实体去前缀:v1+拒答模糊问项:v1+容器规整:v1"


def 生成端身份():
    """当前**生成端**的身份：地址 + 调用方声明的模型名（都取自环境变量）。进 **`键()`**。

    🔴 为什么 key 里必须有它（2026-10-15 夜，一次真实事故）：
    这份缓存的 key 原来是「问句 + 上文」，指纹是「提示词 + 解析规则版本」——
    **两者都不含模型身份**。于是同一句问话，无论由哪个模型解析，答案都是同一份。
    实测后果：微调 lab 的四轮对照（未微调 / v1 / v2 / v3）里 31/40 题**根本没调模型**，
    直接读第一轮写下的意图 → 四轮结果逐字相同 → 被读成「微调没效果」。
    同一件事在生产上更严重：作者在 APP 里把模型从 Spark-4B 换成 Qwen3-8B，
    **旧模型写下的意图仍然会被照用**，而页面上不会留下任何痕迹。

    ⚠️ 它进的是 `键()`（命中/不命中），**不是 `提示指纹()`** —— 后者刻意不含模型身份，
    理由见 `提示指纹()` 的 docstring。改这里不影响「两轮可比性令牌」。

    取环境变量而不是 `意图解析.模型名`：后者是模块常量，
    (a) 会造成 `意图缓存 ← 意图解析` 的循环导入；
    (b) 它只是「调用方声明值」，而这里要的是「这次到底在跟谁说话」。
    地址（`CHATBI_GEN_URL`）= 实际生成端；模型名（`CHATBI_GEN_MODEL`）= 声明的身份
    （微调 lab 用它区分 基线与各 adapter）。两者任一变化 → **键变** → 旧条目自动不命中。
    """
    口 = os.environ.get("CHATBI_GEN_URL") or "（默认生成端）"
    名 = os.environ.get("CHATBI_GEN_MODEL") or ""
    return "%s|%s" % (口, 名)


def 提示指纹(提示文本):
    """hash(**只有**整段提示词)。用途有两个：缓存命中的校验、两轮对照的可比性令牌。

    ⚠️ 2026-10-17 拆分：原来这里是 `hash(提示词 || 解析规则版本)`，于是
    **改一条规则就会让「提示词指纹」变**，而提示词一个字都没动。`比对-逐题.py`
    拿它当「两轮是否同一口径」的令牌，就会报「🔴 换了提示词，数字不可比」——
    假警，还会把人引去查提示词。规则版本的作废职责已挪进 `键()`。
    **判据：指纹只回答「提示词是不是同一份」，别的都不归它管。**

    ⚠️ 这里刻意**不含生成端身份**（与 `键()` 相反）：它有第二个用途 ——
    `评测-盲测集.py` 把它印进报告、`对账-微调前后.py` 拿它当**两轮可比性令牌**
    （「提示词逐字相同 → 数字才可比」）。把模型塞进来会让「微调前 vs 微调后」
    的指纹必然不等，那条硬门槛就废了 —— 那是拿一个 bug 换另一个 bug。
    模型身份属于**「这份答案是谁写的」**，所以它进 `键()`。
    """
    return hashlib.sha1(str(提示文本 or "").encode("utf-8")).hexdigest()[:16]


# 🔴 指纹**算法**版本：它不等于「提示词变了」，但会让新旧指纹无法直接比。
#    没有这个字段的产物 = v1（含规则版本）。比对工具靠它区分两件事：
#      「同一个算法、指纹不同」 → 真的换了提示词 → 不可比、中止
#      「算法不同」             → 只是换了算法 → 警告，但两者不能在指纹上互相作证
指纹算法 = "v2-纯提示词"


# ============================ 存取 ============================

def _载入():
    global _表
    if _表 is not None:
        return _表
    _表 = {"版本": 1, "建立": time.time(), "更新": time.time(), "条目": {}}
    try:
        if os.path.exists(缓存文件):
            with open(缓存文件, encoding="utf-8") as 文:
                旧 = json.load(文)
            if isinstance(旧, dict) and isinstance(旧.get("条目"), dict):
                _表 = 旧
                _记["读盘"] += 1
    except (OSError, ValueError) as 错:                     # noqa: BLE001
        # 缓存坏了**不是**错误 —— 丢掉重来即可，绝不能因此让问数失败。
        _最后错["读"] = "%s: %s" % (type(错).__name__, str(错)[:80])
    return _表


def _写盘():
    if 缓存文件 is None:
        return False
    try:
        os.makedirs(缓存目录, exist_ok=True)
        临时 = 缓存文件 + ".tmp"
        with open(临时, "w", encoding="utf-8") as 文:
            json.dump(_表, 文, ensure_ascii=False, indent=1)
        # 🔴 原子替换：写到一半崩了也不会在磁盘上留下半个 JSON ——
        #    半个 JSON 的下场是「下次启动读不出缓存」，而那看起来像「缓存没用」。
        os.replace(临时, 缓存文件)
        _记["写盘"] += 1
        return True
    except OSError as 错:                                   # noqa: BLE001
        _记["写失败"] += 1
        _最后错["写"] = "%s: %s" % (type(错).__name__, str(错)[:80])
        return False


def _淘汰():
    """超上限时按最近使用淘汰。调用方持锁。"""
    条 = _表["条目"]
    while len(条) > 最多条目:
        最旧 = min(条, key=lambda k: 条[k].get("最近") or 0)
        条.pop(最旧, None)
        _记["淘汰"] += 1


def 取(键值, 指纹):
    """命中返回 {意图, 原文, 用时秒, 缓存: True}；否则 None。"""
    if 关缓存():
        return None
    with _锁:
        条 = _载入()["条目"].get(键值)
        if 条 is None:
            _记["未命中"] += 1
            return None
        if 条.get("提示指纹") != 指纹:
            # 提示词 / 语义层变了 —— 旧答案不再对应任何东西
            _载入()["条目"].pop(键值, None)
            _记["指纹不符"] += 1
            _写盘()
            return None
        条["命中"] = int(条.get("命中") or 0) + 1
        条["最近"] = time.time()
        _记["命中"] += 1
        _写盘()
        return {"意图": 条.get("意图"), "原文": 条.get("原文"),
                "用时秒": 条.get("模型用时秒"), "缓存": True}


def 存(键值, 指纹, 记录):
    """只存**成功**的解析结果。返回是否真的存了。"""
    if 关缓存():
        return False
    意图 = 记录.get("意图")
    if not isinstance(意图, dict) or 记录.get("阻断") or 记录.get("抽取失败"):
        _记["失败不缓存"] += 1
        return False
    with _锁:
        现在 = time.time()
        表 = _载入()
        旧 = 表["条目"].get(键值) or {}
        表["条目"][键值] = {
            "意图": 意图,
            "原文": (记录.get("原文") or "")[:600],
            "模型用时秒": 记录.get("模型用时秒"),
            "提示指纹": 指纹,
            "命中": int(旧.get("命中") or 0),
            "首次": 旧.get("首次") or 现在,
            "最近": 现在,
        }
        表["更新"] = 现在
        _记["存入"] += 1
        _淘汰()
        _写盘()
        return True


def 清空(删文件=True):
    global _表
    with _锁:
        数 = len((_载入()["条目"]) if _表 else {})
        _表 = {"版本": 1, "建立": time.time(), "更新": time.time(), "条目": {}}
        if 删文件:
            try:
                if os.path.exists(缓存文件):
                    os.remove(缓存文件)
            except OSError:
                pass
        return 数


def 统计():
    with _锁:
        条 = (_表["条目"] if _表 is not None else (_载入()["条目"]))
        总 = len(条)
        命中次数 = sum(int(v.get("命中") or 0) for v in 条.values())
    return {"已关闭": 关缓存(), "文件": 缓存文件, "条目": 总, "上限": 最多条目,
            "累计命中次数": 命中次数, **dict(_记),
            **({"最近错误": {k: v for k, v in _最后错.items() if v}} if any(_最后错.values()) else {})}


# ============================ CLI ============================

def 主():
    import argparse
    if hasattr(sys.stdout, "reconfigure"):
        try:
            sys.stdout.reconfigure(errors="replace")
        except Exception:                                   # noqa: BLE001
            pass
    参 = argparse.ArgumentParser(description="ChatBI 意图缓存（B-2）")
    参.add_argument("--统计", action="store_true")
    参.add_argument("--清空", action="store_true")
    参.add_argument("--看", action="store_true", help="列出条目（问句本身不存，只有 key 与命中数）")
    参数 = 参.parse_args()

    if 参数.清空:
        print("已清空 %d 条" % 清空())
        return 0
    if 参数.看:
        表 = _载入()
        for k, v in sorted(表["条目"].items(), key=lambda x: -(x[1].get("命中") or 0))[:40]:
            print("  %s  命中 %-3d  %s" % (k[:10], int(v.get("命中") or 0),
                                        json.dumps(v.get("意图"), ensure_ascii=False)[:70]))
        print("共 %d 条" % len(表["条目"]))
        return 0
    print(json.dumps(统计(), ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(主())