# ---------------------------------------------------------------- 方向兜底

def 方向表(定义):
    """从 YAML 读「方向词 / 度量词」对。**不手抄** —— 手抄的那份一定过期，且过期不报错。

    形状来源：`拒答与澄清.反问兜底.方向`（如 `质量/不良率`）。左边是用户嘴里那个
    含糊的方向，右边是本库能算的度量。它本来是给「反问补方向」用的，
    这里复用成「模型答不出时按方向补意图」的映射表 —— 同一份事实，不另立一份。
    """
    规 = (定义.get("拒答与澄清") or {}).get("反问兜底") or {}
    出 = []
    for 项 in (规.get("方向") or []):
        左, _, 右 = str(项).partition("/")
        if 左.strip() and 右.strip():
            出.append((左.strip(), 右.strip()))
    return 出


def _实体通用词(定义):
    """「说了等于没说」的通用名（供应商 / 物料 / 仓库 / 厂商 …）。

    🔴 与 `拒答._实体通用词` **同一份判据**（都从 YAML `实体别名` 的别称 + 表名 +
       匹配字段生成，不手抄）。必须排除：「供应商」这三个字的片段会命中
       「XX 供应商有限公司」这类库值，把「没说哪一家」误判成「说了哪一家」。
    ⚠️ 两处实现是**同源不同用**：那边判「有没有实体」（读全表值），这边判「是哪个
       实体」（走 `查实体` 回调）。`自检-拒答与澄清` 有一条交叉断言盯着两边同结论。
    """
    词 = set()
    for 规 in ((定义.get("实体别名") or {}).get("实体") or {}).values():
        词 |= {x for x in (规.get("别称") or []) if x}
        词.add(规.get("表") or "")
        词.add(规.get("匹配字段") or "")
    return {w for w in 词 if w}


def _实体片段(定义, 查实体, 问题, 最长=4):
    """从问句里找出一个**库里唯一命中**的实体名片段。返回 (字段, 片段) 或 (None, None)。

    🔴 为什么按 ≥2 字片段判：客户从来不说全称。「精诚的货质量怎么样」里只有
       「精诚」两个字，而库里的值是「东莞精诚五金制品有限公司」—— 按全称判
       会把这道**该答**的题判成「没说哪一家」。
    ⚠️ 只接受**唯一命中**：命中多家说明这个片段太泛（「供应」「恒力」若有同名），
       那时应该澄清，而不是替用户挑一家（YAML `实体别名.匹配策略.唯一性`）。
    ⚠️ 短片段优先（长 2 → 4）：长片段会把「精诚的货」这种跨词的东西也拿去查。
    """
    实体 = (定义.get("实体别名") or {}).get("实体") or {}
    if not 查实体 or not 问题 or not 实体:
        return None, None
    黑 = _实体通用词(定义)
    for 长 in range(2, min(最长, len(问题)) + 1):
        for i in range(len(问题) - 长 + 1):
            片 = 问题[i:i + 长]
            if 片 in 黑:
                continue
            for 规 in 实体.values():
                字段 = 规.get("匹配字段")
                if not 字段:
                    continue
                try:
                    候选 = 查实体(字段, 片)
                except Exception:                     # noqa: BLE001
                    # ⚠️ 校验失败 ≠ 不存在（与 `校验归一` 里那条注释同一件事）：
                    #    这里只是**兜底找过滤**，查不动就当没找到，不阻断、不猜。
                    候选 = None
                if 候选 and len(候选) == 1:
                    return 字段, 片
    return None, None


def _表外问项(定义, 问题):
    """问句是否点了本库**不支持**的问项（退货率 / 库存周转率 / 毛利 / 信用评级 …）。

    🔴 与 `拒答.不支持问项命中` **同一份判据**（都读 `拒答与澄清.范围.不支持问项`）。
       分两处实现是因为层级不同（那边是判定层、这边是解析层兜底），
       自检有一条交叉断言盯着两边同结论 —— 两处判据分叉的后果是
       「这边以为没有、那边以为有」，而两边都不报错。
    ⚠️ 这里**只用来关掉方向兜底**，不做拒答决定 —— 拒答仍由 `拒答.判定` 唯一负责。
    """
    for 组 in (((定义.get("拒答与澄清") or {}).get("范围") or {}).get("不支持问项") or []):
        for w in (组.get("词") or []):
            if w and w in (问题 or ""):
                return w
    return None


def _指标词集(定义, 问题):
    """问句里出现了哪些**指标**（按名称/别名/度量词识别），返回指标名集合。"""
    命中 = set()
    for 指 in 定义["指标"]:
        词汇 = [指["名称"], *(指.get("别名") or []), 指["度量"]["别名"]]
        if any(w and str(w) in (问题 or "") for w in 词汇):
            命中.add(指["名称"])
    return 命中


def 方向兜底(定义, 问题, 查实体=None):
    """模型答不出时，按方向词把问句映射到一个指标。返回 (意图, 说明) 或 (None, None)。

    🔴 为什么需要（2026-10-17 实测 T48「精诚的货质量怎么样？」）：
       7B 模型对「实体 + 方向词 + 怎么样」这类问法**极不稳定**。同一份提示词
       删掉一个示例，它就从「给出 JSON」翻成「反问请选方向」，四次重跑稳定反问；
       再把别名或示例换个写法，又翻回来。**这不是能靠提示词调稳的东西**。
       而方向表在 YAML 里本来就有（反问兜底用的），这是**能规则化**的部分
       —— 按「能规则化的别塞提示词」这条，就该在这里兜，而不是继续改措辞。

    ⚠️ 只认**恰好一个**方向词：命中两个以上 = 真歧义（「又便宜质量又好」这种
       跨指标问句），挑一个猜等于答错一半还看不出来 —— 那种交给跨指标前置/澄清。
    ⚠️ 右边对到的指标也必须**唯一**：对到 0 个（表写了但库没有）或多于 1 个都不兜。
    ⚠️ 问句里有实体就**必须**带上过滤（`_实体片段`）。不带的话「精诚的货质量」
       会答成「全库不良率」：数字算得出来、看着正常，只是答的不是那个人
       —— 比答不出更糟（§9.5「安静地答错」）。
    """
    问题 = 问题 or ""
    # 🔴 闸①：问的是本库**没有**的问项（库存周转率 / 退货率）→ 不兜。
    #    不加这道闸的实测后果（2026-10-17，60 题 T29）：「供应商的库存周转率和
    #    不良率哪个更值得关注？」含方向词「库存」→ 被兜成「库存安全水位」→
    #    **给出了可执行 SQL**，而它本该拒答。兜底把一个「答不了」的问题
    #    加工成了一个「看着能答」的答案 —— 比答不出危险得多。
    if _表外问项(定义, 问题):
        return None, None
    命中 = []
    for 左, 右 in 方向表(定义):
        词 = [x for x in 左.replace("、", "/").split("/") if x]
        if any(w in 问题 for w in 词):
            命中.append((左, 右))
    if len(命中) != 1:
        return None, None
    左, 右 = 命中[0]
    候选 = []
    for 指 in 定义["指标"]:
        词汇 = [指["名称"], *(指.get("别名") or []), 指["度量"]["别名"]]
        if any(右 in str(w) for w in 词汇 if w):
            候选.append(指["名称"])
    if len(候选) != 1:
        return None, None
    # 🔴 闸②：除了方向词指的那个指标，问句里**还点了别的指标** → 跨指标题，不兜。
    #    实测 T54「把交期差的供应商和它们的不良率放一起看看」：
    #    方向词「交期」→ 准时交付率，可问句里还有「不良率」。兜底会只答一半，
    #    另半边需求被**静默丢掉** —— 用户看到一张像模像样的表，却少了他要的那列。
    #    ⚠️ 判据必须放在「候选指标确定之后」：方向词（交期/便宜）不一定出现在
    #       指标词表里（表里写的是「交期达成率」），先定候选才知道该扣掉谁。
    if _指标词集(定义, 问题) - {候选[0]}:
        return None, None
    意图 = {"指标": 候选[0]}
    说明 = "模型没给出可用意图；按方向词「%s」判为指标「%s」" % (左, 候选[0])
    字段, 片 = _实体片段(定义, 查实体, 问题)
    if 字段:
        意图["过滤"] = [{"字段": 字段, "运算符": "模糊", "值": 片}]
        说明 += "；实体按「%s」模糊过滤" % 片
    return 意图, 说明


def 解析(定义, 问题, 查实体=None, 调=_带语法的调, 上下文=None):
    """问题 → {意图, 原文, 阻断, 提示, 用时秒, 抽取失败}

    `上下文`（A-1）：多轮追问的【对话上文】区块，来自 `会话.上下文提示()`。
    不传 = 单轮行为，与本轮改动前完全一致。

    🔴 缓存（B-2）：只缓存**成功**的解析，且 key 里带上文、值里带提示指纹 ——
       见 `意图缓存.py` 模块头。`记["缓存"]` 会如实标出这次是命中还是新算的：
       **评测里出现「命中」就是评测自身的问题**（环境变量没关），
       必须看得见，否则整轮数字都是历史值。
    """
    起 = time.time()
    提示文本 = 构造提示(定义, 问题, 上下文)
    指纹 = 意图缓存.提示指纹(提示文本) if not 意图缓存.关缓存() else None
    键值 = 意图缓存.键(问题, 上下文) if not 意图缓存.关缓存() else None

    if 键值:
        栏 = 意图缓存.取(键值, 指纹)
        if 栏 is not None:
            # 命中：沿用当时归一后的意图。**不再跑一遍校验归一** ——
            # 缓存里存的就是归一结果，再归一是恒等操作（自检「归一幂等」盯着这条）。
            记 = {"原文": 栏.get("原文"), "模型用时秒": 栏.get("用时秒"),
                  "tokens": None, "带上下文": bool(上下文),
                  "提示字符数": len(提示文本), "缓存": "命中",
                  "意图": 栏["意图"], "原始意图": None, "阻断": [], "提示": [],
                  "抽取失败": False, "用时秒": round(time.time() - 起, 2)}
            return 记
        缓存态 = "未命中"
    else:
        缓存态 = "已关闭"

    文本, 用时, 用量 = 调(提示文本)
    原始 = 抽JSON(文本)
    记 = {"原文": 文本, "模型用时秒": 用时,
          "tokens": (用量 or {}).get("completion_tokens"),
          "带上下文": bool(上下文), "提示字符数": len(提示文本), "缓存": 缓存态}

    if not isinstance(原始, dict):
        # 🔴 模型答不出时，先试**规则兜底**（见 `方向兜底`）：问句里有唯一方向词
        #    （质量/交期/库存/工单/采购）就按 YAML 的方向表补出来。
        #    这条兜底**只补「方向」这一个槽**，不猜维度、不猜时间、不猜过滤 ——
        #    它能把「该答的题答出来」，但不会把一个含糊问句编成一个精确问句。
        兜, 兜说 = 方向兜底(定义, 问题, 查实体=查实体)
        if 兜:
            意图, 阻断, 归一提示 = 校验归一(定义, 兜, 查实体=查实体, 问题=问题)
            记.update({"意图": 意图, "原始意图": 兜, "阻断": 阻断,
                       "提示": [兜说] + list(归一提示 or []), "抽取失败": False,
                       "方向兜底": 兜说, "原文": 文本,
                       "用时秒": round(time.time() - 起, 2)})
            # 🔴 **兜底结果不进缓存**：缓存里没有「方向兜底」这个标记，
            #    一旦命中，评测统计就看不见「这题是靠兜底答的」——
            #    §9.5「降级必须可区分」。多花一次模型调用换这份可区分性，值。
            记["缓存"] = "未命中·本次未缓存（方向兜底）"
            return 记
        记.update({"意图": None, "抽取失败": True,
                   "阻断": ["没能从模型输出里解析出 JSON 意图"],
                   "提示": [], "用时秒": round(time.time() - 起, 2)})
        return 记

    意图, 阻断, 归一提示 = 校验归一(定义, 原始, 查实体=查实体, 问题=问题)
    记.update({"意图": 意图, "原始意图": 原始, "阻断": 阻断, "提示": 归一提示,
               "抽取失败": False, "用时秒": round(time.time() - 起, 2)})
    if 键值 is not None:
        # 失败（阻断 / 抽取失败）时 `存` 会拒绝 —— 见 意图缓存.py 纪律 1
        记["缓存"] = "已存" if 意图缓存.存(键值, 指纹, 记) else "未命中·本次未缓存"
    return 记


# ============================ CLI ============================

def 主():
    参 = argparse.ArgumentParser(description="ChatBI 意图解析（问题 → 结构化意图）")
    参.add_argument("--问题", help="单条问题")
    参.add_argument("--看提示词", action="store_true", help="打印槽位说明书就退出")
    参.add_argument("--不校验实体", action="store_true", help="跳过实体存在性检查")
    参数 = 参.parse_args()

    定义 = 语义.载入()
    if 参数.看提示词:
        print(槽位说明书(定义))
        return 0
    if not 参数.问题:
        参.print_help()
        return 2

    连接 = None
    if not 参数.不校验实体:
        连接 = sqlite3.connect("file:%s?mode=ro" % 语义.库路径(定义).replace("?", "%3f"), uri=True)

    def 查实体(字段, 值):
        实体 = 定义["实体别名"]["实体"]
        目标 = next((v for v in 实体.values() if v["匹配字段"] == 字段), None)
        if not 目标 or 连接 is None:
            return None
        列 = 目标["匹配字段"]
        行 = 连接.execute(
            "SELECT DISTINCT %s FROM %s WHERE %s LIKE ?" % (列, 目标["表"], 列),
            ("%" + str(值) + "%",)).fetchall()
        return [r[0] for r in 行]

    记 = 解析(定义, 参数.问题, 查实体=查实体)
    print("问题：%s" % 参数.问题)
    print("模型原文：%s" % (记["原文"] or "").strip()[:400])
    原始 = 记.get("原始意图")
    print("结构化意图：%s" % (json.dumps(原始, ensure_ascii=False) if 原始 else "（抽取失败）"))
    for 行 in 记.get("提示") or []:
        print("  · %s" % 行)
    if 记.get("阻断"):
        for 行 in 记["阻断"]:
            print("  🔴 %s" % 行)
        print("→ 需澄清，不渲染")
        return 1
    print("归一后：%s" % json.dumps(记["意图"], ensure_ascii=False))
    try:
        结果 = 语义.渲染(定义, 记["意图"])
        print()
        print(结果["SQL"])
    except Exception as 错:                        # noqa: BLE001
        print("🔴 渲染失败：%s: %s" % (type(错).__name__, 错))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(主())
