修饰后缀 = ("分布", "情况", "统计", "明细", "数据", "汇总")


def _剥修饰(词):
    """剥掉模型爱加的**纯修饰后缀**，不改动专名。

    实测：「各仓库库存总量分布」比定义里的「各仓库库存总量」多两个字 →
    精确匹配失败 → 一个本来完全正确的意图被判成澄清（A05，第二轮通过、
    第四轮失败，差别只在这两个字）。剥的只是修饰词，不做模糊推测 ——
    「供应商评级」不含这些后缀，不会被碰，那条「反向包含必须禁止」的教训依然成立。
    """
    出 = str(词).strip()
    for s in 修饰后缀:
        if 出.endswith(s) and len(出) > len(s) + 1:
            出 = 出[:-len(s)]
    return 出


def 就近(候选, 词):
    """在候选集合里找唯一对应项。返回 (命中, 问题)。多个候选 = 歧义，不猜。

    🔴 只允许**一个方向**的包含匹配：`词 in 候选名`（词是简称，如「供应商」→「供应商名称」）。
       反方向（候选名是词的子串）必须禁止 —— 实测过：「供应商评级」会被归一成
       「供应商」，SQL 合法、结果也像模像样，只是答的不是问的那件事。
       这类错误比报错危险得多，因为它不会让人停下来看一眼。
    """
    词 = str(词).strip()
    裸 = _剥修饰(词)
    if 裸 and 裸 in 候选:
        return 裸, None
    if 词 in 候选:
        return 词, None
    近 = [c for c in 候选 if (词 and 词 in c) or (裸 and 裸 in c)]
    if len(近) == 1:
        return 近[0], None
    if len(近) > 1:
        return None, "「%s」可能指 %s，请指明是哪一个" % (词, "、".join(近))
    return None, "「%s」不在可用清单里（可用：%s）" % (词, "、".join(候选))


def _对上分组(基, 目标):
    """把「目标」对到某个分组聚合名上；对不上返回 None。

    🔴 为什么单独抽出来：这条「目标 ⊂ 组名」的判断原来在**两个地方**各写一份
       （类型填错时的宽容 / 目标填错时的改判），两份必然在下次改词表时分叉，
       而分叉的表现是「一处救得回、一处救不回」，不报错、只丢题。
       现在两处都走这里，判据只有一份。

    🔴 只允许**单向包含**（目标 ⊂ 组名），与 `就近` 同一方向：
       「检验判定」→「检验判定分布」可以；反方向（组名 ⊂ 目标）禁止 ——
       「供应商评级」被归一成「供应商」那次的教训。
       多个命中 = 歧义，`就近` 自己会拒绝（返回问题串），这里一并当对不上。
    """
    目标 = str(目标 or "").strip()
    if not 目标:
        return None
    组名 = [x["名称"] for x in (基.get("分组聚合") or [])]
    名, 说 = 就近(组名, 目标)
    return 名 if not 说 else None


def 维度别称表(定义):
    """维度名 → 口语别称（**从 YAML `实体别名.实体.别称` 读，不手抄**）。

    🔴 为什么要有这一层（2026-10-14 实测定位）：维度清单里只有「供应商」这一个词，
    而提示词规则 1 要求模型「**原样抄，不要发明新词**」。模型看见「三家厂商 / 哪家 /
    头名是谁」，在清单里找不到「厂商」→ 干脆**不给维度** → SQL 只出一列 `不良率`
    → 答出「最高是 8.3」却答不出「是谁」。盲测 T01 / T02 / T11 / T24 全是这个形态。

    别称的**唯一事实来源**仍是 YAML，这里只做「实体名 → 别称列表」的形状转换。
    """
    实体 = ((定义.get("实体别名") or {}).get("实体") or {})
    出 = {}
    for 名, 规 in 实体.items():
        别 = [x for x in (规.get("别称") or []) if x != 名]
        if 别:
            出[名] = 别
    return 出


def 别称归一维度(定义, 词):
    """把「厂商 / 供货商 / 材料」这类**口语指代**映射到实体名（= 维度名候选）。

    🔴 与 `就近()` 同一条教训：**精确优先，且不许反向吞并**。
    「供应商类别」本身是另一个维度名，绝不能被「供应商」的别称表吞掉
    （同类事故实测过：「供应商评级」被吞成「供应商」，SQL 合法、数字像真的、答错题）。
    所以这里**只认字面相等** —— 词 == 实体名 或 词 ∈ 别称列表，**不做包含匹配**。

    返回实体名或 None。**是否采纳由调用方决定**（还要确认它在本指标的维度清单里，
    否则「厂商」会被塞进一个没有供应商维度的指标）。
    """
    词 = str(词 or "").strip()
    if not 词:
        return None
    for 名, 规 in ((定义.get("实体别名") or {}).get("实体") or {}).items():
        if 词 == 名 or 词 in (规.get("别称") or []):
            return 名
    return None


def 归一指标(定义, 名):
    if not 名:
        return None, "没给出指标"
    名 = str(名).strip()
    for 指 in 定义["指标"]:
        if 指["名称"] == 名:
            return 指["名称"], None
    for 指 in 定义["指标"]:
        if 名 in (指.get("别名") or []):
            return 指["名称"], "指标「%s」归一为「%s」（别名）" % (名, 指["名称"])
    命中 = []
    for 指 in 定义["指标"]:
        词汇 = [指["名称"], *(指.get("别名") or [])]
        if any(名 in v for v in 词汇):            # 同 就近()：只允许「词更短」这一个方向
            命中.append(指["名称"])
    命中 = sorted(set(命中))
    if len(命中) == 1:
        return 命中[0], "指标「%s」归一为「%s」（近似）" % (名, 命中[0])
    if len(命中) > 1:
        return None, "「%s」可能指 %s，请说明是哪一个" % (名, "、".join(命中))
    return None, ("语义层没有定义指标「%s」（可用：%s）"
                  % (名, "、".join(x["名称"] for x in 定义["指标"])))


