def 槽位说明书(定义):
    """把 YAML 里的可选槽位压成模型看得懂的清单。**不手抄**（见模块 docstring）。"""
    行 = ["【指标】（括号里是别名；维度、过滤字段必须原样抄用）"]
    别称表 = 维度别称表(定义)
    for 指 in 定义["指标"]:
        行.append("· %s（%s）" % (指["名称"], "、".join(指.get("别名") or []) or "无别名"))
        维度 = []
        for 维 in 指["维度"]:
            别 = 别称表.get(维)
            维度.append("%s（口语也说「%s」）" % (维, "、".join(别)) if 别 else 维)
        行.append("    维度：%s" % "、".join(维度))
        行.append("    过滤字段：%s" % "、".join(指["过滤字段"]))
    基 = 定义["基础查询"]
    行.append("")
    行.append("【基础查询】用于「有多少/有哪些/合计多少/分布」这类不需要口径的问题")
    行.append("· 计数：%s" % "、".join(基["计数"]))
    行.append("· 枚举：%s" % "、".join(基["枚举字段"]))
    行.append("· 求和：%s" % "、".join(基["原子度量"]))
    行.append("· 分组：%s" % "、".join(x["名称"] for x in 基["分组聚合"]))
    场 = 定义["关联口径"].get("场景模板") or {}
    if 场:
        行.append("")
        行.append("【场景模板】多跳问题用，参数要一起给")
        for 名, 规 in 场.items():
            行.append("· %s —— %s（参数：%s）"
                      % (名, 规["用途"], "、".join(规.get("参数") or {}) or "无"))
    行.append("")
    行.append("【时间表达】只能用这些词，**不要自己算日期**")
    行.append("、".join(定义["时间表达式"]["窗口定义"]))
    行.append('· 也可写 ["指定月份","2026年8月"] 这种明确月份')
    行.append("")
    行.append("【实体过滤】值写口语简称即可（如「东莞精诚」），系统自动模糊匹配，"
              "不要拼全称后缀")
    # 🔴 这一个公司名示例是**诱导源**，但 2026-10-17 的实测证明：删不起。
    #    删掉它（连同【输出】里那个 `"值":"东莞精诚"`）修好了 M12
    #    （「恒力」不再被补成「东莞恒力」），代价却是 7B 模型整体变保守：
    #    60 题 T07/T09 变错、T29/T54 从「澄清」变「硬答」——76.5% → 73.5%，硬答 0 → 2。
    #    这是**按下葫芦浮起瓢**：小模型对提示词长度/词面极其敏感，为一道题动它
    #    会牵动十几道题。所以示例保留，M12 记为已知失败（成因见本节末）。
    #    ⚠️ 真要治，正确的位置是**实体匹配 0 条时剥城市前缀重试**（数据口径改动，
    #       需业务确认），不是继续改提示词措辞。
    return "\n".join(行)


