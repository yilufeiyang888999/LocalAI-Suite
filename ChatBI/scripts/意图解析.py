def _取超时():
    """客户端请求超时（秒）。环境变量 `CHATBI_GEN_TIMEOUT` 可覆盖，取不到/非法 → 180。

    ⚠️ **为什么需要这个开关**：180 s 是给**生产 llama.cpp** 定的 —— 30+ tok/s 时
    700 token 只要 ~23 s，余量充足。但 D23 的**自建推理壳实测只有 3.4 tok/s**
    （2026-10-14 实测，`out/验证冷热.log`：连发 4 次 100 token 全部 28~31 s），
    700 token 要 **206 s > 180 s** —— 余量变成负数，**只要模型写满就必然超时**。
    评测脚本遇到超时是「探活 → 失败 → 整轮中止」，于是 **40 题永远跑不完**。
    这不是偶发卡死，是算术。

    默认值不变：**不设这个变量时行为与从前逐字节相同**（生产口径不受影响）。
    """
    原 = os.environ.get("CHATBI_GEN_TIMEOUT")
    if not 原:
        return 180
    try:
        值 = int(原)
    except (TypeError, ValueError):
        return 180
    return 值 if 值 > 0 else 180


