# -*- coding: utf-8 -*-
"""ChatBI · 拒答与澄清（包 3）

问题 → 「该不该答」。**这一步先于模型执行**（顺序反了会出下面这种事）。

🔴 为什么主题越界必须由确定性检查拦在前面（有实测依据）：
   包 0 摸底时 D 档 5/5 会反问 —— 但那是**问句明显模糊**的场景
   （「这个月怎么样」「帮我看看有没有问题」），问句本身没给出任何可映射的槽位。
   「上个月员工工资总额是多少」是另一种情形：问句**结构完整、指向明确**，
   只是那个主题本库没有。实测模型不会说「我不知道」——它会挑一张真实表硬答
   （比如把「采购订单.订单金额」当工资报出来）：
     SQL 合法、数字来自真实数据、格式漂亮，**只有主题是错的**。
   口径错还能对着定义查，主题错无从对照 —— 更隐蔽。
   → 只能靠确定性的关键词检查拦在前面。

四类处置（判据全部确定性，可单测；顺序即优先级）：
   元问题      问「数据本身」（准不准 / 多新 / 覆盖什么）→ 读元信息直接答，**不必调模型**
               （模型答这类问题会用「应该没问题」这种无根据的保证糊弄）
   拒答·超范围  问的对象本库没有（人力 / 销售客户 / 财务 / 设备 / 售后）→ 明说没有 + 给出路
   澄清·有歧义  问句里的词在库里能被两处解释 → 明说本次按哪个理解（**不阻断**）
   澄清·缺信息  能答但条件不全 → 交给模型反问（本模块只做「兜底补方向」）

设计纪律（沿用作品一的判据铁律）：
  ① **拒答必须给出路**：只说「答不了」，用户的下一步是随机换一种问法，而系统永远答不出
     —— 与「功能不支持」没区别。
  ② **宁可多一句提醒，不可少答一次**：库外词与库内词同时命中时**不拒答**，
     走正常链路 + 强提示。把能答的问题变成答不出，是另一种错误，而且用户无从察觉。
  ③ 歧义词表**不手写** —— 运行时取两个字段取值的交集。手写的第二份清单必然过期，
     过期**不报错**，只是静默失效。
"""

