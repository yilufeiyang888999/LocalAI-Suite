# 取值缓存：同一个字段在一轮跑批里被问很多次，没必要反复查库。
# 注意只缓存**成功的**结果 —— 把失败也缓存住，会把一次偶发故障变成永久故障。
_取值缓存 = {}


# ---------------------------------------------------------------- 词表

def 载入规则(定义):
    return 定义["拒答与澄清"]


def 库内词表(定义):
    """「问的是本库范围」的证据词。

    两个来源拼起来，**都不手抄**：
      · YAML 里显式声明的 `范围.库内关键词`（人工把关，克制而精准）
      · 从定义自动收集：表名 / 表别名 / 指标名与别名 / 维度与过滤字段 / 实体别称
    自动收集保证「新增指标后不用改这里」——这正是手抄清单会漏的地方。
    """
    词 = set()

    def 收(x):
        if x is None:
            return
        if isinstance(x, str):
            for 段 in x.replace("，", ",").split(","):
                段 = 段.strip()
                if len(段) >= 2:
                    词.add(段)
        elif isinstance(x, dict):
            # 🔴 只取**键**。第一版对 dict 递归取值，结果把 SQL 片段
            #    （`表达式: "s.供应商名称"`）整段收进了词表 —— 149 个词里一半是垃圾，
            #    而垃圾词会让「库内命中」几乎恒真 → 库外问题照样硬答。
            #    词表的每一项都必须是**人能说出口的业务词**，不是字段路径。
            for k in x:
                收(k)
        elif isinstance(x, (list, tuple, set)):
            for y in x:
                收(y)

    for 组 in (载入规则(定义)["范围"].get("库内关键词") or []):
        收(组)
    # 从定义自动收集（新增指标不必改这里）
    收(定义["基础查询"]["计数"])
    收(定义["基础查询"]["枚举字段"])
    收(定义["基础查询"]["原子度量"])
    for 指 in 定义["指标"]:
        收(指["名称"])
        收(指.get("别名"))
        收(指["维度"])
        收(指["过滤字段"])
    for 规 in (定义["实体别名"]["实体"] or {}).values():
        收(规.get("别称"))
        收(规.get("表"))
    表别名 = 定义["实体别名"].get("表别名") or {}
    收(表别名)
    收(list(表别名.values()))
    # 「库存记录」这类带后缀的名字，补上主干（客户不会说「库存记录」，会说「库存」）
    for 名 in list(词):
        if 名.endswith(("记录", "数量", "金额", "名称", "编码", "类别")) and len(名) > 3:
            词.add(名[:-2])
    词.discard("")
    return 词


def 库外命中(定义, 问题):
    """问句命中了哪些库外主题词。返回 [(词, 主题, 说明), ...]（按词长降序，长的更具体）。"""
    命中 = []
    for 组 in (载入规则(定义)["范围"]["不支持"] or []):
        主题, 说明 = 组["主题"], 组["说明"]
        for 词 in (组.get("词") or []):
            if 词 in 问题:
                命中.append((词, 主题, 说明))
    命中.sort(key=lambda x: -len(x[0]))
    return 命中


def 库内命中(定义, 问题, 词表=None):
    return [w for w in (词表 or 库内词表(定义)) if w in 问题]


def 元问题命中(定义, 问题):
    """命中了哪条元问题短语；没有则 None。"""
    for 短语 in (载入规则(定义)["元问题"].get("短语") or []):
        if 短语 in 问题:
            return 短语
    return None


def 通用问题命中(定义, 问题):
    """「今天几号 / 你是谁」这类**与本库数据无关**的问题；没有则 None。

    单独拎出来而不是并进 `元问题.短语`：处理方式相同（查定义、不调模型），
    但**答案不同** —— 拿「数据来源 / 时间跨度」那套去回答「今天是星期几」是答非所问。
    """
    规 = (载入规则(定义)["元问题"].get("通用问题") or {})
    for 短语 in (规.get("短语") or []):
        if 短语 in 问题:
            return 短语
    return None


def 通用问题文本(定义, 命中短语):
    """通用问题的回答：明说「我不查这个」+ 给数据范围 + 给出路。**不许编日期。**"""
    规 = (载入规则(定义)["元问题"].get("通用问题") or {})
    源 = 定义["数据源"]
    跨度 = 源.get("时间跨度") or {}
    示例 = (载入规则(定义)["范围"].get("可答示例") or [])[:3]
    return (规.get("措辞") or "这个我答不了。") % (
        "%s ~ %s" % (跨度.get("最早"), 跨度.get("最晚")),
        定义["时间锚点"]["值"],
        "、".join(示例))


def 不支持问项命中(定义, 问题):
    """问句是否**明确要了**本库没有的那个东西（退货率 / 信用评级 / 运到哪些城市）。

    与 `库外命中`（主题）的区别见 YAML 注释：主题是数据范围，顺口提到不等于要它；
    问项是「用户要的东西本身」，命中即拒答，**不再看库内词是否命中** ——
    「各供应商的退货率」里的「供应商」只是维度，证明不了有退货这回事。

    返回 [(词, 说明), ...]（按词长降序：长的更具体，先说它）。
    """
    命中 = []
    for 组 in ((载入规则(定义)["范围"].get("不支持问项")) or []):
        说明 = 组.get("说明") or ""
        for 词 in (组.get("词") or []):
            if 词 and 词 in 问题:
                命中.append((词, 说明))
    命中.sort(key=lambda x: -len(x[0]))
    return 命中


def 有指标名(定义, 问题):
    """问句里是否出现了指标名（含别名）—— 元问题的护栏：出现了就不是纯元问题。"""
    for 指 in 定义["指标"]:
        if 指["名称"] in 问题:
            return 指["名称"]
        for 别 in (指.get("别名") or []):
            if len(别) >= 3 and 别 in 问题:
                return 别
    return None


分组信号词 = ["各", "分别", "分组", "哪种", "每个"]


def 有分组信号(问题):
    """问句是否带「分组 / 细分」意图。带分组意图时，命中了元问题短语也**不算**元问题。

    🔴 为什么需要这条反向护栏（实测）：A24「各主要不良原因分别有多少条记录？」
       命中了元问题短语「多少条记录」→ 被判成元问题，**0.03 s 直接答了元信息**，
       而用户问的是「按不良原因分组的分布」。答案南辕北辙，而且因为走的是
       「元问题」这条不调模型的路，连模型都没机会看见这个问题。
       —— 根因是短语命中只是元问题的**必要不充分**条件：短语可以嵌在完全
       不同的问法里。这与「出现指标名时不算元问题」是同一类护栏。
    """
    return [w for w in 分组信号词 if w in 问题]


