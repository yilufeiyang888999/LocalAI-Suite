def _实体值(定义, 连接):
    """库内实体的**具体值**（供应商名 / 物料名 / 仓库名）。从库读，不抄清单。

    §9.5「同一份事实不许两处定义」：实体清单在 `实体别名.实体`，值在库里 ——
    这里只做二者拼接，不额外维护第三份名字表。
    """
    if 连接 is None:
        return set()
    值 = set()
    for 规 in ((定义.get("实体别名") or {}).get("实体") or {}).values():
        表, 字段 = 规.get("表"), 规.get("匹配字段")
        if 表 and 字段:
            值 |= _取值(连接, 表, 字段)
    return 值


def _实体通用词(定义):
    """「说了等于没说」的通用名（供应商 / 物料 / 仓库 / 厂商 …）。

    🔴 必须排除：T34「那家供应商还行吗」的 3-gram「供应商」会命中
       「XX 供应商有限公司」这类值，从而把**指向不明**误判成「有实体」——
       方向正好相反（该拦的没拦）。
       要排除的只有**表名 / 别称 / 覆盖词**；像「精诚」这种真名片段不在此列。
    """
    词 = set()
    for 规 in ((定义.get("实体别名") or {}).get("实体") or {}).values():
        词 |= {x for x in (规.get("别称") or []) if x}
        词.add(规.get("表") or "")
        词.add(规.get("匹配字段") or "")
    别名 = (定义.get("实体别名") or {}).get("表别名") or {}
    词 |= set(别名.keys()) | set(别名.values())
    词 |= set(载入规则(定义)["范围"].get("覆盖") or [])
    词.discard("")
    return {w for w in 词 if len(w) >= 2}


def _实体值命中(定义, 连接, 问题, 最长=4):
    """问句是否点到了某个**具体实体**（「精诚」命中「东莞精诚五金制品有限公司」）。

    🔴 为什么按 ≥2 字片段判、而不是判「问句包含完整值」：客户从来不说全称。
       「精诚的货质量怎么样」里只有「精诚」两个字，而库里的值是
       「东莞精诚五金制品有限公司」—— 按全称判会把这道**该答**的题判成「无实体」，
       于是「怎么样」触发澄清（T48 实测）。
    """
    值 = _实体值(定义, 连接)
    if not 值 or not 问题:
        return None
    黑 = _实体通用词(定义)
    长句 = len(问题)
    for 长 in range(2, min(最长, 长句) + 1):
        for i in range(长句 - 长 + 1):
            片 = 问题[i:i + 长]
            if 片 in 黑:
                continue
            for v in 值:
                if 片 in v:
                    return 片
    return None


def 指代命中(定义, 问题):
    """指向不明的指代词。**排除时间指示**：「这个月」里的「这个」不是指代实体。

    不排除的话 T31「这个月怎么样」会被记成「指向不明」，
    而它真正的问题是「标准不明」（怎么样）—— 措辞会对不上病因。
    """
    规 = 载入规则(定义).get("模糊问项") or {}
    排 = set(规.get("指代排除后缀") or [])
    命中 = []
    for w in (规.get("指代词") or []):
        i = 问题.find(w)
        while i >= 0:
            j = i + len(w)
            if j >= len(问题) or 问题[j] not in 排:
                命中.append(w)
                break
            i = 问题.find(w, i + 1)
    命中.sort(key=lambda x: -len(x))
    return 命中


def 评价命中(定义, 问题):
    """标准不明的评价性问法（有风险 / 还行吗 / 怎么样）。长词优先（更具体）。"""
    规 = 载入规则(定义).get("模糊问项") or {}
    命中 = [w for w in (规.get("评价词") or []) if w in 问题]
    命中.sort(key=lambda x: -len(x))
    return 命中


def _规模描述(定义, 连接=None):
    """「本库有 12 家供应商、30 个物料、3 个仓库」—— 数字从定义与库取，不写死。

    写死数字的文案会在数据重建后**照旧输出错数字**，而且不报错。
    """
    规模 = (定义.get("数据源") or {}).get("规模") or {}
    段 = []
    for 键, 量词 in (("供应商", "家"), ("物料", "个")):
        if 规模.get(键):
            段.append("%s %s%s" % (规模[键], 量词, 键))
    if 连接 is not None:
        仓 = _取值(连接, "库存", "仓库名称")
        if 仓:
            段.append("%s 个仓库" % len(仓))
    return ("本库有 " + "、".join(段)) if 段 else "本库有多家供应商与多个物料"


def 模糊问项(定义, 问题, 连接=None):
    """指向不明 / 标准不明 → 澄清，**不许替用户挑一个指标**。

    返回 {"类型": "指代"|"评价", "命中词": w, "文本": ...}，不成立返回 None。

    护栏（任一成立 → 不判）：
      ① 有分组信号 —— 问的是分布（「各供应商的情况怎么样」），不是评价
      ② 有实体值 —— 对象已经给了（「精诚的货质量怎么样」），剩下的交给口语映射
    另有「有指标名」，但它**只约束评价分支**（方向给了就不算标准不明）；
    指代分支不看它 —— 对象缺失比方向缺失更硬，「那家的不良率是多少」照样要澄清。
    """
    规 = 载入规则(定义).get("模糊问项") or {}
    if not 规:
        return None
    if 有分组信号(问题):
        return None
    if 连接 is not None and _实体值命中(定义, 连接, 问题):
        return None
    # ⚠️ 指代**不看指标名**：对象缺失比方向缺失更硬。
    #    「那家的不良率是多少」方向是清楚的（不良率），但「那家」没有指代对象，
    #    交给口语映射也映射不出东西 —— 这类必须澄清（自检有反例钉着）。
    代 = 指代命中(定义, 问题)
    if 代:
        文本 = (规.get("指代措辞") or "你说的「%s」我这边对不上是哪一条。") % (
            代[0], _规模描述(定义, 连接))
        return {"类型": "指代", "命中词": 代[0], "文本": 文本}
    if 有指标名(定义, 问题):
        return None
    评 = 评价命中(定义, 问题)
    if 评:
        # 🔴 评价分支**依赖实体值护栏**（「精诚的货质量怎么样」靠它放过）。
        #    无连接 → 护栏失效 → 会误拦该答的题。宁可不判（退回今天的行为），
        #    也不能把能答的变成答不出；返回「跳过」让调用方能与「不触发」区分开。
        if 连接 is None:
            return {"跳过": "无连接：读不到实体值，无法排除「问句已经给了对象」",
                    "命中词": 评[0]}
        文本 = (规.get("评价措辞") or "「%s」在本库没有定义，你指哪方面？") % 评[0]
        return {"类型": "评价", "命中词": 评[0], "文本": 文本}
    return None


# ---------------------------------------------------------------- 歧义

def _取值(连接, 表, 字段):
    键 = (表, 字段)
    if 键 in _取值缓存:
        return _取值缓存[键]
    try:
        行 = [r[0] for r in 连接.execute(
            "SELECT DISTINCT %s FROM %s" % (字段, 表)).fetchall()]
    except Exception:                                    # noqa: BLE001
        return set()                                    # 失败**不入缓存**（见上方注释）
    值 = {str(x).strip() for x in 行 if x is not None and len(str(x).strip()) >= 2}
    _取值缓存[键] = 值
    return 值


def 歧义词(定义, 连接, 规则):
    """按规则算出歧义词表。交集型运行时算，关键词型直接读词表。"""
    if 规则.get("测法") == "关键词":
        return None                                     # 关键词型不需要取值
    甲, 乙 = 规则["甲"], 规则["乙"]
    return sorted(_取值(连接, 甲["表"], 甲["字段"]) & _取值(连接, 乙["表"], 乙["字段"]))


def 歧义提示(定义, 问题, 意图, 连接):
    """问句里的词在库内能被两处解释时，返回一句说明（**提示，不阻断**）。

    为什么默认而不是澄清：「五金件」11/12 与供应商类别同名，但口语里
    「五金件的不良率」几乎总是指**料本身**的质量。硬澄清会把九成能答的问题
    变成答不出 —— 那是另一种错误，且用户会觉得系统在装傻。
    """
    如果 = 意图 or {}
    过滤 = " ".join("%s=%s" % (x.get("字段"), x.get("值")) for x in (如果.get("过滤") or []))
    维度 = " ".join(str(x) for x in (如果.get("维度") or []))
    已用字段 = " ".join([过滤, 维度])

    for 规 in (载入规则(定义)["歧义来源"] or []):
        if 规.get("测法") == "关键词":
            触发 = [w for w in (规.get("触发词") or []) if w in 问题]
            排除 = [w for w in (规.get("排除词") or []) if w in 问题]
            if 触发 and not 排除:
                return 规["措辞"] % (规["默认表述"], 规["另一表述"])
            continue

        交 = 歧义词(定义, 连接, 规) or []
        命中词 = [w for w in 交 if w in 问题]
        if not 命中词:
            continue
        词 = 命中词[0]
        甲, 乙 = 规["甲"], 规["乙"]
        默认表述, 另解 = 甲["表述"], 乙["表述"]
        if 规.get("默认") and str(规["默认"]).startswith("乙"):
            默认表述, 另解 = 乙["表述"], 甲["表述"]
        # 意图里已经显式按另一解读筛了这个词 → 说明用户/模型指明了，只需确认
        if 乙["字段"] in 已用字段 and 词 in 已用字段:
            默认表述, 另解 = 乙["表述"], 甲["表述"]
        return 规["措辞"] % (词, 默认表述, 另解, 词)
    return None


# ---------------------------------------------------------------- 元信息

def 元信息(定义, 连接=None):
    """「数据准不准 / 多新 / 覆盖什么」的答案。

    🔴 诚实边界（写进 YAML 了）：本库是**演示库**（固定种子生成），不是生产数据。
       不许用「数据准确可靠」这类话糊弄 —— 那正是模型容易脱口而出的话。
       只报**能核对**的事实，并告诉用户**怎么自查**。
    """
    源 = 定义["数据源"]
    跨度 = 源.get("时间跨度") or {}
    记 = {
        "数据文件": os.path.basename(str(源.get("文件") or "")),
        "怎么来的": str(源.get("生成脚本") or ""),
        "时间跨度": "%s ~ %s" % (跨度.get("最早"), 跨度.get("最晚")),
        "时间锚点": 定义["时间锚点"]["值"],
        "锚点理由": 定义["时间锚点"].get("理由"),
        "覆盖范围": 载入规则(定义)["范围"].get("一句话"),
        "指标数": len(定义["指标"]),
        "表行数": {},
        "行数合计": None,
        "诚实说明": (
            "本库是**演示数据**——由「%s」以固定随机种子生成，不是生产库导入的，"
            "所以它不存在「准不准」的问题：它是自洽的，但也不代表任何真实企业的经营情况。"
            % os.path.basename(str(源.get("生成脚本") or "建库脚本.py"))),
        "怎么自查": (
            "页面上每个答案都能展开「实际执行的 SQL」——那一条就是真正跑过的语句。"
            "把 SQL 复制到任意 SQLite 客户端连本库执行，结果应逐格一致；"
            "口径的定义写在 eval/指标口径定义-v1.0.yaml，可以对着一行行看。"),
    }
    if 连接 is not None:
        for t in sorted(源.get("规模") or {}):
            try:
                记["表行数"][t] = 连接.execute("SELECT COUNT(*) FROM %s" % t).fetchone()[0]
            except Exception:                            # noqa: BLE001
                continue
        if 记["表行数"]:
            记["行数合计"] = sum(记["表行数"].values())
    return 记


def 元问题文本(定义, 连接, 命中短语):
    信 = 元信息(定义, 连接)
    行 = [信["诚实说明"], ""]
    行.append("**数据来源**：`%s`（%s）" % (信["数据文件"], 信["怎么来的"]))
    行.append("**时间范围**：%s；**相对时间的锚点**：%s（%s）"
              % (信["时间跨度"], 信["时间锚点"], 信["锚点理由"]))
    if 信["表行数"]:
        行.append("**覆盖的表**：%s（共 %d 行）"
                  % ("、".join("%s %d 行" % (k, v) for k, v in 信["表行数"].items()),
                     信["行数合计"]))
    行.append("**能回答什么**：%s" % 信["覆盖范围"])
    行.append("**怎么自查**：%s" % 信["怎么自查"])
    return "\n".join(行), 信


# ---------------------------------------------------------------- 时间边界

# 「2026年8月」「2026-08」「2026/8」—— 年月同时出现时优先按它判（精度更高）
_正则_年月 = re.compile(r"(20\d{2})\s*[-/年]\s*(\d{1,2})\s*月?")
_正则_年 = re.compile(r"(20\d{2})\s*年")
_正则_单月 = re.compile(r"(\d{1,2})\s*月份?")


def _加月(首日, 偏移):
    """首日 + N 个月（只接受每月 1 日）。"""
    总 = 首日.year * 12 + (首日.month - 1) + 偏移
    return datetime.date(总 // 12, 总 % 12 + 1, 1)


def _年月区间(年, 月):
    起 = datetime.date(年, 月, 1)
    return 起, _加月(起, 1)


def 时间越界(定义, 问题):
    """问句里的时间是否**完全落在**数据范围之外。返回 None 或 {类型, 命中, 文本, 区间}。

    🔴 为什么必须有这一层（2026-10-17 实测，分布外题集 O08/O09）：
       「2025 年全年的不良率走势如何？」→ 模型没有任何犹豫，按全区间画了 2026-04~09 的
       月度趋势，标题写着 2025。**数字全部来自真实数据，只有年份是错的**，看不出错。
       「下个月的采购金额预计是多少？」→ 同样给了 SQL，等于把没发生的事算出来当答案。
       措辞层面这是**字面可判**的（年份 / 月份 / 未来词），判在模型前面最便宜。

    判据只认**零交集**：
      · 「今年」= 2026-01-01~2027-01-01，与 2026-04~09 有重叠 → 放行（前三个月缺数，
        那是「部分没有」，该由答案里的时间范围说明，不该拒答）。
      · 「2025 年」→ 止 = 2026-01-01 早于数据最早 2026-04-01 → 零交集 → 拒答。
    """
    规 = 载入规则(定义).get("时间边界") or {}
    源 = 定义["数据源"]
    跨度 = 源.get("时间跨度") or {}
    try:
        最早 = datetime.date.fromisoformat(str(跨度["最早"]))
        最晚 = datetime.date.fromisoformat(str(跨度["最晚"]))
    except (KeyError, ValueError):
        # 定义里没写时间跨度 = 没法判边界。**不猜**（猜错的方向用户没法纠正）。
        return None

    def 有交集(起, 止):
        return 起 <= 最晚 and 止 > 最早

    # ---- 1. 未来 / 预测 ----
    for 词 in (规.get("未来词") or []):
        if 词 and 词 in 问题:
            return {"类型": "未来", "命中": 词, "区间": None,
                    "文本": (规.get("未来措辞") or "本库只有已经发生的数据。")
                            % ("%s" % 最早.isoformat(), "%s" % 最晚.isoformat(), 词)}

    # ---- 2. 显式年月 → 3. 显式年份 → 4. 裸月份（按锚点年份解析）----
    剩余 = 问题
    命中 = None
    区间 = None
    for 匹配 in _正则_年月.finditer(问题):
        年, 月 = int(匹配.group(1)), int(匹配.group(2))
        if not (1 <= 月 <= 12):
            continue
        起, 止 = _年月区间(年, 月)
        if not 有交集(起, 止):
            命中, 区间 = 匹配.group(0), (起, 止)
            break
        剩余 = 剩余.replace(匹配.group(0), " " * len(匹配.group(0)))
    if 命中 is None:
        for 匹配 in _正则_年.finditer(剩余):
            年 = int(匹配.group(1))
            起, 止 = datetime.date(年, 1, 1), datetime.date(年 + 1, 1, 1)
            if not 有交集(起, 止):
                命中, 区间 = 匹配.group(0), (起, 止)
                break
            # 年份被认过 → 把它遮掉，免得下面把「2026 年」里的数字当月份
            剩余 = 剩余.replace(匹配.group(0), " " * len(匹配.group(0)))
    if 命中 is None:
        # 裸月份：没有年份就用**锚点年份**解析（「12 月的不良率」= 2026-12，数据没有）
        try:
            锚年 = datetime.date.fromisoformat(str(定义["时间锚点"]["值"])).year
        except (KeyError, ValueError):
            锚年 = 最早.year
        for 匹配 in _正则_单月.finditer(剩余):
            月 = int(匹配.group(1))
            if not (1 <= 月 <= 12):
                continue
            起, 止 = _年月区间(锚年, 月)
            if not 有交集(起, 止):
                命中, 区间 = 匹配.group(0), (起, 止)
                break
    if 命中 is None:
        return None

    天数 = (最晚 - 最早).days + 1
    return {"类型": "越界", "命中": 命中, "区间": 区间,
            "文本": (规.get("措辞") or "这个问题的时间范围在本库数据之外。")
                    % (最早.isoformat(), 最晚.isoformat(), "%d 天" % 天数, 命中)}


# ---------------------------------------------------------------- 主判定

def 判定(定义, 问题, 连接=None):
    """问句 → 处置。

    返回 {"处置": "元问题"|"拒答"|"放行", ...}：
      · 元问题 → 带 `文本` 与 `元信息`，服务直接返回，**不调模型**
      · 拒答   → 带 `拒答类型` / `文本` / `命中词` / `可答示例`，**不调模型**
      · 放行   → 带 `提示`（可能为空）：库外词与库内词同时命中时给出的强提示
    """
    问题 = (问题 or "").strip()
    规 = 载入规则(定义)

    # ---- 1. 通用问题（与库数据无关：今天几号 / 你是谁）----
    #   放在元问题之前：它比「问数据本身」更靠外一层，答案也不同（不能拿数据来源去答日期）。
    #   **不许编日期** —— 模型被问「今天是星期几」会给出一个像模像样的日期，而它并不知道。
    通用 = 通用问题命中(定义, 问题)
    if 通用:
        return {"处置": "元问题", "命中短语": 通用, "通用": True,
                "文本": 通用问题文本(定义, 通用),
                "元信息": {"时间跨度": "%s ~ %s" % (定义["数据源"]["时间跨度"]["最早"],
                                                 定义["数据源"]["时间跨度"]["最晚"])}}

    # ---- 2. 元问题（问数据本身）----
    #   两道护栏（短语命中只是必要不充分条件）：
    #     ① 有指标名 → 用户要核对的是那个数，不是数据本身
    #     ② 有分组信号（各 / 分别 / 分组）→ 问的是分布，不是「库里有多少」
    分组 = 有分组信号(问题)
    短语 = 元问题命中(定义, 问题)
    if 短语 and not 有指标名(定义, 问题) and not 分组:
        文本, 信 = 元问题文本(定义, 连接, 短语)
        return {"处置": "元问题", "命中短语": 短语, "文本": 文本, "元信息": 信}

    # ---- 3. 不支持问项（要的东西本身不存在）----
    #   🔴 与「主题越界」分开：这一层**不看库内词是否命中**，因为命中的多半只是维度
    #      （「各供应商的退货率」里的「供应商」）。详见 YAML「不支持问项」注释。
    #   ⚠️ 但**问句里同时出现了本库的指标名**时不拒答（与元问题那道护栏同源）：
    #      「供应商的库存周转率和不良率哪个更值得关注？」—— 周转率我们没有，
    #      但不良率有，用户问的是「这两个哪个重要」，直接拒答等于把能答的一半也扔了。
    #      实测（T29）：不加这道护栏，它会被判成拒答而不是澄清。
    问 = 不支持问项命中(定义, 问题)
    if 问 and not 有指标名(定义, 问题):
        词 = sorted({x[0] for x in 问})
        说明 = "；".join(sorted({x[1] for x in 问 if x[1]}))
        文本 = ("这个问题超出本库范围了。\n\n"
                "你问的是 **%s**，而%s。\n\n"
                "本库能答的是：%s\n\n"
                "换个问法试试：\n· %s"
                % ("」「".join(词), 说明 or "本库没有这个指标或字段",
                   "、".join(规["范围"]["覆盖"]),
                   "\n· ".join(规["范围"]["可答示例"][:5])))
        return {"处置": "拒答", "拒答类型": "超范围", "文本": 文本,
                "命中词": 词, "命中主题": ["不支持问项"], "说明": 说明,
                "可答示例": list(规["范围"]["可答示例"])}

    # ---- 4. 主题越界 ----
    外 = 库外命中(定义, 问题)
    if 外:
        内 = 库内命中(定义, 问题)
        词 = sorted({x[0] for x in 外})
        主题 = sorted({x[1] for x in 外})
        if not 内:
            说明 = "；".join(sorted({x[2] for x in 外}))
            文本 = ("这个问题超出本库范围了。\n\n"
                    "你问的是 **%s** 相关的事（命中「%s」），而%s。\n\n"
                    "本库能答的是：%s\n\n"
                    "换个问法试试：\n· %s"
                    % ("、".join(主题), "」「".join(词), 说明,
                       "、".join(规["范围"]["覆盖"]),
                       "\n· ".join(规["范围"]["可答示例"][:5])))
            return {"处置": "拒答", "拒答类型": "超范围", "文本": 文本,
                    "命中词": 词, "命中主题": 主题, "说明": 说明,
                    "可答示例": list(规["范围"]["可答示例"])}
        # 库外词与库内词同时命中 → **不拒答**（见模块头纪律 ②），只提示
        提示 = ("你提到了「%s」（本库没有%s相关数据），不过问句里也提到了本库范围内的对象，"
                "所以照常查了 —— 如果结果不是你想要的，说明问的其实是%s那件事。"
                % ("」「".join(词), "、".join(主题), "、".join(主题)))
        return {"处置": "放行", "提示": [提示], "命中词": 词}

    # ---- 5. 模糊问项（指向不明 / 标准不明）----
    # 放在主题越界之后：越界是硬边界，先拒答；放在时间边界之前：
    #   问句连对象/标准都没成形时，先问清楚比先说时间更自然
    #   （且两者同时成立时，澄清是更可操作的下一步 —— 用户补一句就能继续）。
    模 = 模糊问项(定义, 问题, 连接)
    if 模 and 模.get("跳过"):
        # 降级必须可区分（§9.5）：字面命中但判不了 —— 放行，但把原因带出去。
        # 调用方据此知道「这条规则没执行」，而不是「执行了、结论是放行」。
        return {"处置": "放行", "提示": [], "命中词": [模["命中词"]],
                "模糊问项跳过": 模["跳过"]}
    if 模:
        if 模["类型"] == "指代":
            说明 = ("指向不明：用了指代词「%s」，问句里没有具体实体"
                    "（供应商 / 物料 / 仓库名）" % 模["命中词"])
        else:
            说明 = ("标准不明：用了评价词「%s」，问句里没有指标名，"
                    "也没说按什么口径评价" % 模["命中词"])
        return {"处置": "澄清",
                "澄清类型": 模["类型"],
                "命中词": [模["命中词"]],
                "命中主题": ["模糊问项"],
                "文本": 模["文本"],
                "说明": 说明}

    # ---- 6. 时间边界（问的时间段完全落在数据之外 / 未来）----
    #   放在最后：主题与问项更具体，先判它们；这一层兜「问句本身没问题、只是时间没有」。
    越 = 时间越界(定义, 问题)
    if 越:
        return {"处置": "拒答",
                "拒答类型": "超出数据范围" if 越["类型"] == "越界" else "无预测数据",
                "文本": 越["文本"], "命中词": [越["命中"]],
                "命中主题": ["时间边界"], "时间区间": 越.get("区间"),
                "说明": "问句的时间范围与数据跨度零交集",
                "可答示例": list(规["范围"]["可答示例"])}

    return {"处置": "放行", "提示": []}


# ---------------------------------------------------------------- 反问兜底

# 🔴 模型输出**根本没解析出意图**时，给用户看的话（不是排障信息）。
#
# 为什么单独拎出来（2026-10-15 实测）：`意图解析.解析` 在抽取失败时会把
# 「没能从模型输出里解析出 JSON 意图」塞进 `阻断`，而服务端把 `阻断` 直接拼成
# 「澄清」文本给用户 —— 于是**内部故障被原样上屏**：
#     T31「这个月怎么样？」→ 界面显示「没能从模型输出里解析出 JSON 意图」
# 这句话对用户零信息量，还伪装成了「一次正常的追问」。
# 原串**不丢**：它仍留在应答的 `阻断` 字段里，排障照查（判据可区分）。
解析失败措辞 = "这个问题我还没能准确理解。"


def 方向词表(定义):
    """反问方向词，**从 YAML 取**（不手抄一份 —— 手抄的必然过期，且过期不报错）。

    单独拎出来是因为它有三个调用方（本模块的 反问补强、`评测-盲测集.py`、
    `评测-链路准确率.py`）—— 三处各写一遍 = 判据与实现会在某次改词表后悄悄分叉，
    而分叉的表现是「评测说没方向、系统以为有方向」，两边都不报错。
    """
    规 = 载入规则(定义).get("反问兜底") or {}
    出 = []
    for d in (规.get("方向") or []):
        出 += [x.strip() for x in str(d).split("/") if x.strip()]
    return [w for w in 出 if w]


def 反问补强(定义, 反问, 抽取失败=False):
    """模型的反问如果没给出方向，补上可选方向。

    为什么必须补（实测）：只写「请补充更多信息」，用户的下一步是**随机猜一次**，
    猜不中就再猜 —— 与直接不答没有区别。反问要能**收敛**，必须给候选方向。

    🔴 `抽取失败`（2026-10-15 新增）：模型输出没解析出意图 —— 此时传进来的
       `反问` 是**系统自己拼的内部诊断串**，必须先换成给用户看的话，再补方向。
       「把方向清单贴在内部报错后面」比原来的 bug 更难看，所以这两步必须一起做。

    本函数是「澄清型回答」的**唯一**后处理入口：阻断型（`问数服务.py` 里
    意图为 None / 有阻断）与模型自出型（`应答.类型=="澄清"`）两条路径都走它。
    分成两处实现必然分叉，而分叉的表现正是「越需要方向的澄清越没有方向」——
    见 2026-10-15 v3 盲测 T27/T28/T31。
    """
    规 = 载入规则(定义).get("反问兜底") or {}
    if 抽取失败:
        反问 = 解析失败措辞
    反问 = (反问 or "").strip()
    方向词 = 方向词表(定义)
    if len(反问) >= 12 and any(w in 反问 for w in 方向词):
        return 反问, False
    if not 反问:
        反问 = "这个问题我还需要一点信息才能查。"
    补 = 规.get("补语") or ""
    return (反问 + ("\n\n" + 补 if 补 else "")), True


# ---------------------------------------------------------------- CLI

def 主():
    import argparse

    import 语义层 as 语义
    参 = argparse.ArgumentParser(description="ChatBI 拒答与澄清判定（不调模型）")
    参.add_argument("--问题", required=True)
    参.add_argument("--意图", help="可选的 JSON 意图（用于歧义提示）")
    参.add_argument("--词表", action="store_true", help="打印库内词表就退出")
    参数 = 参.parse_args()

    定义 = 语义.载入()
    if 参数.词表:
        词 = sorted(库内词表(定义))
        print("库内词表 %d 个：%s" % (len(词), "、".join(词)))
        return 0

    import json
    import sqlite3
    连接 = sqlite3.connect("file:%s?mode=ro" % 语义.库路径(定义).replace("?", "%3f"), uri=True)
    try:
        应 = 判定(定义, 参数.问题, 连接)
        print("问题：%s" % 参数.问题)
        print("处置：%s" % 应["处置"])
        for 行 in (应.get("提示") or []):
            print("  · %s" % 行)
        if 应["处置"] in ("拒答", "元问题"):
            print()
            print(应["文本"])
        如果 = json.loads(参数.意图) if 参数.意图 else None
        if 如果:
            歧 = 歧义提示(定义, 参数.问题, 如果, 连接)
            print()
            print("歧义提示：%s" % (歧 or "（无）"))
        return 0
    finally:
        连接.close()


if __name__ == "__main__":
    sys.exit(主())
