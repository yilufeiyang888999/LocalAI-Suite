/* ---------------- 三、取服务端真实数据 ---------------- */
async function 取JSON(路径, 体) {
  const 选 = 体
    ? { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(体) }
    : { method: "GET" };
  const r = await fetch(基址 + 路径, 选);
  const t = await r.text();
  if (!r.ok) throw new Error(路径 + " → HTTP " + r.status + " " + t.slice(0, 200));
  return JSON.parse(t);
}

/* fetch 桩：页面 `就绪()` 会拉 /catalog 与 /health，别让它打真网络 ——
   真实数据已经由本脚本取好，直接喂给页面即可（也保证可离线复跑）。 */
let 真健康 = null, 真目录 = null;
function 造fetch桩() {
  return async (址) => {
    const 用 = String(址).endsWith("/catalog") ? 真目录
             : String(址).endsWith("/health") ? 真健康
             : {};
    return { ok: true, status: 200, json: async () => 用, text: async () => JSON.stringify(用) };
  };
}

/* ---------------- 三点五、ECharts 桩 ---------------- */
/* 只桩页面真正调到的那几个方法。**记下每次 setOption 的 option** ——
   「图里画的是不是应答里的数」只能靠这个断言。
   桩不做任何渲染，所以它证明不了「图好不好看」，但能证明「该出图时出了图、
   喂进去的数据来自应答而不是页面里写死的」—— 后者恰恰是最容易出错的地方。 */
function 造ECharts桩() {
  const 桩 = {
    调用: [],
    取选项() {
      const 次 = 桩.调用.filter((x) => x.组 === "setOption");
      return 次.length ? 次[次.length - 1].option : null;
    },
    取选项数() { return 桩.调用.filter((x) => x.组 === "setOption").length; },
    数(组) { return 桩.调用.filter((x) => x.组 === 组).length; },
    清() { 桩.调用.length = 0; },
    init(盒) {
      const 实 = {
        _option: null, _disposed: false,
        setOption(o, 替换) {
          this._option = o;
          桩.调用.push({ 组: "setOption", option: o, 替换: !!替换 });
        },
        resize() { 桩.调用.push({ 组: "resize" }); },
        dispose() { this._disposed = true; 桩.调用.push({ 组: "dispose" }); },
        isDisposed() { return this._disposed; },
      };
      桩.调用.push({ 组: "init", 盒 });
      return 实;
    },
  };
  return 桩;
}
