/* 只桩页面真正用到的那几个 API。多一个都不桩 —— 桩多了就成了「测桩」而不是「测页面」。 */
function 造元素(标签) {
  const 自 = {
    标签, className: "", textContent: "", title: "", value: "", checked: false,
    type: "", rows: 0, style: {}, children: [], _html: "",
    第一子: null,
    classList: {
      _s: new Set(),
      add(c) { this._s.add(c); },
      remove(c) { this._s.delete(c); },
      contains(c) { return this._s.has(c); },
      toggle(c, 强) {
        const 要 = 强 === undefined ? !this._s.has(c) : !!强;
        要 ? this._s.add(c) : this._s.delete(c);
        return 要;
      },
    },
    addEventListener() {},
    appendChild(子) { this.children.push(子); return 子; },
    focus() {},
    querySelector() { return null; },
    querySelectorAll() { return []; },
  };
  /* innerHTML 一设，子元素就没了（真 DOM 就是这个语义）——
     页面里 `结果.innerHTML = ""` 是「清空上一次结果」，桩必须跟着清，否则断言会串味。 */
  Object.defineProperty(自, "innerHTML", {
    get() { return this._html; },
    set(v) { this._html = String(v); this.children = []; },
  });
  return 自;
}

