# -*- coding: utf-8 -*-
"""ChatBI · 权限白名单（包 6）——「谁可以发起哪种动作」。

定位：包 5 的动作链路让 Agent 能真的**产出要发出去的单据**。
      从「能写文件」那一刻起，「谁可以写」就成了必须回答的问题 ——
      这就是本模块存在的全部理由。

🔴 只管辖「动作链路」。
   知识问答与数据问数是**只读**的，不该被角色拦住 ——
   真要拦，拦的是「哪些数据可见」（行级/列级授权），那是另一个问题。
   两件事混在一起，白名单会说不清自己到底在管什么。

🔴 三条设计纪律

  1. **默认最少权限**：角色表里没写的动作 = 不许做。
     不给「没配就放行」的方便 —— 那种方便在演示里看不出代价，
     上线第一天就会变成事故。
  2. **越权是硬拒**：不生成产物、不落盘、不静默降级。
     「静默降级」（把『发整改通知』悄悄改成『查一下数据』）比拒绝更危险 ——
     用户以为事办了，其实没办，而且连个可核对的对象都没留下。
  3. **拒绝要给出路**：理由里说清「这个动作需要哪个角色」。
     只说「不行」的拒绝，用户下一步只能来问你（与包 3 的拒答同一条纪律）。

角色按**「对外程度」**分档，不按「职级」分 ——
职级是组织问题，对外程度才是风险问题：

  | 角色 | 边界 | 动作 |
  |---|---|---|
  | 操作员 | 只读留痕 | 导出异常台账 |
  | 主管   | 加内部申请（给采购部） | + 生成补货申请 |
  | 管理员 | 加对外发文（给供应商，对方要签字） | + 生成质量整改通知 |
"""

import argparse
import os
import sys

if hasattr(sys.stdout, "reconfigure"):
    try:
        sys.stdout.reconfigure(errors="replace")
    except Exception:                                       # noqa: BLE001
        pass

本目录 = os.path.dirname(os.path.abspath(__file__))
项目目录 = os.path.dirname(本目录)


# ============================ 角色白名单（唯一事实来源） ============================

角色表 = {
    "操作员": {
        "说明": "只读留痕：可导出异常台账；不能提申请、不能对外发文",
        "动作": ["导出异常台账"],
    },
    "主管": {
        "说明": "内部处置：操作员的全部 + 提交补货申请（给采购部）",
        "动作": ["导出异常台账", "生成补货申请"],
    },
    "管理员": {
        "说明": "对外发文：全部动作，含发给供应商的质量整改通知",
        "动作": ["导出异常台账", "生成补货申请", "生成质量整改通知"],
    },
}

# 🔴 HTTP 入口不传角色时用它。**最少权限** ——
#    默认放行是最常见的权限事故形态：测试期没人传角色，看着一切正常。
默认角色 = "操作员"


# ============================ 判定 ============================

def 角色清单():
    """给页面 / /catalog 用（自描述，不手抄到前端）。"""
    return [{"角色": k, "说明": v["说明"], "动作": list(v["动作"])}
            for k, v in 角色表.items()]


def 允许动作(角色):
    v = 角色表.get(角色)
    return list(v["动作"]) if v else []


def 检查(角色, 动作名, 参数=None):
    """角色能不能发起这个动作。返回 `(允许: bool, 理由: str)`。

    角色为 None = **内部直调**（脚本 / 自检 / 单元测试直接 `动作.调用()`），
    不启用权限检查 —— 这条边界是显式的，且会**写进审计**（角色记「（内部）」），
    不是静默放行。真正对外的入口（HTTP `/ask`）永远带角色。
    """
    if 角色 is None:
        return True, "未指定角色 —— 内部直调，未启用权限检查"
    v = 角色表.get(角色)
    if v is None:
        return False, "未知角色「%s」（可用：%s）" % (角色, "、".join(角色表))
    if 动作名 in v["动作"]:
        return True, "角色「%s」允许「%s」" % (角色, 动作名)

    # 拒绝要**给出路** —— 否则用户下一步只能来问人。
    有权限的 = [k for k, x in 角色表.items() if 动作名 in x["动作"]]
    if 有权限的:
        出路 = "该动作需要角色：%s" % "、".join(有权限的)
    else:
        出路 = "该动作不在任何角色的白名单里（可能是白名单漏配）"
    return False, "角色「%s」没有「%s」的权限 —— %s" % (角色, 动作名, 出路)


def 校验配置():
    """白名单自身的一致性检查。返回问题列表（空 = 干净）。

    🔴 为什么必须有这一条：
      白名单是**手写的字符串**。把「生成补货申请」写成「生成补货申请单」，
      不会报任何错 —— 只是那个角色**永远**执行不了该动作，
      而现象是「权限不足」，看上去像权限设计，其实是一个错别字。
      **配置错了却表现为「正常拒绝」，是最难查的一类问题。**
    """
    import 动作                                            # 延迟导入：避免与 动作.py 循环
    真名 = set(动作.动作表)
    问题 = []
    for 角色, v in 角色表.items():
        for a in v["动作"]:
            if a not in 真名:
                问题.append("角色「%s」白名单里的「%s」不是真实动作（可用：%s）"
                            % (角色, a, "、".join(sorted(真名))))
    # 反向检查：有没有动作**谁都不能做**（配置漏了，功能静默消失）
    覆盖 = set()
    for v in 角色表.values():
        覆盖 |= set(v["动作"])
    for a in sorted(真名 - 覆盖):
        问题.append("动作「%s」没分配给任何角色 —— 它将永远无法执行" % a)
    return 问题


def 在产物目录内(路径):
    """路径白名单**核对**（不是拦阻）。

    🔴 真正的拦阻在 `动作._落盘`（越界直接 raise）。这里只把同一个根目录
       拿出来对外报告，根**只读 `动作.产物目录` 这一处** ——
       同一份事实两处定义，改一处不报错、只给错结果（§9.5 已踩过）。
    """
    import 动作
    根 = os.path.normpath(动作.产物目录) + os.sep
    return os.path.normpath(路径).startswith(根)


# ============================ CLI ============================

def 主():
    sys.stdout.reconfigure(errors="replace")
    参 = argparse.ArgumentParser(description="ChatBI 权限白名单（包 6）")
    参.add_argument("--清单", action="store_true", help="打印角色白名单")
    参.add_argument("--校验", action="store_true", help="检查白名单与真实动作是否对齐")
    参.add_argument("--角色", help="判定：角色")
    参.add_argument("--动作", help="判定：动作名")
    参 = 参.parse_args()

    if 参.清单:
        print("默认角色：%s（HTTP 入口不传角色时用它）" % 默认角色)
        for x in 角色清单():
            print("· %s —— %s" % (x["角色"], x["说明"]))
            for a in x["动作"]:
                print("    允许：%s" % a)
        return 0

    if 参.校验:
        问题 = 校验配置()
        if not 问题:
            print("✅ 白名单与真实动作对齐（%d 个角色 / %d 个动作）"
                  % (len(角色表), len({a for v in 角色表.values() for a in v["动作"]})))
            return 0
        for x in 问题:
            print("🔴 %s" % x)
        return 1

    if 参.角色 or 参.动作:
        if not (参.角色 and 参.动作):
            print("判定需要同时给 --角色 与 --动作")
            return 2
        允许, 理由 = 检查(参.角色, 参.动作)
        print("%s %s" % ("✅ 允许" if 允许 else "🚫 拒绝", 理由))
        return 0 if 允许 else 1

    参.print_help()
    return 2


if __name__ == "__main__":
    raise SystemExit(主())
