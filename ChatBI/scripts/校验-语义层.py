def 结构自检(定义, 连接):
    说("=" * 74)
    说("一、结构自检")
    说("=" * 74)
    问题 = []

    # 表清单（从库里实测，不信任定义）
    表清单 = {r[0] for r in 跑(连接, "SELECT name FROM sqlite_master WHERE type='table'")[1]}
    说("库里实测表：%s" % "、".join(sorted(表清单)))

    必需指标键 = ["编号", "名称", "别名", "业务含义", "主表", "度量", "连接",
                  "连接顺序", "维度", "时间字段", "过滤字段", "默认排序", "护栏"]
    必需度量键 = ["别名", "表达式", "精度", "单位", "口径说明"]

    指表 = 定义["指标"]
    说("指标数：%d（%s）" % (len(指表), "、".join(x["名称"] for x in 指表)))
    编号集 = set()
    名称集 = set()
    for 指 in 指表:
        for k in 必需指标键:
            if k not in 指:
                # 允许「过滤字段」为空字典的情形
                if k == "过滤字段" and 指.get("过滤字段") == {}:
                    continue
                问题.append("指标「%s」缺字段 %s" % (指.get("名称"), k))
        for k in 必需度量键:
            if k not in (指.get("度量") or {}):
                问题.append("指标「%s」的度量缺字段 %s" % (指.get("名称"), k))
        if 指["编号"] in 编号集:
            问题.append("指标编号重复：%s" % 指["编号"])
        编号集.add(指["编号"])
        if 指["名称"] in 名称集:
            问题.append("指标名称重复：%s" % 指["名称"])
        名称集.add(指["名称"])

        主表 = 指["主表"]["表"]
        if 主表 not in 表清单:
            问题.append("指标「%s」主表不存在：%s" % (指["名称"], 主表))

        # 连接片段里出现的表名必须真实存在
        for 名, 子句 in (指["连接"] or {}).items():
            for 表 in re.findall(r"\bJOIN\s+([^\s(]+)", 子句):
                if 表 not in 表清单:
                    问题.append("指标「%s」连接「%s」引用了不存在的表：%s"
                                % (指["名称"], 名, 表))
        # 连接顺序必须覆盖全部连接键
        连接键 = set((指["连接"] or {}).keys())
        顺序键 = set(指["连接顺序"] or [])
        if 连接键 != 顺序键:
            问题.append("指标「%s」连接顺序与连接定义不一致：多 %s / 少 %s"
                        % (指["名称"], 顺序键 - 连接键, 连接键 - 顺序键))
        for c in (指.get("必需连接") or []):
            if c not in 连接键:
                问题.append("指标「%s」必需连接未在连接里声明：%s" % (指["名称"], c))

        # 维度/过滤字段引用的连接必须已声明
        for 维, 规 in (指["维度"] or {}).items():
            for c in (规.get("连接") or []):
                if c not in 连接键:
                    # 自连接（如「供应商」连接指向主表自身）也须显式声明
                    问题.append("指标「%s」维度「%s」引用了未声明的连接：%s"
                                % (指["名称"], 维, c))
            if not 规.get("选择") or not 规.get("分组"):
                问题.append("指标「%s」维度「%s」缺 选择/分组" % (指["名称"], 维))
        for 字, 规 in (指["过滤字段"] or {}).items():
            for c in (规.get("连接") or []):
                if c not in 连接键:
                    问题.append("指标「%s」过滤字段「%s」引用未声明连接：%s"
                                % (指["名称"], 字, c))
            if not 规.get("表达式"):
                问题.append("指标「%s」过滤字段「%s」缺表达式" % (指["名称"], 字))

        if not 指.get("时间字段"):
            问题.append("指标「%s」缺时间字段" % 指["名称"])
        if not (指.get("护栏") or []):
            问题.append("指标「%s」没有护栏说明" % 指["名称"])

    # 基础查询 / 场景模板引用的表
    for 名, 规 in (定义["基础查询"]["计数"] or {}).items():
        if 规["表"] not in 表清单:
            问题.append("基础查询.计数「%s」表不存在：%s" % (名, 规["表"]))
    for 名, 规 in (定义["基础查询"]["枚举字段"] or {}).items():
        if 规["表"] not in 表清单:
            问题.append("基础查询.枚举字段「%s」表不存在：%s" % (名, 规["表"]))
    for 名, 规 in (定义["基础查询"]["原子度量"] or {}).items():
        if 规["表"] not in 表清单:
            问题.append("基础查询.原子度量「%s」表不存在：%s" % (名, 规["表"]))
    for 规 in (定义["基础查询"]["分组聚合"] or []):
        if 规["表"] not in 表清单:
            问题.append("基础查询.分组聚合「%s」表不存在：%s" % (规["名称"], 规["表"]))

    if 问题:
        说("🔴 结构问题 %d 条：" % len(问题))
        for p in 问题:
            说("   - %s" % p)
    else:
        说("✅ 结构自检通过（%d 个指标，引用表全部存在，连接/维度/过滤自洽）" % len(指表))
    说()
    return 问题


