def 时间断言(定义):
    说("=" * 74)
    说("二、时间表达式展开断言（锚点 %s）" % 定义["时间锚点"]["值"])
    说("=" * 74)
    断言 = 定义.get("时间展开断言") or {}
    预期 = 断言.get("预期") or {}
    坏 = 0
    for 名, 期 in 预期.items():
        实 = 语义层.展开时间(定义, 名)
        if 实 is None:
            ok = False
            文案 = "（不限）"
        else:
            ok = (实[0] == 期["起"] and 实[1] == 期["止"])
            文案 = "%s ~ %s" % 实
        说("  %-10s %-26s %s  期望 %s ~ %s"
           % (名, 文案, "✅" if ok else "🔴", 期["起"], 期["止"]))
        if not ok:
            坏 += 1
    说()
    return 坏


# ==================== 3. 逐题对账 ====================

def 读题(题集):
    return {t["编号"]: t for t in 题集["题目"]}


def 逐题对账(定义, 连接, 题目):
    说("=" * 74)
    说("三、逐题对账（语义层渲染 SQL vs 题集标准 SQL）")
    说("=" * 74)
    索引 = 定义["对账索引"]["覆盖"]
    通过, 失败, 跳过 = 0, [], []
    详情 = []

    for 题号 in sorted(索引):
        规 = 索引[题号]
        题 = 题目.get(题号)
        if 题 is None or not 题.get("标准SQL"):
            跳过.append(题号)
            说("  %-4s ⏭  无标准 SQL，跳过" % 题号)
            continue
        if 题号 not in 列映射:
            失败.append((题号, "缺列映射（对账脚本配置不全）"))
            说("  %-4s 🔴 缺列映射" % 题号)
            continue
        try:
            渲 = 语义层.渲染(定义, 规["意图"])
        except Exception as 错:                                     # noqa: BLE001
            失败.append((题号, "渲染异常：%s" % 错))
            说("  %-4s 🔴 渲染异常：%s" % (题号, 错))
            continue

        try:
            标列, 标行 = 跑(连接, 题["标准SQL"])
        except Exception as 错:                                     # noqa: BLE001
            失败.append((题号, "标准 SQL 执行失败：%s" % 错))
            说("  %-4s 🔴 标准 SQL 执行失败：%s" % (题号, 错))
            continue
        try:
            实列, 实行 = 跑(连接, 渲["SQL"])
        except Exception as 错:                                     # noqa: BLE001
            失败.append((题号, "渲染 SQL 执行失败：%s" % 错))
            说("  %-4s 🔴 渲染 SQL 执行失败：%s" % (题号, 错))
            说("       SQL：%s" % 渲["SQL"].replace("\n", " ")[:140])
            continue

        映 = 列映射[题号]
        # 标准列必须全部有映射；缺了就是脚本配置问题，不许猜
        未映射 = [c for c in 标列 if c not in 映]
        if 未映射:
            失败.append((题号, "标准列未映射：%s" % 未映射))
            说("  %-4s 🔴 标准列未映射：%s" % (题号, 未映射))
            continue
        实缺 = [c for c in 映.values() if c not in 实列]
        if 实缺:
            失败.append((题号, "渲染 SQL 缺少列：%s" % 实缺))
            说("  %-4s 🔴 渲染 SQL 缺列：%s" % (题号, 实缺))
            continue

        标位 = {c: i for i, c in enumerate(标列)}
        实位 = {c: i for i, c in enumerate(实列)}
        标键 = sorted(tuple(r[标位[c]] for c in 标列) for r in 标行)
        实键 = sorted(tuple(r[实位[映[c]]] for c in 标列) for r in 实行)

        if len(标行) != len(实行):
            失败.append((题号, "行数 %d vs %d" % (len(实行), len(标行))))
            说("  %-4s 🔴 行数 %d（渲染） vs %d（标准）" % (题号, len(实行), len(标行)))
            continue

        差异 = []
        for a, b in zip(标键, 实键):
            for c, x, y in zip(标列, a, b):
                if not 同值(x, y):
                    差异.append("%s: %s vs %s" % (c, y, x))
        if 差异:
            失败.append((题号, "；".join(差异[:3])))
            说("  %-4s 🔴 数值不一致：%s" % (题号, "；".join(差异[:3])))
            continue

        通过 += 1
        首行 = 标键[0] if 标键 else "（空）"
        说("  %-4s ✅ %2d 行；首行 %s   〔%s〕"
           % (题号, len(标行), str(首行)[:56],
              "共 %d 列对账" % len(标列)))
        详情.append({"题号": 题号, "类型": 规["类型"], "行数": len(标行),
                     "列数": len(标列), "SQL": 渲["SQL"]})

    说()
    说("对账合计：%d 通过 / %d 失败 / %d 跳过（分母 %d）"
       % (通过, len(失败), len(跳过), len(索引)))
    if 失败:
        for 题号, 因 in 失败:
            说("   🔴 %s：%s" % (题号, 因))
    说()
    return 通过, 失败, 详情


