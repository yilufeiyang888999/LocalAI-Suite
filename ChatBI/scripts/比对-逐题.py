# -*- coding: utf-8 -*-
"""ChatBI · 逐题比对 —— 判「同一配置跑两遍，逐题输出是否逐字相同」

## 为什么单独一个脚本

`--parallel N` 到底会不会改变输出，只有**逐题 diff** 能回答（§9.5：
「差 1 题」不许当噪声放过）。而两次评测的产物是两份 `盲测结果-*.json`，
人工 diff 二十万字不现实 —— 所以把判据固化成命令。

同一个工具可复用于：
    · #200 `--parallel 1` 连跑两次 → 可复现性基线
    · #201 `--parallel 1` vs `--parallel 2` → 槽位是否影响浮点路径
    · #203 同进程 scale=0 vs scale=1 → 同进程对照的噪声下限

## 比什么、不比什么

比：`SQL` / `意图` / `解读` / `类型` / `结果`（业务产出与判定结论）
不比：`耗时秒` / `模型用时` / `生成时间`（**天然不同，且不是被测对象**）

## 判据纪律

    · **题数不同 ⇒ 退 3（不可比）**，不能「按较少的题数比」—— 那等于
      悄悄换了分母（§9.5：分母必须固定）。
    · **一份题是「跳过」、另一份是「失败」⇒ 记差异**，因为跳过 ≠ 通过
      （§9.5：降级/跳过必须与通过可区分）。
    · 输出**第一处**差异的完整现场（两边原文），不截断到看不见。

用法：

    python scripts/比对-逐题.py eval/盲测结果-40题-parallel1-a.json eval/盲测结果-40题-parallel1-b.json
    python scripts/比对-逐题.py 甲.json 乙.json --名 parallel1-vs-parallel2
"""

import argparse
import json
import os
import sys

脚本目录 = os.path.dirname(os.path.abspath(__file__))
项目目录 = os.path.dirname(脚本目录)

# 参与比对的字段（业务产出 + 判定结论）
比字段 = ["类型", "SQL", "解读", "结果", "分类"]


def 读(路径):
    with open(路径, encoding="utf-8", errors="replace") as 句柄:
        return json.load(句柄)


def 规范化(值):
    """意图是 dict/list —— 用 sorted 序列化保证键顺序不影响判定"""
    if isinstance(值, (dict, list)):
        return json.dumps(值, ensure_ascii=False, sort_keys=True)
    return "" if 值 is None else str(值)


def 取记录(数据, 标签):
    if "记录" not in 数据:
        print("🔴 %s 里没有「记录」字段 —— 不是我认识的评测产物" % 标签)
        sys.exit(3)
    # 按编号索引，题序不同也能对上（题集顺序变化不该被当成输出差异）
    表 = {}
    for 条 in 数据["记录"]:
        表[str(条.get("编号"))] = 条
    return 表


def main():
    解 = argparse.ArgumentParser()
    解.add_argument("甲")
    解.add_argument("乙")
    解.add_argument("--名", default="", help="报告文件名后缀；不给则用两个文件名拼接")
    # 附加对照：只比「意图」（用于 scale 对照，SQL 文本可能因执行器重排而不同）
    解.add_argument("--只比意图", action="store_true",
                    help="只比 意图 / 结果 两个字段（scale 对照用：SQL 文本受执行器重排干扰）")
    # 🔴 口径不可比时**仍然列出逐题差异**（改提示词/改规则后的归因审计用）。
    #    没有它，一改提示词就彻底看不见「哪几题变了」—— 而归因恰恰要靠这个。
    解.add_argument("--强制逐题", action="store_true",
                    help="口径不可比时仍列出逐题差异（只用于归因审计，不是拿来报差异率的）")
    参数 = 解.parse_args()

    数据甲, 数据乙 = 读(参数.甲), 读(参数.乙)
    表甲, 表乙 = 取记录(数据甲, "甲"), 取记录(数据乙, "乙")

    名 = 参数.名 or ("%s-vs-%s" % (
        os.path.splitext(os.path.basename(参数.甲))[0],
        os.path.splitext(os.path.basename(参数.乙))[0]))
    报告路径 = os.path.join(项目目录, "eval", "可复现性-%s.md" % 名)

    行 = []

    def 加(文本=""):
        行.append(文本)
        print(文本)

    加("# 逐题比对 · %s" % 名)
    加()
    加("| — | 甲 | 乙 |")
    加("|---|---|---|")
    加("| 文件 | `%s` | `%s` |" % (os.path.basename(参数.甲), os.path.basename(参数.乙)))
    加("| 题数 | %s | %s |" % (数据甲.get("题数"), 数据乙.get("题数")))
    加("| 标注 | %s | %s |" % (数据甲.get("标注") or "-", 数据乙.get("标注") or "-"))
    加("| 模型（调用方声明） | %s | %s |" % (
        数据甲.get("调用方声明模型") or "-", 数据乙.get("调用方声明模型") or "-"))
    加("| 引擎自报 | %s | %s |" % (数据甲.get("引擎自报") or "-", 数据乙.get("引擎自报") or "-"))
    加("| 提示词指纹 | `%s` | `%s` |" % (
        数据甲.get("提示词指纹") or "-", 数据乙.get("提示词指纹") or "-"))
    加("| 指纹算法 | %s | %s |" % (
        数据甲.get("指纹算法") or "（旧产物·未记录）",
        数据乙.get("指纹算法") or "（旧产物·未记录）"))
    加("| 解析规则版本 | `%s` | `%s` |" % (
        数据甲.get("解析规则版本") or "（旧产物·字段缺失）",
        数据乙.get("解析规则版本") or "（旧产物·字段缺失）"))
    加()

    # ---- 第一道关：题集/指纹是否可比 ----
    可比 = True
    if str(数据甲.get("题数")) != str(数据乙.get("题数")):
        加("🔴 **题数不同（%s vs %s）⇒ 不可比**：分母换了，任何比例都不能直接减。"
          % (数据甲.get("题数"), 数据乙.get("题数")))
        可比 = False
    # 🔴 指纹**算法**不同时不能拿指纹作证（2026-10-17 拆分公式的副作用）：
    #    两边都对，只是算法不同 —— 报「换了提示词」是错的（它一个字没动）。
    #    这时只能警告；「换了提示词」的硬门槛留给**同算法**的两次比。
    #
    # 🔴 2026-10-17 修正：旧产物**没有「指纹算法」字段**时，以前默认当成 v1。
    #    那是**猜**，而且猜错了：`修复后-v3-复跑` 实际是 v2 算的，值 (494e75f3)
    #    与定稿逐位相同，却被当成 v1 → 报「算法不同·不能作证」→ 假警。
    #    改成按证据判，只有两种情形能让指纹作证：
    #      ① 两边算法都写明且相同 → 指纹不同就说「换了提示词」（硬结论）；
    #      ② 指纹值**恰好相同** → 算不出不同值，就不可能换了提示词（同口径）。
    #    其余（缺字段 + 值不同）只能说「无法判定」，不判不可比。
    算甲 = 数据甲.get("指纹算法")
    算乙 = 数据乙.get("指纹算法")
    指甲 = 数据甲.get("提示词指纹") or ""
    指乙 = 数据乙.get("提示词指纹") or ""
    同算法 = bool(算甲) and bool(算乙) and 算甲 == 算乙
    同值 = bool(指甲) and 指甲 == 指乙
    if 同算法 and not 同值:
        # 🔴 只比**提示词**。规则版本另判（见下）——
        #    2026-10-17 之前指纹里混了规则版本，于是「改了规则」会被报成
        #    「换了提示词」，而提示词一个字都没动（假警，还会把人引去查提示词）。
        加("🔴 **提示词指纹不同 ⇒ 换了提示词，不是同一口径**："
          "`%s` vs `%s`。数字差异不能归因于被测量。" % (指甲, 指乙))
        可比 = False
    elif not 同算法 and not 同值:
        加("⚠️ **提示词指纹无法作证**（算法 %s → %s，值 `%s` vs `%s`）—— "
            "两份产物要么算法不同、要么旧产物没记算法，指纹不能互相证明口径；"
            "本次不因此判不可比，改用「同题集重跑逐题比」来证明。"
          % (算甲 or "未记录", 算乙 or "未记录", 指甲 or "-", 指乙 or "-"))
    # 规则版本不同**不算不可比**：提示词一样、只改了规则，差异**可归因于规则**。
    # 但它必须说出来 —— 否则「同样的提示词为什么数字变了」会变成悬案。
    版甲 = 数据甲.get("解析规则版本")
    版乙 = 数据乙.get("解析规则版本")
    if 版甲 and 版乙 and 版甲 != 版乙:
        加("⚠️ **解析规则版本不同**（`%s` → `%s`）—— 提示词是同一份，"
            "差异可归因于解析规则（`校验归一` / 拒答判定），不可归因于模型。" % (版甲, 版乙))
    缺甲 = sorted(set(表甲) - set(表乙))
    缺乙 = sorted(set(表乙) - set(表甲))
    if 缺甲 or 缺乙:
        加("🔴 **题号集合不同** → 只出现在甲：%s；只出现在乙：%s"
          % (缺甲 or "无", 缺乙 or "无"))
        可比 = False

    if not 可比:
        加()
        if not 参数.强制逐题:
            加("结论：**不可比，已中止**（不输出「差异率」以免被当成可解释的数字）。")
            with open(报告路径, "w", encoding="utf-8") as 句柄:
                句柄.write("\n".join(行) + "\n")
            print("\n报告：%s" % 报告路径)
            sys.exit(3)
        # 🔴 `--强制逐题`：口径不可比，但**仍然想看哪几题变了**。
        #    这是改提示词/改规则后的**归因审计**用途 —— 不是拿来报「差异率」的，
        #    所以结论段照样钉死「不可比」，只是把逐题差异列出来供人工核对
        #    「变化是否只落在我预期的那些题上」。
        加("⚠️ `--强制逐题`：仍列出逐题差异，但**口径不可比**，"
            "差异率不作为可解释指标，只用于逐条归因。")

    字段 = ["意图", "结果"] if 参数.只比意图 else (["意图"] + 比字段)

    # ---- 逐题比 ----
    差异 = []
    共同 = [k for k in 表甲 if k in 表乙]
    for 编号 in sorted(共同, key=lambda x: (len(x), x)):
        甲, 乙 = 表甲[编号], 表乙[编号]
        for 字段名 in 字段:
            左, 右 = 规范化(甲.get(字段名)), 规范化(乙.get(字段名))
            if 左 != 右:
                差异.append({"编号": 编号, "字段": 字段名, "甲": 左, "乙": 右,
                             "问题": 甲.get("问题", "")})
                break  # 一题记一次，避免同一题刷屏

    加("## 结论")
    加()
    if not 差异:
        加("✅ **%d 题逐题一致**（比对字段：%s）—— 该配置下输出**可复现**。"
          % (len(共同), " / ".join(字段)))
    else:
        # 🔴 差异**不等于**「不可复现」（2026-10-17）：两轮之间改了解析规则，
        #    差异是**预期的**。把它一律写成「不可复现」，会让人以为要查模型 / 采样参数，
        #    而实际上要查的是「每一条差异能不能被那条规则解释」。
        #    规则版本相同还出现差异，才是真不可复现。
        规则变了 = bool(版甲) and bool(版乙) and 版甲 != 版乙
        if 规则变了:
            加("⚠️ **%d / %d 题不一致**（比对字段：%s）—— 两轮**解析规则版本不同**，"
              "差异**须逐条归因于规则**；归因完成前不判「不可复现」。"
              % (len(差异), len(共同), " / ".join(字段)))
            加()
            加("> 归因方法：把差异逐条对到 `解析规则版本` 里新增的那条规则上。"
              "对不上的那一条才是真复现性问题。")
        else:
            加("🔴 **%d / %d 题不一致**（比对字段：%s）—— 规则版本相同，"
              "输出**不可复现**。" % (len(差异), len(共同), " / ".join(字段)))
        加()
        加("### 第一处差异（完整现场，不截断）")
        加()
        首 = 差异[0]
        加("- 题号：`%s` —— %s" % (首["编号"], 首["问题"]))
        加("- 字段：`%s`" % 首["字段"])
        加()
        加("```")
        加("甲：%s" % 首["甲"])
        加("---")
        加("乙：%s" % 首["乙"])
        加("```")
        加()
        加("### 全部差异清单")
        加()
        加("| 题号 | 字段 | 问题 |")
        加("|---|---|---|")
        for 项 in 差异:
            加("| %s | %s | %s |" % (项["编号"], 项["字段"], 项["问题"]))

    with open(报告路径, "w", encoding="utf-8") as 句柄:
        句柄.write("\n".join(行) + "\n")
    print("\n报告：%s" % 报告路径)
    sys.exit(0 if not 差异 else 1)


if __name__ == "__main__":
    main()
