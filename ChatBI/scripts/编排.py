    参.add_argument("--强制链路", choices=list(链路), help="跳过路由（调试用）")
    参.add_argument("--最大步", type=int, default=最大步数)
    参.add_argument("--角色", help="发起人角色（%s）；缺省 = 内部直调，不检查权限"
                                 % "、".join(权限.角色表))
    参.add_argument("--只看路由", action="store_true", help="只打印路由判定，不调用链路")
    参.add_argument("--清单", action="store_true", help="打印三条链路与路由词表")
    参.add_argument("--json", action="store_true", help="输出完整 JSON")
    参 = 参.parse_args()

    if 参.清单:
        定义 = 定义对象()
        print("三条链路：")
        print("  · 知识问答（RAG 8092）    —— 制度怎么规定的")
        print("  · 数据问数（ChatBI 8095） —— 数字是多少")
        print("  · 动作执行（本地）        —— 帮我出一份…")
        print("\n动作词（%d）：%s" % (len(动作动词), "、".join(动作动词)))
        print("单据名（%d）：%s" % (len(动作名词), "、".join(动作名词)))
        print("制度词（%d）：%s" % (len(制度词), "、".join(制度词)))
        print("数据词：%d 个（含表名/指标/维度/别名，由定义自动收集）"
              % len(拒答.库内词表(定义)))
        print("\n可执行动作：")
        for x in 动作.动作清单():
            print("  · %s —— %s" % (x["动作"], x["用途"]))
        print("\n角色白名单（HTTP 默认角色：%s）：" % 权限.默认角色)
        for x in 权限.角色清单():
            print("  · %s —— %s" % (x["角色"], x["说明"]))
            print("      允许：%s" % "、".join(x["动作"]))
