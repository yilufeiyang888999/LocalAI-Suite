# 🔴 4 步，不是 3 —— 最坏路径是「查数据 → 依据不切题退回 → 换问法重查 → 生成」，
#    正好 4 步。设成 3 的后果（实测）：「帮我起草一份补货申请」在真实链路里
#    走到第 3 步就把预算用光了，**最后什么都没交给用户** ——
#    护栏本身没错，但它把任务挤死了。预算要按最坏路径算，不按典型路径算。
最大步数 = 4

_react提示 = """你是制造业经营分析助手，正在执行一个「动作」任务。你可以使用下面的工具。

【可用工具】
- 查数据：查供应链与生产数据库，返回结果表格。
  参数 {"问题": "一句能直接查数据库的话"}
  ⚠️ 要把用户的**动作型问句改写成查询型问句**：
     用户说「给东莞精诚出一份质量整改通知」
     → 你应先调 {"动作":"查数据","参数":{"问题":"东莞精诚的来料不良率"}}
%s

🔴 **取数是否切题，直接决定单据有没有价值。** 只有「总数 / 记录数」这类结果
   是**不合格的依据** —— 它无法支撑任何处置动作。每类单据该查什么，上面已给出示例。

【硬规则】
1. **生成任何单据之前必须先调用「查数据」** —— 单据里的数字要与查询结果一致，
   不许凭印象写。这一步由你决定查什么，所以要把问句改写准确。
2. 拿到数据后，再调用生成类工具，把对象名（供应商 / 物料）填进参数。
3. 最多 %d 步。已经能完成时，直接给「最终答案」。

【输出格式】只输出一个 JSON，不要解释：
{"思考":"...", "动作":"工具名", "参数":{...}}
或（任务已完成时）
{"思考":"...", "最终答案":"一句话说明做了什么"}

【已完成的过程】
%s

【用户问题】%s
"""


def _工具说明():
    """ReAct 提示词里的「可用工具」段落 —— **从动作表生成，不手抄**。

    🔴 为什么必须生成（实测动机）：首版把工具说明手写在提示词里，而
       「取数应查什么」只写在代码注释里。结果「帮我起草一份补货申请」时，
       模型不知道补货申请该查「缺料清单」，改写成了「需要补货的物料信息」→
       查回来一个「库存记录数 = 67」。**单据照样生成了、数字也是真的，
       但依据完全不切题** —— 这类错不报错、也不违反任何判据。
       把「取数示例」放进动作表（单一事实来源）后，新增动作会自动带上说明。
    """
    行 = []
    for 名, 规 in 动作.动作表.items():
        参 = "、".join('"%s": "%s"' % (k, v) for k, v in (规.get("参数") or {}).items())
        行.append("- %s：参数 {%s}" % (名, 参))
        if 规.get("取数示例"):
            行.append("  取数应查：%s" % 规["取数示例"])
    return "\n".join(行)


def _观察摘要(观, 最多行=3):
    """把一次工具观察压成短文本 —— 提示词里的历史越长，模型越容易跑偏。"""
    if 观 is None:
        return "（无）"
    if isinstance(观, str):
        return 观[:300]
    if isinstance(观, dict):
        if 观.get("错误"):
            return "错误：%s" % 观["错误"]
        if 观.get("动作"):
            return "%s → %s" % (观.get("摘要"), 观.get("文件名") or "")
        类型 = 观.get("类型")
        if 类型 == "SQL":
            列 = 观.get("列") or []
            行 = 观.get("行") or []
            头 = " / ".join(str(x) for x in 列)
            体 = " ； ".join(" , ".join(str(c) for c in r) for r in 行[:最多行])
            return ("查询成功（%d 行）：%s ‖ %s%s"
                    % (观.get("行数", len(行)), 头, 体,
                       " …" if len(行) > 最多行 else ""))
        if 类型 in ("澄清", "拒答", "元问题", "拒绝"):
            return "查询未取到数据（%s）：%s" % (类型, 观.get("澄清") or 观.get("拒答") or "")
        return json.dumps(观, ensure_ascii=False)[:300]
    return str(观)[:300]


def 依据切题(观, 动作名):
    """依据是否**能支撑这个动作**。返回 (是否切题, 说明)。

    🔴 这条护栏的动机（实测，一个「不报错」的坑）：
       「帮我起草一份补货申请」被模型改写成查「需要补货的物料信息」→
       下游返回 `{"基础查询":"计数","目标":"物料"}` → **列只有一个「物料数」，值 30**。
       单据照样生成了、数字也是真的，但依据完全无法支撑处置 ——
       **这类错不报错、也不违反任何已有判据**（缺参数会报错、越界会报错，这个不会）。

       （下游为什么给计数：生成端提示缓存把同一提示词的输出翻到了另一个分支，
         见包 4 的发现。但**编排层不该假设下游永远正确** —— 这正是「依据切题」
         该由编排层兜的原因：下游的不确定性，在编排层留一道确定性检查。）

    🔴 判据为什么用「下游的意图」而不是「猜列名」（第一版在这里判错过）：
       第一版打算匹配列名里有没有「物料名称 / 物料编码」这类词，
       结果 `列 = ["物料数"]` 里**含「物料」子串** → 被误判成切题（自检当场抓出来）。
       而下游应答里本来就有 `意图` = `{"基础查询":"计数","目标":"物料"}` ——
       **它已经明说了这是什么查询**，照它判比猜列名精确得多。
       （与「唯一事实来源」同一条纪律：信息已经在了，不要再造一个近似判据。）

    只判表格结果；非表格（澄清 / 拒答 / 元问题）不在这里判 —— 那是别的护栏的事。
    """
    规 = 动作.动作表.get(动作名) or {}
    if not 规.get("要明细"):
        return True, ""                                     # 该动作只要一个值，不挑
    if not isinstance(观, dict) or 观.get("类型") != "SQL":
        return True, ""
    意图 = 观.get("意图") or {}
    基础 = str(意图.get("基础查询") or "")
    行数 = int(观.get("行数") if 观.get("行数") is not None else len(观.get("行") or []))
    列 = [str(x) for x in (观.get("列") or [])]
    if 基础 in ("计数", "枚举"):
        return False, ("下游把问题理解成了「%s」查询（目标「%s」）—— "
                       "单据要的是**明细清单**，不是总数"
                       % (基础, 意图.get("目标") or ""))
    if 行数 <= 1 and len(列) <= 1:
        return False, ("依据只有一个值（列「%s」）—— 单据要的是明细清单，"
                       "它支撑不了任何处置" % ("、".join(列) or "空"))
    return True, ""


def _轨迹文本(步骤):
    if not 步骤:
        return "（还没有任何动作）"
    行 = []
    for s in 步骤:
        行.append("第%d步 动作=%s 参数=%s" % (s["步"], s["动作"],
                                            json.dumps(s.get("参数") or {}, ensure_ascii=False)))
        行.append("      观察：%s" % s.get("观察"))
    return "\n".join(行)


def 执行动作链路(问题, 定义=None, 最大步=None, 调=意图解析.调模型, 角色=None):
    """手写 ReAct：Thought → Action → Observation，最多 N 步。

    返回 {"步骤": [...], "产物": {...} 或 None, "完成": bool,
          "依据不切题": bool, "被拒": bool, "结束原因": str}

    `角色` 透传给 `动作.调用` 做权限判定；None = 内部直调（不检查权限）。
    """
    步上限 = 最大步 or 最大步数
    步骤 = []
    观察 = None
    结束原因 = "达到步数上限"
    产物 = None
    不切题次数 = 0

    # 🔴 容忍额度（2026-10-18）：模型偶发一次坏输出，不该判成任务失败。
    #    两种坏形态原来各走一个极端 ——
    #      · 解析失败：**一次就 break**，4 步里只用了 1 步就收工；
    #      · 未知动作：**一次都不 break**，注释写「记进轨迹并结束」，实际继续跑，
    #        结束原因被后续覆盖 ⇒ 最后报「达到步数上限」，看起来像「模型想太久」，
    #        而真实原因是「它根本不知道该调哪个工具」。
    #    额度 = 2：第一次把**纠正**喂回去（含可选工具名，否则模型无从改），
    #    连续第二次才收 —— 且结束原因按坏态**分别命名**，三种坏态不许同形。
    #    🔴 为什么不直接 break：会把「偶发不稳」变成「完全不可用」，
    #    这是 7B 在 4 步预算下最不能承受的。
    无效额度 = 2
    连续无效 = 0
    可选动作 = "、".join(["查数据"] + list(动作.动作表))

    for 步 in range(1, 步上限 + 1):
        提示 = _react提示 % (_工具说明(), 步上限, _轨迹文本(步骤), 问题)
        try:
            文本, 用时, _ = 调(提示, 最多token=400)
        except Exception as 错:                              # noqa: BLE001
            结束原因 = "模型不可达：%s" % type(错).__name__
            break
        对 = 意图解析.抽JSON(文本) or {}

        if not 对:
            连续无效 += 1
            步骤.append({"步": 步, "动作": "（解析失败）", "参数": {}, "思考": "",
                        "观察": "模型输出不是合法 JSON：%s —— 请只输出**一个** JSON 对象，"
                                "要么带「动作」，要么带「最终答案」。" % 文本.strip()[:120],
                        "模型原文": 文本})
            if 连续无效 >= 无效额度:
                结束原因 = "连续 %d 次输出不是合法 JSON" % 无效额度
                break
            continue

        if 对.get("最终答案") is not None and not 对.get("动作"):
            连续无效 = 0
            步骤.append({"步": 步, "动作": "最终答案", "参数": {},
                        "思考": str(对.get("思考") or ""),
                        "观察": str(对.get("最终答案")), "模型原文": 文本})
            结束原因 = "模型给出最终答案"
            break

        动作名 = str(对.get("动作") or "").strip()
        参数 = 对.get("参数") if isinstance(对.get("参数"), dict) else {}
        思考 = str(对.get("思考") or "")

        # ---- 查数据 ----
        if 动作名 in ("查数据", "查询", "查数据库"):
            连续无效 = 0            # 有效动作 ⇒ 断掉「连续」计数（连续的定义就是连续）
            查问 = str(参数.get("问题") or "").strip() or 问题
            观察 = 调问数(查问)
            步骤.append({"步": 步, "动作": "查数据", "参数": {"问题": 查问},
                        "思考": 思考, "观察": _观察摘要(观察), "模型原文": 文本})
            continue

        # ---- 生成类动作 ----
        if 动作名 in 动作.动作表:
            连续无效 = 0            # 选对了工具 ⇒ 断掉「连续」计数
            # 🔴 确定性护栏一：生成类动作都声明了「缺依据可生成=False」。
            #    模型跳过「查数据」直接生成时，**编排层补这一步** ——
            #    不能让单据在没有依据的情况下产出（那样数字就是模型编的）。
            if 观察 is None and not 动作.动作表[动作名].get("缺依据可生成"):
                查问 = str(参数.get("查询") or "").strip() or 问题
                观 = 调问数(查问)
                步骤.append({"步": 步, "动作": "查数据", "参数": {"问题": 查问},
                            "思考": "（编排层补的一步：%s 需要依据，模型跳过了取数）"
                                    % 动作名,
                            "观察": _观察摘要(观), "编排层补步": True})
                观察 = 观

            # 🔴 确定性护栏二：依据切题检查。不切题先把结论喂回去让模型换问法重查。
            #    只喂回**一次** —— 无限喂回会让这个任务永远完不成（用户什么都拿不到）。
            #    第二次仍不切题就带着它生成，但轨迹里必须留下记录。
            切题 = None                 # 传给审计：这张单据的依据到底支不支撑它
            警告 = ""
            if 观察 is not None:
                切题, 为什么 = 依据切题(观察, 动作名)
                if not 切题 and 不切题次数 == 0:
                    不切题次数 += 1
                    步骤.append({"步": 步, "动作": "（依据不切题，退回重查）", "参数": 参数,
                                "思考": 思考,
                                "观察": "⚠️ %s —— 请换一个问法重新查（要的是明细，不是计数）"
                                        % 为什么,
                                "退回重查": True, "模型原文": 文本})
                    观察 = None
                    continue
                if not 切题:
                    # ⚠️ 这里**不单独 append 一步**：那会和下面的「生成」用同一个步号，
                    #    轨迹里出现两个「第 4 步」（实测）。同一步的两件事，合成一条记录。
                    #    判据要能区分「退回重查」与「仍不切题」→ 用**不同的键**，不靠步号。
                    警告 = "⚠️ 依据仍不切题（%s）—— 带着它生成。\n" % 为什么

            # 🔴 权限与审计都在 `动作.调用` 这一个关口上（包 6）——
            #    编排层只传上下文（角色 / 依据切题），**不自己判权限**。
            #    多一处判断 = 多一处口径分叉（§9.5「唯一事实来源」）。
            产物 = 动作.调用(动作名, 角色=角色, 依据切题=切题,
                            依据=观察, 问题=问题, **参数)

            if 产物.get("被拒"):
                # 🔴 越权 = 硬拒：不落盘、不「换个动作再试试」。
                #    让模型绕过去换个动作是错的 —— 它没权限是**人的权限问题**，
                #    不是模型的问题；模型绕开一次，权限就等于不存在。
                步骤.append({"步": 步, "动作": 动作名, "参数": 参数, "思考": 思考,
                            "观察": "🚫 权限不足：%s" % 产物.get("拒绝理由"),
                            "模型原文": 文本, "被拒": True})
                结束原因 = "权限不足"
                break

            步骤.append({"步": 步, "动作": 动作名, "参数": 参数, "思考": 思考,
                        "观察": 警告 + _观察摘要(产物), "模型原文": 文本,
                        "不切题": 不切题次数 > 0})
            if 产物.get("错误"):
                # 参数没填对（如缺供应商）→ 把错误当观察喂回去，让模型下一步改。
                结束原因 = "动作缺参数：%s" % 产物["错误"]
                观察 = 产物
                continue
            结束原因 = "动作完成"
            break

        # ---- 空动作名 / 未知动作 ----
        # 🔴 两者都必须**把可选工具喂回去**：原来只说「没有这个工具：X」，
        #    模型不知道有哪些工具可选 ⇒ 下一步还是瞎猜（实测：连续两步吐空动作名，
        #    然后开始反复查数据，4 步用光，用户拿到「未生成任何单据」）。
        连续无效 += 1
        if not 动作名:
            纠正 = ("动作名是空的。请二选一：给「动作」（从下面挑一个），"
                    "或给「最终答案」（说明为什么做不了）。可选动作：%s" % 可选动作)
            本步类型 = "没给出动作名"
        else:
            纠正 = ("没有这个工具：%s。这次不算数 —— 可选动作只有：%s" % (动作名, 可选动作))
            本步类型 = "选了不存在的工具"
        步骤.append({"步": 步, "动作": 动作名 or "（空）", "参数": 参数, "思考": 思考,
                    "观察": 纠正, "模型原文": 文本, "无效": True})
        if 连续无效 >= 无效额度:
            结束原因 = "连续 %d 次%s" % (无效额度, 本步类型)
            break
        continue

    return {"步骤": 步骤, "产物": 产物,
            "完成": bool(产物 and not 产物.get("错误")),
            "依据不切题": 不切题次数 > 0,
            "被拒": any(s.get("被拒") for s in 步骤),
            "结束原因": 结束原因}


# ============================ 人读答复 ============================

def _表文本(列, 行, 最多=15):
    if not 列:
        return ""
    宽 = []
    for i, c in enumerate(列):
        最 = len(str(c))
        for r in 行[:最多]:
            最 = max(最, len(str(r[i])) if i < len(r) else 0)
        宽.append(min(最, 24))
    头 = " | ".join(str(c).ljust(宽[i]) for i, c in enumerate(列))
    线 = "-+-".join("-" * 宽[i] for i in range(len(列)))
    体 = []
    for r in 行[:最多]:
        体.append(" | ".join(str(r[i] if i < len(r) else "").ljust(宽[i])
                            for i in range(len(列))))
    if len(行) > 最多:
        体.append("…（共 %d 行）" % len(行))
    return "\n".join([头, 线] + 体)


def 答复文本(问题, 链路名, 底层, 产物=None, 结束原因=None):
    """把底层链路的原始应答，翻成**同一张脸**（用户不该看见三条链路的差异）。"""
    if 链路名 == "知识问答":
        答 = str(底层.get("answer") or "").strip()
        引 = 底层.get("citations") or []
        尾 = ""
        if 底层.get("refused"):
            尾 = "\n\n（知识库判定资料不足，未作答；若要查数字请直接问指标，如「上月不良率」。）"
        elif 引:
            尾 = "\n\n依据：" + "；".join(
                "%s《%s》%s" % (c.get("rank"), c.get("doc_no"), c.get("section"))
                for c in 引[:3])
        return (答 or "（知识库未返回内容）") + 尾

    if 链路名 == "数据问数":
        类型 = 底层.get("类型")
        if 类型 == "SQL":
            表 = _表文本(底层.get("列") or [], 底层.get("行") or [])
            块 = []
            if 底层.get("口径"):
                块.append("口径：%s" % 底层["口径"])
            if 底层.get("指标"):
                块.append("指标：%s（时间：%s）" % (底层["指标"], 底层.get("时间")))
            块.append("")
            块.append(表 if 表 else "（查询返回 0 行）")
            for x in (底层.get("说明") or []):
                块.append("\n⚠️ %s" % x)
            return "\n".join(块)
        if 类型 == "澄清":
            return "需要补充信息才能查：%s" % 底层.get("澄清")
        if 类型 == "拒答":
            return "%s\n\n本库能答的示例：%s" % (
                底层.get("拒答"), "；".join((底层.get("可答示例") or [])[:3]))
        if 类型 == "元问题":
            return 底层.get("回答") or ""
        return "问数服务返回：%s" % json.dumps(底层, ensure_ascii=False)[:200]

    if 链路名 == "动作执行":
        if 产物 and 产物.get("被拒"):
            # 🔴 越权必须与「参数没填对」区分开：前者要让**换人**，后者要**补参数**。
            #    统一说成「没能生成」，用户会去改问题 —— 而问题根本不在那里。
            return ("🚫 **权限不足，未生成任何单据。**\n%s\n\n"
                    "（换一个有此权限的角色再试，或改走只读链路先查数据。）"
                    % 产物.get("拒绝理由"))
        if 产物 and not 产物.get("错误"):
            头 = "✅ 已生成：%s\n文件：%s\n\n" % (产物.get("摘要"), 产物.get("路径"))
            return 头 + "----- 单据预览 -----\n" + str(产物.get("正文") or "")[:1200]
        if 产物 and 产物.get("错误"):
            return "⚠️ 没能生成单据：%s" % 产物["错误"]
        # 🔴 「没生成」必须说成「没生成」，不能只丢一句「见轨迹」。
        #    动作链路的失败形态里，最危险的一种是**模型只查了数就收工**：
        #    轨迹里有数据、回答里没有单据 —— 用户很容易把轨迹里那行数字当成结果。
        #    所以这里要显式切开两件事：「这是查询结果」≠「这是单据」。
        return ("⚠️ **未生成任何单据。**\n"
                "这个问题被判定为「动作执行」，但执行过程没有产出单据 —— "
                "卡在哪一步见下方执行轨迹。\n"
                "卡住的原因：%s\n"
                "（轨迹里的数据只是**查询结果，不是单据**；如果你本来只想查数，"
                "请把问法改成「…是多少」这类查询句。）"
                % (结束原因 or "未记录（本次没有走到结束判定）"))

    return json.dumps(底层, ensure_ascii=False)[:300]


# ============================ 主入口 ============================

def 执行(问题, 定义=None, 强制链路=None, 最大步=None, 调=意图解析.调模型, 角色=None):
    """编排层唯一入口。返回统一应答 dict。

    `角色` = 发起人的角色（包 6 权限）。None = 内部直调（不检查权限，
    且审计里会记成「（内部）」—— 是显式边界，不是静默放行）。
    """
    定义 = 定义 or 定义对象()
    起 = time.time()
    路 = ({"链路": 强制链路, "依据": "强制", "命中": {}, "理由": "调用方指定",
           "模型用时": None}
          if 强制链路 else 路由(问题, 定义))
    链路名 = 路["链路"]
    底层 = None
    产物 = None
    步骤 = []
    动作结束原因 = None          # 只有动作链路有；「卡在哪」必须能传到回答里
    不切题 = False
    被拒 = False
    错 = None
    try:
        if 链路名 == "知识问答":
            底层 = 调RAG(问题)
        elif 链路名 == "数据问数":
            底层 = 调问数(问题)
        else:
            try:
                执 = 执行动作链路(问题, 定义, 最大步=最大步, 调=调, 角色=角色)
                步骤 = 执["步骤"]
                产物 = 执["产物"]
                动作结束原因 = 执.get("结束原因")
                不切题 = bool(执.get("依据不切题"))
                被拒 = bool(执.get("被拒"))
                # 动作链路有「取数」这一步 —— 把它当作底层依据留档
                for s in 步骤:
                    if s["动作"] == "查数据" and 底层 is None:
                        底层 = {"类型": "动作取数", "问题": s["参数"].get("问题"),
                                "观察": s.get("观察")}
            except Exception as 错2:                          # noqa: BLE001
                错 = "%s: %s" % (type(错2).__name__, 错2)
    except urllib.error.URLError as 错3:
        错 = "依赖服务不可达：%s" % 错3
    except Exception as 错4:                                 # noqa: BLE001
        错 = "%s: %s" % (type(错4).__name__, 错4)

    应答 = {
        "问题": 问题,
        "类型": 链路名,
        "路由": 路,
        "步骤": 步骤,
        "依据不切题": 不切题,
        # 包 6：权限结果。**单独一块**，因为「被拒」与「参数没填对」「依据不切题」
        # 是三种完全不同的事故，混在一句「失败」里就再也分不清该找谁。
        "权限": {"角色": 角色, "被拒": 被拒,
                 "拒绝理由": (产物 or {}).get("拒绝理由")},
        "被拒": 被拒,
        "产物": ({"文件名": 产物.get("文件名"), "路径": 产物.get("路径"),
                  "摘要": 产物.get("摘要"), "动作": 产物.get("动作")}
                 if 产物 and not 产物.get("错误") else None),
        "依据": 底层,
        # 动作链路的「卡在哪一步」：用完步数 / 模型不会挑工具 / 连续坏格式 …
        # 不传出来，「模型不会挑工具」与「预算不够」在界面上完全同形。
        "结束原因": 动作结束原因,
        "错误": 错,
        "耗时": {"合计": round(time.time() - 起, 2)},
        # 🔴 动作嫌疑与改判**单独成块**（与「被拒」「依据不切题」同理）：
        #    它们描述的是「这次链路是猜的」，这是与「答对/答错」正交的一件事。
        #    总是带上这两个键（值为 False / None 也要有）——
        #    缺字段与「判过且否掉」必须可区分（§9.5：缺字段不能当成某个默认值）。
        "疑似动作": 路.get("动作嫌疑") or {"是": False, "证据": [], "否因": ["强制链路未判"]},
        "改判": 路.get("改判"),
    }
    应答["回答"] = (("❌ 处理失败：%s" % 错) if 错
                    else 答复文本(问题, 链路名, 底层 or {}, 产物, 动作结束原因))
    if 路.get("改判"):
        # 🔴 改判必须自己说出来。用户原话里没有「出一份」这类动词，
        #    我们替他猜成了动作 —— 猜就要说明，不能让他以为「我说得很清楚」。
        改 = 路["改判"]
        应答["回答"] = (
            "ℹ️ 这句没有「出一份 / 起草」这类明确说法，但提到了动作类词汇「%s」，"
            "已按**动作执行**处理（原判「%s」只会返回数据、不生成单据）。\n"
            "（如果你只想查数，请改用「…是多少」的问法。）\n\n"
            % ("、".join((路.get("动作嫌疑") or {}).get("证据") or []),
               改.get("原链路"))
            + 应答["回答"])
    if 不切题 and 产物:
        # 🔴 依据不切题时**必须让用户看见** —— 单据本身长得完全正常，
        #    异常只存在于「这张单据的依据其实不支撑它」这件事里。
        #    加在答复最前面（不是附注），因为后果是「拿着它去发通知」。
        应答["回答"] = (
            "⚠️ **本单据的依据可能不切题**（下游把查询理解成了非明细查询，"
            "已尝试换问法重查一次仍未成功）—— 请核对下方依据后再使用。\n\n"
            + 应答["回答"])
    return 应答


