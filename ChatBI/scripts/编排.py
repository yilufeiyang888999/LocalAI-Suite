# ============================ 路由 ============================

def 动作嫌疑(问):
    """用户是不是在要「一份东西」，却没说动作动词（词表盖不住的说法）。

    返回 `{"是": bool, "证据": [...], "否因": [...]}`。
    🔴 `证据` / `否因` 必须都留下：只有这样才能区分
       「没有动作类词汇」（证据为空）与「有词汇但被闸否掉」（否因非空）——
       两者的下一步完全不同：前者该交模型，后者是**判过的结论**。
    """
    if not 问:
        return {"是": False, "证据": [], "否因": ["空问句"]}
    证据 = [w for w in 动作名词 if w in 问]
    if not 证据:
        证据 = [w for w in 处置动词 if w in 问]
    if not 证据:
        return {"是": False, "证据": [], "否因": ["无动作类词汇"]}

    # 闸一：问数信号 → 用户要的是数，不是单据
    数 = [w for w in 问数信号 if w in 问]
    if 数:
        return {"是": False, "证据": 证据, "否因": ["问数信号：%s" % "、".join(数)]}
    # 闸二：制度词 → 问的是规定（规则 3 已先行，这里是防御）。
    #       判断题集 R06「整改通知的流程是什么」正是靠这一条留在知识链路。
    制 = [w for w in 制度词 if w in 问]
    if 制:
        return {"是": False, "证据": 证据, "否因": ["制度词：%s" % "、".join(制)]}
    return {"是": True, "证据": 证据, "否因": []}


def 路由(问题, 定义=None):
    """问题 → {"链路", "依据", "命中", "理由", "动作嫌疑"[, "改判"]}。

    `依据` 取值：`确定性` / `确定性-动作嫌疑`（改判）/ `模型` / `默认（…）`。
    **必须能区分** —— 否则「路由对了」和「路由根本没判、随便落了一条」在日志里长得一样；
    「改判过」和「规则直接判对」也必须能区分，否则改判这件事会变回静默。
    """
    定义 = 定义 or 定义对象()
    问 = str(问题 or "").strip()
    return _动作嫌疑校验(问, _按词表路由(问, 定义))


def _按词表路由(问, 定义):
    """七条规则。**不含嫌疑改判** —— 改判统一在 `_动作嫌疑校验` 里做，
    否则每加一条规则就要记得「这里也要改判」，漏一处就静默（本项目的经典失效）。"""
    命中 = {"动作动词": [], "动作名词": [], "制度词": [], "数据词": [], "时间词": [],
            "元问题短语": None}
    命中["动作动词"] = [w for w in 动作动词 if w in 问]
    命中["动作名词"] = [w for w in 动作名词 if w in 问]
    命中["制度词"] = [w for w in 制度词 if w in 问]
    命中["时间词"] = [w for w in 时间词 if w in 问]
    命中["元问题短语"] = 拒答.元问题命中(定义, 问)
    命中["数据词"] = 拒答.库内命中(定义, 问)

    # ---- 规则 1：动作动词 → 动作执行（最高优先级）----
    # 为什么最高：「给东莞精诚出一份整改通知」里同时含「东莞精诚」（数据词）
    # 与「出一份」（动作动词）。动作是**强意图** —— 它自带「做点什么」，
    # 而数据词只是对象。把对象当意图，就会答成「东莞精诚的不良率是 7.66%」，
    # 用户要的通知没生成，还看不出错（数字是对的）。
    if 命中["动作动词"]:
        return {"链路": "动作执行", "依据": "确定性",
                "命中": 命中, "模型用时": None,
                "理由": "命中动作动词：%s" % "、".join(命中["动作动词"])}

    # ---- 规则 2：动作名词 + 祈使线索 → 动作执行（省略动词的口语说法）----
    祈 = [w for w in 祈使线索 if w in 问]
    if 命中["动作名词"] and 祈 and not 命中["制度词"]:
        return {"链路": "动作执行", "依据": "确定性",
                "命中": 命中, "模型用时": None,
                "理由": "命中单据名「%s」+ 祈使「%s」"
                        % ("、".join(命中["动作名词"]), "、".join(祈))}

    # ---- 规则 3：制度词 → 知识问答（优先于数据词）----
    # 「采购流程怎么规定的」同时含「采购」（数据词）与「流程」（制度词）。
    # 问的是流程 → 知识。反过来的代价是：送进 SQL 链路拿真实表硬答，
    # 而「制度怎么规定的」根本没有对应的列 —— 只能编。
    if 命中["制度词"]:
        return {"链路": "知识问答", "依据": "确定性",
                "命中": 命中, "模型用时": None,
                "理由": "命中制度词：%s" % "、".join(命中["制度词"])}

    # ---- 规则 4：时间限定词 → 数据问数 ----
    # 「这个月怎么样？」「最近有什么异常？」—— 有时间范围、没有具体指标。
    # 制度类问题极少带时间限定（且带「制度」的已被规则 3 拦下）。
    if 命中["时间词"]:
        return {"链路": "数据问数", "依据": "确定性",
                "命中": 命中, "模型用时": None,
                "理由": "命中时间限定词：%s" % "、".join(命中["时间词"])}

    # ---- 规则 5：元问题短语 → 数据问数 ----
    # 「数据准不准？」「这个库有多少条数据」—— 这些短语只可能在**数据链路**里被回答
    # （ChatBI 有一层确定性前置判定，0 秒直接答元信息，根本不调模型）。
    # 🔴 与包 3 的「元问题三条护栏」**不是同一件事**：那三条管的是
    #    「该不该判成元问题」（如「上个月的不良率准吗」含指标名 → 不判元问题）；
    #    这里管的是「去哪个链路」—— 无论判不判元问题，都该去数据链路。
    #    **同一个词表在两处起不同作用，「护栏」不能跨层搬运。**
    元 = 命中["元问题短语"]
    if 元:
        return {"链路": "数据问数", "依据": "确定性", "命中": 命中, "模型用时": None,
                "理由": "命中元问题短语：%s（由 ChatBI 的确定性前置判定直接答）" % 元}

    # ---- 规则 6：数据词 → 数据问数 ----
    if 命中["数据词"]:
        return {"链路": "数据问数", "依据": "确定性",
                "命中": 命中, "模型用时": None,
                "理由": "命中数据词：%s" % "、".join(sorted(命中["数据词"])[:6])}

    # ---- 规则 6.5：动作嫌疑 → 动作执行（不给模型兜底）----
    # 🔴 为什么这一条**必须挡在模型兜底之前**（不是优化，是判据问题）：
    #    「东莞精诚的整改通知」这种句子词表判不出 → 交给模型 → 模型可能判成
    #    「数据问数」，于是用户要的单据变成一个数字。
    #    「要不要做单」这件事**不能交给不可复现的模型决定**：
    #    同一句两次跑出不同链路，用户就永远不知道「为什么这次没做单」。
    #    顺带，把它变成确定性分支后，路由评测才能要求这类题**必过**，
    #    否则一条恒定时好时坏的规则没有判据可言。
    嫌 = 动作嫌疑(问)
    if 嫌["是"]:
        return _改判为动作(命中, 嫌, "数据问数", "默认（规则未命中）",
                           "词表未命中任何动作动词 / 祈使线索，按默认链路会走数据问数")

    # ---- 规则 7：都不命中 → 模型兜底 ----
    return _模型路由(问, 命中)


_路由提示 = """你是意图路由。判断用户这句话该交给哪个助手，**只输出一个 JSON**。

三个助手的职责：
- 知识问答：答「制度 / 流程 / 规定 / 标准怎么写的」——依据是公司制度文档
- 数据问数：答「某个数字是多少」——依据是供应链与生产数据库
- 动作执行：帮用户「生成一份单据 / 导出报表」——例如整改通知、补货申请、异常台账

只输出 JSON，形如 {"链路":"知识问答"}，不要解释。
链路的值只能是：知识问答 / 数据问数 / 动作执行

用户问题：%s
"""


def _模型路由(问题, 命中):
    """规则判不出时才走这里。返回的 `依据` 标成 `模型` —— 让「兜底」可被看见。"""
    try:
        文本, 用时, _ = 意图解析.调模型(_路由提示 % 问题, 最多token=64)
    except Exception as 错:                                  # noqa: BLE001
        return {"链路": "数据问数", "依据": "默认（模型不可达）",
                "命中": 命中, "模型用时": None,
                "理由": "模型不可达（%s），落默认链路数据问数" % type(错).__name__}
    对 = 意图解析.抽JSON(文本) or {}
    选 = str(对.get("链路") or "").strip()
    if 选 not in 链路:
        # 模型给了个不认识的链路 —— 不能把原始串透传给下游（下游只认三个名字）
        选 = "数据问数"
        return {"链路": 选, "依据": "默认（模型输出不可用）",
                "命中": 命中, "模型用时": 用时,
                "理由": "模型原始输出：%s" % 文本.strip()[:60]}
    return {"链路": 选, "依据": "模型", "命中": 命中, "模型用时": 用时,
            "理由": "规则未命中任何词表，交模型判定"}


# 改判依据。单独一个常量 —— 判据与文案都要能引用同一个字面量
# （两处各写一遍，改一处就有一边永远不匹配，且不报错）。
依据_改判 = "确定性-动作嫌疑"


def _改判为动作(命中, 嫌, 原链路, 原依据, 原理由):
    """构造「改判成动作执行」的路由结果。**唯一的一处构造点** ——
    两处各拼一份（规则 6.5 与嫌疑校验）必然会有一天漏改一边，而漏改的那边不报错。"""
    return {"链路": "动作执行", "依据": 依据_改判, "命中": 命中 or {},
            "模型用时": None, "动作嫌疑": 嫌,
            "改判": {"原链路": 原链路, "原依据": 原依据, "原理由": 原理由},
            "理由": ("命中动作类词汇「%s」，但没有动作动词 / 祈使线索 —— "
                     "原判「%s（%s）」只会返回数据、不生成单据；"
                     "疑似动作请求，改判动作执行。原理由：%s"
                     % ("、".join(嫌["证据"]), 原链路, 原依据, 原理由))}


def _动作嫌疑校验(问, 路):
    """给路由结果打上 `动作嫌疑`，并在它落到**只读链路**时改判为动作执行。

    🔴 为什么必须改判，而不是只加一句提示：
       提示能救「看懂了的人」，救不了「看到数字就以为是答案的人」——
       而这条链路的失效形态正是后者：语句里全是正常的词、返回的是一行正常的数。
       用户要的是整改通知，拿到的是「东莞精诚的不良率 7.66%」，他不会觉得有任何异常。

    🔴 为什么改判安全（成本不对称）：
       改判错了 → 动作链路走一遍，产出的是**草稿**（`outbox/` 里的一份 md，
       需要人签字才发出），用户立刻看见「它给我做了个单据」；
       不改判 → 用户以为查到了，单据根本没做，而且他可能拿这个数字去开会。
       宁可多做一份带「草稿」字样的单据，也不能把动作请求变成一个数字。

    🔴 只改判两种情形（其余保留）：
       · 原判「数据问数」—— 正是「静默答另一个问题」的现场；
       · 原判来自**模型兜底** —— 兜底不可复现（同一句两次可能不同），
         不能让它决定「要不要做单」；确定性给出的链路才保留。
       确定性判成「知识问答」的不动：那是制度词判出来的，用户问的是规定
       （`动作嫌疑` 的第二道闸也会把这类句子的嫌疑否掉，两道保持一致）。
    """
    嫌 = 动作嫌疑(问)
    路 = dict(路)
    路["动作嫌疑"] = 嫌
    if not 嫌["是"] or 路.get("链路") == "动作执行":
        return 路
    if 路.get("链路") == "知识问答" and str(路.get("依据") or "") == "确定性":
        return 路
    return _改判为动作(路.get("命中"), 嫌, 路.get("链路"),
                       str(路.get("依据") or ""), str(路.get("理由") or ""))


