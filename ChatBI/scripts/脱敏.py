# -*- coding: utf-8 -*-
"""ChatBI · 视图层脱敏（B-3）—— 敏感列按角色掩码

要解决的问题：`供应商表` 里有评级、`采购订单` 里有金额、`物料` 里有标准单价。
现在这些列**任何人问一句就能看到**。演示库无所谓，但「问数系统直接连生产库」
的第一天，这就是一个必须已经在位的东西。

🔴 三条位置纪律（位置错了，功能看起来一样是好的）

  1. **在服务端做，不在前端做。** 前端脱敏 = 数据已经完整送到浏览器了，
     F12 / 改 JS / 直接 curl 接口都能拿到原值。「界面上看不见」不是脱敏。
  2. **在喂模型之前做。** A-2 的解读会把结果集整段喂给模型写一句话 ——
     如果把原始值喂过去，敏感数据就多了一份流向（而且是流向一个**会把它写进
     回答文本**的地方）。所以顺序是：查到 → 脱敏 → 用户看到的同时、喂给模型的是
     **已经摘掉敏感列的版本**。
  3. **在结果层做，不在 SQL 层做。** 脱敏改的是「显示什么」，不改「算得对不对」：
     把金额列从 SELECT 里去掉，会让结果集少一列（更糟的是聚合口径跟着变）。
     行级权限（B-5）才是改 SQL 的那个 —— 两者不要混。

🔴 掩码方式：`***`，并且**在应答里说明「隐藏了哪几列、什么角色能看」**。
   不说的话，「这列是敏感」与「这列查出来是空的」在界面上长得一模一样，
   而前者是可以去申请权限的，后者是要去查数据的 —— 两种完全不同的下一步。

🔴 角色没传 = 用 `权限.默认角色`（最少权限）。默认放行是最常见的权限事故形态：
   测试期没人传角色，看着一切正常。
"""

import argparse
import json
import os
import sys

本目录 = os.path.dirname(os.path.abspath(__file__))
项目目录 = os.path.dirname(本目录)
if 本目录 not in sys.path:
    sys.path.insert(0, 本目录)

import 权限                                             # noqa: E402

if hasattr(sys.stdout, "reconfigure"):
    try:
        sys.stdout.reconfigure(errors="replace")
    except Exception:                                    # noqa: BLE001
        pass

掩码 = "***"

# ============================ 敏感列（唯一事实来源） ============================
# 🔴 为什么写在**这里**而不是口径定义 YAML 里：
#    YAML 管「数字怎么算」（口径），这里管「给谁看什么」（展示策略）。
#    两件事的变更理由完全不同 —— 加一个敏感列不该触发口径变更影响面（A-5）
#    的评测重跑，改一个口径也不该让脱敏规则跟着动。混在一起就会互相误伤。

敏感列 = {
    "采购单价": {
        "可见角色": ["管理员"],
        "说明": "供应商报价 —— 泄露等于把议价底牌交给对手",
    },
    "标准单价": {
        "可见角色": ["管理员"],
        "说明": "内部核价基准，与采购单价的差就是利润空间",
    },
    "订单金额": {
        "可见角色": ["主管", "管理员"],
        "说明": "单笔金额可反推采购节奏与供应商份额",
    },
    "供应商评级": {
        "可见角色": ["主管", "管理员"],
        "说明": "内部评级外传会影响与供应商的关系",
    },
    # 🔴 这一条是**补上来的**，理由值得记下来：前四列写的都是「采购单价 / 标准单价 /
    #    订单金额 / 供应商评级」—— 业务上确实敏感，但**语义层当前一个都产不出来**
    #    （五个指标的渲染列名只有：供应商 / 物料 / 物料类别 / 月份 / 仓库名称 /
    #     不良率 / 准时率 / 水位百分比 / 达成率 / 采购金额）。
    #    也就是说前四列挂的是一个**永不触发的钩子**：
    #      · 自检里「HTTP 上验脱敏」那条断言**从写下起就不可能通过**（它期望一个
    #        不存在的列被掩码）；
    #      · 而界面上「脱敏生效」这件事**永远演示不出来** —— 看起来像没做。
    #    所以补上「采购金额」：按供应商汇总的采购额能反推份额与议价结构，
    #    业务上确实该限，而且它是**真会出现在结果里的列**。
    #    ⚠️ 教训：敏感列名必须与语义层**实际产出的列名**对得上，
    #       否则配置再正确也只是挂在墙上。
    "采购金额": {
        "可见角色": ["主管", "管理员"],
        "说明": "按供应商汇总的采购额可反推份额与议价结构",
    },
}

关脱敏 = bool(os.environ.get("CHATBI_NO_MASK"))          # 自检 / 排障用


def 是敏感列(列名):
    """列名 → 命中的敏感列名（无则 None）。

    🔴 **只做正向包含**（敏感列名出现在列名里），**绝不做反向**。

    反向（`列名 in 敏感列名`）看着更宽容，实测是**误伤源**：
    短列名会命中所有「以它为前缀的敏感列」——
    `是敏感列("供应商")` 命中「供应商**评级**」（因为「供应商」是它的子串），
    于是**供应商名称整列被掩成 `***`**。实测现场（盲测 v2 T19）：

        「上月哪家供应商不良绿最高」→ 实测 (***, 7.66) ≠ 基准 (东莞精诚五金制品有限公司, 7.66)

    表格照样出、数字照样真，唯一的线索是那一列变成了星号 ——
    而它看起来像「数据没查出来」，不像「被策略藏起来了」。
    反向匹配还带**歧义**：`"单价" in "采购单价"` 与 `"单价" in "标准单价"` 同时成立，
    取第一个 = 用了一组可能不对的「可见角色」（决定谁能看的那份配置）。

    要支持「列名更短」的场景，正确做法是**显式写别名**，不是靠子串猜 ——
    与口径定义里的「实体别名」同一条纪律：**映射要写下来，不要算出来**。
    """
    名 = str(列名 or "").strip()
    if len(名) < 2:
        return None                                      # 单字列名不参与匹配（「价」会误伤）
    for 敏 in 敏感列:
        if 敏 in 名:
            return 敏
    return None


def 可见(敏, 角色):
    规 = 敏感列.get(敏) or {}
    return 角色 in (规.get("可见角色") or [])


def 脱敏(列, 行, 角色=None):
    """给结果集按角色掩码。返回 (列, 行, 隐藏清单, 说明文本 or None)。

    🔴 `角色 is None` = **内部直调**（脚本 / 自检 / 单测），不启用脱敏 ——
       与 `权限.检查` 和 `行级.应用` 是同一条边界。
       这条边界安全的前提是：**HTTP 入口永远解析出角色**（解析不出就 401，
       见 `问数服务.处理器.do_POST` 的 `要身份()`）。所以 None 只可能来自进程内直调。
       ⚠️ 曾经写成 `角色 or 权限.默认角色`，结果是内部直调也被当成「操作员」脱敏 ——
          行级与脱敏对同一个 None 给出两种解释，自检里立刻表现为 3 项失败。

    隐藏清单里每项：{列, 敏感列, 可见角色}
    """
    if 关脱敏 or 角色 is None:
        return list(列 or []), [list(r) for r in (行 or [])], [], None
    列 = list(列 or [])
    行 = [list(r) for r in (行 or [])]

    改到 = []                                            # [(下标, 敏感列名, 可见角色)]
    for i, c in enumerate(列):
        敏 = 是敏感列(c)
        if 敏 and not 可见(敏, 角色):
            改到.append((i, 敏, list((敏感列.get(敏) or {}).get("可见角色") or [])))
    if not 改到:
        return 列, 行, [], None

    for r in 行:
        for i, _敏, _角 in 改到:
            if i < len(r) and r[i] is not None:
                r[i] = 掩码
    隐藏 = [{"列": 列[i], "敏感列": 敏, "可见角色": 角} for i, 敏, 角 in 改到]
    名 = "、".join("「%s」" % x["列"] for x in 隐藏)
    谁 = "、".join(sorted({r for x in 隐藏 for r in x["可见角色"]}))
    说明 = ("已按角色「%s」隐藏敏感列 %s（值显示为 %s）—— 这些列只有 %s 可见。"
            "隐藏发生在服务端、且在送给模型之前，不是界面上的遮挡。"
            % (角色, 名, 掩码, 谁 or "无角色（配置为空）"))
    return 列, 行, 隐藏, 说明


def 摘列(列, 行, 隐藏):
    """把被隐藏的列**整列摘掉**，用于喂模型（A-2 解读）。

    为什么不喂 `***` 让模型自己避开：模型看到星号会去描述它
    （「某列显示为星号」），那句描述本身就暴露了「这里有一列敏感数据」，
    而且会挤掉真正该说的那句话。模型压根不知道有这列，最干净。
    """
    if not 隐藏:
        return list(列 or []), [list(r) for r in (行 or [])]
    去 = set()
    for x in 隐藏:
        try:
            去.add(list(列).index(x["列"]))
        except ValueError:
            pass
    if not 去:
        return list(列 or []), [list(r) for r in (行 or [])]
    新列 = [c for i, c in enumerate(列) if i not in 去]
    新行 = [[v for i, v in enumerate(r) if i not in 去] for r in (行 or [])]
    return 新列, 新行


def 清单():
    """给页面 / /catalog 用（自描述，不手抄到前端）。"""
    return [{"列": k, "可见角色": list(v["可见角色"]), "说明": v["说明"]}
            for k, v in 敏感列.items()]


def 可能列名(定义):
    """语义层**可能产出**的结果列名（用来发现「永不触发的敏感列」）。

    取法（只用载入后的定义，不猜）：指标名 + 度量别名 + 各指标的维度名。
    这三样就是渲染结果的列名来源（维度里若写了 `AS` 别名，载入后已展开），
    所以它是个**偏保守**的集合 —— 多算了不会误报，少算了会误报。
    """
    出 = set()
    for x in (定义.get("指标") or []):
        出.add(str(x.get("名称") or ""))
        出.add(str((x.get("度量") or {}).get("别名") or ""))
        for d in (x.get("维度") or []):
            出.add(str(d))
    出.discard("")
    return 出


def 挂空清单(定义):
    """哪些敏感列**永远不会出现在结果里**（语义层产不出这些列名）。返回列名列表。

    🔴 为什么单列一个函数、**不放进 `校验配置()` 的「问题」**：
       它们**不是配置错误** —— 业务上确实敏感，只是当前可答范围还没覆盖到
       （比如「采购单价」要等有了按单价的口径才会出现在结果里）。
       但必须让人看得见：否则脱敏就成了**挂在墙上的钩子** ——
       配置正确、自检看着也对，而真实链路上一次都不会触发。
       这次实测踩到的就是它：`自检-B档.py` 第五节那条「HTTP 上验脱敏」的断言
       **从写下起就不可能通过**，因为它期望一个不存在的列被掩码。
    """
    可能 = 可能列名(定义)
    return [m for m in 敏感列 if m not in 可能]


def 校验配置():
    """敏感列表自身的一致性检查。返回问题列表（空 = 干净）。

    🔴 手写的角色名写错一个字，不会报错 —— 只是**那个角色永远看不到该列**
       （表现为「隐藏」，看着像策略），或者**所有人都看不到**（配置写成了空角色）。
       两类都表现为「正常运行」，所以必须有这条自查（同 权限.校验配置）。
    """
    问题 = []
    真角色 = set(权限.角色表)
    for 敏, 规 in 敏感列.items():
        角 = 规.get("可见角色") or []
        if not 角:
            问题.append("「%s」的可见角色为空 —— 这一列将对**所有人**隐藏（把默认角色写全了吗）" % 敏)
        for r in 角:
            if r not in 真角色:
                问题.append("「%s」写了未知角色「%s」（可用：%s）"
                            % (敏, r, "、".join(sorted(真角色))))
        if 真角色 and 真角色 <= set(角):
            问题.append("「%s」对所有角色可见 —— 那它就不是敏感列，从表里删掉" % 敏)
    # 🔴 敏感列之间**不许互相包含**：`是敏感列` 取第一个命中，两条互为子串时
    #    命中的可能是错的那条 → 用错了一组「可见角色」（谁能看这件事配错了）。
    #    实测踩过的是**反向**那一半（通用列名吞掉敏感列），但正反两个方向同源：
    #    只要匹配靠子串而不是靠显式映射，就会在某个数据上出错。
    名表 = sorted(敏感列)
    for i, a in enumerate(名表):
        for b in 名表[i + 1:]:
            if a in b or b in a:
                问题.append("「%s」与「%s」互相包含 —— 匹配会命中错的那条，"
                            "把其中一个改成不重叠的名字（或显式写别名）" % (a, b))
    return 问题


# ============================ CLI ============================

def 主():
    参 = argparse.ArgumentParser(description="ChatBI 视图层脱敏（B-3）")
    参.add_argument("--清单", action="store_true")
    参.add_argument("--校验", action="store_true")
    参.add_argument("--试", action="store_true", help="按每个角色跑一遍示例结果集")
    参.add_argument("--列", help="逗号分隔列名")
    参.add_argument("--行", default="[]", help="JSON 二维数组")
    参.add_argument("--角色")
    参数 = 参.parse_args()

    if 参数.清单:
        print("默认角色（不传角色时用它）：%s" % 权限.默认角色)
        for x in 清单():
            print("· %-8s 可见：%s ｜ %s" % (x["列"], "、".join(x["可见角色"]), x["说明"]))
        return 0

    if 参数.校验:
        问题 = 校验配置()
        if not 问题:
            print("✅ 敏感列表自洽（%d 列 / 角色来自 权限.角色表 唯一来源）" % len(敏感列))
            return 0
        for x in 问题:
            print("🔴 %s" % x)
        return 1

    if 参数.试:
        列 = ["供应商名称", "采购单价", "订单金额", "供应商评级", "不良率"]
        行 = [["东莞精诚", 12.5, 88000, "A", 7.66],
             ["宁波恒力", 9.8, 152000, "B", 5.12]]
        for 角 in 权限.角色表:
            新列, 新行, 隐藏, 说明 = 脱敏(列, 行, 角)
            print()
            print("【%s】隐藏 %d 列" % (角, len(隐藏)))
            print("  " + " | ".join(str(c) for c in 新列))
            for r in 新行:
                print("  " + " | ".join(str(v) for v in r))
            print("  → 喂模型时会摘掉：" + ("、".join(x["列"] for x in 隐藏) or "（无）"))
            if 说明:
                print("  说明：" + 说明)
        return 0

    列 = [x for x in (参数.列 or "").split(",") if x]
    行 = json.loads(参数.行)
    # CLI 里没给 `--角色` 时用**默认角色**（最少权限）—— 与 HTTP 入口一致。
    # 内部直调的 None 分支是给进程内调用留的，CLI 是人手在敲，不该走那条。
    新列, 新行, 隐藏, 说明 = 脱敏(列, 行, 参数.角色 or 权限.默认角色)
    print(json.dumps({"列": 新列, "行": 新行, "隐藏": 隐藏, "说明": 说明,
                      "角色": 参数.角色 or 权限.默认角色},
                     ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(主())
