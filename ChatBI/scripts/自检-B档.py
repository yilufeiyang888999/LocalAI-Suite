def 第一节_缓存():
    说("=" * 74)
    说("一、B-2 意图缓存（只存成功 / 指纹不符作废 / 上下文进 key）")
    说("=" * 74)
    好 = True
    意图缓存.清空()
    指纹甲 = 意图缓存.提示指纹("提示词甲")
    指纹乙 = 意图缓存.提示指纹("提示词乙")
    键甲 = 意图缓存.键("上个月不良率最高的三家")
    好 &= 判("提示指纹不同 → 指纹不同", 指纹甲 != 指纹乙, "sha1 前 16 位")
    好 &= 判("key 与提示指纹是两回事",
            键甲 != 指纹甲 and len(键甲) == 20,
            "key = 问句+上文+生成端身份（2026-10-15 夜补：漏了身份会让换模型后"
            "仍复用旧答案，而这事不报错）")

    好 &= 判("空缓存取不到", 意图缓存.取(键甲, 指纹甲) is None, "反例：没存过就是 None")
    记录 = {"意图": {"指标": "来料不良率"}, "原文": "{}", "模型用时秒": 1.2,
           "阻断": [], "抽取失败": False}
    好 &= 判("存得进", 意图缓存.存(键甲, 指纹甲, 记录) is True, "只存成功的")
    # 🔴 上一判失败时这里取到 None —— 不兜底的话 AttributeError 崩掉整个自检，
    #   后面十几条判据全没了（失败也要把现场跑完，§9.5：中断必须与通过可区分）。
    栏 = 意图缓存.取(键甲, 指纹甲) or {}
    好 &= 判("取得回", bool(栏) and 栏.get("意图", {}).get("指标") == "来料不良率",
             "命中：%s" % json.dumps(栏.get("意图"), ensure_ascii=False))
    好 &= 判("命中计数在涨", (意图缓存.取(键甲, 指纹甲) or {}).get("缓存") is True, "")
    好 &= 判("命中次数累计", 意图缓存.统计()["累计命中次数"] >= 2,
             "累计 %d" % 意图缓存.统计()["累计命中次数"])

    # 🔴 关键反例：提示词变了（A-4 改提示词）→ 旧缓存**必须**作废
    好 &= 判("提示指纹不符 → 不命中（关键）", 意图缓存.取(键甲, 指纹乙) is None,
             "A-4 改提示词后若还命中旧缓存，重跑会得到「改进前后一样」的假数字")
    好 &= 判("指纹不符会计数", 意图缓存.统计()["指纹不符"] >= 1,
             "指纹不符 %d 次" % 意图缓存.统计()["指纹不符"])

    # 🔴 关键：失败不缓存 —— 一次模型抖动不该被永久固化
    键败 = 意图缓存.键("一句会被阻断的话")
    存了 = 意图缓存.存(键败, 指纹甲, {"意图": {"指标": None}, "阻断": ["没给出指标"],
                                "抽取失败": False})
    好 &= 判("失败的解析不缓存（关键）", 存了 is False and 意图缓存.取(键败, 指纹甲) is None,
             "缓存了失败 = 把一次抖动永久固化，且下次看起来「还是同样的澄清」")
    好 &= 判("存失败会计数", 意图缓存.统计()["失败不缓存"] >= 1,
             "失败不缓存 %d 次" % 意图缓存.统计()["失败不缓存"])

    # 🔴 关键：上下文进 key —— 否则「那上个月呢」会命中单轮的答案
    键无上文 = 意图缓存.键("那上个月呢")
    键有上文 = 意图缓存.键("那上个月呢", "【对话上文】上一轮：八月份不良率")
    好 &= 判("同一问句 + 不同上文 → 不同 key（关键）", 键无上文 != 键有上文,
             "共用 key 会让追问命中单轮的答案 —— 答的不是那个问题")
    好 &= 判("规范化：多余空白不影响",
            意图缓存.键("上个月  不良率\n最高") == 意图缓存.键(" 上个月 不良率 最高 "),
             "只做无损规范化（不动标点与语气词）")
    好 &= 判("规范化不改变含义：不同问句仍是不同 key",
            意图缓存.键("上月不良率") != 意图缓存.键("上月不良率表"), "反例：不能宽到误合")

    好 &= 判("落盘文件是合法 JSON",
            os.path.exists(意图缓存.缓存文件)
            and isinstance(json.load(open(意图缓存.缓存文件, encoding="utf-8")).get("条目"), dict),
            os.path.basename(意图缓存.缓存文件))
    好 &= 判("没有留下 .tmp 半成品", not os.path.exists(意图缓存.缓存文件 + ".tmp"),
             "原子替换（os.replace）后不该有残留")

    # 容量淘汰：直接构造，不借 `存`（`存` 每次都写盘，慢且会掩盖淘汰逻辑）
    原上限 = 意图缓存.最多条目
    try:
        意图缓存.最多条目 = 3
        意图缓存.清空()
        现在 = time.time()
        意 = {"版本": 1, "建立": 现在, "更新": 现在, "条目": {}}
        for i in range(6):
            意["条目"]["k%d" % i] = {"意图": {}, "最近": 现在 + i}
        意图缓存._表 = 意
        意图缓存._淘汰()
        好 &= 判("超上限按最近使用淘汰", len(意图缓存._表["条目"]) == 3,
                 "留下：%s" % "、".join(sorted(意图缓存._表["条目"])))
    finally:
        意图缓存.最多条目 = 原上限
        意图缓存.清空()

    # 开关：函数式（每次读环境变量），所以随时能改
    旧 = os.environ.get("CHATBI_NO_INTENT_CACHE")
    try:
        os.environ["CHATBI_NO_INTENT_CACHE"] = "1"
        好 &= 判("关缓存时取不到也不写", 意图缓存.取(键甲, 指纹甲) is None
                 and 意图缓存.存(键甲, 指纹甲, 记录) is False,
                 "关掉后既不读也不写 —— 评测必须走这条路")
    finally:
        if 旧 is None:
            os.environ.pop("CHATBI_NO_INTENT_CACHE", None)
        else:
            os.environ["CHATBI_NO_INTENT_CACHE"] = 旧
    好 &= 判("开关是函数式（不在 import 时定死）",
            isinstance(意图缓存.关缓存(), bool) and 意图缓存.关缓存() is False,
            "评测脚本在文件头 import，常量式的开关会在那一刻定死 —— 这个顺序坑踩过")
    return 好


# ============================ 二、B-3 脱敏 ============================

示例列 = ["供应商名称", "采购单价", "订单金额", "供应商评级", "不良率", "订单金额合计"]
示例行 = [["东莞精诚", 12.5, 88000, "A", 7.66, 88000],
         ["宁波恒力", 9.8, 152000, "B", 5.12, 152000]]


def 第二节_脱敏():
    说()
    说("=" * 74)
    说("二、B-3 视图层脱敏（分角色掩码；含「管理员能看到真值」的反例）")
    说("=" * 74)
    好 = True

    o列, o行, o隐, o说 = 脱敏.脱敏(示例列, 示例行, "操作员")
    好 &= 判("操作员：单价被掩码", o行[0][1] == 脱敏.掩码, "采购单价 → %s" % o行[0][1])
    好 &= 判("操作员：金额被掩码", o行[0][2] == 脱敏.掩码, "订单金额 → %s" % o行[0][2])
    好 &= 判("操作员：不良率**不受影响**", o行[0][4] == 7.66,
             "脱敏只能碰敏感列 —— 多掩一列 = 把能用的数据也藏了")

    # 🔴 反例：只测「能掩码」的话，一个「一律掩码」的实现也会全绿
    a列, a行, a隐, a说 = 脱敏.脱敏(示例列, 示例行, "管理员")
    好 &= 判("管理员：看到真值（反例）", a行[0][1] == 12.5 and a行[0][2] == 88000,
             "一律脱敏 = 管理员也看不到 = 权限设计反而失效")
    好 &= 判("管理员：隐藏清单为空", a隐 == [] and a说 is None, "无隐藏就不该出说明")

    g列, g行, g隐, _ = 脱敏.脱敏(示例列, 示例行, "主管")
    好 &= 判("主管：金额可见、单价不可见",
            g行[0][2] == 88000 and g行[0][1] == 脱敏.掩码, "两列不同档")

    # 🔴 内部直调（None）必须**不脱敏** —— 与 权限.检查 / 行级.应用 同一条边界。
    #    这条曾经不一致（脱敏把 None 当默认角色），自检里表现为 3 项失败。
    n列, n行, n隐, _ = 脱敏.脱敏(示例列, 示例行, None)
    好 &= 判("角色 None = 内部直调，不脱敏", n行[0][1] == 12.5 and n隐 == [],
             "HTTP 入口保证角色非 None（否则 401），所以 None 只来自进程内直调")

    好 &= 判("正向包含：更长的列名也命中", o行[0][5] == 脱敏.掩码,
             "「订单金额合计」包含「订单金额」—— 敏感列名出现在列名里就算命中")
    # 🔴 下面三条是**修 bug 时补的反例**。原来这里写的是「短列名也命中」，
    #    把「反向包含」（列名是敏感列名的子串）钉成了**期望行为** ——
    #    于是自检 77/77 全绿，而真机上供应商名整列变成 `***`。
    #    现场：盲测 v2 T19「上月哪家供应商不良绿最高」→ 实测 (***, 7.66)。
    #    教训：**判据写歪了，全绿只证明「实现与判据一致」，不证明功能对**。
    好 &= 判("🔴 反例：通用列名「供应商」不许命中", 脱敏.是敏感列("供应商") is None,
             "它是「供应商评级」的子串 —— 命中就意味着供应商名整列变 ***")
    好 &= 判("🔴 反例：列名不许被反向吞掉", 脱敏.是敏感列("单价") is None,
             "「单价」同时是「采购单价」和「标准单价」的子串 → 反向匹配还带歧义"
             "（取第一个 = 用了一组可能不对的可见角色）")
    好 &= 判("单字列名不误伤", 脱敏.是敏感列("价") is None, "长度下限 2")
    好 &= 判("不相关列名不命中", 脱敏.是敏感列("供应商名称") is None, "")

    摘列, 摘行 = 脱敏.摘列(示例列, 示例行, o隐)
    # 操作员看不到：采购单价 / 订单金额 / 供应商评级 / 订单金额合计（「订单金额合计」由包含匹配命中）
    # 留下：供应商名称 / 不良率 —— 断言写死值，是为了把「下标对齐」也钉住。
    好 &= 判("摘列：喂模型的版本不含敏感列（是摘掉，不是喂星号）",
            摘列 == ["供应商名称", "不良率"] and 脱敏.掩码 not in 摘行[0],
            "给模型的列：%s" % "、".join(摘列))
    好 &= 判("摘列：剩下的列与值一一对应",
            摘行[0] == ["东莞精诚", 7.66], "行：%s" % 摘行[0])
    好 &= 判("摘列：无隐藏时原样返回", 脱敏.摘列(示例列, 示例行, [])[0] == 示例列, "")
    好 &= 判("说明里点名了列与可见角色",
            "采购单价" in o说 and "管理员" in o说 and "服务端" in o说,
            (o说 or "")[:60])

    好 &= 判("配置自查干净", 脱敏.校验配置() == [],
             "（%d 列敏感列，角色名来自 权限.角色表）" % len(脱敏.敏感列))

    # 反向自查：故意塞一条「所有角色可见」的假规则，自查必须报出来
    假 = {"测试列": {"可见角色": list(权限.角色表), "说明": "假"}}
    try:
        脱敏.敏感列.update(假)
        问 = 脱敏.校验配置()
        好 &= 判("自查能抓出「全员可见」的假敏感列", any("从表里删掉" in x for x in 问),
                 "配置错却表现为「正常运行」是最难查的一类")
    finally:
        脱敏.敏感列.pop("测试列", None)
    return 好


# ============================ 三、B-4 身份 ============================

def 第三节_身份():
    说()
    说("=" * 74)
    说("三、B-4 身份（HMAC 验签；含「改一个字符就验不过」的反例）")
    说("=" * 74)
    好 = True

    令 = 身份.签("主管", "张三")
    好 &= 判("签得出来且带 v1 前缀", 令.startswith("v1."), 令[:28] + "…")
    载 = 身份.验(令)
    好 &= 判("验得过且角色正确", 载["角色"] == "主管" and 载["主体"] == "张三",
             "角色=%s 主体=%s" % (载["角色"], 载["主体"]))

    # 🔴 反例：改一个字符
    坏 = 令[:-1] + ("0" if 令[-1] != "0" else "1")
    try:
        身份.验(坏)
        好 &= 判("改一个字符就验不过（反例）", False, "🔴 验过了 —— 签名没起作用")
    except 身份.身份错 as 错:
        好 &= 判("改一个字符就验不过（反例）", True, str(错)[:52])

    # 🔴 反例：换个角色名重新拼载荷（不提权就白做 B-4 了）
    篡 = 令.split(".")
    try:
        import base64
        原 = json.loads(base64.urlsafe_b64decode(篡[1] + "=" * (-len(篡[1]) % 4)).decode())
        原["角色"] = "管理员"
        新 = base64.urlsafe_b64encode(json.dumps(原, ensure_ascii=False,
                                             separators=(",", ":"),
                                             sort_keys=True).encode()).decode().rstrip("=")
        身份.验("v1.%s.%s" % (新, 篡[2]))
        好 &= 判("把角色改成管理员也验不过（反例）", False, "🔴 提权成功了")
    except 身份.身份错:
        好 &= 判("把角色改成管理员也验不过（反例）", True, "签名覆盖整个载荷")

    好 &= 判("过期令牌验不过", _试过期() is False, "签一个已过期的令牌（-1 秒），必须拒")

    好 &= 判("未知角色签不出来", _试签未知() is False,
             "签出一个用不了的角色，现象是「这人什么都不让看」，像策略其实是错别字")

    # 换密钥 → 旧令牌验不过（说明签名真的依赖密钥）
    旧密 = os.environ.get("CHATBI_TOKEN_SECRET")
    try:
        os.environ["CHATBI_TOKEN_SECRET"] = "另一个密钥"
        好 &= 判("换密钥后旧令牌验不过", _试验(令) is False,
                 "签名真的依赖密钥，不是一个装饰性的前缀")
    finally:
        os.environ["CHATBI_TOKEN_SECRET"] = 旧密

    # 🔴 令牌优先于裸角色 —— 防提权
    果 = 身份.解析(令牌=身份.签("操作员"), 裸角色="管理员")
    好 &= 判("有令牌时裸角色被忽略（防提权）", 果["角色"] == "操作员" and 果["来源"] == "令牌",
             "拿低权限令牌 + 请求体写「管理员」→ 仍是操作员")
    果 = 身份.解析(令牌="v1.xxx.yyy", 裸角色="管理员")
    好 &= 判("令牌无效时**不退回**裸角色", 果["角色"] is None and 果["来源"] == "令牌无效",
             "退回等于「拿个假令牌就能降级到自称」，而现象是照常工作")

