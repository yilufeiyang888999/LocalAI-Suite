def 请求(基址, 路径, 体=None, 头=None, 超时=60):
    try:
        请 = urllib.request.Request(基址 + 路径, method="GET")
        if 体 is not None:
            请 = urllib.request.Request(基址 + 路径, data=json.dumps(体).encode("utf-8"),
                                     headers={"Content-Type": "application/json"}, method="POST")
        for k, v in (头 or {}).items():
            请.add_header(k, v)
        应 = 绕代理.open(请, timeout=超时)
    except urllib.error.HTTPError as 错:
        正文 = ""
        try:
            正文 = 错.read().decode("utf-8", "replace")[:300]
        except Exception:                                # noqa: BLE001
            pass
        try:
            return 错.code, json.loads(正文)
        except ValueError:
            return 错.code, {"raw": 正文}
    return 应.status, json.loads(应.read().decode("utf-8"))


