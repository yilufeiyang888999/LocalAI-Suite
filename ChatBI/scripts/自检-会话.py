    环境 = dict(os.environ)
    # 关掉不相关的新特性，让这一节只测会话：解读会多调一次模型（拖慢且无关），
    # 缓存会让第二轮命中第一轮的意图（那就测不到会话了）。
    环境["CHATBI_NO_INSIGHT"] = "1"
    环境["CHATBI_NO_PROMPT_CACHE"] = "1"
    环境["CHATBI_NO_INTENT_CACHE"] = "1"
    进程 = subprocess.Popen([sys.executable, 脚本, "--端口", str(端口), "--无上屏"],
                        cwd=项目目录, env=环境,
                        stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    基址 = "http://127.0.0.1:%d" % 端口
    全好 = True
    try:
        就绪 = False
        for _ in range(60):
            if 进程.poll() is not None:
                break
            try:
                请求(基址, "/health", 超时=2)
                就绪 = True
                break
            except Exception:                            # noqa: BLE001
                time.sleep(0.5)
        if not 就绪:
            输出 = ""
            if 进程.poll() is not None and 进程.stdout:
                输出 = 进程.stdout.read().decode("utf-8", "replace")[-400:]
            return 判("服务启动", False, "没起来；输出：%s" % 输出.replace("\n", " ")[:180])

        判("服务启动", True, "GET /health 通")
        健 = 请求(基址, "/health")
        全好 &= 判("/health 带会话统计", isinstance(健.get("会话"), dict),
                   "会话统计：%s" % json.dumps(健.get("会话") or {}, ensure_ascii=False)[:90])

        # 会话清空接口（不依赖模型）
        清 = 请求(基址, "/session", {"会话": "自检-清一清"})
        全好 &= 判("POST /session 清空", 清.get("已清") is not None, "返回 %s" % 清.get("已清"))

        深 = 请求(基址, "/health?deep=1", 超时=40)
        在 = (深.get("生成端") or {}).get("可达")
        if not 在 or 跳过模型:
            未查("/ask 多轮（真调模型）",
                 "生成端 8000 不可达或已跳过：%s" % ((深.get("生成端") or {}).get("说明", "") or "参数决定"))
            return 全好

        # ---- 第一轮：完整问题，落进会话 ----
        甲 = "会话-自检-甲"
        请求(基址, "/session", {"会话": 甲})
        应1 = 请求(基址, "/ask", {"问题": "八月份来料不良率最高的三家供应商", "会话": 甲})
        类1 = 应1.get("类型")
        全好 &= 判("第一轮出结果", 类1 == "SQL",
                   "%s ｜ %s" % (类1, (应1.get("口径") or 应1.get("澄清") or "")[:46]))
        if 类1 == "SQL":
            意图1 = 应1.get("意图") or {}
            全好 &= 判("第一轮意图带指标", bool(意图1.get("指标")),
                       json.dumps(意图1, ensure_ascii=False)[:90])
            全好 &= 判("第一轮未承接", not (应1.get("会话") or {}).get("已承接上一轮"),
                       "首轮没有上一轮可承接")

            # ---- 第二轮：残缺追问，必须承接 ----
            应2 = 请求(基址, "/ask", {"问题": "那上个月呢", "会话": 甲})
            会2 = 应2.get("会话") or {}
            全好 &= 判("第二轮承接上一轮", bool(会2.get("已承接上一轮")),
                       "沿用：%s ｜ 提示：%s" % ("、".join(会2.get("沿用") or []),
                                              "；".join(应2.get("提示") or [])[:60]))
            好2 = 应2.get("类型") == "SQL" and (应2.get("意图") or {}).get("指标") == 意图1.get("指标")
            全好 &= 判("第二轮指标未被换掉", 好2,
                       "指标 %s（第一轮 %s）" % ((应2.get("意图") or {}).get("指标"),
                                             意图1.get("指标")))
            全好 &= 判("第二轮沿用说明可读", bool(会2.get("沿用说明")),
                       (会2.get("沿用说明") or "（缺）")[:70])

            # 🔴 反例：**换一个会话**问同一句残缺话 → **不许**承接
            乙 = "会话-自检-乙"
            请求(基址, "/session", {"会话": 乙})
            应3 = 请求(基址, "/ask", {"问题": "那上个月呢", "会话": 乙})
            全好 &= 判("新会话**不**承接（反例）",
                       not (应3.get("会话") or {}).get("已承接上一轮"),
                       "类型 %s（应为澄清，不许答出甲的指标）" % 应3.get("类型"))
            全好 &= 判("新会话残缺话→澄清", 应3.get("类型") != "SQL",
                       "实际 %s" % 应3.get("类型"))

            # 不带会话 → 行为与单轮一致（零回归的最后一道闸）
            应4 = 请求(基址, "/ask", {"问题": "那上个月呢"})
            全好 &= 判("不带会话 = 单轮行为", 应4.get("类型") != "SQL"
                       and 应4.get("会话", {}).get("id") is None,
                       "类型 %s ｜ 会话 id %s" % (应4.get("类型"), 应4.get("会话", {}).get("id")))
        return 全好
    finally:
        进程.terminate()
        try:
            进程.wait(timeout=10)
        except subprocess.TimeoutExpired:
            进程.kill()


