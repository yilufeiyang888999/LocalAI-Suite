def 选空闲端口():
    """🔴 不能直接占用默认端口：8095 上大概率正跑着一个真实实例，
    自检起的服务要么起不来（端口占用）、要么把用户的服务顶掉。"""
    s = socket.socket()
    try:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]
    finally:
        s.close()


