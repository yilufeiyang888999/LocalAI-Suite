def 第二节_合并():
    说()
    说("=" * 74)
    说("二、兜底合并（本轮覆盖 + 上轮承接；确定的规则，不做推测）")
    说("=" * 74)
    好 = True

    好 &= 判("能自立·指标", 会话.能自立({"指标": "来料不良率"}), "有指标 = 自立")
    好 &= 判("能自立·基础查询", 会话.能自立({"基础查询": "计数"}), "有基础查询 = 自立")
    好 &= 判("能自立·场景", 会话.能自立({"场景": "C13_缺料物料"}), "有场景 = 自立")
    好 &= 判("不能自立·纯澄清", not 会话.能自立({"澄清": "需要明确指标"}),
             "🔴 只有澄清不算自立 —— 追问「那上个月呢」正是这一形态")
    好 &= 判("不能自立·零散槽位", not 会话.能自立({"时间": "上月"}),
             "只有时间没有指标 = 缺主体，要承接")

    出, 沿用 = 会话.兜底合并(上轮, {"澄清": "需要明确指标", "时间": "上月"})
    好 &= 判("追加上月：清掉澄清", "澄清" not in 出, "兜底成功就不再是澄清")
    好 &= 判("追加上月：换时间", 出.get("时间") == "上月",
             "本轮给的覆盖 → %s" % json.dumps(出.get("时间"), ensure_ascii=False))
    好 &= 判("追加上月：继承指标", 出.get("指标") == "来料不良率", "指标沿用上一轮")
    好 &= 判("追加上月：继承维度", 出.get("维度") == ["供应商"], "维度沿用")
    好 &= 判("沿用清单不含本轮给的项", "时间" not in 沿用 and "指标" in 沿用,
             "沿用：%s" % "、".join(沿用))

    出2, 沿用2 = 会话.兜底合并(上轮, {"维度": ["物料"]})
    好 &= 判("换维度是**替换**不是并集", 出2.get("维度") == ["物料"],
             "并集会变成交叉表（行数爆炸且答非所问）：%s" % json.dumps(出2.get("维度"), ensure_ascii=False))
    好 &= 判("换维度时时间沿用", 出2.get("时间") == ["指定月份", "2026年8月"], "时间没提 → 沿用")

    出3, 沿用3 = 会话.兜底合并(上轮, {})
    好 &= 判("空本轮 = 全沿用", 沿用3 == ["指标", "维度", "时间", "排序", "限制"],
             "沿用：%s" % "、".join(沿用3))

    说明 = 会话.沿用说明(沿用3, 出3)
    好 &= 判("沿用说明可读", bool(说明) and "来料不良率" in 说明 and "2026年8月" in 说明,
             (说明 or "")[:70])
    好 &= 判("无形中沿用时不出说明", 会话.沿用说明([], {}) is None, "没沿用就不说")

    出4, 沿用4 = 会话.兜底合并({}, {"时间": "上月"})
    好 &= 判("无上轮基底 → 不凭空造", 出4.get("指标") is None and 沿用4 == [],
             "上一轮没东西可继承时不许补")

    # ---- 主动路径的披露（`靠上文补全`）----
    # 🔴 **两侧都要测**：只测「能报出承接」的话，一个「无论什么都报承接」的实现
    #    会全绿 —— 而那正是最坏的形态：用户明明自己说了指标，系统还说「是我替你补的」。
    #    所以下面四条里有三条是反例。
