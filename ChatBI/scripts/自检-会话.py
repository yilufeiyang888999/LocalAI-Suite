"""ChatBI · A-1 自检：多轮追问（会话态 + 指代消解）

五节（每节都要能区分「通过」与「没检查」）：
  一、会话表本体     记 / 取 / 清空 / 过期 / 上限淘汰 —— 纯内存，不调模型
  二、兜底合并       本轮覆盖 + 上轮承接；**维度是替换不是并集**（反例见下）
  三、零回归        不带会话时提示词逐字节不变（单轮是主路径，不能被新功能碰到）
  四、归一幂等       上一轮意图是**已归一**的，再归一一次必须不变 —— 兜底的前提
  五、HTTP + 多轮    真起服务、真发两轮；含**反例**：换一个会话就**不准**承接

🔴 反例为什么必须有：只测「追问能继承」的话，一个「无论谁来都拿上一次的意图」的
   实现也会全绿 —— 而那正是最危险的形态（张冠李戴，且不报错）。
   所以第五节同时判：**新会话问同一句 → 不许承接**。

`--跳过模型` 只跑一~四节（它们不需要 8000），第五节标「未检查」而不是「通过」。
"""

