def 第一节_判定():
    说("=" * 74)
    说("一、确定性判定（拒答 / 放行 / 元问题 —— 正例与反例都要测）")
    说("=" * 74)
    件 = 问数服务.问数器()
    连接 = 件.连接()
    全好 = True
    try:
        说("  ---- 正例：该拒的必须拒 ----")
        for 名, 问, 词 in 拒答正例:
            应 = 拒答.判定(件.定义, 问, 连接)
            好 = 应["处置"] == "拒答" and 词 in (应.get("命中词") or [])
            # 「拒答必须给出路」—— 判据不是「有没有拒」，而是「拒的同时有没有告诉用户能问什么」
            有出路 = "本库能答" in (应.get("文本") or "")
            全好 &= 判("拒·" + 名, 好 and 有出路,
                       "%s 命中%s 出路%s" % (应["处置"], 应.get("命中词"),
                                          "有" if 有出路 else "**缺**"))
        说("  ---- 反例：库外词 + 库内词同时命中 → 必须放行 ----")
        for 名, 问, 词 in 放行反例:
            应 = 拒答.判定(件.定义, 问, 连接)
            好 = 应["处置"] == "放行" and bool(应.get("提示"))
            全好 &= 判("放·" + 名, 好, "%s%s" % (应["处置"],
                       ("；提示：" + (应.get("提示") or [""])[0][:44]) if 应.get("提示") else ""))
        说("  ---- 元问题：不调模型直接答 ----")
        for 名, 问, 短语 in 元问题正例:
            应 = 拒答.判定(件.定义, 问, 连接)
            好 = 应["处置"] == "元问题" and 应.get("命中短语") == 短语
            文本 = 应.get("文本") or ""
            # 诚实边界：必须明说是演示数据，不许做「准确可靠」的保证
            诚实 = "演示数据" in 文本 and "准不准" in 文本
            全好 &= 判("元·" + 名, 好 and 诚实,
                       "%s ｜ 诚实标注 %s" % (应["处置"], "有" if 诚实 else "**缺**"))
        说("  ---- 元问题护栏：问句含指标名 → 不判元问题 ----")
        for 名, 问 in 元问题反例:
            应 = 拒答.判定(件.定义, 问, 连接)
            全好 &= 判("非元·" + 名, 应["处置"] == "放行", 应["处置"])

        # ---- 不支持问项（2026-10-17）：要的东西本身不存在 → 拒答 ----
        说("  ---- 不支持问项：要的东西本身没有 → 拒答（不看库内词）----")
        for 名, 问, 词 in 问项正例:
            应 = 拒答.判定(件.定义, 问, 连接)
            好 = 应["处置"] == "拒答" and 词 in (应.get("命中词") or [])
            全好 &= 判("问项·" + 名, 好, "%s 命中%s" % (应["处置"], 应.get("命中词")))
        # 🔴 反向包含反例：库里有「供应商评级」这个枚举字段 → 「评级」不能进问项词表
        应 = 拒答.判定(件.定义, "各供应商评级的分布", 连接)
        全好 &= 判("问项·不误伤「供应商评级」", 应["处置"] == "放行",
                   "%s（库里真有这个枚举字段）" % 应["处置"])

        # ---- 交叉断言：同一份判据两处实现，必须同结论（2026-10-17）----
        # 🔴 `意图解析._表外问项` 用它**关掉方向兜底**（表外问项不该被兜成能答），
        #    `拒答.不支持问项命中` 用它**判拒答**。两处读的是同一段 YAML，
        #    但实现是两份 —— 分叉的表现是「解析层以为能做、判定层以为不能」，
        #    两边都不会报错，只会让同一句话在两条路径上得到相反结论。
        for 问 in ["各供应商的退货率是多少？", "库存周转率怎么样？",
                   "上个月的不合格率是多少？", "各供应商评级的分布"]:
            左 = bool(拒答.不支持问项命中(件.定义, 问))
            右 = bool(意图解析._表外问项(件.定义, 问))
            全好 &= 判("交叉·表外问项两处同结论「%s」" % 问[:10], 左 == 右,
                       "拒答=%s 解析=%s" % (左, 右))

        # ---- 时间边界（2026-10-17）：与数据跨度零交集才拒答 ----
        说("  ---- 时间边界：零交集拒答 / 有交集放行 ----")
        for 名, 问, 词 in 时间拒答:
            应 = 拒答.判定(件.定义, 问, 连接)
            好 = 应["处置"] == "拒答" and any(词 in w for w in (应.get("命中词") or []))
            全好 &= 判("时间拒·" + 名, 好, "%s 命中%s" % (应["处置"], 应.get("命中词")))
        for 名, 问 in 时间放行:
            应 = 拒答.判定(件.定义, 问, 连接)
            全好 &= 判("时间放·" + 名, 应["处置"] == "放行", 应["处置"])

        # ---- 模糊问项（2026-10-17）：指向不明 / 标准不明 → 澄清 ----
        说("  ---- 模糊问项：不许替用户挑指标，但也不许拦该答的口语问法 ----")
        for 名, 问, 类型, 词 in 模糊正例:
            应 = 拒答.判定(件.定义, 问, 连接)
            文本 = 应.get("文本") or ""
            好 = (应["处置"] == "澄清" and 应.get("澄清类型") == 类型
                  and 词 in (应.get("命中词") or []))
            # 措辞必须**定向**（给出可选方向），否则用户的下一步是随机猜一次
            定向 = ("补一个名字" in 文本) or ("来料不良率" in 文本)
            全好 &= 判("模·" + 名, 好 and 定向,
                       "%s %s 定向%s" % (应["处置"], 应.get("命中词"),
                                         "有" if 定向 else "**缺**"))
        for 名, 问, 期 in 模糊反例:
            应 = 拒答.判定(件.定义, 问, 连接)
            全好 &= 判("模反·" + 名, 应["处置"] == 期,
                       "%s（期望 %s）" % (应["处置"], 期))
        # 🔴 降级必须可区分：无连接时实体值判不了，规则**不启用**（不是「通过」）
        应 = 拒答.判定(件.定义, "精诚的货质量怎么样？", None)
        全好 &= 判("模·无连接时不误判（护栏①降级可见）", 应["处置"] == "放行",
                   "%s（无连接 ⇒ 不读实体值 ⇒ 宁放行不误拦）" % 应["处置"])

        # ---- 通用问题：处置=元问题，但答案必须是「我不查这个」，不是数据来源 ----
        说("  ---- 通用问题：不编日期，明说只读本库 ----")
        for 名, 问, 词 in 通用问题正例:
            应 = 拒答.判定(件.定义, 问, 连接)
            文本 = 应.get("文本") or ""
            好 = (应["处置"] == "元问题" and 词 in (应.get("命中短语") or "")
                  and "不查" in 文本)
            全好 &= 判("通用·" + 名, 好,
                       "%s ｜ %s" % (应["处置"], 文本.replace("\n", " ")[:46]))
        return 全好
    finally:
        连接.close()


