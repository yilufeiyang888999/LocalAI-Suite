def 第二节_歧义():
    说()
    说("=" * 74)
    说("二、歧义提示（默认 + 说明另解；**不阻断**）")
    说("=" * 74)
    件 = 问数服务.问数器()
    连接 = 件.连接()
    全好 = True
    try:
        规 = {x["名称"]: x for x in 拒答.载入规则(件.定义)["歧义来源"]}
        交 = 拒答.歧义词(件.定义, 连接, 规["类别词"]) or []
        说("  运行时算出的交集词（%d 个）：%s" % (len(交), "、".join(交)))
        全好 &= 判("交集非空", len(交) >= 5, "若为 0，说明两个字段取值不再重合，规则要重审")

        意 = {"指标": "来料不良率", "过滤": [{"字段": "物料类别", "值": "五金件"}]}
        提 = 拒答.歧义提示(件.定义, "五金件的不良率是多少", 意, 连接)
        全好 &= 判("交集词命中", bool(提) and "物料类别" in (提 or "") and "供应商类别" in (提 or ""),
                   (提 or "（无提示）")[:52])

        提2 = 拒答.歧义提示(件.定义, "结构件的不良率", 
                          {"指标": "来料不良率", "过滤": [{"字段": "物料类别", "值": "结构件"}]}, 连接)
        全好 &= 判("非交集词不报", not 提2, "「结构件」只在物料侧存在 → 无歧义")

        提3 = 拒答.歧义提示(件.定义, "各物料类别的达成率", {"指标": "生产工单达成率"}, 连接)
        全好 &= 判("关键词型·达成", bool(提3) and "数量达成" in (提3 or ""), (提3 or "（无）")[:52])

        提4 = 拒答.歧义提示(件.定义, "各物料类别的按期完工率", {"指标": "生产工单达成率"}, 连接)
        全好 &= 判("关键词型·排除", not 提4, "说了「按期」就不该再提示")

        # 反问兜底：只写「请补充」的反问必须被补上方向；已经给出方向的不得重复补
        短 = "请补充更多信息"
        补, 补过 = 拒答.反问补强(件.定义, 短)
        全好 &= 判("反问补方向", 补过 and ("质量" in 补 or "交期" in 补), 补.splitlines()[-1][:52])
        长的 = "您想了解质量（不良率）、交期（准时率）还是库存？"
        补2, 补过2 = 拒答.反问补强(件.定义, 长的)
        全好 &= 判("反问不重复补", (not 补过2) and 补2 == 长的, 补2[:52])

        # 🔴 抽取失败（2026-10-15 v3 直证）：模型输出**没解析出意图**时，传进来的
        #    「反问」是系统自己拼的**内部诊断串** —— 它不能上屏，但方向仍要给。
        #    （v3 里 T31「这个月怎么样？」界面上显示的就是「没能从模型输出里解析出
        #      JSON 意图」，对用户零信息量，还伪装成了一次正常的追问。）
        生, 生过 = 拒答.反问补强(件.定义, "没能从模型输出里解析出 JSON 意图", 抽取失败=True)
        全好 &= 判("解析失败·诊断串不上屏", "没能从模型输出里解析出" not in 生,
                   生.splitlines()[0][:52])
        全好 &= 判("解析失败·仍给出方向",
                   bool(生过) and any(w in 生 for w in 拒答.方向词表(件.定义)),
                   生.splitlines()[-1][:52])
        return 全好
    finally:
        连接.close()


