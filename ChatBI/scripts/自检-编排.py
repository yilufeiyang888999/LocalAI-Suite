def 主():
    sys.stdout.reconfigure(errors="replace")
    参 = argparse.ArgumentParser(description="ChatBI 包 5 自检 · 编排层")
    参.add_argument("--跳过模型", action="store_true", help="不跑需要 8000 的节")
    参.add_argument("--跳过HTTP", action="store_true", help="不跑第六节")
    参.add_argument("--只路由", action="store_true", help="只跑一、二节并出报告")
    参 = 参.parse_args()

    定义 = 编排.定义对象()
    题集 = 读题集()
    起 = time.time()
    # 🔴 自检不污染产物目录：把 `动作.产物目录` 临时改到一个子目录，结束时整个删掉。
    #    否则每跑一次自检，`outbox/` 里就多几张「自检01 / 自检02」的单据 ——
    #    几次之后没人分得清哪些是演示产物、哪些是自检垃圾。
    #    （`产物目录` 是模块级唯一事实来源，改它一处即可 —— 不在多处拼路径的好处。）
    原产物目录 = 动作.产物目录
    动作.产物目录 = os.path.join(原产物目录, "_自检")
    import shutil                                          # noqa: E402
    说("=" * 74)
    说("ChatBI 包 5 自检 · 编排层（意图路由 + 手写 ReAct + 动作产物）")
    说("时间：%s" % time.strftime("%Y-%m-%d %H:%M:%S"))
    说("生成端提示缓存：%s"
       % ("**关**（可复现模式）" if 编排.意图解析.关提示缓存
          else "开（服务端默认 —— 路由兜底题会不稳，评测请加 CHATBI_NO_PROMPT_CACHE=1）"))
    说("=" * 74)

    确定性 = 第一节_确定性(题集, 定义)
    兜底 = 第二节_兜底(题集, 定义, 参.跳过模型)

    if not 参.只路由:
        第三节_护栏(定义)
        第四节_产物(定义)
        第五节_端到端(定义, 参.跳过模型)
        if not 参.跳过HTTP:
            第六节_HTTP(定义, 参.跳过模型)

    耗时 = time.time() - 起
    说("")
    说("=" * 74)
    说("合计：%d 通过 / %d 失败 / %d 未检查（%.1f s）"
       % (通过数, 失败数, 未查数, 耗时))
    说("=" * 74)
    写报告(题集, 确定性, 兜底, 耗时)
    说("路由评测报告：%s" % 报告文件)

    # 清掉自检产生的产物（见开头说明）
    try:
        if os.path.isdir(动作.产物目录):
            shutil.rmtree(动作.产物目录)
        说("自检产物已清理（临时目录 %s）" % 动作.产物目录)
    except OSError as 错:
        说("⚠️ 自检产物清理失败：%s" % 错)
    finally:
        动作.产物目录 = 原产物目录

    日志目录 = os.path.join(项目目录, "logs")
    os.makedirs(日志目录, exist_ok=True)
    with open(os.path.join(日志目录, "自检-编排.log"), "w", encoding="utf-8") as 句柄:
        句柄.write("\n".join(日志行) + "\n")
    return 0 if 失败数 == 0 else 1


if __name__ == "__main__":
    raise SystemExit(主())
