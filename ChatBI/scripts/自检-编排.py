def 第六节_HTTP(定义, 跳过模型):
    说("")
    说("=" * 74)
    说("六、HTTP 冒烟（真起 8096）")
    说("=" * 74)
    端口 = 8096
    try:
        import socket
        s = socket.socket()
        s.settimeout(0.6)
        占用 = s.connect_ex(("127.0.0.1", 端口)) == 0
        s.close()
        if 占用:
            未查("HTTP 冒烟", "端口 %d 已被占用（先停掉再跑）" % 端口)
            return
    except OSError:
        pass

    脚本 = os.path.join(本目录, "编排服务.py")
    进 = subprocess.Popen([sys.executable, 脚本, "--端口", str(端口), "--无上屏"],
                         cwd=项目目录, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    基 = "http://127.0.0.1:%d" % 端口
    try:
        起 = time.time()
        通 = False
        while time.time() - 起 < 20:
            try:
                # 🔴 timeout 必须 > /health 最坏耗时（启动初期 ~4 s，探活占锁）
                #    —— timeout=2 时每次都超时，端到端稳定假红（2026-10-17 实测）。§9.5
                绕代理.open(基 + "/health", timeout=6).read()
                通 = True
                break
            except Exception:                              # noqa: BLE001
                time.sleep(0.4)
        判("服务起来（/health 通）", 通, "端口 %d" % 端口)
        if not 通:
            return
        健 = json.loads(绕代理.open(基 + "/health", timeout=5).read().decode())
        判("health 带 log_file 与链路状态",
           bool(健.get("log_file")) and len(健.get("链路") or {}) == 3,
           "链路：%s" % "、".join("%s=%s" % (k, "✅" if v.get("可达") else "🔴")
                              for k, v in (健.get("链路") or {}).items()))
        目 = json.loads(绕代理.open(基 + "/catalog", timeout=5).read().decode())
        判("catalog 带三条链路与动作",
           len(目.get("链路") or []) == 3 and len(目.get("动作") or []) == 3, "")
        # 动作嫌疑的**两侧**都要能从这里读到：只暴露嫌疑词表、不暴露否掉它的闸，
        # 「为什么这句没被改判」就只能去读代码（配置要能被实际产出证明）。
        词 = 目.get("路由词表") or {}
        判("catalog 带动作嫌疑两侧词表",
           len(词.get("处置动词") or []) > 0 and len(词.get("问数信号") or []) > 0,
           "处置动词 %d / 问数信号 %d"
           % (len(词.get("处置动词") or []), len(词.get("问数信号") or [])))

        def POST(路, 体):
            """返回 (状态码, 对象)。

            🔴 必须接住 `HTTPError`。判据里有「非法输入必须回 400」这一条 ——
               如果 helper 只在 2xx 时返回，那**判据会在验证服务正确行为时崩掉**：
               服务规规矩矩回了 400，脚本却抛异常退出，于是「服务对了」被记成「自检失败」。
               （这是本项目第 N 次踩「判据本身出错」的坑，与包 3 的 `耗时 or 9` 同类。）
            """
            req = urllib.request.Request(基 + 路,
                                         data=json.dumps(体, ensure_ascii=False).encode(),
                                         headers={"Content-Type": "application/json"},
                                         method="POST")
            try:
                with 绕代理.open(req, timeout=180) as 应:
                    return 应.status, json.loads(应.read().decode())
            except urllib.error.HTTPError as 错:
                try:
                    return 错.code, json.loads(错.read().decode())
                except Exception:                          # noqa: BLE001
                    return 错.code, {}

        码, 路 = POST("/route", {"问题": "给东莞精诚出一份质量整改通知"})
        判("/route 只判路由不调链路", 码 == 200 and 路.get("链路") == "动作执行",
           "→ %s（%s）" % (路.get("链路"), 路.get("依据")))
        # 🔴 判「Python 层对了」不等于「用户看得见」：字段可能在 HTTP 序列化处被吃掉，
        #    也可能被前端当成空对象。这一条钉的是**对外表现**。
        码, 路2 = POST("/route", {"问题": "东莞精诚的整改通知"})
        判("/route 带动作嫌疑与改判",
           码 == 200 and 路2.get("链路") == "动作执行"
           and bool(路2.get("改判")) and (路2.get("动作嫌疑") or {}).get("是") is True,
           "改判自 %s" % (路2.get("改判") or {}).get("原链路"))
        if 跳过模型:
            未查("/ask 端到端", "--跳过模型 跳过了")
        else:
            码, 应 = POST("/ask", {"问题": "一共有多少家供应商？"})
            判("/ask 端到端", 码 == 200 and 应.get("类型") == "数据问数" and not 应.get("错误"),
               "%s｜%.2f s" % (应.get("类型"), 应.get("总耗时秒", 0)))
            码, 坏 = POST("/ask", {"问题": "x", "强制链路": "不存在的链路"})
            判("/ask 非法强制链路 → 400", 码 == 400 and "error" in 坏,
               "HTTP %d｜%s" % (码, str(坏.get("error"))[:40]))
    finally:
        进.terminate()
        try:
            进.wait(timeout=5)
        except subprocess.TimeoutExpired:
            进.kill()


