def 请求(基址, 路径, 体=None, 超时=180):
    try:
        if 体 is None:
            应 = 绕代理.open(基址 + 路径, timeout=超时)
        else:
            请 = urllib.request.Request(基址 + 路径, data=json.dumps(体).encode("utf-8"),
                                     headers={"Content-Type": "application/json"}, method="POST")
            应 = 绕代理.open(请, timeout=超时)
    except urllib.error.HTTPError as 错:
        正文 = ""
        try:
            正文 = 错.read().decode("utf-8", "replace")[:300]
        except Exception:                                # noqa: BLE001
            pass
        raise RuntimeError("HTTP %s %s：%s" % (错.code, 路径, 正文)) from None
    return json.loads(应.read().decode("utf-8"))


def 请求原样(基址, 路径, 体=None, 超时=30):
    """同 请求()，但**不把 4xx 变成异常**。

    「必拒」类判据要能看见状态码本身：只测 200 的话，一个「什么都不校验、
    见什么写什么」的反馈接口也会全绿 —— 而它的现象（脏数据进台账）几个月后才显形。
    """
    try:
        if 体 is None:
            应 = 绕代理.open(基址 + 路径, timeout=超时)
        else:
            请 = urllib.request.Request(基址 + 路径, data=json.dumps(体).encode("utf-8"),
                                     headers={"Content-Type": "application/json"}, method="POST")
            应 = 绕代理.open(请, timeout=超时)
        码, 原 = 应.status, 应.read().decode("utf-8", "replace")
    except urllib.error.HTTPError as 错:
        码, 原 = 错.code, 错.read().decode("utf-8", "replace")
    try:
        return 码, json.loads(原)
    except ValueError:
        return 码, {"_原文": 原[:200]}


def 生成端Slot卡死(地址, 超时=6):
    """`/health` 通 ≠ 能生成 —— 返回 True 表示「活着但 slot 卡死」。

    🔴 实测形态（本机 2026-10-13）：llama-server 的**唯一 slot** 被一个中途断开的
       客户端占死时，`/health`・`/props`・`/v1/models` 全部**秒回 200**，
       而任何生成请求**永远不返回**（客户端侧只看到超时）。
       `/slots` 的处理器要拿**和推理同一把**锁 → 它超时就是 slot 卡死的判据。
       不做这个区分的话，本节会把「slot 卡死」报成「服务没起」，把人送去启动一个
       已经在跑的服务。现场确认与处置见 `scripts/诊断-生成端卡死.py`。

    ⚠️ `意图解析.生成服务` 是**完整 endpoint**（`.../v1/chat/completions`），
       不是 base URL。直接往后拼 `/slots` 会拿到 404，而 404 会被误读成「不卡」——
       实测踩过一次。所以这里先取 origin。
    """
    if not 地址:
        return False
    解 = urllib.parse.urlsplit(地址 if "//" in 地址 else "http://" + 地址)
    根 = "%s://%s" % (解.scheme or "http", 解.netloc)
    起 = time.time()
    try:
        绕代理.open(根.rstrip("/") + "/slots", timeout=超时).read(64)
        return False                                     # 拿到了锁 → slot 是空闲的
    except Exception:                                    # noqa: BLE001
        # 只有**超时**算卡死；明确的 4xx（没开 /slots 端点）不算。
        return (time.time() - 起) >= 超时 - 0.5


def 挑空闲端口():
    """让系统分一个当前没人在听的端口 —— HTTP 冒烟用它起**自己的**服务。

    🔴 为什么不能沿用 8095：本脚本实测踩过一次，代价是**正式反馈台账被写脏**。
       8095 上跑着外部实例时，本脚本起的子进程**绑不上端口、静默退出**，
       而紧随其后的就绪探测打到的**正是那个外部实例** → 「服务启动 ✅」，
       于是第六节所有断言（包括「反馈真的落盘了」）都打在**别人的服务**上：
         · 结论错（测的不是本脚本起的那个进程）；
         · 还顺手把自检的假反馈写进了外部实例的正式台账 ——
           本脚本特意把 `CHATBI_FEEDBACK_DIR` 指到临时目录，
           但那只对**自己起的子进程**有效。
       这与「唯一事实来源」是同一类错误：**环境不是自己造的，验证就没有意义。**
    """
    import socket
    s = socket.socket()
    s.bind(("127.0.0.1", 0))
    口 = s.getsockname()[1]
    s.close()
    return 口


def 端口能绑(端口):
    """能不能在这个端口上起服务 —— 用 bind 试，比「探测 /health 通不通」更本质。"""
    import socket
    s = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    try:
        s.bind(("127.0.0.1", 端口))
        return True
    except OSError:
        return False
    finally:
        s.close()


