# ============================ 七、A-2 解读 ============================

示例应 = {
    "列": ["供应商", "不良率"], "行": [["东莞精诚", 7.66], ["宁波恒力", 5.12]],
    "行数": 2, "口径": "来料不良率 = 不合格数 / 进货数", "时间": "2026-08",
    "指标": "来料不良率", "单位": "%", "SQL": "SELECT 1 LIMIT 9999",
}


def 桩(文本):
    """造一个「模型」，只回固定文本 —— 解读链路的所有分支都能这么测，不需要 8000。"""
    def 调(提示, 超时=0, 最多token=0):
        return (文本, 0.01, {})
    return 调


def 第七节_解读():
    说()
    说("=" * 74)
    说("七、A-2 一句话解读（防编造是主要设计，不是附属功能）")
    说("=" * 74)
    好 = True

    # ---- 允许数字集合：这是出口检查的全部依据，它错一点检查就废 ----
    许 = 解读.允许数字(示例应)
    好 &= 判("允许数字 · 含结果集里的值", 7.66 in 许 and 5.12 in 许, "7.66 / 5.12")
    好 &= 判("允许数字 · 含行数", 2.0 in 许, "共 2 行")
    好 &= 判("允许数字 · 含口径里的数字", 2026 in 许 and 8 in 许,
             "口径文本里的数字要收 —— 否则「按 2026 年 8 月口径」这种正确解读会被误杀")
    好 &= 判("🔴 允许数字 · **不含 SQL**（含了等于放空检查）", 9999 not in 许,
             "SQL 里有 LIMIT / 日期常量，把它们放进来，模型只要抄一个 SQL 里的数就能过检")

    # ---- 必放：真的只是复述 ----
    好 &= 判("必放 · 只复述结果集的解读通过",
             解读.查编造("东莞精诚的不良率最高，为 7.66%。", 示例应)[0],
             "7.66 在结果里")
    好 &= 判("必放 · 0 行时「没有匹配到记录」通过",
             解读.查编造("没有匹配到记录。", {**示例应, "行": [], "行数": 0})[0],
             "无数字的解读不该被拦")

    # ---- 必拒：编出来的（这才是防编造存在的理由）----
    好, 疑 = 解读.查编造("两家供应商平均不良率为 6.39%。", 示例应)
    好 &= 判("必拒 · 算出来的均值被判编造", (not 好) and "6.39" in 疑,
             "被拦的数：%s" % "、".join(疑))
    好 &= 判("必拒 · 凭空的比例被判编造",
             not 解读.查编造("东莞精诚占了 60% 的量。", 示例应)[0], "60 不在结果里")
    好 &= 判("必拒 · 抄 SQL 里的数字也算编造",
             not 解读.查编造("限额是 9999。", 示例应)[0], "SQL 不是允许来源")

    # ---- 整条链路：解读() 的返回契约 ----
    果 = 解读.解读("问", 示例应, 调=桩("两家供应商平均不良率为 6.39%。"))
    好 &= 判("解读() · 编造 → 文本被丢弃（不是照发）",
             果.get("文本") is None and 果.get("编造") is True,
             "丢弃理由：%s" % (果.get("错误") or "")[:46])
    好 &= 判("解读() · 丢弃时保留了原文与可疑数字（可事后复核）",
             果.get("原文本") and 果.get("可疑数字"),
             "只丢不留痕 = 永远不知道它编了什么")

    好果 = 解读.解读("问", 示例应, 调=桩("东莞精诚的不良率最高，为 7.66%。"))
    好 &= 判("解读() · 合规 → 原样返回", 好果.get("文本") == "东莞精诚的不良率最高，为 7.66%。",
             "文本=%s" % 好果.get("文本"))
    好 &= 判("解读() · 返回用时（能看出它拖了多久）", 好果.get("用时秒") is not None, "")

    脏 = 解读.解读("问", 示例应, 调=桩("## 解读\n东莞精诚 7.66% 最高。\n（顺便说下）"))
    好 &= 判("解读() · Markdown 与第二行被收拾成一句",
             脏.get("文本") == "东莞精诚 7.66% 最高。", "得到：%s" % 脏.get("文本"))
    空 = 解读.解读("问", 示例应, 调=桩("   "))
    好 &= 判("解读() · 空产出 → 明确报「模型没产出内容」", 空.get("文本") is None and 空.get("错误"),
             "空字符串不能当成一条解读发出去")

    def 抛错桩(提示, 超时=0, 最多token=0):
        raise RuntimeError("模型不可达")
    错果 = 解读.解读("问", 示例应, 调=抛错桩)
    好 &= 判("🔴 解读() · 模型不可达 → **不抛异常**、照常返回错误说明",
            错果.get("文本") is None and bool(错果.get("错误")),
            "数据已经查到了，不能因为写不出一句话就不给 —— 解读绝不拖垮答案")

    # ---- 提示词：转述的依据必须都在里面，且明令不许算 ----
    提 = 解读.构造提示("上月哪家供应商不良率最高？", 示例应)
    好 &= 判("提示词 · 带上口径 / 时间 / 对象 / 单位",
             all(x in 提 for x in ("来料不良率", "2026-08", "%")),
             "不喂依据，模型只能用常识补 —— 那就是编")
    好 &= 判("提示词 · 明令不许算新数字", "不许计算" in 提, "")
    好 &= 判("提示词 · 数据区是结果集本身（不是 SQL）",
             "东莞精诚" in 提 and "SELECT" not in 提,
             "喂 SQL 会诱发「解释这条语句」而不是「转述这个结果」")
    return 好


