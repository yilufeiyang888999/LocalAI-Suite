def 逐格相同(甲, 乙):
    if len(甲) != len(乙):
        return False
    for a, b in zip(甲, 乙):
        if isinstance(a, float) and isinstance(b, float):
            if abs(a - b) > 1e-9:
                return False
        elif a != b:
            return False
    return True


