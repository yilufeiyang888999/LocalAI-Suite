"""ChatBI · A-4：盲测集评测（40 题）—— 检验「50 题 97.5%」是不是自出题自己答。

为什么要单独一个脚本、单独一个题集
-----------------------------------
50 题集的题与语义层是同一个作者写的，金标准还用了「期望意图 → 渲染」这条路 ——
**它证明的是「题集 + 定义 + 渲染器自洽」，证明不了「模型能听懂没见过的问法」。**
本脚本换一批**问法形态不同**的题（同义改写 / 口语 / 错别字 / 跨指标 / 真实日志），
金标准**全部独立手写 SQL**、不经语义层渲染。

判据（比 50 题集多一条，理由写在这里而不是散在代码里）
------------------------------------------------------
  · 结果集            —— 必须给出正确结果
  · **结果集或澄清**  —— 正确结果 或 明确澄清，都算通过
        用于错别字题：对错别字，澄清是**安全**行为（用户重打一遍即可）；
        **给错答案才是失败** —— confidence wrong 是三种错里最贵的
        （BIRD 里「自信地答错」比「说不确定」代价高得多）。
  · 处置              —— 必须给出指定处置（澄清 / 拒答 / 元问题）

复用而不是重抄：结果集比对（列超集容忍 / 值键 / 行集合）直接用 50 题集脚本里的那份 ——
同一份判据两处实现，改一处不报错、只给错报告（§9.5「唯一事实来源」）。

用法：
    python scripts/评测-盲测集.py                 # 全量 40 题（需要 8000 生成端）
    python scripts/评测-盲测集.py --类 同义改写    # 只跑某一类
    python scripts/评测-盲测集.py --限制 5        # 试水
    python scripts/评测-盲测集.py --加对照        # 再跑 `eval/对照题集-1题.json`（**不进主尺分母**，报告单独成节）

🔴 **“附加对照”是给“主尺不许动”准备的口子**：主尺 40 题是历史基线（v1~v8 都按它算），
改它 = 全部断代。所以「同语义换个说法能不能过」这类验证走**独立题集 + `--加对照`**，
汇总时按 `对照` 标记切开，**结论单独报**，绝不混进执行准确率（分母不同不能平均）。
"""

