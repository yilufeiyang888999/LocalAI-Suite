def 汇总(记录表):
    # 🔴 类序**不能写死**（2026-10-17 修）。
    #    旧版写死主尺那五类，新题集（分布外「主题外/表外字段/时间外/元问题/实体外值」、
    #    多问法「按意图组」）的类名一个都不在列表里 → 整张「分类别」表被打空。
    #    空表与「本来就没有分类」**同形**，看不出是判据漏了还是真没数据 —— 这正是
    #    §9.5「判据看不出自己漏了什么」。改为：已知五类优先保序，其余按首次出现顺序补在后面。
    已知序 = ["同义改写", "口语", "错别字", "跨指标", "真实日志"]
    出现序 = []
    for r in 记录表:
        类 = r.get("类") or "-"
        if 类 not in 出现序:
            出现序.append(类)
    类序 = [类 for 类 in 已知序 if 类 in 出现序] + \
           [类 for 类 in 出现序 if 类 not in 已知序]

    按类 = {}
    for 类 in 类序:
        子 = [r for r in 记录表 if (r.get("类") or "-") == 类]
        if not 子:
            continue
        好 = sum(1 for r in 子 if r["结果"] == "通过")
        形态 = {}
        for r in 子:
            if r["结果"] != "通过":
                键 = r.get("分类") or "未分类"
                形态[键] = 形态.get(键, 0) + 1
        按类[类] = {"题数": len(子), "通过": 好,
                    "通过率": round(好 * 100.0 / len(子), 1), "失败形态": 形态}

    # 护栏：分类别表必须覆盖全部题。漏题说明分组维度又跟题集对不上了。
    已归 = sum(汇["题数"] for 汇 in 按类.values())
    if 记录表 and 已归 != len(记录表):
        说("🔴 分类覆盖不全：%d / %d 题未归入任何类 —— 分类别表在漏题"
          % (len(记录表) - 已归, len(记录表)))

    # 结果集口径 / 处置口径 分开 —— 与 50 题集同一条纪律
    结题 = [r for r in 记录表 if r["判据"] in ("结果集", "结果集或澄清")]
    处题 = [r for r in 记录表 if r["判据"] == "处置"]
    统计 = {
        "结果集题": {"题数": len(结题), "通过": sum(1 for r in 结题 if r["结果"] == "通过")},
        "处置题": {"题数": len(处题), "通过": sum(1 for r in 处题 if r["结果"] == "通过")},
        "安全澄清（错别字题给了澄清而非硬答）":
            sum(1 for r in 记录表 if r.get("分类") == "安全澄清"),
        "硬答（该澄清却给出 SQL）":
            sum(1 for r in 记录表 if str(r.get("分类") or "").startswith("该") and "硬答" in str(r.get("分类"))),
    }
    if 结题:
        统计["结果集题"]["执行准确率"] = round(统计["结果集题"]["通过"] * 100.0 / len(结题), 1)
    if 处题:
        统计["处置题"]["处置准确率"] = round(统计["处置题"]["通过"] * 100.0 / len(处题), 1)
    return 按类, 统计


def 读50题对照():
    """50 题集的机器可读结果（**读文件，不重跑**）。缺了就说缺了，不编数字。"""
    if not os.path.exists(对照文件):
        return None
    try:
        with open(对照文件, encoding="utf-8") as 句柄:
            return json.load(句柄)
    except (OSError, ValueError):
        return None


