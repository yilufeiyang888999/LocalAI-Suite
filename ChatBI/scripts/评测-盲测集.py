def 确认全权(基址):
    """起服务之后先证明「这个角色确实不受限」—— 否则上面那段注释就是空话。

    走 `/spec`（不调模型），只问两件事：行级受不受限、有没有列被隐藏。
    任一条不成立就**中止评测**：带着受限的身份跑出来的数字，没法和任何东西比。
    """
    探 = {"意图": {"指标": "来料不良率", "维度": ["供应商"], "限制": 3},
          "角色": 评测角色}
    try:
        应 = 请求(基址, "/spec", 探)
    except Exception as 错:                                  # noqa: BLE001
        return False, "探测 /spec 失败：%s: %s" % (type(错).__name__, str(错)[:90])
    级 = 应.get("行级") or {}
    if 级.get("受限"):
        return False, "角色「%s」仍被行级限定：%s" % (评测角色, (级.get("说明") or "")[:90])
    if 应.get("隐藏列"):
        return False, "角色「%s」仍有隐藏列：%s" % (评测角色, "、".join(应["隐藏列"]))
    return True, ("角色「%s」：行级不受限、无隐藏列 → 测的是模型本身" % 评测角色)


