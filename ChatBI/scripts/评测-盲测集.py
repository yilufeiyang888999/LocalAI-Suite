def 主():
    参 = argparse.ArgumentParser(description="ChatBI A-4：盲测集评测（40 题）")
    参.add_argument("--类", default="", help="只跑某一类（同义改写 / 口语 / 错别字 / 跨指标 / 真实日志）")
    参.add_argument("--题集", default="",
                    help="题集文件名（放 eval/ 下，如 问数盲测集-扩样本20题.json）。"
                         "**不给 = 用 40 题主尺**，产物名也与历史逐字节一致（v1~v8 不断代）。"
                         "给了 → 产物文件名跟题集名走，不会覆盖 40 题的历史产物。")
    参.add_argument("--限制", type=int, default=0, help="只跑前 N 题")
    参.add_argument("--端口", type=int, default=0, help="评测用服务端口（默认 0 = 让系统分）")
    参.add_argument("--跳过对照", action="store_true", help="不读 50 题集结果做对照")
    参.add_argument("--加对照", action="store_true",
                    help="额外跑 `eval/对照题集-1题.json`（**不进主尺分母**，单独成节）。"
                         "主尺 40 题一字不动 —— 改主尺 = v1~v8 全部断代")
    参.add_argument("--标注", default="",
                    help="轮次标注，写进产物文件名（如 v1 / v2）。"
                         "**不写 = 覆盖基准产物，会丢掉上一轮的数字**")
    参数 = 参.parse_args()
    # 🔴 --题集 要重指模块级全局 题集文件 —— 不声明 global 的话，
    #   本函数内的赋值会让它全程被当局部变量，后面 open(题集文件) 直接 UnboundLocalError
    #   （实测：首版 --题集 就这么炸的，而且炸在**不用 --题集**的默认路径上 —— 波及主尺）。
    global 题集文件

    # 产物落点：带标注 → 另存一份，不覆盖基准（v1/v2 对照要能同时看到）
    # 🔴 --题集：只有**显式给了**才换题集与产物名 —— 默认路径（40 题主尺）连产物名
    #   都与历史逐字节一致，这是「v1~v8 不断代」的保证。派生规则：题集文件名
    #   去掉「问数盲测集-」前缀（如 问数盲测集-扩样本20题.json → 盲测结果-扩样本20题.json）；
    #   其它命名的题集（分布外/多问法）直接用原文件名。
    后缀 = ("-" + 参数.标注) if 参数.标注 else ""
    if 参数.题集:
        题集文件 = os.path.join(项目目录, "eval", 参数.题集)
        if not os.path.exists(题集文件):
            说("🔴 找不到题集文件：%s" % 题集文件)
            return 1
        题集名 = os.path.splitext(参数.题集)[0]
        产物名 = 题集名.replace("问数盲测集-", "") if 题集名.startswith("问数盲测集-") else 题集名
        报告路径 = os.path.join(项目目录, "eval", "盲测报告-%s%s.md" % (产物名, 后缀))
        结果路径 = os.path.join(项目目录, "eval", "盲测结果-%s%s.json" % (产物名, 后缀))
    else:
        报告路径 = os.path.splitext(报告文件)[0] + 后缀 + ".md"
        结果路径 = os.path.splitext(结果文件)[0] + 后缀 + ".json"

    说("ChatBI A-4 盲测 · 评测集外部性")
    说("时间：%s" % time.strftime("%Y-%m-%d %H:%M:%S"))
    说("生成端提示缓存：%s" % ("**关**（可复现模式）" if 意图解析.关提示缓存
                           else "开（**同一提示词可能两种答案，测出的数字不可复现**；"
                                "请用 CHATBI_NO_PROMPT_CACHE=1 重跑）"))
    # 🔴🔴 语义缓存必须关 —— **硬门槛，不关就中止**（2026-10-15 夜新增）。
    #
    # 为什么升级成「中止」而不是「打印一行」：
    #   10-14~10-15 的四轮微调对照，`跑对照.py` 只设了 `CHATBI_NO_PROMPT_CACHE`
    #   （那是生成端前缀复用，自建壳根本不看），漏了 `CHATBI_NO_INTENT_CACHE`
    #   （这才是服务端**语义缓存**）。后果：4 轮里 31/40 题**根本没调模型**，
    #   直接读第一轮写下的意图 —— 而缓存 key 只含「问句 + 上文」，**不含模型身份**，
    #   于是「四轮结果逐字相同」被读成了「微调没效果」，还据此写了报告。
    #   旧版这里也只打印一行、且只看生成端那个开关 → **判据停在最便宜的那一层**。
    #
    # 「降级/兜底必须与正常路径可区分」：缓存没关 = 这轮数字与「模型」无关，
    #   它与「模型很差」在数字上**同形**。所以这里不给它继续跑的机会。
    if 意图缓存.关缓存():
        说("语义缓存（问句→意图）：**关**（可复现模式）✅")
    else:
        说("🔴 语义缓存（问句→意图）：**开** —— 中止。")
        说("   这一轮数字会**跨轮、跨模型复用**：key 只含「问句 + 上文」，不含模型身份，")
        说("   第一轮写下的意图会被后面每一轮原样读走（表现：几轮结果逐字相同）。")
        说("   修法：`CHATBI_NO_INTENT_CACHE=1` 与本脚本一起给上；")
        说("   落点：`%s`（本仓历史污染的物证就在这个文件里）。" % 意图缓存.缓存文件)
        return 1

    with open(题集文件, encoding="utf-8") as 句柄:
        题集 = json.load(句柄)
    题目 = list(题集["题目"])
    if 参数.类:
        题目 = [t for t in 题目 if t["类"] == 参数.类]
    if 参数.限制:
        题目 = 题目[:参数.限制]
    说("题集：%s ｜ 本次 %d 题" % (题集["版本"], len(题目)))

    # ---- 附加对照题（可选，**不进主尺分母**）----
    附加题 = []
    附加集 = None
    if 参数.加对照:
        if not os.path.exists(对照题集文件):
            说("🔴 找不到附加对照题集：%s" % 对照题集文件)
            return 1
        with open(对照题集文件, encoding="utf-8") as 句柄:
            附加集 = json.load(句柄)
        for t in 附加集["题目"]:
            附加题.append(dict(t, 对照=True))
        说("附加对照题集：%s ｜ 加 %d 题（**单独统计，不进上面的分母**）"
            % (附加集["版本"], len(附加题)))

    定义 = 语义.载入()
    # 提示词指纹：做两轮对照之前，先确认**用的是同一版提示词**。
    # 靠文件名 / 时间戳猜是不可靠的 —— 改过提示词却忘了记，
    # 现象会是「模型退化了」（把工程改动记到模型头上，方向找错）。
    # ⚠️ 它**只反映提示词**；解析规则版本另存一个字段（2026-10-17 拆分），
    #    否则改一条规则就会让「两轮不可比」，而提示词其实一个字没动。
    提示词指纹 = 意图缓存.提示指纹(
        意图解析.构造提示(定义, "样例问题：上月不良率最高的三家供应商", None))
    说("提示词指纹：%s ｜ 解析规则版本：%s" % (提示词指纹, 意图缓存.解析规则版本))
    连接 = 护栏.连库(语义.库路径(定义))
    基准缓存 = {}
    引擎自报 = None          # 引擎自报的模型名（在下面 try 里取；取不到就是 None）
    try:
        # 先跑一遍金标准 SQL —— 金标准自己跑不动，后面测模型毫无意义
        坏 = 0
        for 题 in (题目 + 附加题):
            if 题.get("标准SQL"):
                try:
                    基准缓存[题["编号"]] = (lambda d: (d["列"], d["行"]))(
                        护栏.执行(连接, 题["标准SQL"]))
                except Exception as 错:                            # noqa: BLE001
                    坏 += 1
                    说("  🔴 %s 金标准 SQL 跑不动：%s" % (题["编号"], 错))
        说("金标准 SQL 预跑：%d 条可执行 ｜ %d 条失败" % (len(基准缓存), 坏))
        if 坏:
            说("🔴 金标准有问题 —— **先修题集再测模型**（否则把题的错记到模型头上）")
            return 1

        端口 = 参数.端口 or _选端口()
        服务器, 基址 = 起服务(端口)
        说("  服务已起：%s（进程内，无管道）" % 基址)
        在, 说明 = 意图解析.生成端在吗()
        说("  生成端：%s %s" % ("✅" if 在 else "⚠️ ", 说明))
        if not 在:
            # 🔴 首次体检偶发超时（Q4_K_M/Q5_K_M 切换后冷启动、服务刚起时的竞争）。
            #    再给一次更宽的窗口 —— 但**重试要留痕**：把第一次的原因也打出来，
            #    否则「重试成功」和「一直不可达」在日志里同形（§9.5）。
            说("  首次体检失败（%s），10 秒后用 20 秒窗口重试……" % 说明)
            time.sleep(10)
            在, 二次说明 = 意图解析.生成端在吗(超时=20)
            if 在:
                说("  ✅ 重试成功（首次失败原因：%s）" % 说明)
            说明 = 二次说明
        if not 在:
            服务器.shutdown()
            # 🔴 文案里的地址必须取自**实际配置**，不能写死 8000 ——
            #    写死的话，指着 18000 失败时报告会说「8000 不可达」，把人往错方向带。
            说("🔴 生成端 %s 不可达，盲测无法进行：%s" % (意图解析.生成服务, 说明))
            return 1

        # 🔴 「模型是谁」要**让引擎自报**，不能拿调用方填的常量当实测值
        #    （§9.5 第五类错误）。微调前后对照会把 CHATBI_GEN_URL 指到自建推理壳上，
        #    这时写死的「Spark-X2.5-4B-Q6_K」就是假的，而报告本身看不出来。
        引擎自报 = 意图解析.生成端自报家门()
        if 引擎自报:
            说("  引擎自报模型：%s%s" % (引擎自报, "" if 引擎自报 == 意图解析.模型名
                                     else " ⚠️ **与调用方声明的「%s」不一致 → 报告按自报值写**"
                                          % 意图解析.模型名))
        else:
            说("  ⚠️ 引擎未自报模型名（`/v1/models` 取不到）—— 报告写调用方声明值"
               "「%s」并标明「引擎未自报」" % 意图解析.模型名)

        # 🔴 先证明「评测身份不受限」再跑题 —— 带着受限的身份跑，数字和谁都不能比。
        全权, 全权说明 = 确认全权(基址)
        说("  评测身份：%s %s" % ("✅" if 全权 else "🔴", 全权说明))
        if not 全权:
            服务器.shutdown()
            说("🔴 评测身份不是全权 —— 行级 / 脱敏会把它自己的行为记到模型头上，中止。"
               "（详见本脚本 顶部 `评测角色` 那段）")
            return 1

        方向 = 方向词(定义)
        记录表 = []
        中断说明 = ""
        全部 = 题目 + 附加题
        主尺题数 = len(题目)
        try:
            for i, 题 in enumerate(全部, 1):
                # 主尺被中断 → 附加题也不跑（跑一半的对照没有意义，还会多占一次生成端）
                if i > 主尺题数 and 中断说明:
                    break
                if i > 1 and (i - 1) % 每批题数 == 0:
                    好, 说0 = 意图解析.生成端在吗()
                    if not 好:
                        中断说明 = "第 %d 题前生成端失联：%s" % (i, 说0)
                        说("  ⚠️  %s —— 中止，已跑部分照实记录" % 中断说明)
                        break
                    说("  ── 批间探活 ✅（第 %d 题前）" % i)
                记 = 判一题(基址, 题, 连接, 基准缓存, 方向)
                记录表.append(记)
                标 = {"通过": "✅", "失败": "🔴"}[记["结果"]]
                说(" %2d/%d  %s %-5s [%-4s]%s %s" % (i, len(全部), 标, 记["编号"],
                                                 记["类"],
                                                 " ★对照" if 题.get("对照") else "",
                                                 题["问题"][:32]))
                说("          %s" % ((记.get("分类") or "") + " " + (记.get("说明") or ""))[:96])
                if 记["结果"] == "失败" and 记.get("意图"):
                    说("          归一意图：%s" % json.dumps(记["意图"], ensure_ascii=False)[:110])
                # 🔴 请求异常 = 生成端很可能已失联（slot 没归还）。**当场探活、当场止损**，
                #   否则要等到下一个批边界才发现 —— 中间白跑一整批（实测：一题 180 s 超时后，
                #   接着发的请求全都在排队等锁，等于把等待时间乘上批大小）。
                if 记.get("分类") == "请求异常":
                    好, 说0 = 意图解析.生成端在吗()
                    if not 好:
                        中断说明 = "第 %d 题（%s）请求异常后探活失败：%s" % (i, 记["编号"], 说0)
                        说("  ⚠️  %s —— 中止，已跑部分照实记录" % 中断说明)
                        break
        finally:
            服务器.shutdown()
            try:
                服务器.server_close()
            except Exception:                                    # noqa: BLE001
                pass
    finally:
        连接.close()

    # 🔴 **主尺与附加对照必须分开汇总** —— 分母不同就不能混着平均。
    #    主尺 = 40 题（历史基线，v1~v8 都按它算）；附加 = 本题集（结论单独一节）。
    主尺记录 = [r for r in 记录表 if not r.get("对照")]
    附加记录 = [r for r in 记录表 if r.get("对照")]

    # 🔴 逐题核一遍「这题到底调没调模型」（2026-10-15 夜新增）。
    #    上面那道闸门看的是**起跑时**的开关；这里看的是**实际发生的事**——
    #    两者都要，因为「开关开着但没人读」和「开关关了」在日志里长得一样。
    #    判据：`意图缓存` 字段只能是「已关闭」/「未命中…」；出现「命中」= 这题的数字
    #    来自历史某一轮的模型（很可能是别的模型），与「模型很差」同形。
    #
    # 🔴 2026-10-17 修：原来写的是 `"命中" in str(...)` —— **反向包含**。
    #    「未命中·本次未缓存（方向兜底）」里就有「命中」两个字，于是**每一道走
    #    方向兜底的题都被误报成「命中缓存」**，整轮被当成作废（T29/T48/T54 那次）。
    #    这正是「子串匹配必须防反向包含」的同一条教训：判「是不是命中」要**精确
    #    相等**，不能问「里面有没有这两个字」。
    命中题 = [r["编号"] for r in 主尺记录 + 附加记录
              if str(r.get("意图缓存") or "").strip() == "命中"]
    if 命中题:
        说()
        说("🔴 有 %d 题命中语义缓存（%s）—— 这些题的数字不是本轮模型算的。"
           % (len(命中题), "、".join(命中题[:10])))
        说("   按「环境不是自己造的，验证就没有意义」处置：**本轮作废**，别写进报告。")
        return 1

    按类, 统计 = 汇总(主尺记录)
    附按类, 附统计 = 汇总(附加记录) if 附加记录 else (None, None)
    对照 = None if 参数.跳过对照 else 读50题对照()

    说()
    说("=" * 74)
    说("分类别（分母 = 该类全部题数，不可执行题不剔除）")
    说("=" * 74)
    说("%-8s %-6s %-6s %-8s %s" % ("类", "题数", "通过", "通过率", "主要失败形态"))
    for 类, 汇 in 按类.items():
        形 = "、".join("%s×%d" % (k, v) for k, v in
                      sorted(汇["失败形态"].items(), key=lambda x: -x[1])[:3]) or "—"
        说("%-8s %-6d %-6d %-8s %s" % (类, 汇["题数"], 汇["通过"], "%.0f%%" % 汇["通过率"], 形))
    说()
    说("执行准确率（结果集口径）：%s%%（%d/%d）"
        % (统计["结果集题"].get("执行准确率"), 统计["结果集题"]["通过"], 统计["结果集题"]["题数"]))
    说("处置准确率：%s%%（%d/%d）"
        % (统计["处置题"].get("处置准确率"), 统计["处置题"]["通过"], 统计["处置题"]["题数"]))
    说("安全澄清 %d ｜ **硬答（该澄清却给 SQL）%d**"
        % (统计["安全澄清（错别字题给了澄清而非硬答）"], 统计["硬答（该澄清却给出 SQL）"]))
    if 对照:
        c = 对照.get("统计", {}).get("结果集题", {})
        说("对照 50 题集：%s%%（%s/%s）｜ 盲测：%s%%"
           % (c.get("执行准确率"), c.get("通过"), c.get("题数"),
              统计["结果集题"].get("执行准确率")))
    if 附加记录:
        结附 = (附统计 or {}).get("结果集题", {})
        说()
        说("=" * 74)
        说("附加对照题（★ **不进上面的分母** —— 主尺 40 题一字未动）")
        说("=" * 74)
        for r in 附加记录:
            说("  %s %-5s %s" % ("✅" if r["结果"] == "通过" else "🔴", r["编号"], r["问题"]))
            说("        %s" % ((r.get("分类") or "") + " " + (r.get("说明") or ""))[:96])
            if r.get("意图"):
                说("        意图：%s" % json.dumps(r["意图"], ensure_ascii=False)[:110])
        说("  对照结果集口径：%s/%s ｜ **这一节只回答「同语义说全能不能过」，"
           "不并入执行准确率**" % (结附.get("通过"), 结附.get("题数")))
    应跑 = (sum(1 for t in 题目 if t.get("判据") == "结果集"),
            sum(1 for t in 题目 if t.get("判据") == "处置"))
    用时总 = sum(r.get("耗时秒") or 0 for r in 记录表)
    说("总用时 %.1f s，平均 %.1f s/题" % (用时总, 用时总 / max(len(记录表), 1)))
    异常数 = sum(1 for r in 记录表 if r.get("分类") == "请求异常")
    if 异常数:
        说("⚠️  其中 %d 条请求异常（耗时已计入总用时 —— 别再把它们当 0）" % 异常数)
    if 中断说明:
        说("🔴 **本次未跑完**：已跑 %d / 应跑 %d 题 —— 上面的百分比分母是「已跑」，"
           "与跑满的轮次不可直接比" % (len(主尺记录), 应跑[0] + 应跑[1]))
        说("   中断原因：%s" % 中断说明)

    模型显示 = (引擎自报 or "%s（**调用方声明**，引擎未自报）" % 意图解析.模型名)
    写报告(题集, 主尺记录, 按类, 统计, 对照, 报告路径,
          指纹=提示词指纹, 实跑=len(题目), 应跑=应跑, 中断说明=中断说明,
          附记录=附加记录, 附统计=附统计, 模型显示=模型显示,
          题集名=参数.题集)
    输出 = {
        "生成时间": time.strftime("%Y-%m-%d %H:%M:%S"),
        # 🔴 模型名优先用**引擎自报**值；取不到才退回声明值并标明（不静默用常量）。
        "模型": 模型显示,
        "引擎自报": 引擎自报,
        "调用方声明模型": 意图解析.模型名,
        "提示词模式": ("精简(CHATBI_LEAN_PROMPT=1)" if os.environ.get("CHATBI_LEAN_PROMPT")
                   else "完整"),
        "题集": 题集["版本"],
        "题数": len(题目),
        "提示词指纹": 提示词指纹,
        "指纹算法": 意图缓存.指纹算法,
        "解析规则版本": 意图缓存.解析规则版本,
        "标注": 参数.标注,
        "统计": 统计,
        "按类": 按类,
        "50题对照": (对照 or {}).get("统计", {}).get("结果集题") if 对照 else None,
        "记录": 主尺记录,
        "附加对照": {
            "题集": (附加集["版本"] if 附加题 else None),
            "统计": 附统计,
            "记录": 附加记录,
        },
    }
    with open(结果路径, "w", encoding="utf-8") as 句柄:
        json.dump(输出, 句柄, ensure_ascii=False, indent=2)
    说()
    说("结果：%s" % 结果路径)
    说("报告：%s" % 报告路径)
    说("提示词指纹：%s（换提示词 → 指纹变 → 两轮不可比）" % 提示词指纹)
    _落日志()
    # 退出码分三态 —— **「未跑完」必须与「跑完但有题没过」分得开**：
    #   0 = 全对 ｜ 1 = 跑完但有题没过（**正常结果，不是故障**）｜ 3 = 未跑完
    # 实测教训（v6 / v7 各踩一次）：以前只有 0/1，于是「91.3% 跑满 40/40」与
    # 「脚本崩了」在任务状态里**同形**，每次都得翻日志才能确认到底跑没跑完。
    if 中断说明:
        说("退出码 3 = **未跑完**（已跑 %d / 应跑 %d）—— 不是「有题没过」"
           % (len(主尺记录), 应跑[0] + 应跑[1]))
        return 3
    全对 = (统计["结果集题"]["通过"] == 统计["结果集题"]["题数"]
            and 统计["处置题"]["通过"] == 统计["处置题"]["题数"])
    说("退出码 %d = %s" % (0 if 全对 else 1,
                          "全对" if 全对 else "跑完但有题没过（正常结果，不是故障）"))
    return 0 if 全对 else 1


def _选端口():
    """自动找一个空闲端口 —— 避免和正在跑的 8095 撞（撞了会「连到旧实例」，测出的数字是旧的）。"""
    import socket
    s = socket.socket()
    s.bind(("127.0.0.1", 0))
    口 = s.getsockname()[1]
    s.close()
    return 口


def _落日志():
    目录 = os.path.join(项目目录, "logs")
    os.makedirs(目录, exist_ok=True)
    路径 = os.path.join(目录, "评测-盲测集.log")
    with open(路径, "w", encoding="utf-8") as 句柄:
        句柄.write("\n".join(日志行) + "\n")
    print("日志已写入 %s" % 路径)


