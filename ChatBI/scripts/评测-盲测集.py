def 判一题(基址, 题, 连接, 基准缓存, 方向词):
    编号, 判据, 类 = 题["编号"], 题.get("判据"), 题.get("类")
    # 🔴 `对照` 标记 = 这道题来自**附加题集**，**不进主尺分母**。
    #    主尺（40 题）是历史基线，改它 = v1~v8 全部断代；附加题只做「同语义换个说法」
    #    的存在性验证，结论单独成节 —— 分母不同就不能混着平均。
    #    分布外/多问法题集没有「档」字段（它们不按 A~D 分档，只有类）——
    #    用 .get 兜成 "-"；判据处置分支的 `题["期望处置"]` 保持硬取：
    #    处置题没有期望处置 = 题集作者写错了，要炸就炸在造数时，别静默。
    记 = {"编号": 编号, "档": 题.get("档", "-"), "类": 类, "判据": 判据, "问题": 题["问题"],
          "对照": bool(题.get("对照"))}
    起 = time.time()
    try:
        应 = 请求(基址, "/ask", {"问题": 题["问题"], "执行": True,
                                "角色": 评测角色})
    except Exception as 错:                                      # noqa: BLE001
        记.update({"结果": "失败", "分类": "请求异常",
                   "说明": "%s: %s" % (type(错).__name__, str(错)[:110]),
                   # 🔴 异常题**也要记耗时**：不记的话 `总用时` 会把它静默当 0。
                   #   实测（2026-10-14）：某题 180 s 请求超时被漏掉，报告写「总用时 42.1 s」，
                   #   看着像跑得很快 —— 其实那一刻生成端已经卡死了（slot 没归还）。
                   "耗时秒": round(time.time() - 起, 2)})
        return 记
    记["类型"] = 应.get("类型")
    记["SQL"] = 应.get("SQL")
    记["耗时秒"] = round(time.time() - 起, 2)
    记["解读"] = 应.get("解读")
    记["模型用时"] = (应.get("耗时") or {}).get("意图")
    # 🔴 缓存态逐题留证（2026-10-15 夜）：`模型用时=0` 有好几个来源
    #    （拒答/元问题/跨指标本来就**不调模型**，那是对的；缓存命中则是**错的**），
    #    只看耗时数字分不出这两者 —— 必须记下服务端自报的缓存态本身。
    记["意图缓存"] = 应.get("意图缓存")

    # ---- 处置题 ----
    if 判据 == "处置":
        期望 = 题["期望处置"]
        实测 = 应.get("类型")
        if 实测 != 期望:
            记.update({"结果": "失败", "分类": "%s→%s" % (期望, 实测),
                       "说明": "期望 %s，实测 %s" % (期望, 实测)})
            if 实测 == "SQL":
                记["分类"] = "该%s却硬答" % 期望
                记["说明"] = ("给出了可执行 SQL —— 硬答：%s"
                              % (应.get("SQL") or "").replace("\n", " ")[:110])
            return 记
        if 期望 == "澄清":
            文本 = 应.get("澄清") or ""
            有方向 = any(w in 文本 for w in 方向词)
            记["澄清文本"] = 文本
            记["反问已补方向"] = bool(应.get("反问已补方向"))
            if not 有方向:
                记.update({"结果": "失败", "分类": "澄清无方向",
                           "说明": "反问没给出可选方向，用户下一步只能随机猜：%s"
                                   % 文本[:90]})
                return 记
            # 🔴 **三档，不是两档**（2026-10-15 深夜补）。
            #    原实现只有「模型自发 / 系统兜底补」，于是**跨指标规则前置**产生的澄清
            #    被记成了「模型自发」。实测（`对照-跨指标-开` 那一轮）：
            #    T25/T26/T27/T28/T30 五题的 `模型用时 = None` —— **压根没调模型**，
            #    是 `跨指标.py` 拦下后直接给的定向澄清，报告却写成模型自己会说。
            #    后果有两层：① 报告在**替模型记功**；② 一臂开一臂关的 A/B 差异
            #    被标签抹平（两轮都是「模型自发」，看着毫无区别）。
            #    与「把调用方填的标签当引擎实测值」同族：**标签分不出，就等于没测**。
            #    口径收进 `评测口径.py` 一份（原来抄在两个评测脚本里，属「同一判据
            #    两处实现」）；判据只认服务端自报字段，不看耗时猜。
            码, 文 = 评测口径.澄清来源(应)
            记["澄清来源"] = 码
            记.update({"结果": "通过", "说明": "澄清并给出方向%s" % 文})
            return 记
        记.update({"结果": "通过", "说明": "处置正确：%s" % 期望})
        if 期望 == "拒答":
            记["拒答文本"] = 应.get("拒答")
            记["命中主题"] = 应.get("命中主题")
        return 记

    # ---- 结果集题（含「结果集或澄清」）----
    if 应.get("类型") != "SQL":
        实测 = 应.get("类型")
        if 判据 == "结果集或澄清" and 实测 == "澄清":
            # 错别字题：澄清 = 安全行为，算通过。**但要看它是真澄清还是蒙的** ——
            # 记下文本，人复核时能看到它到底说了什么。
            记.update({"结果": "通过", "分类": "安全澄清",
                       "说明": "给了澄清而非硬答（错别字题允许）：%s"
                               % (应.get("澄清") or "")[:80]})
            return 记
        类 = {"拒答": "误拒（能答却拒）", "元问题": "误判元问题",
              "澄清": "未答出（澄清）", "拒绝": "护栏拒绝", "错误": "服务错误"}.get(
            实测, "未答出（%s）" % 实测)
        记.update({"结果": "失败", "分类": 类,
                   "说明": (应.get("澄清") or 应.get("拒答") or 应.get("错误")
                            or 应.get("拒绝") or "")[:120]})
        return 记

    if 编号 not in 基准缓存:
        基准缓存[编号] = (lambda d: (d["列"], d["行"]))(护栏.执行(连接, 题["标准SQL"]))
    好, 分类, 说明 = 比结果(基准缓存[编号], (应.get("列") or [], 应.get("行") or []))
    记["行数"] = 应.get("行数")
    记["基准行数"] = len(基准缓存[编号][1])
    记["系统说明"] = 应.get("说明") or []
    记["归一提示"] = 应.get("提示") or []
    记["意图"] = 应.get("意图")
    if 好:
        记.update({"结果": "通过", "说明": 说明})
    else:
        记.update({"结果": "失败", "分类": 分类, "说明": 说明})
    return 记


def 方向词(定义):
    """反问方向词，从 YAML 取 —— 不手抄（手抄的必然过期且不报错）。"""
    规 = 定义["拒答与澄清"].get("反问兜底") or {}
    出 = []
    for d in (规.get("方向") or []):
        出 += [x.strip() for x in str(d).split("/") if x.strip()]
    return 出


