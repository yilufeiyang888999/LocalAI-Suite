# ============================ 结果比对 ============================

def 值键(值):
    """一行里的一个单元格压成可比较的字符串。浮点保留 2 位（等价容差 0.005）。"""
    if 值 is None:
        return "None"
    if isinstance(值, bool):
        return "1" if 值 else "0"
    if isinstance(值, (int, float)):
        return "%.2f" % float(值)
    return str(值).strip()


def 行集合(行):
    return sorted(tuple(值键(x) for x in r) for r in 行)


def 投影到(基准列, 实列, 实行):
    """把实测结果投影到基准列上。返回 (投影后行, 错误说明)。

    🔴 这里是「列超集容忍」的实现点：实测多带的列直接忽略，缺列才算错。
       为什么不能要求列完全相同：语义层渲染的列由定义决定（如 M3 会多带
       「库存合计 / 安全库存」让业务能自己复核），比手写基准 SQL 多列是**设计意图**。
       反之要求「列数相等」会把这种刻意的可核对性判成失败。
    """
    位置 = []
    for 列 in 基准列:
        if 列 not in 实列:
            return None, "缺列「%s」（实测列：%s）" % (列, "、".join(str(x) for x in 实列))
        位置.append(实列.index(列))
    return [tuple(r[i] for i in 位置) for r in 实行], None


def 比结果(基准, 实测):
    """基准/实测 = (列名, 行列表)。返回 (是否一致, 分类, 说明)。"""
    if 基准 is None:
        return None, "无基准", ""
    基列, 基行 = 基准
    实列, 实行 = 实测
    投影, 错 = 投影到(基列, 实列, 实行)
    if 错:
        return False, "缺列", 错
    if len(投影) != len(基行):
        return False, "行数不符", "实测 %d 行 vs 基准 %d 行（列 %s）" % (
            len(投影), len(基行), "、".join(str(x) for x in 基列))
    if 行集合(投影) != 行集合(基行):
        差 = []
        for a, b in zip(行集合(投影), 行集合(基行)):
            if a != b:
                差.append("实测 %s ≠ 基准 %s" % ("(" + ", ".join(a) + ")",
                                                "(" + ", ".join(b) + ")"))
            if len(差) >= 2:
                break
        return False, "口径错", "行数相同但取值不同 ｜ " + " ｜ ".join(差)
    return True, "通过", "%d 行 × %d 列 逐格一致" % (len(基行), len(基列))


