def 离线对账(题集, 题目, 连接, 定义):
    """题集 + 定义 + 渲染器 三者自洽性。不调模型。"""
    说("=" * 74)
    说("① 离线对账（不调模型）：期望意图 → 渲染 → 与标准 SQL 结果比对")
    说("=" * 74)
    记录 = []
    通过 = 失败 = 跳过 = 0

    基准缓存 = {}
    for 题 in 题目:
        编号 = 题["编号"]
        期望处置 = 题.get("期望处置")

        # ---- D 档：拒答 / 元问题 是确定性的，可以离线判；澄清需要模型 ----
        if 期望处置 in ("拒答", "元问题"):
            判定 = 拒答.判定(定义, 题["问题"], 连接)
            期望映射 = {"拒答": "拒答", "元问题": "元问题"}
            好 = 判定["处置"] == 期望映射[期望处置]
            记录.append({"编号": 编号, "期望处置": 期望处置,
                         "实测处置": 判定["处置"], "通过": 好})
            if 好:
                通过 += 1
                说("  ✅ %-5s 处置=%-4s（确定性，不调模型）" % (编号, 判定["处置"]))
            else:
                失败 += 1
                说("  🔴 %-5s 期望 %s，实测 %s" % (编号, 期望处置, 判定["处置"]))
            continue
        if 期望处置 == "澄清":
            跳过 += 1
            说("  ⏭  %-5s 澄清类需模型，离线不判" % 编号)
            continue

        # ---- A/B/C 档：期望意图 → 渲染 + 执行 ----
        意图 = 题.get("期望意图")
        if not 意图:
            跳过 += 1
            说("  ⏭  %-5s 题集没给期望意图" % 编号)
            continue
        try:
            渲染 = 语义.渲染(定义, 意图)
            SQL = 渲染["SQL"]
            通, 原因 = 护栏.检查(SQL, 已知表=护栏.读表名(连接))
            if not 通:
                raise RuntimeError("护栏拒绝：%s" % 原因)
            实测 = (lambda d: (d["列"], d["行"]))(护栏.执行(连接, SQL))
        except Exception as 错:                                  # noqa: BLE001
            失败 += 1
            记录.append({"编号": 编号, "通过": False,
                         "错误": "%s: %s" % (type(错).__name__, 错), "SQL": None})
            说("  🔴 %-5s 渲染/执行失败：%s: %s" % (编号, type(错).__name__, str(错)[:70]))
            continue

        if 编号 not in 基准缓存:
            基准缓存[编号] = (lambda d: (d["列"], d["行"]))(
                护栏.执行(连接, 题["标准SQL"]))
        好, 分类, 说明 = 比结果(基准缓存[编号], 实测)
        记录.append({"编号": 编号, "通过": 好, "分类": 分类, "说明": 说明, "SQL": SQL})
        if 好:
            通过 += 1
            说("  ✅ %-5s %s" % (编号, 说明))
        else:
            失败 += 1
            说("  🔴 %-5s [%s] %s" % (编号, 分类, 说明))
            说("        期望意图：%s" % json.dumps(意图, ensure_ascii=False))
            说("        渲染 SQL：%s" % SQL.replace("\n", " ")[:150])

    说()
    说("  离线对账：通过 %d ｜ 失败 %d ｜ 跳过 %d（澄清类需模型）" % (通过, 失败, 跳过))
    return 记录, 通过, 失败, 跳过


