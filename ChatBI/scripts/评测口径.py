# -*- coding: utf-8 -*-
"""评测口径：**跨评测脚本共享的判据口径**（纯函数，不依赖模型 / 网络 / 数据库）。

为什么要有这个文件
------------------
2026-10-15 深夜补跑 #11 的 40 题 A/B 时抓到一处**替模型记功**的判据 bug：

    「澄清给没给方向」这一档原来只有两档 —— `（模型自发）` / `（系统兜底补）`。
    而跨指标前置规则（`跨指标.py`）产生的定向澄清**既不进模型、也不走 `拒答.反问补强`**，
    于是它落进了「模型自发」那一档。实测物证（`对照-跨指标-开` 那一轮）：
    T25/T26/T27/T28/T30 五题的 `模型用时 = None`（**压根没调模型**），
    报告却写着「模型自己会说」；更糟的是**一臂开一臂关的 A/B 差异被标签抹平** ——
    两轮都显示「模型自发」，看着毫无区别。

同族坑：「把调用方填的标签当引擎实测值」「判据可能把错钉成期望行为」。
⇒ 档位必须以**服务端自报的字段**为准（`跨指标` / `反问已补方向`），不看耗时猜。

🔴 而这段逻辑原本**抄在两份评测脚本里**（`评测-盲测集.py`、`评测-链路准确率.py`）——
    「同一判据两处实现」正是本项目记过的坑（改一处不报错、只给错报告）。
    所以收成这里一份，两边都 import 它。

自测（不加载模型、不连服务）：
    python 评测口径.py --自测
"""

澄清来源档 = ("跨指标规则前置", "系统兜底补", "模型自发")


def 澄清来源(应):
    """应答 dict → (机器码, 展示文本)。**判据只认服务端自报字段。**

    `应` 是 `/ask` 回来的整份应答（或任何带这些键的 dict）：
      · `跨指标`        —— 跨指标前置规则拦下的（值是命中的指标名列表；空列表 = 没拦）
      · `反问已补方向`  —— 走了 `拒答.反问补强()` 补的方向
    两个都没有 = 模型自己给的。
    """
    应 = 应 or {}
    if 应.get("跨指标"):
        return "跨指标规则前置", "（**跨指标规则前置**，未进模型）"
    if 应.get("反问已补方向"):
        return "系统兜底补", "（系统兜底补）"
    return "模型自发", "（模型自发）"


def 自测():
    """四条用例。🔴 第 3 条是**反例**：跨指标规则与补方向标志同时为真时，
    必须以**跨指标规则前置**为准 —— 那种组合正常不会出现（规则路径不经过反问补强），
    但优先级必须钉死，否则哪天两条路接上了，档位会静默错报。"""
    用例 = [
        # (名字, 应答, 期望机器码, 期望文本必须含)
        ("① 规则前置（未进模型）", {"跨指标": ["来料不良率", "准时交付率"]},
         "跨指标规则前置", ["跨指标规则前置", "未进模型"]),
        ("② 系统兜底补", {"反问已补方向": True}, "系统兜底补", ["系统兜底补"]),
        ("③ 反例：两个标志同时为真 → 规则优先",
         {"跨指标": ["A", "B"], "反问已补方向": True}, "跨指标规则前置", ["跨指标规则前置"]),
        ("④ 模型自发（什么都没标）", {}, "模型自发", ["模型自发"]),
        ("⑤ 反例：跨指标是**空列表** = 没拦，不能算规则前置",
         {"跨指标": []}, "模型自发", ["模型自发"]),
    ]
    坏 = 0
    for 名, 应, 期望码, 必含 in 用例:
        码, 文 = 澄清来源(应)
        好 = (码 == 期望码) and all(s in 文 for s in 必含)
        print("  %s %-38s → %-14s %s" % ("✅" if 好 else "🔴", 名, 码, 文))
        if not 好:
            坏 += 1
            print("      期望 %s，文本必须含 %s" % (期望码, 必含))
    print("\n  自测：%d/%d 通过" % (len(用例) - 坏, len(用例)))
    return 0 if 坏 == 0 else 1


if __name__ == "__main__":
    import argparse
    参 = argparse.ArgumentParser(description="评测口径纯函数")
    参.add_argument("--自测", action="store_true")
    参 = 参.parse_args()
    if 参.自测:
        raise SystemExit(自测())
    print("档位定义：%s" % " / ".join(澄清来源档))
    print("用法：import 评测口径 → 评测口径.澄清来源(应)")
