# -*- coding: utf-8 -*-
"""ChatBI · 跨指标前置规则（报告第七节 #11）

问句里**同时出现两个不同指标**（名称或别名）→ **直接澄清，不进模型**。

🔴 为什么这条必须由纯规则做（有实测依据，不是设计洁癖）：
   40 题盲测 A 类「硬答」4 题里有 3 题（T25/T26/T30）是**跨指标**问法。最有信息量的是 T25：
     问「各供应商的不良率和准时交付率分别是多少？」
     模型输出 `{"指标": ["来料不良率","准时交付率"], "基础查询": "计数", "目标": "供应商"}`
     → 渲染成 `SELECT COUNT(*) AS 供应商数 FROM 供应商`
   **两个指标它识别得明明白白**，却顺手给了一个「能跑的结构」——
   宁可答非所问，也不说「我一次只能答一个」。
   三轮微调实测（v1 199 条 / v2 223 条 / v3 统一格式）：硬答**始终是 4 题**，
   加同族样本、把输出格式写整齐都压不动。这是**输出策略**问题，不是识别能力问题。
   而「两个指标词共现」是**字面可判**的 —— 把它交给模型，等于用 26 分钟 GPU
   去买一个字符串匹配能做的事，而且实测买不到。
   → 落到既有架构里已经定好的那一层：**问句 → 前置判定（纯规则）→ 意图解析（模型）**
     （与 拒答.py 的元问题/拒答同层、同顺序纪律）。

🔴 澄清必须**定向**（这是本规则与 #7 那类 bug 的分界）：
   报告 #11 的原话 —— 现有澄清话术对跨指标**并不定向**：给的是「质量/交期/库存/工单/采购」
   这份**通用**五类清单，用户还得自己猜该挑哪个，而且它压根没说「一次只能答一个」。
   本规则的澄清直接说清「一次只按一个指标算」+ 把这句话里命中的指标**原样列出来**让用户挑。

设计纪律（沿用本项目既有铁律）：
  ① **词表不手抄** —— 从 YAML 的 `指标[*].名称 / 别名` 取。手抄的第二份必然过期，
     而过期**不报错**，只是静默漏判。
  ② **最长优先 + 区间不重叠** —— 别名之间互为子串（「交期达成率」⊃「达成率」），
     不按最长匹配就会把**一个**指标数成两个 → 正常单指标问句被误判成跨指标。
  ③ **按指标去重** —— 同一指标的名称与别名同时出现（「来料不良率」⊃「不良率」）
     是同一件事，不算跨指标。
  ④ **宁可漏判，不可误判** —— 漏判的后果是「照旧走模型」（最坏等于现在）；
     误判的后果是「能答的问题被变成答不出」，而用户无从察觉。

## A/B 开关

`CHATBI_NO_CROSS_METRIC=1` 关掉本规则。**只为「这条规则到底改了什么」的对照实验存在** ——
本项目铁律：一条规则的影响力必须能被单独测出来，而不是靠「机制说得通」。
⚠️ 关掉时 `判定()` 返回的 `说明` 会写明「已关闭」，**降级必须与通过可区分**。
⚠️ **别在常规跑批里设它** —— 那等于把规则静默摘掉，而产物文件名不会自己变。
"""

import os
import sys

if hasattr(sys.stdout, "reconfigure"):
    try:
        sys.stdout.reconfigure(errors="replace")
    except Exception:                                    # noqa: BLE001
        pass


_否 = ("", "0", "false", "no", "off", "关", "否", "none", "null")


def 关规则():
    """A/B 开关。**每次读环境变量**（与 `意图缓存.关缓存()` 同一理由：
    谁先 import 谁后设变量不该影响结果）。

    🔴 **不能只写 `bool(os.environ.get(...))`**（2026-10-15 深夜，当场抓到）：
    环境变量**永远是字符串**，而 `"0"` 是**真值** → `CHATBI_NO_CROSS_METRIC=0`
    会把规则**关掉**，设它的人却以为自己写的是「0 = 不关」。
    实测就是这么发生的：`跑对照.py` 写的是 `"1" if 参.无跨指标 else "0"`，
    本意「默认开、传参才关」→ 实际**两条臂都是关的**。起跑探针当场拦住（没跑出脏数字），
    但若不拦，A/B 会得到一组「这条规则没影响」的数字，**而且不报错**。
    同族的坑：`意图缓存.关缓存()` / `意图解析.关提示缓存` 用的也是 `bool(...)` 写法 ——
    往那儿写 `"0"` 同样会「把缓存关掉」。**规则：要「开」就 unset，别写 `"0"`。**
    """
    return str(os.environ.get("CHATBI_NO_CROSS_METRIC") or "").strip().lower() not in _否


# ---------------------------------------------------------------- 词表

def 载入规则(定义):
    return 定义["跨指标前置"]


def 指标词表(定义):
    """指标词 → [(词, 指标名)]（只收长度 ≥ 2 的词）。

    两个来源都在 YAML 里，**不手抄**：
      · `指标[*].名称`（如「来料不良率」）
      · `指标[*].别名`（如「不良率」「不合格率」「OTD」）
    """
    出 = []
    for 指 in 定义["指标"]:
        名 = 指["名称"]
        for w in [名] + list(指.get("别名") or []):
            w = str(w).strip()
            if len(w) >= 2:
                出.append((w, 名))
    return 出


def 命中指标(定义, 问题, 词表=None):
    """问句命中了哪些指标。返回 [(指标名, 命中的词, 起始位置), ...]，按起始位置排序。

    这是本模块的**核心**，两条规则缺一不可（都会咬人，而且咬错了不报错）：

    🔴 ① **最长优先 + 区间不重叠**：别名互为子串是常态 ——
       「交期达成率」是 M2 的别名，而「达成率」是 M4 的别名，
       两者在第 2~6 字符上重叠。若把命中的词都算一遍，一个 M2 的问句
       会被数成「M2 + M4」两个指标 → **误判成跨指标**（正是纪律 ④ 说的那种错）。
       做法：把所有出现位置按「词长降序」排，长的先占位，与已占位区间相交的丢弃。

    🔴 ② **按指标去重**：同一指标的名称与别名同时出现（「来料不良率」⊃「不良率」）
       是同一件事，不是两个指标。去重发生在**调用方**（判定），这里只保证区间不重叠。
    """
    占位 = []
    for 词, 名 in (词表 if 词表 is not None else 指标词表(定义)):
        起 = 问题.find(词)
        while 起 != -1:
            占位.append((起, 起 + len(词), 名, 词))
            起 = 问题.find(词, 起 + 1)
    # 长词先占位；同长时左边的先占（顺序不影响正确性，但要稳定，便于单测断言）
    占位.sort(key=lambda x: (-(x[1] - x[0]), x[0]))
    定 = []
    for 起, 止, 名, 词 in 占位:
        if any(not (止 <= a or 起 >= b) for a, b, _, _ in 定):
            continue
        定.append((起, 止, 名, 词))
    定.sort(key=lambda x: x[0])
    return [(名, 词, 起) for 起, 止, 名, 词 in 定]


def 判定(定义, 问题):
    """问句 → 是否跨指标 + 定向澄清文本。

    返回 {"跨指标": bool, "指标": [...按出现顺序去重的指标名...],
          "命中": [(指标名, 词, 位置)...], "文本": str|None, "说明": str|None}

    `文本` 直接作为应答的 `澄清` 字段用（**不经过 拒答.反问补强** —— 这段措辞本身
    已经是定向的，再加一份通用五类清单会把定向信息稀释掉）。
    """
    问题 = (问题 or "").strip()
    if 关规则():
        # 🔴 关掉时**必须留下痕迹** —— 否则「规则没触发」与「规则被摘掉」同形。
        return {"跨指标": False, "指标": [], "命中": [], "文本": None,
                "说明": "跨指标规则已按 CHATBI_NO_CROSS_METRIC **关闭**（A/B 对照用）"}
    规 = 载入规则(定义)
    阈值 = int(规.get("阈值") or 2)

    命中 = 命中指标(定义, 问题)
    指标, 提到 = [], []
    for 名, 词, _ in 命中:
        if 名 not in 指标:
            指标.append(名)
        if 词 not in 提到:
            提到.append(词)

    if len(指标) < 阈值:
        return {"跨指标": False, "指标": 指标, "命中": 命中, "文本": None, "说明": None}

    候选 = "\n".join((规.get("候选") or "· 只看「%s」") % x for x in 指标)
    文本 = (规.get("措辞") or "%s\n\n%s") % ("、".join("「%s」" % w for w in 提到), 候选)
    return {
        "跨指标": True, "指标": 指标, "命中": 命中,
        "文本": 文本.rstrip(),
        "说明": "这句话同时提到了 %d 个指标，我一次只按一个口径算 —— 已改为**先问清你说的是哪个**"
                % len(指标),
    }


# ---------------------------------------------------------------- CLI

def 主():
    import argparse

    import 语义层 as 语义
    参 = argparse.ArgumentParser(description="ChatBI 跨指标前置判定（不调模型）")
    参.add_argument("--问题", required=True)
    参.add_argument("--词表", action="store_true", help="打印指标词表就退出")
    参数 = 参.parse_args()

    定义 = 语义.载入()
    if 参数.词表:
        词 = 指标词表(定义)
        print("指标词表 %d 个（%d 个指标）：%s"
              % (len(词), len(定义["指标"]),
                 "、".join("%s→%s" % (w, n) for w, n in 词)))
        return 0

    应 = 判定(定义, 参数.问题)
    print("问题：%s" % 参数.问题)
    print("跨指标：%s" % ("是" if 应["跨指标"] else "否"))
    print("命中：%s" % ("、".join("%s（%s）" % (n, w) for n, w, _ in 应["命中"]) or "（无）"))
    if 应["文本"]:
        print()
        print(应["文本"])
    return 0


if __name__ == "__main__":
    sys.exit(主())
