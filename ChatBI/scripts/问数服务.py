"""ChatBI · 问数服务（包 2）· 端口 8095

链路：自然语言 → 前置判定（拒答/元问题/跨指标，**不调模型**）→ 意图解析（模型）
      → 语义层渲染 SQL → 只读护栏 → 执行 → 表格 + 口径说明

分层的意义（每一层都能单独解释自己）：
  · 先判「该不该答」，再问模型「怎么答」—— 反过来会让模型拿真实表回答库外主题
  · 模型只做「中文问句 → 槽位」，**不写 SQL、不碰口径**
  · 语义层把槽位**确定性**拼成 SQL（同一意图永远同一 SQL，可 diff、可单测）
  · 护栏不认来源只认语句（只读连接 + 白名单 + 超时）
  · 服务只做搬运与措辞 —— 口径错的三种典型（对手册的倒数第二行才算）在这里**没有发生的位置**
  · **字面可判的规则一律不进模型**（跨指标 ≥2 个指标词共现 → 直接澄清，见 跨指标.py）

路由：
  GET  /            问数页面
  GET  /health      状态（含 log_file / 反馈统计 / 会话统计 —— 缺了就是旧实例在跑）
  GET  /catalog     指标 / 维度 / 时间表达 / 可答范围 / 示例问题（页面用）
  POST /ask         {"问题":"...", "执行":true, "解读":true, "会话":"可选（A-1 多轮）"} —— 走模型
  POST /spec        {"意图": {...}, "执行": true}      —— 不走模型（调试 / 前端复算）
  POST /feedback    {"问题":..., "评价":"好评|差评", "纠正":"...", ...} —— A-3 反馈留痕
  POST /session     {"会话":"id"} 清空该会话（A-1；不传 = 全清）

应答的 `类型`（五种，语义互斥 —— 混着用就没有判据了）：
  SQL     有结果集
  澄清    能答但缺条件 / 问句有歧义 / 一次要了两个指标 → 用户补充后可继续
  拒答    主题超出本库范围 → 再补充也没用，必须告诉用户**本库能答什么**
  元问题  问「数据本身」（准不准 / 多新）→ 读元信息直接答，不调模型
  拒绝    护栏拒绝了这条语句（不该出现，出现即为 bug 信号）
  错误    异常（含模型不可达）

🔴 三个沿用作品一踩出来的纪律（不要重新发明）：
  1. **关键路径禁写控制台**：控制台被鼠标拖选会永久阻塞 → 服务「活着但不应答」。
     落盘在调用线程、上屏交后台线程，两者分开（作品一实测：同线程时文件也跟着不涨）。
  2. **HTTP 路由一律 ASCII**：`self.path` 是原始请求行，中文会被百分号编码 →
     比中文字面量永远不等 → 静默 404。
  3. `/health` 必须带 `log_file`：否则分不清「新代码没生效」和「功能没触发」。
"""

