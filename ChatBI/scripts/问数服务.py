class 容忍断连的服务器(ThreadingHTTPServer):
    """浏览器预连接 / 刷新 / 关标签页会让客户端半途走掉 —— 那是**正常现象**，
    默认却会打一整页 Traceback，看的人会认定服务崩了。
    只吞 ConnectionError 家族（真 bug 仍走父类完整堆栈），并计数暴露给 /health ——
    否则「扛住了断连」和「根本没触发断连」在控制台上长得一模一样。"""

    客户端断连次数 = 0
    已报过 = 0

    def handle_error(self, 请求, 客户端):
        错 = sys.exc_info()[1]
        if not isinstance(错, ConnectionError):
            return super().handle_error(请求, 客户端)
        类 = type(self)
        类.客户端断连次数 += 1
        if 类.已报过 < 3:
            类.已报过 += 1
            地址 = ("%s:%s" % 客户端[:2]) if isinstance(客户端, tuple) else str(客户端)
            日志("· 客户端提前断开（%s，来自 %s）—— 正常，服务不受影响"
                 % (type(错).__name__, 地址))


页面内容 = None                                          # 启动时读一次（避免被浏览器缓存坑）

# 页面要用到的第三方静态资源（本地落盘，不走 CDN —— 内网 / 断网都得能用）。
# **白名单式**：只认表里这几条精确路径，不做任何路径拼接 ——
# 拼接就等于把「谁能被读」交给请求方（`/vendor/../../etc/passwd`）。
静态资源 = {}


class 处理器(BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.1"                        # ASCII：约定属性名，中文会被忽略

    问数器实例 = None
    页面内容 = None
    静态资源 = {}                                        # 路径 → (字节, Content-Type)

    def log_message(self, 格式, *参数):                    # noqa: A003
        """默认实现直接写 stderr —— 请求线程不能碰控制台（模块头第 1 条）。"""
        日志("· %s %s" % (self.command, urllib.parse.unquote(self.path)))

    def _发跨域头(self):
        """Tauri webview 里前端是直接 fetch 本机服务的（与作品一同一模式），
        少了跨域头只会得到一个笼统的 CORS 失败，既看不到状态码也看不到响应体。"""
        self.send_header("Access-Control-Allow-Origin", "*")
        self.send_header("Access-Control-Allow-Methods", "GET, POST, OPTIONS")
        self.send_header("Access-Control-Allow-Headers", "Content-Type")

    def _发(self, 码, 对象):
        体 = json.dumps(对象, ensure_ascii=False, indent=2).encode("utf-8")
        self.send_response(码)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(体)))
        self._发跨域头()
        self.end_headers()
        self.wfile.write(体)

    def _发页面(self):
        if 处理器.页面内容 is None:
            self._发(503, {"error": "问数页面未就绪", "hint": "web/index.html 缺失或读取失败"})
            return
        体 = 处理器.页面内容.encode("utf-8")
        self.send_response(200)
        self.send_header("Content-Type", "text/html; charset=utf-8")
        self.send_header("Content-Length", str(len(体)))
        self.send_header("Cache-Control", "no-store")
        self._发跨域头()
        self.end_headers()
        self.wfile.write(体)

    def _发静态(self, 路径):
        """白名单命中才走这里；`路径` 必须是表里的原样键。"""
        体, 类型 = 处理器.静态资源[路径]
        self.send_response(200)
        self.send_header("Content-Type", 类型)
        self.send_header("Content-Length", str(len(体)))
        self.send_header("Cache-Control", "no-store")
        self._发跨域头()
        self.end_headers()
        self.wfile.write(体)

    def do_OPTIONS(self):                                # noqa: N802
        self.send_response(204)
        self._发跨域头()
        self.send_header("Content-Length", "0")
        self.end_headers()

    def do_GET(self):                                    # noqa: N802
        解 = urllib.parse.urlparse(self.path)
        路径 = urllib.parse.unquote(解.path)              # 中文别名兜底
        查询 = urllib.parse.parse_qs(解.query)
        if 路径 in ("/", "/index.html", "/问数页"):
            self._发页面()
            return
        if 路径 in 处理器.静态资源:
            self._发静态(路径)
            return
        if 路径 == "/favicon.ico":
            self.send_response(204)
            self._发跨域头()
            self.send_header("Content-Length", "0")
            self.end_headers()
            return
        if 路径 in ("/health", "/状态"):
            深入 = 查询.get("deep", ["0"])[0] not in ("0", "", "false")
            try:
                记 = 处理架().健康(深入=深入)
                记["端口"] = self.server.server_address[1]
                记["client_aborts"] = type(self.server).客户端断连次数
                self._发(200, 记)
            except Exception as 错:                        # noqa: BLE001
                self._发(500, {"error": str(错)})
            return
        if 路径 in ("/catalog", "/目录"):
            try:
                self._发(200, 处理架().目录())
            except Exception as 错:                        # noqa: BLE001
                self._发(500, {"error": str(错)})
            return
        self._发(404, {"error": "没有这个路径", "path": 解.path})

    def do_POST(self):                                   # noqa: N802
        路径 = urllib.parse.unquote(urllib.parse.urlparse(self.path).path)
        长 = int(self.headers.get("Content-Length") or 0)
        try:
            体 = json.loads(self.rfile.read(长).decode("utf-8")) if 长 else {}
        except (ValueError, UnicodeDecodeError) as 错:
            self._发(400, {"error": "请求体不是合法 JSON：%s" % 错})
            return
        架 = 处理架()
        只读 = bool(体.get("执行", True))
        上限 = int(体.get("上限") or 护栏.结果行数上限)
        # ---- B-4：身份 → 角色。**令牌优先于裸角色**（否则拿个低权限令牌就能提权）----
        身 = 身份.解析(令牌=(体.get("令牌") or self.headers.get("X-ChatBI-Token")),
                      裸角色=体.get("角色"))
        角色 = 身.get("角色")
        # 401 只在真正要用角色的两个入口上给 —— `/feedback` 没有角色也照样记
        # （反馈的价值在于内容，不在于谁提的）。
        def 要身份():
            if 角色 is not None:
                return True
            self._发(401, {"error": 身.get("错误") or "身份不可用",
                           "身份来源": 身.get("来源"),
                           "提示": "本地演示可以直接带上 {\"角色\":\"管理员\"}；"
                                   "生产请改用 令牌（scripts/身份.py --签 --角色 管理员）"})
            return False
        try:
            if 路径 in ("/feedback", "/反馈"):
                # A-3：用户反馈入口。**评价必须绑定它评价的那一问** ——
                # 只记一句「不对」的事后无法复现，也无法判断是模型错、语义层错
                # 还是题目本身有歧义。带上意图 / SQL / 类型，这条反馈才是可复算的案例。
                问题 = (体.get("问题") or "").strip()
                if not 问题:
                    self._发(400, {"error": "缺少「问题」—— 反馈必须绑定它评价的那一问"})
                    return
                评 = 反馈.归一评价(体.get("评价"))
                if 评 is None:
                    self._发(400, {"error": "「评价」只接受 好评/差评（或 ✅/❌ / 👍/👎 / good/bad）",
                                   "收到": 体.get("评价")})
                    return
                记 = 反馈.记({
                    "问题": 问题, "评价": 体.get("评价"),
                    "纠正": (体.get("纠正") or "").strip(),
                    "点评": (体.get("点评") or "").strip(),
                    "会话": 体.get("会话"), "角色": 体.get("角色"),
                    "类型": 体.get("类型"), "意图": 体.get("意图"),
                    "SQL": 体.get("SQL"), "行数": 体.get("行数"),
                })
                日志("反馈 %s：%s%s" % (评, 问题[:30],
                                     "（带纠正）" if 记.get("纠正") else ""))
                self._发(200, {"已记录": True, "评价归一": 评,
                               "文件": 反馈.文件(), "写失败": 记.get("_写失败")})
                return
            if 路径 in ("/session", "/会话"):
                # A-1：清会话。前端点「新对话」时调；不调也只是自然过期，不影响正确性。
                清 = 会话.清空(体.get("会话") or None)
                self._发(200, {"已清": 清, "统计": 会话.统计()})
                return
            if 路径 in ("/ask", "/问数"):
                if not 要身份():
                    return
                问题 = (体.get("问题") or "").strip()
                if not 问题:
                    self._发(400, {"error": "缺少「问题」"})
                    return
                会话id = (体.get("会话") or "").strip() or None
                起 = time.time()
                应 = 架.问数(问题, 执行=只读, 上限=上限,
                            要解读=bool(体.get("解读", True)),
                            会话id=会话id, 角色=角色)
                应["总耗时秒"] = round(time.time() - 起, 2)
                日志("问：%s  →  %s（%s，%s s）%s"
                     % (问题[:40], 应.get("类型"),
                        (应.get("口径") or 应.get("澄清") or "")[:36], 应["总耗时秒"],
                        "  [会话承接]" if (应.get("会话") or {}).get("已承接上一轮") else ""))
            elif 路径 in ("/spec", "/按意图"):
                if not 要身份():
                    return
                意图 = 体.get("意图")
                if not isinstance(意图, dict):
                    self._发(400, {"error": "缺少「意图」对象"})
                    return
                应 = 架.按意图(意图, 执行=只读, 上限=上限, 角色=角色)
                日志("按意图：%s  →  %s" % (json.dumps(意图, ensure_ascii=False)[:60],
                                           应.get("类型")))
            else:
                self._发(404, {"error": "没有这个路径"})
                return
            # B-4：身份来源**必须随应答返回** —— 不然「验过的身份」与「自称的身份」
            # 在结果里一模一样，而这两者的可信度完全不同。
            if isinstance(应, dict):
                应["身份"] = {"来源": 身.get("来源"), "角色": 角色,
                              "主体": 身.get("主体"), "要求令牌": 身份.强制令牌()}
            self._发(200, 应)
        except Exception as 错:                            # noqa: BLE001
            日志("🔴 请求异常：%s: %s" % (type(错).__name__, 错))
            self._发(500, {"error": "%s: %s" % (type(错).__name__, 错)})


def 处理架():
    """每请求一个问数器？不 —— 问数器本质无状态（连接按次建），共享一个即可。
    这里包一层是为了让「定义载入失败」变成 500 而不是把服务带崩。"""
    if 处理器.问数器实例 is None:
        处理器.问数器实例 = 问数器()
    return 处理器.问数器实例


