def 启动自检(架):
    日志("=" * 74, 加时间=False)
    日志("ChatBI 问数服务 v%s —— 自然语言 → 意图 → SQL → 只读执行" % 服务版本, 加时间=False)
    日志("=" * 74, 加时间=False)
    日志("数据源：%s" % 架.库)
    日志("口径定义：%s" % 语义.定义文件)
    坏 = 0
    try:
        连接 = 架.连接()
        try:
            表 = sorted(护栏.读表名(连接))
            日志("只读连接 ✅ %d 张表：%s" % (len(表), "、".join(表)))
        finally:
            连接.close()
    except Exception as 错:                                  # noqa: BLE001
        坏 += 1
        日志("🔴 数据库打开失败：%s: %s" % (type(错).__name__, 错))
    # 护栏自检：必拒 + 必放两侧都要过 —— 只测拒会把「一律拒绝」当成通过
    真表 = {"供应商", "物料", "采购订单", "到料检验", "库存", "生产工单"}
    例外 = []
    for 名, 语句 in 护栏.必拒:
        if 护栏.检查(语句, 已知表=真表)[0]:
            例外.append("应拒却放行：%s" % 名)
    for 名, 语句 in 护栏.必放:
        if not 护栏.检查(语句, 已知表=真表)[0]:
            例外.append("应放却拒绝：%s" % 名)
    if 例外:
        坏 += len(例外)
        for x in 例外:
            日志("🔴 %s" % x)
    else:
        日志("护栏自检 ✅ 必拒 %d 例 / 必放 %d 例" % (len(护栏.必拒), len(护栏.必放)))
    return 坏


def 主():
    参 = argparse.ArgumentParser(description="ChatBI 问数服务")
    参.add_argument("--端口", type=int, default=默认端口)
    参.add_argument("--主机", default="127.0.0.1")
    参.add_argument("--无上屏", action="store_true", help="只落盘，不往控制台打（后台跑用）")
    参数 = 参.parse_args()

    开日志文件()
    threading.Thread(target=(丢弃线程 if 参数.无上屏 else 上屏线程), daemon=True).start()

    架 = 问数器()

    页 = os.path.join(项目目录, "web", "index.html")
    if os.path.exists(页):
        try:
            with open(页, encoding="utf-8") as 句柄:
                处理器.页面内容 = 句柄.read()
        except OSError as 错:
            日志("🔴 问数页面读取失败：%s" % 错)
    else:
        日志("🔴 问数页面不存在：%s" % 页)

    # 页面依赖的本地静态资源：**启动时读进内存**（同页面一样，改完要重启才生效）。
    # 键是请求路径、值是磁盘文件与 Content-Type —— 请求方只能按原样键取，拼不出别的路径。
    静态表 = (
        ("/vendor/echarts.min.js", ("web", "vendor", "echarts.min.js"),
         "application/javascript; charset=utf-8"),
    )
    for 请求路径, 分段, 类型 in 静态表:
        全 = os.path.join(项目目录, *分段)
        if not os.path.exists(全):
            日志("⚠️  静态资源不存在：%s（页面上的图表会画不出来）" % 全)
            continue
        try:
            with open(全, "rb") as 句柄:
                处理器.静态资源[请求路径] = (句柄.read(), 类型)
        except OSError as 错:
            日志("🔴 静态资源读取失败：%s" % 错)
    if 处理器.静态资源:
        日志("静态资源 %d 个：%s" % (len(处理器.静态资源), "、".join(处理器.静态资源)))

    坏 = 启动自检(架)
    在, 说明 = 意图解析.生成端在吗()
    日志("生成端 %s（%s）：%s" % ("✅" if 在 else "⚠️ ", 意图解析.生成服务, 说明))
    if not 在:
        日志("   → 意图解析用不了，但 /spec 与护栏/渲染/执行链路仍可用")
    日志("页面：http://%s:%d/      目录：/catalog      状态：/health?deep=1"
         % (参数.主机, 参数.端口))

    服务器 = 容忍断连的服务器((参数.主机, 参数.端口), 处理器)
    服务器.daemon_threads = True
    try:
        服务器.serve_forever()
    except KeyboardInterrupt:
        日志("收到中断，退出")
    finally:
        服务器.server_close()
    return 1 if 坏 else 0


if __name__ == "__main__":
    sys.exit(主())
