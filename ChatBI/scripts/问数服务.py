# ---------------------------------------------------------------- 日志
# 见模块头第 1 条。落盘与上屏**不在同一根线程**：控制台被冻住时文件必须照常增长。
日志文件 = None
日志队列 = queue.Queue(maxsize=2000)
控制台丢弃数 = 0
日志写锁 = threading.Lock()


def 开日志文件():
    global 日志文件
    try:
        目录 = os.path.join(项目目录, "logs")
        os.makedirs(目录, exist_ok=True)
        日志文件 = os.path.join(目录, "问数-%s.log" % time.strftime("%Y%m%d"))
        return 日志文件
    except OSError:
        日志文件 = None
        return None


def _落盘(行0):
    if 日志文件 is None:
        return
    try:
        with 日志写锁:
            with open(日志文件, "a", encoding="utf-8") as 文:
                文.write(行0)
    except OSError:
        pass


def 上屏线程():
    """全进程**唯一**的控制台写者。被「拖选」冻住时只冻它自己。"""
    while True:
        行0 = 日志队列.get()
        if 行0 is None:
            return
        try:
            sys.stdout.write(行0)
            sys.stdout.flush()
        except Exception:                                # noqa: BLE001
            pass


def 丢弃线程():
    """`--无上屏` 时的替身：队列照常被消费，只是不往控制台写。
    少了它，队列会涨到 maxsize 之后开始计数丢弃 —— 计数会虚高，判据就失真了。"""
    while True:
        if 日志队列.get() is None:
            return


def 日志(内容, 加时间=True):
    global 控制台丢弃数
    行0 = ("  %s  %s\n" % (time.strftime("%H:%M:%S"), 内容)) if 加时间 else (内容 + "\n")
    _落盘(行0)
    try:
        日志队列.put_nowait(行0)
    except queue.Full:
        控制台丢弃数 += 1


# ---------------------------------------------------------------- 核心装配

class 问数器:
    """意图 → SQL → 结果。HTTP 层只搬运，逻辑全在这里（可脱离服务单测）。"""

    def __init__(self, 定义=None, 库=None):
        self.定义 = 定义 or 语义.载入()
        self.库 = 库 or 语义.库路径(self.定义)
        # A-1 用：指标名 → 别名表。判「本轮问句里有没有自己说出这个指标」时
        # 必须连别名一起认（用户写「不合格率」也是自己说了，不算系统替它承接）。
        # 唯一事实来源仍是 YAML 的 `别名`，这里只是摊平成字典，不另存一份。
        self.指标别名 = {x["名称"]: list(x.get("别名") or [])
                      for x in (self.定义.get("指标") or [])}

    # ---- 基础件 ----
    def 连接(self):
        return 护栏.连库(self.库)

    def 查实体(self, 连接, 字段, 值):
        """按「实体别名」映射查同名候选。字段不是实体名则返回 None（不检查）。"""
        实体 = self.定义["实体别名"]["实体"]
        目标 = next((v for v in 实体.values() if v["匹配字段"] == 字段), None)
        if not 目标:
            return None
        列 = 目标["匹配字段"]
        行 = 连接.execute(
            "SELECT DISTINCT %s FROM %s WHERE %s LIKE ?" % (列, 目标["表"], 列),
            ("%" + str(值) + "%",)).fetchall()
        return [r[0] for r in 行]

    def 疑似漏抽筛选(self, 连接, 问题, 意图):
        """问题里点名了库内的**实体名或枚举取值**，但意图里没有按它筛选 → 返回一句提示。

        为什么这件事**不能只靠模型**（实测踩到）：问「宁波恒力精密铸造的准时交付率」，
        模型给回 `{"指标":"准时交付率","过滤":[]}` —— 过滤条件整条丢了，
        于是答案从「这家企业」变成「**全公司** 88.4%」。数字依然像模像样，
        不报错、不犹豫，只有把问题和答案并排看才发现答的不是问的。
        这类错只能由确定性检查兜：库里的实体名和枚举取值就那么多，扫一遍很便宜。

        两类线索（第二类是包 4 评测补上的）：
          · 实体名（供应商 / 物料 / 仓库）：取前 4 字作简称比对问句
          · **枚举取值**（物料类别 / 供应商类别 / 检验判定 / 工单状态 / 订单状态）：
            整值比对 —— 实测 B28「五金件的不良率是多少？」模型把过滤整条丢了，
            而「五金件」不是实体名，第一类扫描抓不到它。

        **只提示、不阻断** —— 宁可多一句提醒，不可少答一次（见 scripts/拒答.py 纪律②）。
        """
        已筛 = " ".join(str(x.get("值") or "") for x in (意图.get("过滤") or []))
        已筛 += " " + " ".join(str(x) for x in (意图.get("维度") or []))
        线索 = []
        # ① 实体名（供应商 / 物料 / 仓库）
        for 规 in (self.定义["实体别名"]["实体"] or {}).values():
            列, 表 = 规["匹配字段"], 规["表"]
            try:
                名字 = [r[0] for r in 连接.execute(
                    "SELECT DISTINCT %s FROM %s" % (列, 表)).fetchall()]
            except Exception:                          # noqa: BLE001
                continue
            for 全名 in 名字:
                简称 = str(全名)[:4]
                if len(简称) >= 2 and 简称 in 问题 \
                        and 简称 not in 已筛 and str(全名) not in 已筛:
                    线索.append(str(全名))
        # ② 枚举取值（类别 / 判定 / 状态）—— 整值比对
        for 字段, 表 in (("物料类别", "物料"), ("供应商类别", "供应商"),
                        ("检验判定", "到料检验"), ("工单状态", "生产工单"),
                        ("订单状态", "采购订单")):
            try:
                取值 = [r[0] for r in 连接.execute(
                    "SELECT DISTINCT %s FROM %s" % (字段, 表)).fetchall()]
            except Exception:                          # noqa: BLE001
                continue
            for 值 in 取值:
                词 = str(值 or "").strip()
                if len(词) >= 2 and 词 in 问题 and 词 not in 已筛:
                    线索.append("%s=%s" % (字段, 词))
        if 线索:
            return ("⚠️ 问题里提到了「%s」，但这次查询**没有按它筛选** —— "
                    "这个结果把它的范围也一起算进去了。只想看它的话，请再问一次并点名。"
                    % "、".join(sorted(set(线索))[:3]))
        return None

    def 口径说明(self, 结果, 意图):
        """答案必须随附口径（定义里的「呈现」护栏）。指标类自带，其余在这里补。"""
        if 结果.get("口径"):
            return 结果["口径"]
        if 结果.get("类型") == "场景模板":
            场 = (self.定义["关联口径"].get("场景模板") or {}).get(意图.get("场景")) or {}
            return "场景模板「%s」：%s" % (意图.get("场景"), 场.get("用途", ""))
        基 = self.定义["基础查询"]
        目标 = 意图.get("目标")
        if 意图.get("基础查询") == "计数":
            规 = 基["计数"].get(目标) or {}
            return "统计 %s 的记录数" % 规.get("表", 目标)
        if 意图.get("基础查询") == "枚举":
            规 = 基["枚举字段"].get(目标) or {}
            return "列出 %s.%s 的全部取值" % (规.get("表", ""), 规.get("字段", ""))
        if 意图.get("基础查询") == "求和":
            return "对「%s」求和" % 目标
        命 = next((x for x in 基["分组聚合"] if x["名称"] == 目标), None)
        if 命:
            return "按 %s 分组，取 %s" % (命["分组字段"], 命["聚合"])
        return ""

    def 空结果说明(self, 连接, 意图):
        """定义里的硬要求：区分「实体不存在」与「条件无匹配」，措辞不同。
        两者在结果里长得一模一样（都是 0 行），混着说会把「名字打错」误导成「没数据」。"""
        模糊条 = [x for x in (意图.get("过滤") or []) if x.get("运算符") == "模糊"]
        for 条 in 模糊条:
            候选 = self.查实体(连接, 条["字段"], 条["值"])
            if 候选 is not None and not 候选:
                return ("库里没有名称含「%s」的%s —— 这不是「查不到数据」，"
                        "是这个名字不存在" % (条["值"], 条["字段"]))
        if 模糊条:
            return "名称本身是存在的，是这组筛选条件没有匹配到记录"
        return "该查询条件没有匹配到任何记录"

    # ---- 主流程 ----
    def 按意图(self, 意图, 执行=True, 上限=护栏.结果行数上限, 连接=None, 角色=None):
        """意图 → SQL → 结果。意图来自模型或前端，一律**重新校验**（不信任何上游）。

        `角色`（B-3）：决定敏感列脱敏。**`/ask` 与 `/spec` 都必须传** ——
        只堵一条路等于没堵（另一条能直接拿到原值）。
        """
        自建 = 连接 is None
        连接 = 连接 or self.连接()
        起 = time.time()
        try:
            # ---- B-5：行级限定。**必须在执行任何 SQL 之前** ----
            # 放在最前面还有一个理由：`查实体` 与 `疑似漏抽筛选` 用的都是这条连接，
            # 它们也会跟着受限 —— 否则「被隔离的供应商名」会从提示语里漏出去。
            #
            # ⚠️ `角色 is None` = **内部直调**（脚本 / 自检 / 单测直接 `按意图()`），
            #    与 `权限.检查` 的边界一致：不启用检查，但这条边界是显式的。
            #    HTTP 入口永远会解析出角色（最差是「默认角色」），所以外部走不到这里。
            if 角色 is not None:
                级 = 行级.应用(连接, 角色)
                if 级.get("阻断"):
                    # 遮蔽没能完全生效 → **不执行这条查询**。
                    # 「部分遮蔽」比「不遮蔽」更危险：它看起来是生效的。
                    return {"类型": "拒绝", "意图": 意图, "角色": 角色,
                            "拒绝": 级["说明"], "行级": 级,
                            "耗时": {"合计": round(time.time() - 起, 2)}}
            else:
                级 = {"已遮蔽": [], "受限": False, "内部直调": True, "说明": None}

            归一, 阻断, 提示 = 意图解析.校验归一(
                self.定义, 意图,
                查实体=lambda 字, 值: self.查实体(连接, 字, 值))
            if 阻断:
                return {"类型": "澄清", "意图": 归一, "阻断": 阻断, "提示": 提示,
                        "澄清": "；".join(阻断),
                        "耗时": {"合计": round(time.time() - 起, 2)}}
            if 归一.get("澄清"):
                # 模型自己判定「问句信息不足」—— 这是 D 档的**正确行为**，不是错误。
                # 曾经漏了这条分支：澄清型意图一路走到渲染，渲染器说「意图必须含指标」
                # → 对外表现为「服务出错」。同一个现象有两种解释，
                # 判据就没了 —— 必须在这里就把它们分开。
                return {"类型": "澄清", "意图": 归一, "阻断": [],
                        "澄清": 归一["澄清"], "提示": 提示,
                        "耗时": {"合计": round(time.time() - 起, 2)}}

            结果 = 语义.渲染(self.定义, 归一)
            SQL = 结果["SQL"]

            通, 原因 = 护栏.检查(SQL, 已知表=护栏.读表名(连接))
            if not 通:
                return {"类型": "拒绝", "意图": 归一, "SQL": SQL, "拒绝": 原因,
                        "耗时": {"合计": round(time.time() - 起, 2)}}

            应答 = {
                "类型": "SQL",
                "意图": 归一,
                "SQL": SQL,
                "口径": self.口径说明(结果, 归一),
                "时间": 结果.get("时间") or "不限（全区间）",
                "单位": 结果.get("单位"),
                "指标": 结果.get("指标") or 归一.get("目标") or 归一.get("场景"),
                "护栏": {"结果上限": 上限, "语句检查": 原因},
                "提示": 提示,
                "说明": [],
                "角色": 角色 or "（内部直调）",
                "行级": {k: v for k, v in 级.items() if k != "说明"},
                "耗时": {"渲染": 0.0, "查询": None, "合计": None},
            }
            if 级.get("说明"):
                # 受限必须说出来（同 A-1 的「承接要说」）：
                # 「只看到 1 个仓库」与「库里就 1 个仓库」在结果里长得一模一样。
                应答["说明"].append(级["说明"])
            if not 执行:
                应答["耗时"]["合计"] = round(time.time() - 起, 2)
                return 应答

            数据 = 护栏.执行(连接, SQL, 上限=上限)
            # ---- B-3：视图层脱敏（**在这里、不在前端、不在 SQL 层**）----
            # 位置的三条理由见 脱敏.py 模块头。放在这里的好处是 `/ask` 与 `/spec`
            # 两条路径自动都覆盖 —— 只堵一边等于没堵（另一条能拿到原值）。
            新列, 新行, 隐藏列, 脱敏说明 = 脱敏.脱敏(数据["列"], 数据["行"], 角色)
            应答["列"] = 新列
            应答["行"] = 新行
            应答["行数"] = len(新行)
            应答["截断"] = 数据["截断"]
            应答["耗时"]["查询"] = 数据["用时秒"]
            应答["耗时"]["合计"] = round(time.time() - 起, 2)
            if 隐藏列:
                应答["隐藏列"] = 隐藏列
                应答["角色"] = 角色 or 权限.默认角色
                应答["说明"].append(脱敏说明)
            if 数据["截断"]:
                应答["说明"].append(
                    "结果超过 %d 行已截断显示 —— 请收窄条件（没有静默丢数据，"
                    "但没显示的部分确实没给你看）" % 上限)
            if not 数据["行"]:
                应答["说明"].append(self.空结果说明(连接, 归一))
            return 应答
        except Exception as 错:                              # noqa: BLE001
            return {"类型": "错误", "意图": 意图,
                    "错误": "%s: %s" % (type(错).__name__, 错),
                    "耗时": {"合计": round(time.time() - 起, 2)}}
        finally:
            if 自建:
                连接.close()

    def 问数(self, 问题, 执行=True, 上限=护栏.结果行数上限, 要解读=True,
             会话id=None, 角色=None):
        """问题 → 前置判定（拒答/元问题）→ 意图（模型）→ 结果。模型只在倒数第二步出现。

        🔴 顺序不能反：**先判「该不该答」，再问模型「怎么答」**。
           反过来的后果（实测）：问「上个月员工工资总额」，模型会挑一张真实表硬答 ——
           SQL 合法、数字来自真实数据、只有主题是错的，而且无从对照检查。
           详见 scripts/拒答.py 模块头。

        `要解读`（A-2）：结果出来后**再调一次模型**写一句话。它失败不影响答案 ——
           数据已经查到了，不能因为写不出一句话就不给（见 scripts/解读.py）。

        `会话id`（A-1）：带上它 = 多轮追问。**不传时全链路与本轮改动前一致**
           （提示词逐字节相同、不做任何继承）—— 单轮问法是主路径，不能被新功能碰到。
        """
        连接 = self.连接()
        起 = time.time()
        try:
            # ---- 0. 该不该答（确定性，不调模型）----
            # 会话不参与这一步：拒答/元问题只看**本轮问句文本**。
            # 让上文影响它的后果是「上一轮问了在库内的主题，这一轮问员工工资也被放行」。
            判 = 拒答.判定(self.定义, 问题, 连接)
            if 判["处置"] == "元问题":
                return {"类型": "元问题", "问题": 问题, "回答": 判["文本"],
                        "元信息": 判["元信息"], "命中短语": 判["命中短语"],
                        "提示": [], "说明": [],
                        "耗时": {"意图": None, "合计": round(time.time() - 起, 2)}}
            if 判["处置"] == "拒答":
                return {"类型": "拒答", "问题": 问题, "拒答类型": 判["拒答类型"],
                        "拒答": 判["文本"], "命中词": 判["命中词"],
                        "命中主题": 判["命中主题"], "可答示例": 判.get("可答示例") or [],
                        "提示": 判.get("提示") or [], "说明": [],
                        "耗时": {"意图": None, "合计": round(time.time() - 起, 2)}}
            前置提示 = 判.get("提示") or []

            # ---- 0.6 跨指标（纯规则，**先于模型**）----
            # 问句里同时出现两个不同指标 → 直接澄清。
            #
            # 🔴 为什么放在模型前面（三轮微调实测）：模型**认得出来**这两个指标，
            #    但它宁可选一个能跑的降级结构交差（T25 渲染成 `SELECT COUNT(*) FROM 供应商`），
            #    也不说「我一次只能答一个」。这是**输出策略**，加样本、改格式都压不动；
            #    而「两个指标词共现」是**字面可判**的 —— 属于这一层的活。
            #    顺序沿用 0. 的理由：**先判「该不该答」，再问模型「怎么答」**。
            #
            # 读的是**本轮问句文本**，不看上文（与 0. 一致）：让上文影响它，会得出
            # 「上一轮问的是不良率，这一轮问交期+采购也被拦」——把能答的变成答不出。
            #
            # 澄清文本**不经过** `拒答.反问补强`：这段措辞本身已是**定向候选**
            # （把命中的指标原样列出来让用户挑），再加一份通用五类清单只会把定向信息稀释掉。
            # 见 跨指标.py 模块头与 eval/指标口径定义-v1.0.yaml「十、跨指标前置」。
            跨 = 跨指标.判定(self.定义, 问题)
            if 跨["跨指标"]:
                日志("跨指标前置：命中 %s → 直接澄清（不进模型）" % "、".join(跨["指标"]))
                return {"类型": "澄清", "问题": 问题,
                        "澄清": 跨["文本"], "阻断": [],
                        "跨指标": 跨["指标"],
                        "提示": 前置提示 + ([跨["说明"]] if 跨.get("说明") else []),
                        "说明": [], "模型原文": None, "意图缓存": None,
                        "会话": {"id": 会话id, "轮次": len(会话.取(会话id)),
                                 "已承接上一轮": False, "沿用": []},
                        "耗时": {"意图": None, "合计": round(time.time() - 起, 2)}}

            # ---- 0.7 模糊问项（纯规则，**先于模型**）----
            # 指向不明（「那家」「这个」）或标准不明（「有风险」「还行吗」）→ 直接澄清。
            #
            # 🔴 为什么必须挡在模型前面（2026-10-17 实测，60 题 D 档 T34/T57）：
            #    「那家供应商还行吗」「哪家供应商有风险？」—— 模型**没有犹豫**，
            #    都渲染成「不良率最高那家」的 SQL。它答的不是用户问的问题，
            #    而是**自己挑了一个**指标去答，结果看起来像模像样，用户不会起疑。
            #    这比「答不出」危险：答不出用户会换个问法，答错了用户会拿去用。
            #    判据是字面的（指代词 / 评价词），属于这一层，不必用 GPU 去买。
            #
            # 放在跨指标之后：跨指标是**能力边界**（一次只能答一个），
            # 模糊问项是**问句不完整**（连对象或标准都没给）—— 先讲硬边界，再谈补全。
            # 三条护栏（有指标名 / 有分组信号 / 有实体值）在 `拒答.模糊问项` 里，
            # 它们保证「精诚的货质量怎么样」这类**该答**的口语问法不被拦。
            if 判["处置"] == "澄清":
                # ⚠️ 多轮例外：指代词**在有上文时可能指的就是上一轮那个对象**（A-1 承接）。
                #    这时拦下来等于把多轮能力废掉 —— 用户明明刚说过是哪家。
                #    没有上文才拦：单轮里「那家」确实无处可指。
                #    （评价类不受此例外：「有风险」即使知道是哪家，标准仍然不明。）
                有上文 = bool(会话id) and bool(会话.取(会话id))
                if 有上文 and 判.get("澄清类型") == "指代":
                    日志("模糊问项：指代「%s」但有上文（%d 轮），交给承接"
                        % (判.get("命中词"), len(会话.取(会话id))))
                else:
                    日志("模糊问项前置：%s（%s）→ 直接澄清（不进模型）"
                        % (判.get("命中词"), 判.get("澄清类型")))
                    return {"类型": "澄清", "问题": 问题,
                            "澄清": 判["文本"], "阻断": [],
                            "模糊问项": 判.get("澄清类型"), "命中词": 判.get("命中词"),
                            "提示": 前置提示 + ([判["说明"]] if 判.get("说明") else []),
                            "说明": [], "模型原文": None, "意图缓存": None,
                            "会话": {"id": 会话id, "轮次": len(会话.取(会话id)),
                                     "已承接上一轮": False, "沿用": []},
                            "耗时": {"意图": None, "合计": round(time.time() - 起, 2)}}

            # ---- 0.5 A-1：取对话上文 ----
            上文, 上轮意图 = 会话.上下文提示(会话id)

            # ---- 1. 问题 → 意图（模型唯一参与的一步）----
            记 = 意图解析.解析(
                self.定义, 问题,
                查实体=lambda 字, 值: self.查实体(连接, 字, 值),
                上下文=上文)

            阻断 = 记.get("阻断") or []
            意图 = 记.get("意图")
            沿用, 兜底说明 = [], None

            # ---- 1.5 A-1 兜底：本轮自己立不起来 → 拿上一轮当基底重算 ----
            # 🔴 触发条件是**确定的**（`会话.能自立` 只看有没有 指标/基础查询/场景）：
            #    模型已经给了一个能独立成立的意图 → 一概不改（那是新问题或已完整）；
            #    模型给不出能成立的意图、而上一轮有 → 才继承。
            #    「猜」在这里是不能接受的：猜错的形态是**答出一个上下文正确、
            #    语义错误的结果**，既不报错也不知道要去核对什么。
            if (not 记.get("抽取失败")) and 上轮意图 and not 会话.能自立(意图 or {}):
                合并, 沿用 = 会话.兜底合并(上轮意图, 意图 or {})
                归2, 阻2, 提2 = 意图解析.校验归一(
                    self.定义, 合并,
                    查实体=lambda 字, 值: self.查实体(连接, 字, 值))
                if not 阻2:
                    意图, 阻断 = 归2, []
                    记["意图"] = 归2
                    记["提示"] = (记.get("提示") or []) + [
                        "本轮问句自身不完整，已**承接上一轮**理解"] + 提2
                    兜底说明 = 会话.沿用说明(沿用, 归2)
                    if 兜底说明:
                        记["提示"].append(兜底说明)
                else:
                    # 带着上文也答不了 → 用**合并后**的阻断说法（更能体现缺什么）
                    阻断 = 阻2
                    意图 = 归2
                    if 沿用:
                        记["提示"] = (记.get("提示") or []) + [
                            "本轮问句自身不完整，已承接上一轮理解"]

            # ---- 1.6 A-1：模型**自己**补全了的追问，也要如实披露 ----
            # 1.5 是「系统替它补」，这里是「它自己补的 —— 但用户有权知道这回事」。
            # 🔴 两条路径都得报：上下文提示词要求模型「输出完整意图」，模型通常就照做了，
            #    于是 1.5 根本不触发 —— 只报 1.5 的话，承接提示 UI **永远不亮**，
            #    而现象很像「会话没生效」，会把人送去查会话表（会话表其实是好的）。
            #    判据是**保守**的（只认字面，见 会话.靠上文补全），宁可漏报不许误报。
            if 上轮意图 and not 沿用 and 会话.能自立(意图 or {}):
                承主动 = 会话.靠上文补全(上轮意图, 问题, 意图 or {},
                                     别名=self.指标别名)
                if 承主动:
                    沿用 = 承主动
                    记["提示"] = (记.get("提示") or []) + [
                        "本轮问句自身不完整，已**沿用上一轮**的条件理解"]
                    兜底说明 = 会话.沿用说明(承主动, 意图 or {})
                    if 兜底说明:
                        记["提示"].append(兜底说明)

            if 意图 is None or 阻断:
                应 = {"类型": "澄清", "问题": 问题,
                      "澄清": "；".join(阻断) or "没能把这个问法转成可执行的查询",
                      "阻断": 阻断,
                      "提示": (记.get("提示") or []) + 前置提示,
                      "说明": [],
                      "模型原文": 记.get("原文"),
                      "意图缓存": 记.get("缓存"),
                      "会话": {"id": 会话id, "轮次": len(会话.取(会话id)),
                               "已承接上一轮": bool(沿用), "沿用": 沿用},
                      "耗时": {"意图": 记.get("用时秒"),
                               "合计": round(time.time() - 起, 2)}}
                # 🔴 阻断型澄清也必须补方向（2026-10-15 v3 盲测直证）。
                #
                # 补方向原来只挂在下面那条 `类型=="澄清"` 的分支上，而它的前置条件
                # 是 `not 应.get("阻断")` —— 于是形成一个**反向筛选**：
                #   模型自己给出规范澄清（无阻断）→ 补方向 ✅
                #   意图被系统判定有问题（有阻断）→ 直接 return，**不补** ❌
                # 越需要引导用户的澄清，越拿不到方向。v3 里 T27/T28/T31 全落在这条路。
                #
                # `抽取失败` 为真时，拼出来的「澄清」是内部诊断串，由 反问补强
                # 换成给用户看的话（见 `拒答.解析失败措辞`）—— 原串仍在 `阻断` 里。
                应["澄清"], 应["反问已补方向"] = 拒答.反问补强(
                    self.定义, 应["澄清"], 抽取失败=bool(记.get("抽取失败")))
                return 应

            # ---- 2. 意图 → SQL → 结果 ----
            应 = self.按意图(意图, 执行=执行, 上限=上限, 连接=连接, 角色=角色)
            应["问题"] = 问题
            应["模型原文"] = 记.get("原文")
            应["提示"] = (记.get("提示") or []) + 前置提示 + (应.get("提示") or [])
            应.setdefault("说明", [])
            if 应.get("类型") == "SQL":
                # 漏抽实体的兜底检查挂在「问数」这一层
                #（只有这里同时握有问题原文与最终意图）
                漏 = self.疑似漏抽筛选(连接, 问题, 应.get("意图") or {})
                if 漏:
                    应["说明"].append(漏)
                # 歧义词提示：问句里的词在库内能被两处解释（提示，不阻断）
                歧 = 拒答.歧义提示(self.定义, 问题, 应.get("意图") or {}, 连接)
                if 歧:
                    应["说明"].append(歧)
            elif 应.get("类型") == "澄清" and not 应.get("阻断"):
                # 模型自己判定「信息不足」并要求反问 —— 给反问补上**可选方向**。
                # 只写「请补充更多信息」的反问，用户的下一步是随机猜一次，
                # 猜不中就再猜 —— 与不答没有区别（见 拒答.反问补强）。
                新, 补过 = 拒答.反问补强(self.定义, 应.get("澄清"))
                应["澄清"] = 新
                应["反问已补方向"] = 补过

            # ---- A-2：一句话解读（表与图之外的第三样东西）----
            # 🔴 只对**有结果集**的应答做。澄清 / 拒答 / 元问题的措辞已经各自写好了，
            #    再让模型加一句只会把明确的处置说得含糊。
            应["解读"] = None
            if 应.get("类型") == "SQL" and 要解读:
                if 解读.关解读:
                    应["解读说明"] = "已用 CHATBI_NO_INSIGHT 关闭"
                else:
                    try:
                        # 🔴 B-3 与 A-2 的接缝：解读会把结果集整段喂给模型。
                        #    给模型的必须是**摘掉敏感列**的版本，而不是带 `***` 的版本 ——
                        #    星号会让模型去描述它（「某列显示为星号」），那句描述本身
                        #    就暴露了「这里有一列敏感数据」，还挤掉了真正该说的那句话。
                        视图 = 应
                        if 应.get("隐藏列"):
                            视图 = dict(应)
                            视图["列"], 视图["行"] = 脱敏.摘列(
                                应["列"], 应["行"], 应["隐藏列"])
                        果 = 解读.解读(问题, 视图)
                        应["解读"] = 果.get("文本")
                        if 果.get("错误"):
                            应["解读说明"] = 果["错误"]
                        if 果.get("编造"):
                            应["解读编造"] = 果.get("可疑数字")
                        应["耗时"]["解读"] = 果.get("用时秒")
                    except Exception as 错:                  # noqa: BLE001
                        # 解读是锦上添花 —— 它炸了不能把答案一起带走。
                        应["解读说明"] = "解读失败：%s: %s" % (type(错).__name__, str(错)[:60])

            # ---- A-1：记入会话（只记**真出了结果**的这一轮）----
            # 🔴 只记 SQL 轮：被阻断的意图是「已验证不可用」的，继承它只会把同一个
            #    失败原样复制到下一轮。会话里能当基底的，只能是跑通过的东西。
            记轮 = 0
            if 应.get("类型") == "SQL":
                记轮 = 会话.记(会话id, 问题, 应.get("意图"), "SQL",
                               (应.get("口径") or "")[:80])
            应["会话"] = {"id": 会话id, "轮次": 记轮,
                          "已承接上一轮": bool(沿用),
                          "沿用": 沿用, "沿用说明": 兜底说明}
            # B-2：这次意图是**新算的**还是**命中缓存**，必须能被上层看见 ——
            # 评测里出现「命中」就是评测自身没关缓存，得当场发现（见 意图缓存.py）。
            应["意图缓存"] = 记.get("缓存")
            应["耗时"]["意图"] = 记.get("用时秒")
            应["耗时"]["合计"] = round(time.time() - 起, 2)
            return 应
        finally:
            连接.close()

    # ---- 目录（给页面 / 给编排层看）----
