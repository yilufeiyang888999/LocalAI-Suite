# ============================ HTTP ============================

def 取(基址, 方法, 路径, 体=None, 超时=客户端超时):
    """返回 (状态码, 应答对象, 错误文本)。**对 4xx/5xx 也要读 body** ——
    负例判据靠的就是 body 里的 error，读不到就只能判「不通」，分不清 403 与 404。

    🔴 路径必须 `quote` 一次再拼：`Request(url)` 内部按 ascii 编码整个 URL，
    带中文的路径会当场抛 `UnicodeEncodeError` —— 而那个异常长得**像服务不通**，
    会被误读成「服务没起来」（本次实测踩到过）。
    """
    数据 = None
    if 体 is not None:
        数据 = json.dumps(体, ensure_ascii=False).encode("utf-8")
    全址 = 基址 + urllib.parse.quote(路径, safe="/?=&")
    请 = urllib.request.Request(全址, data=数据, method=方法)
    请.add_header("Content-Type", "application/json")
    try:
        with 代理绕过.open(请, timeout=超时) as 应:
            原 = 应.read().decode("utf-8", "replace")
            return 应.status, _试解析(原), None
    except urllib.error.HTTPError as 错:
        try:
            原 = 错.read().decode("utf-8", "replace")
        except Exception:                                     # noqa: BLE001
            原 = ""
        return 错.code, _试解析(原), None
    except Exception as 错:                                   # noqa: BLE001
        return None, None, "%s: %s" % (type(错).__name__, 错)


def _试解析(文本):
    try:
        return json.loads(文本)
    except ValueError:
        return {"_原文": 文本[:400]}


