def 读源码版本(文件名):
    """从源码里读 `服务版本 = "x"`。**用正则读而不是 import** ——
    import 这些模块会连带初始化一堆东西，验收脚本不该有那种副作用。"""
    try:
        with open(os.path.join(脚本目录, 文件名), encoding="utf-8") as 句柄:
            文本 = 句柄.read()
    except OSError:
        return None
    命 = re.search(r'^服务版本\s*=\s*"([^"]+)"', 文本, re.M)
    return 命.group(1) if 命 else None


def 跑契约(基址表):
    行 = []
    for 条 in 契约清单():
        码, 应, 错 = 取(基址表[条["服务"]], 条["方法"], 条["路径"], 条["体"])
        if 错:
            行.append(dict(条, 状态="失败", 实测码=None, 实码=None, 缺字段=[], 详情=错))
            continue
        缺 = [k for k in 条["字段"] if not isinstance(应, dict) or k not in 应]
        好 = (码 == 条["码"]) and not 缺
        详情 = "码 %s" % 码
        if 码 != 条["码"]:
            详情 += "（期望 %s）" % 条["码"]
        if 缺:
            详情 += " ｜ 缺字段：%s" % "、".join(缺)
        行.append(dict(条, 状态="通过" if 好 else "失败", 实测码=码, 缺字段=缺, 详情=详情))

    # ---- 版本一致性：/health 报的版本 vs 源码常量 ----
    for 服务, 文件 in (("问数", "问数服务.py"), ("编排", "编排服务.py")):
        _, 应, 错 = 取(基址表[服务], "GET", "/health")
        源 = 读源码版本(文件)
        报 = (应 or {}).get("版本")
        好 = (错 is None) and (源 is not None) and (报 == 源)
        行.append({
            "服务": 服务, "方法": "GET", "路径": "/health(版本)",
            "码": 200, "字段": [], "说明": "服务报的版本必须等于源码常量（抓「旧实例在跑」）",
            "状态": "通过" if 好 else "失败", "实测码": None, "缺字段": [],
            "详情": "服务报 %r ｜ 源码 %r" % (报, 源) + ("" if 好 else "  ← 不一致，服务可能是旧版本"),
        })
    return 行


