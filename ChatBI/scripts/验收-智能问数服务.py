def 判链路(用例, 应):
    """返回 (好, 详情)。判「路由走对了」+「底层结构成立」两件事。"""
    路 = 应.get("路由") or {}
    底 = 应.get("依据")
    错 = 应.get("错误")
    if 错:
        return False, "链路报错：%s" % 错
    if 应.get("类型") != 用例["期望链路"]:
        return False, "路由到了「%s」（期望 %s，依据 %s）" % (
            应.get("类型"), 用例["期望链路"], 路.get("依据"))
    if 用例["名"] == "知识问答":
        好 = isinstance(底, dict) and bool(底.get("answer"))
        return 好, "依据=%s ｜ 引用 %d 条" % (
            type(底).__name__, len((底 or {}).get("citations") or []))
    行 = (底 or {}).get("行")
    好 = isinstance(底, dict) and 底.get("类型") == "SQL" and isinstance(行, list) and len(行) > 0
    return 好, "底层类型=%s ｜ 列 %s ｜ 行 %d" % (
        (底 or {}).get("类型"), "、".join((底 or {}).get("列") or []), len(行 or []))


