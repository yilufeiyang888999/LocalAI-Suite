# -*- coding: utf-8 -*-
"""
RRF 改良对照：能把「平账」变成净增益吗？（作品一 · D2）
========================================================

问题
----
等权 RRF（向量 + BM25）实测是**平账，不是增益** —— 整体 R@1 与单通道一字不差。
机制：收益与损失在类别之间对冲掉了：

    短小关键  0.67 → 0.78  （+11pp）
    跨文档    0.25 → 0.75  （+50pp）
    表格      0.83 → 0.83  （  0  ）
    长文档    0.88 → 0.62  （−26pp）  ← **唯一的亏损源**

长文档为什么亏：块长 → BM25 的 TF 项大，`b=0.75` 的长度归一化压不住 →
**长块被系统性高估**，把向量排好的结果顶下去。

三个可在线判定的改法
--------------------
都不依赖「答案类别」这种**离线信息**（检索时不知道答案属于哪一类）：

    F1  b 加强      BM25 的长度归一化 b：0.75 → 0.9（专治长块被高估）
    F2  BM25 截断   只融合 BM25 的 Top-N（排到 200 名的块本就不该投票）
    F3  向量加权    w向量 = 2, wBM25 = 1

判据（可判定）
--------------
主判据：整体 R@1 **超过单通道最好值**（脚本里动态取 max(A,B)，不再写死数字）——
        那才叫净增益，不是「不低于」。
护栏 1：长文档类 R@1 不得低于向量的长文档类水平（向量的强项不能被融合拖下去）。
护栏 2：库外题首名向量分不得被抬高。
辅判据：与基线的**配对胜负** —— 库内题数决定分辨率
        （33 条时 1 题 = 3.03pp，扩到 60 条后 1 题 = 1.67pp），均值会骗人。

零第三方依赖。
"""

import importlib.util
import json
import os
import sys

脚本目录 = os.path.dirname(os.path.abspath(__file__))
根目录 = os.path.dirname(脚本目录)
输出目录 = os.path.join(根目录, "eval")
结果文件 = os.path.join(输出目录, "RRF加权-结果.json")

RRF_K = 60
BM25_K1 = 1.2
基线b = 0.75
检索模块 = None      # 主流程里注入（BM25 打分要用它的 bigram 分词）


def 载入(文件名, 别名):
    路 = os.path.join(脚本目录, 文件名)
    规范 = importlib.util.spec_from_file_location(别名, 路)
    模块 = importlib.util.module_from_spec(规范)
    规范.loader.exec_module(模块)
    return 模块


def BM25打分参数(索引, 查询文本, k1=BM25_K1, b=基线b):
    """参数化版 BM25 —— 只为把 b 抽出来做对照，算法与主脚本逐字一致。"""
    词列表 = 检索模块.切二元组(查询文本)
    N, 平均长 = 索引["N"], 索引["平均长"]
    得分 = [0.0] * N
    if not 词列表 or 平均长 <= 0:
        return 得分
    for 词 in 词列表:
        该词idf = 索引["idf"].get(词)
        if 该词idf is None:
            continue
        for 序 in range(N):
            f = 索引["词频"][序].get(词)
            if not f:
                continue
            分母 = f + k1 * (1.0 - b + b * 索引["长度"][序] / 平均长)
            得分[序] += 该词idf * f * (k1 + 1.0) / 分母
    return 得分


def 加权RRF(序向量, 序BM25, w向量=1.0, wBM25=1.0, 平滑=RRF_K, b截断=None):
    """RRF 加权 + 可选「BM25 只投前 N 名」。

    向量序是全量的 → 融合结果覆盖所有块，截断不会让块凭空消失。
    """
    融合 = {}
    for 位次, i in enumerate(序向量, start=1):
        融合[i] = 融合.get(i, 0.0) + w向量 / (平滑 + 位次)
    for 位次, i in enumerate(序BM25, start=1):
        if b截断 is not None and 位次 > b截断:
            break
        融合[i] = 融合.get(i, 0.0) + wBM25 / (平滑 + 位次)
    return [i for i, _ in sorted(融合.items(), key=lambda x: -x[1])]


def 求排名(序, 正确集):
    if not 正确集:
        return None
    for 位次, i in enumerate(序, start=1):
        if i in 正确集:
            return 位次
    return None


def 指标(明细, 类别=None):
    """R@1 / R@3 / R@5 / MRR（分母固定 = 该组题数）。"""
    行 = [x for x in 明细
          if x["类别"] != "库外" and (类别 is None or x["类别"] == 类别)]
    总 = len(行)
    if not 总:
        return None
    排 = [x["排名"] for x in 行]
    有效 = [r for r in 排 if r is not None]
    return {"题数": 总,
            "R@1": sum(1 for r in 有效 if r == 1) / 总,
            "R@3": sum(1 for r in 有效 if r <= 3) / 总,
            "R@5": sum(1 for r in 有效 if r <= 5) / 总,
            "MRR": sum(1.0 / r for r in 有效) / 总,
            "不可召回": 总 - len(有效)}


def 主流程():
    global 模, 检索模块
    sys.stdout.reconfigure(errors="replace")
    检索 = 载入("检索-混合.py", "检索")
    检索模块 = 检索
    模 = 检索.载入分块模块()
    检索.模 = 模

    文档列表 = 模.读语料()
    查询集 = 模.查询集

    # 基座与主脚本一致：S13 软表保-1200
    块列表 = []
    for 文档 in 文档列表:
        for 前缀, 正文 in 模.切标题结构(文档, 1200, False, 软表格=True):
            if len(正文.strip()) >= 8:
                块列表.append((文档["文号"], 前缀, 正文))
    嵌入文本 = [(前 + "\n" + 文) for _, 前, 文 in 块列表]

    print("=" * 96)
    库内数 = sum(1 for _, _, _, _, 类 in 查询集 if 类 != "库外")
    print(" RRF 改良对照    基座 S13 软表保-1200    %d 块    %d 库内 + %d 库外"
          % (len(块列表), 库内数, len(查询集) - 库内数))
    print("=" * 96)

    print("\n算块向量 / BM25 索引 …")
    块向量表 = 模.取向量(检索.默认服务, 嵌入文本, 标签="  嵌入")
    块模表 = [模.求模长(v) for v in 块向量表]
    BM25索引 = 检索.建BM25索引(嵌入文本)

    正确集表 = 检索.找正确块(块列表, 查询集)

    # ---------- 方案定义 ----------
    方案 = [
        ("A 纯向量",          lambda v序, b序, b序09: v序),
        ("B 纯BM25",          lambda v序, b序, b序09: b序),
        ("C 等权RRF(基线)",   lambda v序, b序, b序09: 加权RRF(v序, b序)),
        ("F1 b=0.90",         lambda v序, b序, b序09: 加权RRF(v序, b序09)),
        ("F2 BM25截断20",     lambda v序, b序, b序09: 加权RRF(v序, b序, b截断=20)),
        ("F3 向量×2",         lambda v序, b序, b序09: 加权RRF(v序, b序, w向量=2.0)),
        ("F4 F1+F3",          lambda v序, b序, b序09: 加权RRF(v序, b序09, w向量=2.0)),
    ]

    明细表 = {名: [] for 名, _ in 方案}
    库外表 = {名: [] for 名, _ in 方案}
    向量缓存 = {}

    print("[跑] %d 个方案 × %d 题 …" % (len(方案), len(查询集)))
    for 编号, 问句, 目标, 金标准, 类别 in 查询集:
        序向量, 分向量 = 检索.向量排序(问句, 块向量表, 块模表, 向量缓存)
        分b = BM25打分参数(BM25索引, 问句, b=基线b)
        b序 = sorted(range(len(分b)), key=lambda i: -分b[i])
        分b09 = BM25打分参数(BM25索引, 问句, b=0.90)
        b序09 = sorted(range(len(分b09)), key=lambda i: -分b09[i])

        for 名, 生成 in 方案:
            序 = 生成(序向量, b序, b序09)
            明细表[名].append({"编号": 编号, "类别": 类别,
                               "排名": 求排名(序, 正确集表[编号]) if 类别 != "库外" else None})
            if 类别 == "库外" and 序:
                库外表[名].append({"编号": 编号, "首名文号": 块列表[序[0]][0],
                                  "向量分": round(分向量[序[0]], 4)})

    # ---------- 表 1：总表 ----------
    print()
    print("=" * 96)
    print(" 表 1 · 总表（R@1 / R@3 / R@5 / MRR）")
    print("=" * 96)
    print(" " + 模.补空格("方案", 20) + 模.补空格("R@1", 10) + 模.补空格("R@3", 10)
          + 模.补空格("R@5", 10) + 模.补空格("MRR", 10) + "判据：R@1 > 基线C ?")
    print(" " + "-" * 88)
    指标表 = {名: 指标(明细表[名]) for 名, _ in 方案}
    基线R1 = 指标表["C 等权RRF(基线)"]["R@1"]
    for 名, _ in 方案:
        m = 指标表[名]
        通过 = "✅ 净增益" if m["R@1"] > 基线R1 + 1e-9 else ("＝ 持平" if abs(m["R@1"] - 基线R1) < 1e-9 else "❌ 不如")
        print(" " + 模.补空格(名, 20) + 模.补空格("%.4f" % m["R@1"], 10)
              + 模.补空格("%.4f" % m["R@3"], 10) + 模.补空格("%.4f" % m["R@5"], 10)
              + 模.补空格("%.4f" % m["MRR"], 10) + 通过)

    # ---------- 表 2：分类 R@1 ----------
    print()
    print("=" * 96)
    print(" 表 2 · 分类 R@1（看亏损源治好了没有 —— 长文档是唯一亏损源）")
    print("=" * 96)
    print(" " + 模.补空格("方案", 20)
          + "".join(模.补空格(类别, 12) for 类别 in ("表格", "短小关键", "长文档", "跨文档")))
    print(" " + "-" * 88)
    for 名, _ in 方案:
        单元 = []
        for 类别 in ("表格", "短小关键", "长文档", "跨文档"):
            m = 指标(明细表[名], 类别)
            单元.append(模.补空格("%.4f" % m["R@1"], 12) if m else 模.补空格("-", 12))
        print(" " + 模.补空格(名, 20) + "".join(单元))

    # ---------- 表 3：配对胜负（对基线 C） ----------
    print()
    print("=" * 96)
    库内数 = 指标表["C 等权RRF(基线)"]["题数"]
    print(" 表 3 · 与基线 C（等权 RRF）的配对胜负 —— %d 题里 1 题 = %.1fpp，胜负比均值可靠"
          % (库内数, 100.0 / 库内数))
    print("=" * 96)
    基 = {x["编号"]: x["排名"] for x in 明细表["C 等权RRF(基线)"] if x["类别"] != "库外"}
    print(" " + 模.补空格("方案", 20) + 模.补空格("胜", 6) + 模.补空格("平", 6)
          + 模.补空格("负", 6) + "净胜题（胜−负）")
    print(" " + "-" * 88)
    for 名, _ in 方案:
        if 名.startswith(("A ", "B ", "C ")):
            continue
        胜 = 平 = 负 = 0
        for x in 明细表[名]:
            if x["类别"] == "库外":
                continue
            a, b = 基[x["编号"]], x["排名"]
            if a is None and b is None:
                平 += 1
            elif a is None:
                胜 += 1
            elif b is None:
                负 += 1
            elif b < a:
                胜 += 1
            elif b == a:
                平 += 1
            else:
                负 += 1
        print(" " + 模.补空格(名, 20) + 模.补空格(胜, 6) + 模.补空格(平, 6)
              + 模.补空格(负, 6) + "%+d" % (胜 - 负))

    # ---------- 表 4：库外护栏 ----------
    print()
    print("=" * 96)
    print(" 表 4 · 库外护栏（首名块的向量分 —— 融合若把无关块顶上来，分数会明显抬高）")
    print("=" * 96)
    print(" " + 模.补空格("方案", 20)
          + "".join(模.补空格(x["编号"], 10) for x in 库外表["A 纯向量"]))
    print(" " + "-" * 88)
    for 名, _ in 方案:
        值 = {x["编号"]: x["向量分"] for x in 库外表[名]}
        print(" " + 模.补空格(名, 20)
              + "".join(模.补空格("%.4f" % 值.get(x["编号"], float("nan")), 10)
                        for x in 库外表["A 纯向量"]))
    最大基线 = max(x["向量分"] for x in 库外表["A 纯向量"])
    抬高 = []
    for 名, _ in 方案:
        值 = {x["编号"]: x["向量分"] for x in 库外表[名]}
        超 = [k for k, v in 值.items() if v > 最大基线 + 1e-9]
        if 超:
            抬高.append("%s（%s）" % (名, "、".join(超)))
    print()
    print(" 护栏：%s" % ("✅ 无方案抬高库外首名分数" if not 抬高 else "⚠ 抬高：" + "；".join(抬高)))

    # ---------- 结论 ----------
    最好 = max(方案, key=lambda p: 指标表[p[0]]["R@1"])
    最好m = 指标表[最好[0]]
    print()
    print("=" * 96)
    print(" 结论")
    print("=" * 96)
    print(" 最优方案：**%s**（R@1 %.4f，MRR %.4f）" % (最好[0], 最好m["R@1"], 最好m["MRR"]))
    长文档 = {名: 指标(明细表[名], "长文档")["R@1"] for 名, _ in 方案}
    print(" 长文档类：%s" % "，".join("%s %.4f" % (k, v) for k, v in 长文档.items()))
    单通道最好 = max(指标表["A 纯向量"]["R@1"], 指标表["B 纯BM25"]["R@1"])
    print(" %s" % ("✅ 达成净增益：最优融合 R@1 %.4f > 单通道最好值 %.4f"
                   % (最好m["R@1"], 单通道最好)
                   if 最好m["R@1"] > 单通道最好 + 1e-9 else
                   "⚠ 未达成净增益：最优融合 R@1 %.4f 未能超过单通道最好值 %.4f"
                   % (最好m["R@1"], 单通道最好)))

    with open(结果文件, "w", encoding="utf-8") as 文件:
        json.dump({"基座": "S13 软表保-1200", "块数": len(块列表),
                   "指标": 指标表, "明细": 明细表, "库外": 库外表,
                   "长文档R@1": 长文档, "最优": 最好[0]},
                  文件, ensure_ascii=False, indent=2)
    print("\n 已落盘 %s" % 结果文件)
    return 0


if __name__ == "__main__":
    sys.exit(主流程())
