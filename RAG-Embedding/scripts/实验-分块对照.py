def 规范化(文本):
    """去掉 Markdown 强调符与换行，供金标准匹配用（只影响匹配，不影响向量）。"""
    文本 = 文本.replace("**", "").replace("`", "")
    文本 = 文本.replace("<br>", " ").replace("<br/>", " ").replace("<br />", " ")
    return re.sub(r"\s+", " ", 文本)


表格行模式 = re.compile(r"^\s*\|")
分隔行模式 = re.compile(r"^\s*\|[\s\-:|]+\|\s*$")


def 提取文号(正文, 文件名):
    """文号取文件头信息表里的「**XX编号**」栏。

    字号不固定：文件编号 / 表单编号 / **协议编号** —— 都见过。
    早期版本只写了「文件|表单」，导致技术协议（协议编号）匹配失败、回退成文件名，
    块前缀里的文号是错的。**别枚举字号，用 `[^*]*编号` 通配。**
    """
    m = re.search(r"\|\s*\*\*([^*\n]{0,8}编号)\*\*\s*\|\s*([A-Za-z0-9\-]+)\s*\|", 正文)
    if m:
        return m.group(2)
    主干 = os.path.splitext(文件名)[0]
    m = re.search(r"([A-Z]{2,4}(?:\-[A-Z]{2,4})?\-[A-Za-z0-9\-]+)$", 主干)
    return m.group(1) if m else 主干


def 读语料():
    文档列表 = []
    for 名 in sorted(os.listdir(语料目录)):
        if not 名.endswith(".md"):
            continue
        with open(os.path.join(语料目录, 名), encoding="utf-8") as 文件:
            正文 = 文件.read()
        标题 = ""
        for 行 in 正文.split("\n"):
            if 行.startswith("# "):
                标题 = 行[2:].strip()
