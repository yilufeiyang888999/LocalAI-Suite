def 设终端编码():
    for 流 in (sys.stdout, sys.stderr):
        if hasattr(流, "reconfigure"):
            流.reconfigure(errors="replace")


def 显示宽(文本):
    宽 = 0
    for 字符 in str(文本):
        宽 += 2 if ord(字符) > 0x2E80 else 1
    return 宽


def 补空格(文本, 目标宽):
    文本 = str(文本)
    return 文本 + " " * max(0, 目标宽 - 显示宽(文本))


def 截断(文本, 目标宽):
    出, 宽 = "", 0
    for 字符 in str(文本):
        宽 += 2 if ord(字符) > 0x2E80 else 1
        if 宽 > 目标宽 - 2:
            return 出 + "…"
        出 += 字符
    return 出


def 取向量(服务地址, 文本列表, 每批=8, 标签=""):
    """调用 OpenAI 兼容 /v1/embeddings，分批发，按 index 还原顺序。"""
    全部 = []
    for 起 in range(0, len(文本列表), 每批):
        批 = 文本列表[起:起 + 每批]
        载荷 = json.dumps({"input": 批, "model": "bge-m3"},
                          ensure_ascii=False).encode("utf-8")
        请求 = urllib.request.Request(
            服务地址.rstrip("/") + "/v1/embeddings",
            data=载荷, headers={"Content-Type": "application/json"})
        with urllib.request.urlopen(请求, timeout=600) as 响应:
            数据 = json.loads(响应.read().decode("utf-8"))
        条目 = sorted(数据["data"], key=lambda 项: 项["index"])
        全部.extend(项["embedding"] for 项 in 条目)
        if 标签:
            print("      %s %d/%d" % (标签, min(起 + 每批, len(文本列表)),
                                      len(文本列表)), end="\r")
    if 标签:
        print(" " * 40, end="\r")
    return 全部


def 求模长(向量):
    return math.sqrt(sum(值 * 值 for 值 in 向量))


def 点积(甲, 乙):
    return sum(map(operator.mul, 甲, 乙))


