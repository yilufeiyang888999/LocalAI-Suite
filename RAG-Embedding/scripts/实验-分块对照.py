class 装填器:
    """把若干「行」按块上限装成块；同一标题下的内容可连续装填。

    标题前缀（文号 + 章节路径）计入块上限预算 —— 否则「块大小」会因为
    前缀长度不同而失真，族内比较就不可信了。
    """

    def __init__(self, 上限, 标题前缀, 出块):
        self.上限 = 上限
        self.标题前缀 = 标题前缀
        self.出块 = 出块
        self.缓冲 = []
        self.已用 = len(标题前缀) + 1

    def _冲刷(self):
        if self.缓冲:
            self.出块(self.标题前缀, "\n".join(self.缓冲).strip("\n"))
            self.缓冲 = []
            self.已用 = len(self.标题前缀) + 1

    def 加文本行(self, 行文本):
        """普通行：贪心装填，装不下就冲刷；单行超限则硬切（这一步会切断表格行）。"""
        剩余文本 = 行文本
        while 剩余文本:
            剩余额度 = self.上限 - self.已用
            if len(剩余文本) + 1 <= 剩余额度:
                self.缓冲.append(剩余文本)
                self.已用 += len(剩余文本) + 1
                return
            if self.缓冲:
                self._冲刷()
                continue
            # 缓冲为空且单行超限 → 硬切
            片 = 剩余文本[: self.上限]
            self.缓冲.append(片)
            self.已用 += len(片) + 1
            self._冲刷()
            剩余文本 = 剩余文本[self.上限:]

    def 加表格整块(self, 表行):
        """表格整块入块：能塞进当前缓冲就塞，否则单独成块；超长按行分组并重复表头。

        注意：本方法**强制表格独占一块**（装不下就冲刷并只放表）。
        这正是「无差别表格保护」的代价 —— 表格与前后文被剥离开。
        """
        总长 = sum(len(x) + 1 for x in 表行)
        if self.缓冲 and self.已用 + 总长 <= self.上限:
            for 行文本 in 表行:
                self.缓冲.append(行文本)
                self.已用 += len(行文本) + 1
            return
        self._冲刷()
        if 总长 + len(self.标题前缀) + 1 <= self.上限 or len(表行) <= 2:
            self.出块(self.标题前缀, "\n".join(表行))
            return
        表头, 分隔, 数据 = 表行[0], 表行[1], 表行[2:]
        预算 = self.上限 - len(self.标题前缀) - len(表头) - len(分隔) - 3
        组, 长 = [], 0
        for 行文本 in 数据:
            if 组 and 长 + len(行文本) + 1 > 预算:
                self.出块(self.标题前缀, "\n".join([表头, 分隔] + 组))
                组, 长 = [], 0
            组.append(行文本)
            长 += len(行文本) + 1
        if 组:
            self.出块(self.标题前缀, "\n".join([表头, 分隔] + 组))

    def 加表格软保护(self, 表行):
        """表格**不被切开**，但允许与前后文同块。

        与 加表格整块 的唯一差别：表格装不进当前缓冲时，冲刷后把表**放在新块的头部**
        而不是**独占整块** —— 后续文本行还能接着装进这一块。
        """
        总长 = sum(len(x) + 1 for x in 表行)
        if self.缓冲 and self.已用 + 总长 <= self.上限:
            for 行文本 in 表行:
                self.缓冲.append(行文本)
                self.已用 += len(行文本) + 1
            return
        if 总长 + len(self.标题前缀) + 1 <= self.上限:
            self._冲刷()
            for 行文本 in 表行:
                self.缓冲.append(行文本)
                self.已用 += len(行文本) + 1
            return
        # 表格本身就超过块上限 —— 只能分组，但每组都带表头
        self.加表格整块(表行)

    def 加表格逐行(self, 表行):
        """表格行级索引：每行单独成块，并重复表头与标题路径。"""
        if len(表行) <= 2:
            return
        表头, 分隔 = 表行[0], 表行[1]
        for 行文本 in 表行[2:]:
            self.出块(self.标题前缀, "\n".join([表头, 分隔, 行文本]))

    def 收尾(self):
        self._冲刷()


