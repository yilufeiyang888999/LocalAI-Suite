def 拆节(正文, 文号, 标题):
    """按 Markdown 标题拆节，返回 [(标题路径, [行...]), ...]；标题行本身不进正文。"""
    节列表 = []
    标题栈 = {}
    当前路径 = None
    当前行 = []

    def 当前前缀():
        if not 标题栈:
            return 文号 + " " + 标题
        各级 = []
        for 级 in sorted(标题栈):
            if 级 == 1:
                各级.append(文号 + " " + 标题)
            else:
                各级.append(标题栈[级])
        return " > ".join(各级)

    for 行 in 正文.split("\n"):
        m = re.match(r"^(#{1,4})\s+(.*)$", 行)
        if m:
            级别 = len(m.group(1))
            标题栈 = {k: v for k, v in 标题栈.items() if k < 级别}
            标题栈[级别] = m.group(2).strip()
            if 当前路径 is not None:
                节列表.append((当前路径, 当前行))
            当前路径 = 当前前缀()
            当前行 = []
        else:
            当前行.append(行)
            if 当前路径 is None:
                当前路径 = 当前前缀()
    if 当前路径 is not None:
        节列表.append((当前路径, 当前行))
    return [项 for 项 in 节列表 if "".join(项[1]).strip()]


def 拆区块(行列表):
    """把一节的正文行拆成 [('文本', 行) | ('表格', 行)] 区块序列。"""
    区块列表 = []
    文本行 = []

    def 收文本():
        if 文本行:
            区块列表.append(("文本", list(文本行)))
            文本行.clear()

    for 行 in 行列表:
        if 表格行模式.match(行):
            收文本()
            if 区块列表 and 区块列表[-1][0] == "表格":
                区块列表[-1][1].append(行)
            else:
                区块列表.append(("表格", [行]))
        else:
            文本行.append(行)
    收文本()
    return 区块列表


def 切固定长度(文档, 上限, 重叠=0):
    """因子族 A：定长 / 按行吸附。文档级前缀，无章节路径。"""
    前缀 = 文档["文号"] + " " + 文档["标题"]
    块 = []
    正文 = 文档["正文"]
    起点, 全long = 0, len(正文)
    while 起点 < 全long:
        终点 = min(起点 + 上限, 全long)
        if 终点 < 全long:
            断点 = 正文.rfind("\n", 起点 + int(上限 * 0.6), 终点)
            if 断点 > 起点:
                终点 = 断点 + 1
        段 = 正文[起点:终点].strip("\n")
        if 段.strip():
            块.append((前缀, 段))
        下一步 = 终点 - 重叠
        起点 = 下一步 if 下一步 > 起点 else 起点 + 上限
    return 块


def 切标题结构(文档, 上限, 表格保护, 表格行级=False, 章节前缀=True, 软表格=False):
    """因子族 B/C：按标题拆节，节内装填。表格保护/行级为开关。

    章节前缀=False 时只保留「文号 + 文档标题」前缀 —— 这是**对照组**：
    边界逻辑完全相同，只有「章节路径是否进块内容」这一个变量不同。

    软表格=True 时启用「表格不切开、但允许与前后文同块」（见 装填器.加表格软保护）。
    """
    块 = []
    文档级前缀 = 文档["文号"] + " " + 文档["标题"]
    for 路径, 行列表 in 拆节(文档["正文"], 文档["文号"], 文档["标题"]):
        前缀 = 路径 if 章节前缀 else 文档级前缀
        装 = 装填器(上限, 前缀, lambda 前, 文: 块.append((前, 文)))
        for 类型, 行组 in 拆区块(行列表):
            if 类型 == "表格":
                if 表格行级:
                    装.加表格逐行(行组)
                elif 软表格:
                    装.加表格软保护(行组)
                elif 表格保护:
                    装.加表格整块(行组)
                else:
                    for 行 in 行组:
                        装.加文本行(行)
            else:
                for 行 in 行组:
                    装.加文本行(行)
        装.收尾()
    return 块


