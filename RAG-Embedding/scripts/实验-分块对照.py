def 校验金标准(文档列表):
    """金标准片段必须真存在。不存在就拒跑 —— 否则「漏检」与「检索差」无法区分。"""
    全库 = {文档["文号"]: 规范化(文档["正文"]) for 文档 in 文档列表}
    合并 = " \u0000 ".join(全库.values())
    问题 = []
    for 编号, 问句, 目标, 金标准, 类别 in 查询集:
        if 类别 == "库外":
            continue
        for 片段 in 金标准:
            规范片段 = 规范化(片段)
            if 规范片段 and 规范片段 not in 合并:
                问题.append("  %s 金标准片段在语料中找不到：%s" % (编号, 片段))
    return 问题


def 统计表格结构(块列表):
    """结构性指标：表格块里有多少块丢了表头（孤儿行）。"""
    表格块 = 有表头 = 0
    for _, _, 文 in 块列表:
        if any(表格行模式.match(行) for 行 in 文.split("\n")):
            表格块 += 1
            if any(分隔行模式.match(行) for 行 in 文.split("\n")):
                有表头 += 1
    return 表格块, 有表头


def 配对胜负(甲, 乙):
    """逐题比较两个方案：甲胜/平/乙胜。

    库外题没有金标准（排名恒为 None → 两边都记 10^6 → 恒平），
    因此它们只放大「平」的计数、不参与胜负判断 —— 这与「分母固定」并不冲突：
    分母仍是全部题目，只是库外题在任何方案下都判平。
    """
    Z = {编: 排 for 编, _, 排, _ in 甲["明细"]}
    Y = {编: 排 for 编, _, 排, _ in 乙["明细"]}
    甲胜 = 平 = 乙胜 = 0
    for 编 in Z:
        if 编 not in Y:
            continue
        a = Z[编] if Z[编] is not None else 10 ** 6
        b = Y[编] if Y[编] is not None else 10 ** 6
        if a < b:
            甲胜 += 1
        elif a > b:
            乙胜 += 1
        else:
            平 += 1
    return 甲胜, 平, 乙胜


def 跑一个方案(名称, 切分函数, 文档列表, 服务地址, 查询向量, 查询模):
    print()
    print("-" * 92)
    print(" 跑方案 " + 名称)
    print("-" * 92)

    块列表 = []          # (文档文号, 前缀, 正文)
    for 文档 in 文档列表:
        for 前缀, 正文 in 切分函数(文档):
            if len(正文.strip()) >= 8:
                块列表.append((文档["文号"], 前缀, 正文))

    嵌入文本 = [(前 + "\n" + 文) for _, 前, 文 in 块列表]
    向量表 = 取向量(服务地址, 嵌入文本, 标签="嵌入")
    模表 = [求模长(向) for 向 in 向量表]
    规范块文 = [规范化(文) for _, _, 文 in 块列表]

    # 预筛：哪些块含哪条题的全部金标准（合取）
    候选 = {}
    for 序, (编号, 问句, 目标, 金标准, 类别) in enumerate(查询集):
        if 类别 == "库外":
            continue
        片段们 = [规范化(x) for x in 金标准 if 规范化(x)]
        命中块 = [i for i, 文 in enumerate(规范块文)
                  if all(片 in 文 for 片 in 片段们)]
        候选[序] = 命中块

    命中排名, 库外最高分, 库内正确分, 不可召回 = [], [], [], []
    逐题明细 = []
    前三域外 = 0

    for 序, (编号, 问句, 目标, 金标准, 类别) in enumerate(查询集):
        分列表 = []
        for i in range(len(块列表)):
            if 模表[i] == 0:
                分列表.append((-1.0, i))
            else:
                分列表.append((点积(查询向量[序], 向量表[i]) / (查询模[序] * 模表[i]), i))
        分列表.sort(key=lambda 项: (-项[0], 项[1]))
        最高分, 最高块 = 分列表[0]

        if 类别 == "库外":
            库外最高分.append(最高分)
            逐题明细.append((编号, 类别, None, 最高分, 分列表[:3], 块列表))
            continue

        命中的 = 候选[序]
        if not 命中的:
            不可召回.append(编号)
            命中排名.append(None)
            逐题明细.append((编号, 类别, None, 最高分, 分列表[:3], 块列表))
            continue

        排名 = None
        分数 = None
        for 位, (分, 块序) in enumerate(分列表, start=1):
            if 块序 in 命中的:
                排名, 分数 = 位, 分
                break
        命中排名.append(排名)
        库内正确分.append(分数)
        逐题明细.append((编号, 类别, 排名, 分数, 分列表[:3], 块列表))

    # 🔴 分母固定 = 库内题**全部**计入，不可召回题记「必然未命中」（不是从分母里剔除）。
    #    理由：不可召回是**该方案自己的边界策略**造成的（把金标准切散了），
    #    属于方案的失分，不能通过「不算它」来美化。剔除后分母会在方案之间变化
    #    （S11 会变成 44/59 而非 44/60），使各行数字不可比。
    库内题数 = len(命中排名)
    无穷 = 10 ** 9
    排名们 = [r if r is not None else 无穷 for r in 命中排名]
    r1 = sum(1 for r in 排名们 if r == 1) / 库内题数
    r3 = sum(1 for r in 排名们 if r <= 3) / 库内题数
    r5 = sum(1 for r in 排名们 if r <= 5) / 库内题数
    mrr = sum((1.0 / r) for r in 排名们 if r < 无穷) / 库内题数

    表格块, 有表头 = 统计表格结构(块列表)
    库内均分 = sum(库内正确分) / len(库内正确分) if 库内正确分 else 0.0
    库外均分 = sum(库外最高分) / len(库外最高分) if 库外最高分 else 0.0

    结果 = {
        "方案": 名称,
        "块数": len(块列表),
        "平均块长": sum(len(文) for _, _, 文 in 块列表) / max(1, len(块列表)),
        "recall@1": r1, "recall@3": r3, "recall@5": r5, "MRR": mrr,
        "不可召回": 不可召回,
        "表格块": 表格块, "有表头": 有表头,
        "库内均分": 库内均分, "库外均分": 库外均分,
        "库外闯入前三": 前三域外,
        "明细": [(编号, 类别, 排名, 分数) for 编号, 类别, 排名, 分数, _, _ in 逐题明细],
        "_分列表": {编号: 分列表 for 编号, _, _, _, 分列表, _ in 逐题明细},
        "_块列表": 块列表,
    }
    print("   块数 %d，平均块长 %.0f 字，recall@1 %.4f，recall@3 %.4f，MRR %.4f"
          % (len(块列表), 结果["平均块长"], r1, r3, mrr))
    return 结果


def 分类指标(结果, 类别):
    """🔴 分母固定为**该类全部题数**，不剔除「结构性不可召回」的题。

    早先版本只统计 排 is not None 的题 → 分母随可召回数浮动，
    「检索失败」与「没有可检的东西」表现相同 = 没有判据。
    扩到 60 题后必须钉死分母，否则类别间不可比。
    """
    全部 = [排 for 编, 类, 排, _ in 结果["明细"] if 类 == 类别]
    if not 全部:
        return None, None, 0
    命中 = [r for r in 全部 if r is not None]
    r1 = sum(1 for r in 命中 if r == 1) / len(全部)
    r3 = sum(1 for r in 命中 if r <= 3) / len(全部)
    return r1, r3, len(全部)


def 长文档指标(结果):
    """长文档子集 = 目标文档落在 QP-01 / QP-06 的题。分母同样固定为该子集全部题数。"""
    目标编号 = {编号 for 编号, _, 目标, _, 类 in 查询集
                if 类 != "库外" and set(目标) & 长文档集}
    全部 = [排 for 编, 类, 排, _ in 结果["明细"] if 编 in 目标编号]
    if not 全部:
        return None, None, 0
    命中 = [r for r in 全部 if r is not None]
    r1 = sum(1 for r in 命中 if r == 1) / len(全部)
    r3 = sum(1 for r in 命中 if r <= 3) / len(全部)
    return r1, r3, len(全部)


