# -*- coding: utf-8 -*-
"""
拒答规则实测（作品一 · D4）
============================

背景
----
`重排对照-报告.md` §三.4 量化过一个结论：**单一全局阈值做不到**。

    库内题最高重排分 … 最低 -2.37
    库外题最高重排分 ：O03=2.65  O06=0.18  O01=-4.39  O05=-5.37  O02=-6.02  O04=-8.95

O03 / O06 落在**库内分数区间内部**，要拦住它们得把阈值提到 3.0，代价是误拒 33% 库内题。

`诊断-库外线索.py` 找到了第二类判据的物理形态：
**O03 的 Top-3 块里真的引用了库外文档**（QW-DD-05 / QW-QC-01 / QW-QC-02 / QW-WM-03），
而库内对照题（K01 / L01）的 Top-3 一个都没有。→ 「**引用链是否闭合**」是可判的。

本脚本把这条规则**量化**，而不是"看着合理就用"：
    · 分母固定：库内 60 题 / 库外 6 题，**全部**参与，不挑样本；
    · 三条规则各自单独评估，再看并用 —— 否则说不清是哪条起了作用；
    · **误伤率与拦截率同等重要** —— 只报拦截率是在给自己发奖。

三条规则
--------
    类1 分数阈值   ：全库（= 池内 Top-50，已验证 10/10 等价）最高重排分 ≤ 阈值
    类2 引用链闭合 ：**Top-1 块**内出现「本文档体系前缀」的编号且**不在库内文号表**
                     Top-1 = 答案的直接依据；改用 Top-3 会误伤 4/60 库内题（见下）
    类③ 生成端     ：不能在这里测（要调 LLM），留给 `验收-知识库服务.py`

类2 的两个关键约束（都是实测踩出来的）：
  · **必须用修正后的编号正则**。第一版 `[A-Z]{2,6}(-[A-Z]{2,6}){1,2}-\\d+` 会把
    `JC-GY-2026-006` 截成 `JC-GY-2026` → 库内文档被误判成库外引用 → 库内题大面积误伤。
  · **必须用前缀白名单**。`QR-` 是记录表单（不入库是正常的），`ISO-` / `GB-` 是外部标准 ——
    它们都不是"本文档体系的文档"，混进来只会制造假阳性。

用法：
    python scripts/实验-拒答规则.py                # 全 66 题
    python scripts/实验-拒答规则.py --前N 5         # 冒烟
"""

import importlib.util
import json
import os
import re
import sys
import time

脚本目录 = os.path.dirname(os.path.abspath(__file__))
根目录 = os.path.dirname(脚本目录)
输出目录 = os.path.join(根目录, "eval")
题目文件 = os.path.join(输出目录, "题目.json")
结果文件 = os.path.join(输出目录, "拒答规则-结果.json")

向量服务 = "http://127.0.0.1:8082"
重排服务 = "http://127.0.0.1:8085"

池深 = 50
取块数 = 3
分数阈值 = -3.0        # 库内最低 -2.37（余量 0.63）、库外最近 -4.39（余量 1.39）

def 载入(文件名, 别名):
    路 = os.path.join(脚本目录, 文件名)
    规范 = importlib.util.spec_from_file_location(别名, 路)
    模块 = importlib.util.module_from_spec(规范)
    规范.loader.exec_module(模块)
    return 模块


def 抽文档号(文本):
    """转发到 `检索-混合.py` 的**单一实现** —— 同一格式多实现必然漂移。

    编号正则与前缀白名单都放在那里（服务与实验共用同一份）。
    """
    return 检.抽文档号(文本)


def 主流程():
    global 检                       # `抽文档号` 转发要用它
    sys.stdout.reconfigure(errors="replace")
    前N = None
    if "--前N" in sys.argv:
        前N = int(sys.argv[sys.argv.index("--前N") + 1])

    检 = 载入("检索-混合.py", "检索")
    模 = 检.载入分块模块()
    检.模 = 模
    重 = 载入("实验-重排对照.py", "重排")

    文档列表 = 模.读语料()
    块列表 = []
    for 文档 in 文档列表:
        for 前缀, 正文 in 模.切标题结构(文档, 1200, False, 软表格=True):
            if len(正文.strip()) >= 8:
                块列表.append((文档["文号"], 前缀, 正文))
    嵌入文本 = [(前 + "\n" + 文) for _, 前, 文 in 块列表]
    库内文号 = {文档["文号"] for 文档 in 文档列表}

    print("=" * 100)
    print(" 拒答规则实测    基座 S13 软表保-1200    %d 块    池深 %d    Top-%d"
          % (len(块列表), 池深, 取块数))
    print("=" * 100)
    print(" 库内文号表（%d）：%s" % (len(库内文号), "、".join(sorted(库内文号))))
    print(" 类1 阈值 %+.2f ｜ 类2 前缀白名单 %s" % (分数阈值, " ".join(检.文档前缀)))
    print()

    print("算 BM25 索引 …")
    BM25索引 = 检.建BM25索引(嵌入文本)

    题集 = json.load(open(题目文件, encoding="utf-8"))["题目"]
    if 前N:
        题集 = 题集[:前N]

    明细 = []
    print("[跑] %d 题 …\n" % len(题集))
    起 = time.time()
    for 序号, 题 in enumerate(题集, start=1):
        编号, 问句, 类别 = 题["编号"], 题["问"], 题["类别"]
        序B, _ = 检.BM25排序(问句, BM25索引)
        池 = 序B[:池深]
        分 = 重.重排打分(重排服务, 问句,
                        [(块列表[i][1] + "\n" + 块列表[i][2]) for i in 池], 标签=编号)
        分表 = {i: s for i, s in zip(池, 分)}
        最高 = max(分表.values())
        全序 = sorted(池, key=lambda i: -分表[i]) + 序B[池深:]
        取 = 全序[:取块数]

        # 类2 两个口径：
        #   Top-1 = 答案的**直接依据**（收窄后，见 `查看-拒答题块.py` 的块级证据）
        #   Top-3 = 含「顺带提及」（宽口径，第一版用的，误伤 4/60 库内题）
        引用1 = sorted(抽文档号(嵌入文本[全序[0]]) - 库内文号)
        引用集 = set(引用1)
        for i in 取[1:]:
            引用集 |= (抽文档号(嵌入文本[i]) - 库内文号)
        引用3 = sorted(引用集)

        命中类1 = 最高 <= 分数阈值
        命中类2 = bool(引用1)          # Top-1 口径
        命中类2宽 = bool(引用3)        # Top-3 口径

        明细.append({
            "编号": 编号, "类别": 类别, "问": 问句,
            "最高分": round(最高, 4),
            "命中类1": 命中类1, "命中类2": 命中类2, "命中类2宽": 命中类2宽,
            "库外引用Top1": 引用1, "库外引用Top3": 引用3,
            "拒答": 命中类1 or 命中类2,
        })
        print("  [%2d/%d] %-5s %-8s 最高分 %7.2f  类1%s 类2(Top1)%s%s"
              % (序号, len(题集), 编号, 类别, 最高,
                 "✓" if 命中类1 else "·", "✓" if 命中类2 else "·",
                 ("  库外引用 " + "、".join(引用1)) if 引用1 else
                 (("  (Top3 有 " + "、".join(引用3) + ")") if 引用3 else "")))

    print("\n      用时 %.1f s" % (time.time() - 起))

    # ---------------- 混淆矩阵 ----------------
    库内 = [x for x in 明细 if x["类别"] != "库外"]
    库外 = [x for x in 明细 if x["类别"] == "库外"]

    def 指标(名, 判据):
        内拒 = [x for x in 库内 if 判据(x)]
        外拦 = [x for x in 库外 if 判据(x)]
        # 库外没被拦 = 漏网，等于系统会对库外问题硬答
        漏 = [x["编号"] for x in 库外 if not 判据(x)]
        return {"名": 名, "库内误拒": len(内拒), "库内误拒题": [x["编号"] for x in 内拒],
                "库外拦截": len(外拦), "库外漏网": 漏}

    四档 = [指标("类1 仅分数阈值", lambda x: x["命中类1"]),
            指标("类2(Top-3) 宽口径", lambda x: x["命中类2宽"]),
            指标("类2(Top-1) 收窄", lambda x: x["命中类2"]),
            指标("类1+类2(Top-1)", lambda x: x["拒答"])]

    print()
    print("=" * 100)
    print(" 规则效果（库内 %d 题 / 库外 %d 题；分母固定，不挑样本）" % (len(库内), len(库外)))
    print("=" * 100)
    print(" " + "规则".ljust(24) + "库内误拒".ljust(16) + "库外拦截".ljust(12) + "库外漏网")
    print(" " + "-" * 88)
    for x in 四档:
        print(" " + x["名"].ljust(24)
              + ("%d/%d (%.1f%%)" % (x["库内误拒"], len(库内),
                                     100.0 * x["库内误拒"] / max(1, len(库内)))).ljust(16)
              + ("%d/%d" % (x["库外拦截"], len(库外))).ljust(12)
              + ("、".join(x["库外漏网"]) or "无 ✅"))
    print()
    for x in 四档:
        if x["库内误拒题"]:
            print("  %s 误拒库内：%s" % (x["名"], "、".join(x["库内误拒题"])))

    print()
    print("=" * 100)
    print(" 库内题里触发类2 的样本（需人工核查：是「真线索在库外」还是「顺带提及」）")
    print("=" * 100)
    有引用 = [x for x in 库内 if x["命中类2宽"]]
    if not 有引用:
        print("  （无）")
    for x in 有引用:
        print("  %-5s %-8s 最高分 %6.2f  Top-1 库外号 %-14s Top-3 并集 %s  「%s」"
              % (x["编号"], x["类别"], x["最高分"],
                 "、".join(x["库外引用Top1"]) or "—",
                 "、".join(x["库外引用Top3"]) or "—", x["问"]))

    # ---------------- 分数分布 ----------------
    print()
    print("=" * 100)
    print(" 分数分布（类1 的分离度）")
    print("=" * 100)
    内分 = sorted(x["最高分"] for x in 库内)
    外分 = sorted((x["最高分"], x["编号"]) for x in 库外)
    print("  库内 %d 题最高分：最低 %.2f  中位 %.2f  最高 %.2f"
          % (len(内分), 内分[0], 内分[len(内分) // 2], 内分[-1]))
    print("  库外 %d 题最高分：%s" % (len(外分), "  ".join("%s=%.2f" % (n, s) for s, n in 外分)))
    拦得 = [x for x in 库外 if x["命中类1"]]
    print("  阈值 %+.2f 处，库外被类1 拦下的：%s" % (分数阈值, "、".join(x["编号"] for x in 拦得) or "无"))

    with open(结果文件, "w", encoding="utf-8") as 文件:
        json.dump({"基座": "S13 软表保-1200", "池深": 池深, "取块数": 取块数,
                   "分数阈值": 分数阈值, "文档前缀": list(检.文档前缀),
                   "库内文号": sorted(库内文号),
                   "规则指标": 四档, "明细": 明细}, 文件, ensure_ascii=False, indent=2)
    print("\n 已落盘 %s" % 结果文件)
    return 0


if __name__ == "__main__":
    sys.exit(主流程())
