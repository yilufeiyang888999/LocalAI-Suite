# -*- coding: utf-8 -*-
"""提示词 A/B 对照：同一份资料、同一组采样参数，**只换提示词**。

为什么需要这个脚本（方法论，别省）：
  ① **n=5 不够**。生成端在 temperature=0 **都不是确定函数**（见 `诊断-生成确定性.py`），
     5 次采样里「3/5 vs 4/5」的差别纯属噪声 —— 拿它判提示词好坏等于没有判据。
     本脚本默认 n=20，并要求**至少配一道对照题**。
  ② **判据要能区分「好」和「没变」**：只看一个事实的命中率会被单点波动带偏，
     所以用**多事实计数**（--期望 里的子串全部出现才算命中）。
  ③ **必须配一道非目标题型**：改动供应商维度的提示词，会把「记录写错怎么改」
     这类**与供应商无关**的题也污染出「资料未提及不良率…」的废话。
     **类3 判据 2026-10-09 已重写为「按位置判」**（见 `知识库服务.py` 的 `判生成端拒答()`）：
     拒答词只有出现在**答案开头**（说明它是主句）或答案极短时，才算拒答 ——
     长答案里出现「未提及 / 资料不足」不再被判拒答（旧口径在这类题上 **10/10 误杀**）。
     「误触类3判据」这一列**看到 0 才算干净**；非 0 就要点进那条答案看清是真拒答还是误杀。
     本列直接调用服务里的判据函数，不另抄词表（防漂移）。

用法：
  # 供应商题（测覆盖度）：期望交付率 56.9% 每次都出现
  python scripts\\实验-提示词对照.py --问 "宁波恒力不良率" --期望 "2.03,56.9" --臂 现行 原版 候选

  # 非供应商题（测污染 + 类3 误触）
  python scripts\\实验-提示词对照.py --问 "记录写错了应该怎么改" --期望 "划单横线" --每臂 10

臂：现行 = 服务里**正在跑**的提示词（从 `知识库服务.py` 直接取，永远不漂移）；
    其余为脚本内的候选写法（第 3 条要求的不同写法）。
"""

import os
import sys
import json
import argparse
import importlib.util
import urllib.request

脚本目录 = os.path.dirname(os.path.abspath(__file__))
生成服务 = "http://127.0.0.1:8000"

# ---------- 候选写法：只改「要求」块，其余与现行保持一致 ----------
前置 = ("你是制造业质量与工艺领域的文档助手。请**只根据下面提供的资料**回答用户的问题。\n\n"
      "要求：\n"
      "1. 直接给结论，控制在 120 字以内；\n"
      "2. 引用资料中的数值、编号时必须**逐字照抄**，不要改写、不要推算；\n")
收尾 = ("4. 若资料不足以回答问题，只回答「资料不足」，不要补充资料之外的内容。\n\n")

候选表 = {
    # 改动前的原版：只有 3 条，没有"覆盖度"要求
    "原版": 前置 + "3. 若资料不足以回答问题，只回答「资料不足」，不要补充资料之外的内容。\n\n",

    # 抽象："多条结论必须全部列出" —— 比原版好，但不如点名维度
    "抽象": 前置 + ("3. 资料中与该对象相关的结论若有多条，**必须全部列出**，不要只挑一条说；\n"
                  "   尤其不能漏掉「不达标 / 风险 / 触发条件」类的结论；\n") + 收尾,

    # 点名维度但不加条件 —— 覆盖度最高，但会污染非供应商题 + 触发类3 误判
    "无约束": 前置 + ("3. 回答前先逐个核对资料中该对象的以下维度，**凡资料里有的都要写出来**：\n"
                    "   质量（不良率 / 不合格批）、交付（准时交付率）、评级、要求的动作；\n") + 收尾,

    # 点名维度 + 肯定式"一句话带出"，但仍不加条件
    "一句话": 前置 + ("3. 回答前先逐个核对资料中该对象的以下维度，把资料里**已有的结论用一句话带出**：\n"
                    "   质量（不良率 / 不合格批）、交付（准时交付率）、评级、要求的动作；\n") + 收尾,

    # 现行写法（与 `知识库服务.py` 一致，作为对照；改了服务要同步这里）
    "条件化": 前置 + ("3. **若问题涉及某家供应商**，回答前先逐个核对资料中该供应商的以下维度，\n"
                    "   把资料里已有的结论**用一句话带出**：质量（不良率 / 不合格批）、交付（准时交付率）、评级、要求的动作；\n"
                    "   **若问题不涉及供应商（如工艺、记录、检验规则等），直接回答即可**；\n") + 收尾,
}


def 载入服务模块():
    规范 = importlib.util.spec_from_file_location("知识库服务_对照", os.path.join(脚本目录, "知识库服务.py"))
    模块 = importlib.util.module_from_spec(规范)
    规范.loader.exec_module(模块)
    return 模块


def 生成(提示):
    载荷 = json.dumps({
        "messages": [{"role": "user", "content": 提示}],
        "temperature": 0.1, "max_tokens": 400,
        "chat_template_kwargs": {"enable_thinking": False},
    }, ensure_ascii=False).encode("utf-8")
    请求 = urllib.request.Request(生成服务 + "/v1/chat/completions", data=载荷,
                                  headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(请求, timeout=300) as 响应:
        return (json.loads(响应.read().decode("utf-8"))
                ["choices"][0]["message"].get("content") or "").strip()


def 主():
    解析 = argparse.ArgumentParser()
    解析.add_argument("--问", required=True, help="测试问句")
    解析.add_argument("--期望", required=True, help="逗号分隔；**全部出现**才算命中")
    解析.add_argument("--臂", default="现行 原版 条件化", help="空格分隔；'现行' = 服务里正在跑的提示词")
    解析.add_argument("--每臂", type=int, default=20)
    args = 解析.parse_args()

    服 = 载入服务模块()
    # 🔴 判据只有一份实现（在服务里）。**不要在这里另抄一份词表** ——
    #    抄了就会漂移：2026-10-09 收紧类3 后，旧抄法会把长正常答案里的「未提及」
    #    也算成误触，与生产行为不符。
    判拒 = 服.判生成端拒答
    指纹 = "拒答词出现在开头 %d 字内 ∨ 答案 ≤ %d 字 ｜ 词表 %s" % (
        服.拒答词开窗, 服.短答案上限, 服.拒答词)

    print("建基座 …", flush=True)
    服.建基座()
    结果 = 服.检索(args.问, 3)
    资料 = 服.拼资料(结果["取"])
    期望 = [x for x in args.期望.split(",") if x]

    尾 = "\n{警示}【资料】\n{资料}\n\n【问题】{问句}\n"
    提示表 = {"现行": 服.提示模板.format(警示="", 资料=资料, 问句=args.问)}
    for 名, 头 in 候选表.items():
        提示表[名] = (头 + 尾).format(警示="", 资料=资料, 问句=args.问)

    print("=" * 92)
    print("问句：%s" % args.问)
    print("期望事实：%s ｜ 类3 判据：%s" % (期望, 指纹))
    print("检索 Top-3：%s ｜ 资料 %d 字"
          % ([服.基座["块列表"][i][0] for i in 结果["取"]], len(资料)))
    print("=" * 92)

    汇总 = []
    for 名 in args.臂.split():
        if 名 not in 提示表:
            print("  ⚠ 未知臂：%s（可选：%s）" % (名, "、".join(提示表)))
            continue
        命中 = 触雷 = 0
        长和 = 0
        print()
        print("── %s ──" % 名)
        for i in range(1, args.每臂 + 1):
            答案 = 生成(提示表[名])
            全中 = all(e in 答案 for e in 期望)
            雷 = 判拒(答案)
            命中 += 1 if 全中 else 0
            触雷 += 1 if 雷 else 0
            长和 += len(答案)
            print("  第 %2d | 覆盖%s | 类3误判:%s | %s"
                  % (i, "✅" if 全中 else "❌", "".join(雷) or "—",
                     答案.replace("\n", " ")[:200]))
        汇总.append((名, 命中, 触雷, 长和 // args.每臂))

    print()
    print("=" * 92)
    print("汇总（分母固定 = %d）｜问句：%s" % (args.每臂, args.问))
    print("  %-8s %-12s %-16s %s" % ("臂", "覆盖命中", "误触类3判据", "平均字数"))
    for 名, 命中, 触雷, 均长 in 汇总:
        print("  %-8s %-12s %-16s %s"
              % (名, "%d/%d" % (命中, args.每臂), "%d/%d" % (触雷, args.每臂), 均长))
    print("=" * 92)
    return 0


if __name__ == "__main__":
    sys.exit(主())
