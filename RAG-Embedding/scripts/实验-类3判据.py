# -*- coding: utf-8 -*-
"""类3 判据的**对抗对照** —— 旧口径 vs 生产判据，喂**真实答案**。

为什么需要这个脚本（方法论，别省）：
  ① **判据自己也需要判据**。旧口径把 5 个拒答词一视同仁，看着"更严更安全"，
     实际上 `未提及` / `资料中没有` 在**正常答案里也是合理表述** ——
     实测：无约束提示词下，模型**答对了 S012**，却因为对资料里缺数据的维度写了
     「资料中未提及该供应商的不良率」，整条答案被判成拒答 → **10/10 全被误杀**。
  ② **必须用真实答案，不能用手编字符串**。手编样本只能证明"我这个判据能处理这个串"，
     证明不了"真实分布下会怎样"。本脚本用 `服.调生成` 出真答案。
  ③ **配对设计**：同一份资料、同一组采样参数、同一批答案文本，**只换判据** ——
     所以生成端的非确定性不进入判据比较（同一答案文本喂两套判据，见 `诊断-生成确定性.py`
     关于"生成端不是确定函数"的实测）。
  ④ **判据只有一份实现**：本脚本的"新判据"直接调 `服.判生成端拒答`，
     **不另抄一份** —— 抄了就会漂移，验的就不是生产行为了。
  ⑤ **2026-10-09 二次重写后判据多了一个维度**：除了「拒答词是不是主句」，
     还有「**类2 信号**（检索到的 Top-1 引用了库外文档）」—— 后者是**确定性**的，
     用来兜住「模型把拒答词写到句子后半段」的情况（O03 同一题两种句序，实测漏网 12/12）。
     所以下面的护栏每条样本都标注**实测的**类2 信号状态，**只断言真实场景** ——
     拿一个不成立的假设场景去断言判据，等于自己造失败（上一版就这么踩了一次）。

用法：
  python scripts\\实验-类3判据.py                 # 默认每题每臂 10 次
  python scripts\\实验-类3判据.py --每臂 20
"""

import importlib.util
import os
import sys

sys.stdout.reconfigure(errors="replace")
脚本目录 = os.path.dirname(os.path.abspath(__file__))


def 载入(文件名, 别名):
    规范 = importlib.util.spec_from_file_location(别名, os.path.join(脚本目录, 文件名))
    模块 = importlib.util.module_from_spec(规范)
    规范.loader.exec_module(模块)
    return 模块


服 = 载入("知识库服务.py", "知识库服务")
对照 = 载入("实验-提示词对照.py", "提示词对照")

# 新判据 = 生产函数（不另写）
判新 = 服.判生成端拒答


def 判旧(答案):
    """收紧前的旧口径：任一拒答词命中即判拒答。

    `服.拒答词` 现在是**合并表**（强词 + 弱词），正好等价于旧行为 ——
    它被保留下来只用于这类对照与展示，生产判据请用 `判生成端拒答()`。
    """
    return [w for w in 服.拒答词 if w in 答案]


尾 = "\n{警示}【资料】\n{资料}\n\n【问题】{问句}\n"


def 主():
    每臂 = 10
    if "--每臂" in sys.argv:
        每臂 = int(sys.argv[sys.argv.index("--每臂") + 1])
    只跑 = []
    if "--题" in sys.argv:
        只跑 = sys.argv[sys.argv.index("--题") + 1].split()

    print("建基座 …", flush=True)
    服.建基座()

    场景 = [("T06", "哪家供应商目前处于观察期", "供应商题·资料缺维度（旧判据的雷区）"),
            ("L02", "记录写错了应该怎么改", "非供应商题")]
    if 只跑:
        场景 = [x for x in 场景 if x[0] in 只跑]

    print("=" * 104)
    print(" 类3 判据对抗：旧口径（5 词一视同仁） vs 生产判据")
    print(" 生产判据 = ① 拒答词出现在答案开头 %d 字内 ∨ 答案 ≤ %d 字（此时全篇都算窗口内）；"
          "② **类2 信号非空**时承认缺资料即算" % (服.拒答词开窗, 服.短答案上限))
    print(" 词表     = %s" % (服.拒答词,))
    print("=" * 104)

    for 题号, 问句, 说明 in 场景:
        结果 = 服.检索(问句, 3)
        资料 = 服.拼资料(结果["取"])
        臂 = {
            "现行提示词": 服.提示模板.format(警示="", 资料=资料, 问句=问句),
            "无约束提示词": (对照.候选表["无约束"] + 尾).format(警示="", 资料=资料, 问句=问句),
        }
        print()
        print("┌─ %s ｜ %s ｜ %s（资料 %d 字）" % (题号, 问句, 说明, len(资料)))
        for 臂名, 提示 in 臂.items():
            旧误 = 新误 = 0
            长和 = 0
            例 = []
            新例 = []
            for _ in range(每臂):
                答案 = 服.调生成(提示)
                长和 += len(答案)
                旧命 = 判旧(答案)
                新命 = 判新(答案)
                旧误 += 1 if 旧命 else 0
                新误 += 1 if 新命 else 0
                if 旧命 and not 新命 and len(例) < 2:
                    例.append((旧命, 答案))
                if 新命 and len(新例) < 3:
                    新例.append((新命, 答案))
            print("│  %-14s 旧判拒答 %2d/%d ｜ 生产判据判拒答 %2d/%d ｜ 均长 %3d 字"
                  % (臂名, 旧误, 每臂, 新误, 每臂, 长和 // 每臂))
            for 旧命, 答 in 例:
                print("│      ↳ 旧口径误杀、生产判据释放：命中%s" % 旧命)
                print("│        %s" % 答.replace("\n", " ")[:220])
            for 新命, 答 in 新例:
                # 🔴 必须逐条看清：判拒答 ≠ 判对了 —— 也可能是「短正常答案被误杀」。
                print("│      ⚠ 生产判据也判拒答（%d 字，命中%s）—— 需人工确认：真拒答 还是 误杀？"
                      % (len(答), 新命))
                print("│        %s" % 答.replace("\n", " ")[:220])
        print("└" + "─" * 100)

    # ---------- 统一单元护栏：每条样本带**实测的**类2 信号状态 ----------
    print()
    print("=" * 104)
    print(" 单元护栏：真拒答不得放过 / 正常答案不得误杀（每条标注实测类2 信号状态）")
    print("=" * 104)
    护栏 = [
        # ---- 库外：必须判拒答（漏网方向）----
        ("库外·类1 直接给（O01 实样）", "资料不足", False, True),
        ("库外·O03 句序甲（拒答词在前）",
         "资料不足。处理流程见文档 **QW-DD-05**，但该文档不在本知识库中。", True, True),
        # ↓ 修复前 12/12 全漏网：拒答词首现位 40，落在 12 字窗口外 —— 纯位置判必漏
        ("🔴 库外·O03 句序乙（实测 10/10 此形态）",
         "电镀废液处理流程见 **QW-DD-05**，排放口由环保专员每周取样送检。  资料不足", True, True),
        ("🔴 库外·O03 句序乙·变形（首现位 63）",
         "电镀废液处理流程见 **QW-DD-05**，排放口由环保专员每周取样送检。"
         "由于 **QW-DD-05** 不在本知识库中，故资料不足。", True, True),
        ("弱词式拒答·短", "资料中没有相关信息", False, True),
        # ↓ 2026-10-10 三改提示词后实测漏网 1/5 的形态：模型只声明「不在本知识库中」
        #   却不带「资料不足」—— 旧词表接不住，靠 `库外拒答词`（仅类2 信号时启用）兜住。
        ("🔴 库外·只声明文档不在库（10-10 实测漏网形态）",
         "电镀废液的处理流程见 QW-DD-05，但该文档不在本知识库中。", True, True),
        ("🔴 库外·只声明文档不在库·无类2 信号时不误伤",
         "该工艺要求参见 QW-DD-05，但该文档不在本知识库中。", False, False),
        # ---- 库内：必须作答（误杀方向）----
        # ↓ 真实采样样本（无约束提示词，1/20）：**前半句答对了**，尾巴带「故资料不足」。
        #   这条是「强词一票」都扛不住的证据，也是判据改「按位置判」的直接原因。
        ("库内·L02 污染尾巴（n=20 实测 1/20）",
         "根据资料，记录写错后应划单横线更正，不得涂改，在旁边写正确值并签名。"
         "资料未提及不良率、准时交付率、评级等维度，故资料不足。", False, False),
        ("库内·T06 对缺维度写「未提及」（旧口径 10/10 误杀）",
         "根据资料，处于观察期的供应商是东莞市佳合线材有限公司（S012）。资料中未提及该供应商的不良率。",
         False, False),
        ("库内·长正常答案含「未提及」",
         "东莞精诚（S001）2026年8月不良率为 7.66%，当月判不合格批数为 12 批，该资料未提及注册资本信息。",
         False, False),
        ("库内·P06 实样（**唯一带类2 信号**，答案干净）",
         "向欧盟出口的表面处理件必须确认钝化体系为三价铬，是因为欧盟客户要求禁用六价铬。", True, False),
        ("极短正常答案", "是。", False, False),
    ]
    好 = 0
    for 名, 文, 有信号, 期望 in 护栏:
        实 = bool(判新(文, 有信号))
        ok = 实 == 期望
        好 += 1 if ok else 0
        print(" %-44s 类2=%-2s 期望=%-4s 实得=%-4s 旧口径=%-5s %s"
              % (名[:42], "有" if 有信号 else "无", "拒答" if 期望 else "作答",
                 "拒答" if 实 else "作答", "拒答" if 判旧(文) else "作答",
                 "✅" if ok else "❌"))
    print(" → %d/%d %s" % (好, len(护栏), "✅ 全部符合预期" if 好 == len(护栏) else "✗ 有偏差"))
    print()
    print(" 判据的固有代价：库内题若同时满足「类2 信号非空」+「答案里出现拒答词」会被误判。")
    print(" 离线统计全 66 题：该组合当前出现 0 次（唯一带类2 信号的库内题 P06，答案不含拒答词）。")
    return 0


if __name__ == "__main__":
    sys.exit(主())
