def 重排段(服务, 问句, 文档段, 起始序号):
    """给一段文档打分，返回 [(全局序号, 分数)]。

    为什么要能二分降级：
      服务端物理批（`n_ubatch`）是硬上限 —— 实测 512 时「块 > 512 token」
      会让**整批**返回 `input (N tokens) is too large to process`（HTTP 500），
      而不是只丢那一条。所以失败时二分重试，把长尾块隔离出去；
      真的只剩单块还失败，就是硬失败（块本身超过物理批），如实报错。

    为什么要用返回里的 `index` 回填：
      服务返回的 results 已按分数降序，**顺序不是请求顺序** ——
      想当然按返回顺序对齐会张冠李戴，且不报错。
    """
    体 = json.dumps({"query": 问句, "documents": 文档段},
                    ensure_ascii=False).encode("utf-8")
    最后错 = None
    for 试 in range(重试次数):
        try:
            请求 = urllib.request.Request(服务 + "/rerank", data=体,
                                          headers={"Content-Type": "application/json"})
            with urllib.request.urlopen(请求, timeout=600) as 响应:
                数据 = json.loads(响应.read())
            return [(起始序号 + int(项["index"]), float(项["relevance_score"]))
                    for 项 in 数据["results"]]
        except Exception as 错:                          # noqa: BLE001
            最后错 = 错
            if 试 < 重试次数 - 1:
                time.sleep(2)
    if len(文档段) <= 1:
        raise RuntimeError("单块打分失败（块长 %d 字，可能超过服务端物理批）：%s"
                           % (len(文档段[0]), 最后错))
    print("\n      ↻ %d 块一批失败（%s）→ 二分重试" % (len(文档段), 最后错), flush=True)
    半 = len(文档段) // 2
    return (重排段(服务, 问句, 文档段[:半], 起始序号)
            + 重排段(服务, 问句, 文档段[半:], 起始序号 + 半))


def 重排打分(服务, 问句, 文档列表, 标签=""):
    """返回与 文档列表 **等长同序** 的分数表。"""
    分 = [None] * len(文档列表)
    for 起 in range(0, len(文档列表), 每批条数):
        for 序号, 值 in 重排段(服务, 问句, 文档列表[起:起 + 每批条数], 起):
            分[序号] = 值
    缺 = [i for i, x in enumerate(分) if x is None]
    if 缺:
        raise RuntimeError("%s 重排有 %d 块未拿到分数（如第 %d 块）"
                           % (标签, len(缺), 缺[0]))
    return 分


def 按分排序(块序号列表, 重排分表):
    """按重排分降序（分数相同保持原相对次序 → 稳定排序）。"""
    return sorted(块序号列表, key=lambda i: -重排分表[i])


def 派生顺序(基线序, 重排分表, 池深):
    """重排后的完整排序 = 池内按分重排 + 池外按原序接在后面。"""
    return 按分排序(基线序[:池深], 重排分表) + 基线序[池深:]


# ---------------------------------------------------------------------------
# 二、主流程
# ---------------------------------------------------------------------------

def 主流程():
    global 检, 模
    检 = 加载模块("检索-混合.py", "混合检索")
    模 = 检.载入分块模块()
    # `检索-混合.py` 里的函数引用的是它**自己模块级**的分块模块变量，
    # 而那个变量只在它的 `主流程()` 里被赋值。我们只导入、不调用它的主流程，
    # 所以必须把这个引用补上 —— 否则 `找正确块` 之类会炸在 `模 为 None`。
    检.模 = 模
    模.设终端编码()
    仅护栏 = "--仅护栏" in sys.argv

    文档列表 = 模.读语料()
    问题 = 模.校验金标准(文档列表)
    if 问题:
        print("✗ 金标准校验失败，拒跑（金标准不存在时，「没命中」与「检索差」无法区分）：")
        for 行 in 问题:
            print(行)
        return 1

    查询集 = 模.查询集
    题数上限 = 取参数("--前N")
    冒烟模式 = 题数上限 is not None
    if 冒烟模式:
        查询集 = 查询集[:int(题数上限)]
        print("⚠ 冒烟模式：只跑前 %s 题，指标不可当结论" % 题数上限)
    库内数 = sum(1 for _, _, _, _, 类 in 查询集 if 类 != "库外")

    # 基座与 `检索-混合.py` 完全一致，否则护栏会红
    块列表 = []
    for 文档 in 文档列表:
        for 前缀, 正文 in 模.切标题结构(文档, 1200, False, 软表格=True):
            if len(正文.strip()) >= 8:
                块列表.append((文档["文号"], 前缀, 正文))
    嵌入文本 = [(前 + "\n" + 文) for _, 前, 文 in 块列表]
    全部块序 = list(range(len(块列表)))

    print("=" * 100)
    print(" 重排对照    基座 S13 软表保-1200    %d 块    %d 题（%d 库内 + %d 库外；1 题 = %.2fpp）"
          % (len(块列表), len(查询集), 库内数, len(查询集) - 库内数, 100.0 / 库内数))
    print("=" * 100)

    print("\n[1/5] 算块向量 …")
    起 = time.time()
    块向量表 = 模.取向量(检.默认服务, 嵌入文本, 标签="  嵌入")
    块模表 = [模.求模长(向) for 向 in 块向量表]
    print("      完成，用时 %.1f s" % (time.time() - 起))

    print("[2/5] 建 BM25 索引 …")
    起 = time.time()
    BM25索引 = 检.建BM25索引(嵌入文本)
    print("      词表 %d 个 bigram，用时 %.1f s" % (len(BM25索引["idf"]), time.time() - 起))

    正确块表 = 检.找正确块(块列表, 查询集)
    空集 = [编号 for 编号, 集 in 正确块表.items() if not 集]
    if 空集:
        print("      ⚠ 结构性不可召回（无任何一块含完整金标准）：%s" % "、".join(空集))

    证据组表 = 检.读证据组()
    规范块表 = [模.规范化(文) for _, _, 文 in 块列表]
    if 证据组表:
        问题 = 检.校验证据组(块列表, 证据组表)
        if 问题:
            print("✗ 证据组校验失败，拒跑（否则「覆盖不到」与「证据根本不存在」无法区分）：")
            for 行 in 问题:
                print(行)
            return 1

    # ---------- A/B/C 三通道 + 护栏（前移） ----------
    print("[3/5] 算 A/B/C 三通道 + 护栏校验 …")
    起 = time.time()
    向量缓存 = {}
    原始序表, 逐题信息 = {}, []
    for 编号, 问句, 目标, 金标准, 类别 in 查询集:
        序A, _ = 检.向量排序(问句, 块向量表, 块模表, 向量缓存)
        序B, _ = 检.BM25排序(问句, BM25索引)
        原始序表[编号] = {"A": 序A, "B": 序B, "C": 检.RRF融合([序A, 序B])}
        逐题信息.append({"编号": 编号, "问句": 问句, "类别": 类别,
                         "目标": 目标, "金标准": 金标准})
    print("      用时 %.1f s" % (time.time() - 起))

    基准排名表 = {}
    for 新名, 键 in 基线映射:
        基准排名表[新名] = {
            题["编号"]: (检.求排名(原始序表[题["编号"]][键], 正确块表[题["编号"]])
                        if 题["类别"] != "库外" else None)
            for 题 in 逐题信息}

    护栏问题, 硬失败 = [], False
    if os.path.exists(混合结果文件):
        with open(混合结果文件, encoding="utf-8") as 文件:
            旧 = json.load(文件)
        for 新名, _键 in 基线映射:
            旧名 = 旧名映射[新名]
            旧列 = 旧["明细"].get(旧名, [])
            旧编号 = [x["编号"] for x in 旧列]
            if len(旧编号) != len(set(旧编号)):
                护栏问题.append("  ⚠ 旧结果 %s 里有重复编号（字典取值会丢题），比较不可信" % 旧名)
            旧明细 = {x["编号"]: x["排名"] for x in 旧列}
            新明细 = 基准排名表[新名]
            差 = [(k, 旧明细[k], 新明细.get(k)) for k in 旧明细
                  if 旧明细[k] != 新明细.get(k)]
            if 差:
                明细 = "、".join("%s(旧 %s → 新 %s)" % (k, a, b) for k, a, b in 差[:8])
                if 冒烟模式:
                    护栏问题.append("  ⚠（冒烟模式，不判失败）%s ≡ %s 差 %d 题：%s"
                                    % (新名, 旧名, len(差), 明细))
                else:
                    硬失败 = True
                    护栏问题.append("  ✗ %s ≡ %s 差 %d 题：%s" % (新名, 旧名, len(差), 明细))
            else:
                print("      ✅ %s ≡ %s（%d 题逐题一致）" % (新名, 旧名, len(旧明细)))
    else:
        护栏问题.append("  ⚠ 找不到 %s → 无法自查基座是否漂移（**跳过 ≠ 通过**）"
                        % os.path.basename(混合结果文件))
    for 行 in 护栏问题:
        print(行)
    if 硬失败:
        print("\n✗ 基座漂移（块列表 / 向量服务 / 评测集变了）—— 结果不可与 66 题基线比较，拒出报告。")
        return 1
    if 仅护栏:
        print("\n（--仅护栏：到此为止）")
        return 0

    # ---------- 一次重排全库 ----------
    print("[4/5] 全库重排（%d 题 × %d 块 = %d 对，CPU 服务 %s）…"
          % (len(查询集), len(块列表), len(查询集) * len(块列表), 默认重排服务))
    起 = time.time()
    重排分表 = {}
    for 题 in 逐题信息:
        编号 = 题["编号"]
        重排分表[编号] = 重排打分(默认重排服务, 题["问句"], 嵌入文本, 标签=编号)
        题["最高重排分"] = round(max(重排分表[编号]), 4)
        print("      %-5s 完成  %6.1f s" % (编号, time.time() - 起), end="\r")
    耗时 = time.time() - 起
    print("      全部完成，用时 %.1f s（%.0f ms/对）"
          % (耗时, 耗时 * 1000 / (len(查询集) * len(块列表))))

    # ---------- 派生各方案 ----------
    print("[5/5] 派生各方案并算指标 …")
    明细表, 方案序表 = {}, {}
    for 名称, 基线, 池深 in 方案表:
        明细 = []
        本方案序 = {}
        for 题 in 逐题信息:
            编号, 类别 = 题["编号"], 题["类别"]
            if 基线 == "G":
                序 = 按分排序(全部块序, 重排分表[编号])
            elif 池深 is None:
                序 = 原始序表[编号][基线]
            else:
                序 = 派生顺序(原始序表[编号][基线], 重排分表[编号], 池深)
            本方案序[编号] = 序
            排名 = 检.求排名(序, 正确块表[编号]) if 类别 != "库外" else None
            证据组 = 证据组表.get(编号)
            覆盖 = None
            if 证据组:
                覆盖数, 覆盖总, 覆盖明细, 同块排 = 检.算证据覆盖(
                    证据组, 序, 块列表, 规范块表)
                覆盖 = {"覆盖": 覆盖数, "总数": 覆盖总, "组": 覆盖明细,
                        "同块齐备排名": 同块排}
            首序 = 序[0] if 序 else None
            明细.append({
                "编号": 编号, "类别": 类别, "目标": 题["目标"], "金标准": 题["金标准"],
                "排名": 排名, "首名块": 首序,
                "首名文号": 块列表[首序][0] if 首序 is not None else None,
                "首名重排分": round(重排分表[编号][首序], 4) if 首序 is not None else None,
                "正确块数": len(正确块表[编号]),
                "证据覆盖": 覆盖,
            })
        明细表[名称] = 明细
        方案序表[名称] = 本方案序

    汇总表 = {名: 检.汇总(明细表[名]) for 名, _, _ in 方案表}

    # ---------- 表 1：总表 ----------
    print()
    print("=" * 100)
    print(" 表 1 · 重排对照总表（%d 题：%d 库内 + %d 库外；**分母固定 = 库内题数**）"
          % (len(查询集), 库内数, len(查询集) - 库内数))
    print("=" * 100)
    print(" " + 模.补空格("方案", 24) + 模.补空格("R@1", 10) + 模.补空格("R@3", 10)
          + 模.补空格("R@5", 10) + 模.补空格("MRR", 10) + "对 B 的判据")
    print(" " + "-" * 92)
    B1 = 汇总表["B 纯BM25"]["recall@1"]
    for 名, _, _ in 方案表:
        m = 汇总表[名]
        if 名 == "B 纯BM25":
            判 = "＝ 基线（最优单通道）"
        elif m["recall@1"] > B1 + 1e-9:
            判 = "✅ 超过 B"
        elif abs(m["recall@1"] - B1) < 1e-9:
            判 = "＝ 持平"
        else:
            判 = "❌ 不如 B"
        print(" " + 模.补空格(名, 24) + 模.补空格("%.4f" % m["recall@1"], 10)
              + 模.补空格("%.4f" % m["recall@3"], 10)
              + 模.补空格("%.4f" % m["recall@5"], 10)
              + 模.补空格("%.4f" % m["MRR"], 10) + 判)

    # ---------- 表 2：分类 ----------
    类别表 = ("表格", "短小关键", "长文档", "跨文档")
    print()
    print("=" * 100)
    print(" 表 2 · 按类别 R@1 / MRR（看重排动的是哪一块）")
    print("=" * 100)
    print(" " + 模.补空格("方案", 24)
          + "".join(模.补空格("%s(%d)" % (类, sum(1 for t in 逐题信息 if t["类别"] == 类)), 15)
                    for 类 in 类别表))
    print(" " + "-" * 96)
    for 名, _, _ in 方案表:
        print(" " + 模.补空格(名, 24), end="")
        for 类 in 类别表:
            行 = 检.分类汇总(明细表[名], 类)
