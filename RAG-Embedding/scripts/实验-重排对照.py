# -*- coding: utf-8 -*-
"""
重排对照（作品一 · D3）
======================

为什么还要重排
--------------
扩集到 66 题（60 库内）后五通道结论翻转：**B 纯 BM25 反超所有融合方案**
（R@1 0.8333 > C 0.8000 > A 0.7667 > D 0.7333 > E 0.6167），
RRF 调参（F1~F4）已被证伪（F4 配对净胜从 +2 变 −2）。
目前**唯一还没被证伪的增益路径是 cross-encoder 重排** ——
它既不看字面重合、也不看向量距离，而是把 (问句, 块) 拼起来过一遍模型直接打相关性分。

设计：一次重排全库，离线派生所有方案
------------------------------------
重排打分是**逐 (问句, 块) 对独立**的，于是：

    先给全库 290 块打分、再取某通道 Top-N 按分数重排
    ≡
    只把那个 Top-N 送去打分

（子集里的相对顺序不变。）所以只跑一遍重排（66 × 290 ≈ 19k 对），
就能离线派生任意池深、任意基线通道的方案。

这不只是省时间 —— 更是判据要求：**各方案的重排分必须来自同一次打分**，
否则「方案甲比方案乙好」里会混进「两次打分的批次差异」这一额外变量。

判据
----
    · 主判据：R@1 是否超过 **B 纯 BM25 = 0.8333**。
    · 分辨率：60 库内题 → **1 题 = 1.67pp**。
    · 配对胜负 vs B（1 题级别的差异只有配对胜负看得见，均值会骗人）。
    · 护栏：A/B/C 三通道须与 `混合检索-结果.json` **逐题一致** ——
      不一致说明基座变了（块列表 / 向量服务 / 评测集），全部作废。
      **护栏放在重排之前** —— 基座漂移应当在十几秒内发现，
      而不是跑满 5 分钟才告诉你「作废」。
    · 靶子：P01（跨文档）、P07（真多跳）。
    · 附带产出：重排分的**库内 / 库外分离度** —— 这是 10-12 拒答阈值的候选判据。

零第三方依赖（只用标准库）。分块与 BM25/RRF/向量全部复用 `检索-混合.py`，
不复制实现（同一格式多实现必须交叉验证，否则迟早漂移）。

用法：
    python scripts/实验-重排对照.py              全跑
    python scripts/实验-重排对照.py --前N 3      只跑前 3 题（冒烟）
    python scripts/实验-重排对照.py --仅护栏      只算 A/B/C 并做护栏（约 15 s）
"""

