def 平均秩(表):
    """降序平均秩（1 起），并列取平均 —— Spearman 的前提。"""
    序 = sorted(range(len(表)), key=lambda i: -表[i])
    秩 = [0.0] * len(表)
    i = 0
    while i < len(序):
        j = i
        while j + 1 < len(序) and 表[序[j + 1]] == 表[序[i]]:
            j += 1
        平均 = (i + j) / 2.0 + 1
        for k in range(i, j + 1):
            秩[序[k]] = 平均
        i = j + 1
    return 秩


def 斯皮尔曼(甲, 乙):
    n = len(甲)
    if n < 2:
        return 1.0
    秩甲, 秩乙 = 平均秩(甲), 平均秩(乙)
    d2 = sum((a - b) ** 2 for a, b in zip(秩甲, 秩乙))
    return 1.0 - 6.0 * d2 / (n * (n * n - 1))


def 前K集合(表, K):
    return set(sorted(range(len(表)), key=lambda i: -表[i])[:K])


def 比分数(甲, 乙):
    最大, 逐位同 = 0.0, 0
    for a, b in zip(甲, 乙):
        d = abs(a - b)
        if d > 最大:
            最大 = d
        if a == b:
            逐位同 += 1
    return 最大, 逐位同, len(甲)


