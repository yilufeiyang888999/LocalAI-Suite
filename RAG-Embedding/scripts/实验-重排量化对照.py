# -*- coding: utf-8 -*-
"""
重排量化对照：Q8_0 vs FP16（作品一 · D3 补充）
=============================================

问题
----
默认检索链用的是 bge-reranker-v2-m3-**Q8_0**（606 MiB）。它比 FP16（1.1 GiB）小 45%，
推理也更快 —— 但**量化是否伤了重排质量**？没测就不能说。

判据
----
    · **唯一变量 = 重排模型。** 基座（S13 软表保-1200 / 290 块）、评测集（66 题）、
      批大小（16）、服务参数（`-t 24 --parallel 1 -b 2048 -ub 2048`）全部固定。
    · **同一批 (问句, 块) 对、在同一进程内先后送两个服务** —— 这是"分数级比对"
      能成立的前提。分两次独立运行去比，差异里会混进批次噪声。
    · 主判据：方案 **RB50**（推荐配置）的 R@1 / R@3 / R@5 / MRR 是否变化。
      其中 **R@3 与 MRR 最要紧** —— 最终交给生成端的正是重排后的 Top-3。
    · 辅判据：每题 Top-3 / Top-5 成员重合率、Spearman 秩相关、逐题配对胜负。

为什么要先跑 `诊断-重排可复现性.py`
----------------------------------
实测（3 题 × 60 块）：

    ┌──────┬──────┬───────┬──────────────────────┬────────────┐
    │ 端口 │ 模型 │ 槽数  │ 同批连打两次最大差   │ 批量无关   │
    ├──────┼──────┼───────┼──────────────────────┼────────────┤
    │ 8086 │ FP16 │ 4     │ 2.5e-02 ~ 3.0e-02    │ ❌ 6.9e-02 │
    │ 8090 │ FP16 │ 1     │ 0.000e+00            │ ✅         │
    │ 8085 │ Q8_0 │ ?     │ 0.000e+00            │ ✅         │
    │ 8088 │ Q8_0 │ 1     │ 0.000e+00            │ ✅         │
    └──────┴──────┴───────┴──────────────────────┴────────────┘

且 **8085 与 8088 逐位完全相同（60/60）** —— 说明 Q8_0 对槽数免疫（整数点积），
而 FP16 的浮点归约在多槽/批组成变化下**不可复现**。

**所以本脚本必须跑在 `--parallel 1` 上**，否则量出来的"量化差异"里会混进
"同一个模型两次跑都不一样"的噪声 —— 那就不是量化的代价，是部署的代价。

池的选择
--------
只打每题「**向量 Top-20 ∪ BM25 Top-50**」的并集池（约 60~70 块），而不是全库 290 块：

  · 与全库等价 —— 重排逐对独立（且批量无关性已实测），池内排序 = 全库排序的前缀；
  · 更贴合上线 —— 真实检索也只把召回池送去重排（全库重排每题 4.4 s vs 池内 0.75 s，CPU）；
  · 省 5 倍时间。

代价：本脚本**不能派生 RG（全局重排）** —— 但 RG 在 `重排对照-报告.md` 里已被判定
「与 RB50 同分、纯浪费」，不需要纳入量化对照。

用法：
    python scripts/实验-重排量化对照.py
    python scripts/实验-重排量化对照.py --前N 3      冒烟
    python scripts/实验-重排量化对照.py --仅护栏      只验基座（约 15 s）
"""

