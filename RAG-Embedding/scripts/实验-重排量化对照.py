def 主流程():
    global 检, 模, 排
    检 = 加载模块("检索-混合.py", "混合检索")
    模 = 检.载入分块模块()
    # 同 `实验-重排对照.py`：只导入不调主流程时，分块模块的引用要手工补上
    检.模 = 模
    排 = 加载模块("实验-重排对照.py", "重排对照")
    模.设终端编码()
    仅护栏 = "--仅护栏" in sys.argv

    文档列表 = 模.读语料()
    问题 = 模.校验金标准(文档列表)
    if 问题:
        print("✗ 金标准校验失败，拒跑（金标准不存在时，「没命中」与「检索差」无法区分）：")
        for 行 in 问题:
            print(行)
        return 1

    查询集 = 模.查询集
    题数上限 = 取参数("--前N")
    冒烟模式 = 题数上限 is not None
    if 冒烟模式:
        查询集 = 查询集[:int(题数上限)]
        print("⚠ 冒烟模式：只跑前 %s 题，指标不可当结论" % 题数上限)
    库内数 = sum(1 for _, _, _, _, 类 in 查询集 if 类 != "库外")

    块列表 = []
    for 文档 in 文档列表:
        for 前缀, 正文 in 模.切标题结构(文档, 1200, False, 软表格=True):
            if len(正文.strip()) >= 8:
                块列表.append((文档["文号"], 前缀, 正文))
    嵌入文本 = [(前 + "\n" + 文) for _, 前, 文 in 块列表]

    print("=" * 104)
    print(" 重排量化对照    Q8_0 vs FP16    基座 S13 软表保-1200（%d 块）    %d 题（%d 库内）    1 题 = %.2fpp"
          % (len(块列表), len(查询集), 库内数, 100.0 / 库内数))
    print(" 服务：甲 %s=%s    乙 %s=%s    池 = 向量Top%d ∪ BM25Top%d"
          % (服务甲[0], 服务甲[1], 服务乙[0], 服务乙[1], 向量池, BM25池))
    print("=" * 104)

    print("\n[1/6] 算块向量（%s）…" % 检.默认服务)
    起 = time.time()
    块向量表 = 模.取向量(检.默认服务, 嵌入文本, 标签="  嵌入")
    块模表 = [模.求模长(向) for 向 in 块向量表]
    print("      完成，用时 %.1f s" % (time.time() - 起))

    print("[2/6] 建 BM25 索引 …")
    起 = time.time()
    BM25索引 = 检.建BM25索引(嵌入文本)
    print("      词表 %d 个 bigram，用时 %.1f s" % (len(BM25索引["idf"]), time.time() - 起))

    正确块表 = 检.找正确块(块列表, 查询集)
    空集 = [编号 for 编号, 集 in 正确块表.items() if not 集]
    if 空集:
        print("      ⚠ 结构性不可召回：%s" % "、".join(空集))

    # ---------- 基线序 + 护栏（前移） ----------
    print("[3/6] 算 A/B 基线序 + 护栏校验 …")
    起 = time.time()
    向量缓存 = {}
    原始序表, 逐题信息 = {}, []
    for 编号, 问句, 目标, 金标准, 类别 in 查询集:
        序A, _ = 检.向量排序(问句, 块向量表, 块模表, 向量缓存)
        序B, _ = 检.BM25排序(问句, BM25索引)
        原始序表[编号] = {"A": 序A, "B": 序B}
        逐题信息.append({"编号": 编号, "问句": 问句, "类别": 类别,
                         "目标": 目标, "金标准": 金标准})
    print("      用时 %.1f s" % (time.time() - 起))

    基线映射 = (("A 纯向量", "A"), ("B 纯BM25", "B"))
    旧名映射 = {"A 纯向量": "A 向量", "B 纯BM25": "B BM25"}
    基准排名表 = {}
    for 新名, 键 in 基线映射:
        基准排名表[新名] = {
            题["编号"]: (检.求排名(原始序表[题["编号"]][键], 正确块表[题["编号"]])
                        if 题["类别"] != "库外" else None)
            for 题 in 逐题信息}

    护栏问题, 硬失败 = [], False
    if os.path.exists(混合结果文件):
        with open(混合结果文件, encoding="utf-8") as 文件:
            旧 = json.load(文件)
        for 新名, _键 in 基线映射:
            旧名 = 旧名映射[新名]
            旧列 = 旧["明细"].get(旧名, [])
            旧明细 = {x["编号"]: x["排名"] for x in 旧列}
            新明细 = 基准排名表[新名]
            # 冒烟模式下只比共同题 —— 否则「题不在本次子集里」会被误报成基座漂移
            比较集 = ([k for k in 旧明细 if k in 新明细] if 冒烟模式
                      else list(旧明细))
            差 = [(k, 旧明细[k], 新明细.get(k)) for k in 比较集
                  if 旧明细[k] != 新明细.get(k)]
            if 差:
                明细 = "、".join("%s(旧 %s → 新 %s)" % (k, a, b) for k, a, b in 差[:8])
                护栏问题.append("  ✗ %s ≡ %s 差 %d 题：%s" % (新名, 旧名, len(差), 明细))
                if not 冒烟模式:
                    硬失败 = True
            else:
                print("      ✅ %s ≡ %s（%d 题逐题一致）" % (新名, 旧名, len(比较集)))
    else:
        护栏问题.append("  ⚠ 找不到 %s → 无法自查基座是否漂移（**跳过 ≠ 通过**）"
                        % os.path.basename(混合结果文件))
    for 行 in 护栏问题:
        print(行)
    if 硬失败:
        print("\n✗ 基座漂移 —— 结果不可与既有基线比较，拒出报告。")
        return 1
    if 仅护栏:
        print("\n（--仅护栏：到此为止）")
        return 0

    # ---------- 构造池 ----------
    池表 = {}
    for 题 in 逐题信息:
        编号 = 题["编号"]
        池表[编号] = sorted(set(原始序表[编号]["A"][:向量池])
                            | set(原始序表[编号]["B"][:BM25池]))
    print("      池大小：最小 %d，最大 %d，平均 %.1f 块"
          % (min(len(v) for v in 池表.values()), max(len(v) for v in 池表.values()),
             sum(len(v) for v in 池表.values()) / len(池表)))

    # ---------- 两个模型各打一遍（同一批对、同一进程） ----------
    服务表 = [服务甲, 服务乙]
    分表明细 = {}
    for 名, 服务 in 服务表:
        print("[4/6] 【%s】打分（%d 题 × 平均 %.1f 块）…"
              % (名, len(查询集), sum(len(v) for v in 池表.values()) / len(池表)))
        起 = time.time()
        对总数 = 0
        本表 = {}
        for 题 in 逐题信息:
            编号 = 题["编号"]
            池 = 池表[编号]
            分 = 排.重排打分(服务, 题["问句"], [嵌入文本[i] for i in 池], 标签=编号)
            本表[编号] = {块: 值 for 块, 值 in zip(池, 分)}
            对总数 += len(池)
        print("      【%s】完成，%d 对，用时 %.1f s（%.0f ms/对）"
              % (名, 对总数, time.time() - 起, (time.time() - 起) * 1000 / 对总数))
        分表明细[名] = 本表
        if not 冒烟模式:
            print("      第 1 题示例分（前 5 块）：%s"
                  % "  ".join("%.3f" % v for v in
                              [本表[逐题信息[0]["编号"]][i] for i in 池表[逐题信息[0]["编号"]][:5]]))

    # ---------- 派生各方案 ----------
    print("[5/6] 派生各方案并算指标 …")
    指标表 = {}     # (模型, 方案) -> 汇总
    排名表 = {}     # (模型, 方案) -> {编号: 排名}
    for 名, _服务 in 服务表:
        for 方案名, 基线, 池深 in 方案表:
            明细 = []
            排名表[(名, 方案名)] = {}
            for 题 in 逐题信息:
                编号, 类别 = 题["编号"], 题["类别"]
                分 = 分表明细[名][编号]
                基线序 = 原始序表[编号][基线]
                序 = 排.派生顺序(基线序, {i: 分[i] for i in 基线序[:池深]}, 池深)
                排名 = 检.求排名(序, 正确块表[编号]) if 类别 != "库外" else None
                排名表[(名, 方案名)][编号] = 排名
                首序 = 序[0] if 序 else None
                明细.append({
                    "编号": 编号, "类别": 类别, "排名": 排名,
                    "首名块": 首序, "首名文号": 块列表[首序][0] if 首序 is not None else None,
                    "首名重排分": round(分[首序], 4) if 首序 is not None else None,
                })
            指标表[(名, 方案名)] = 检.汇总(明细)

    # ---------- 表 1：指标对照 ----------
    print()
    print("=" * 104)
    print(" 表 1 · 指标对照（分母固定 = %d 库内题；1 题 = %.2fpp）" % (库内数, 100.0 / 库内数))
    print("=" * 104)
    print(" " + 模.补空格("方案", 24) + 模.补空格("模型", 10) + 模.补空格("R@1", 10)
          + 模.补空格("R@3", 10) + 模.补空格("R@5", 10) + 模.补空格("MRR", 10) + "ΔR@1 / ΔR@3 / ΔMRR")
    print(" " + "-" * 100)
    for 方案名, _b, _d in 方案表:
        基 = 指标表[(服务甲[0], 方案名)]
        for 名, _s in 服务表:
            m = 指标表[(名, 方案名)]
            差 = ""
            if 名 == 服务乙[0]:
                差 = "%+.4f / %+.4f / %+.4f" % (m["recall@1"] - 基["recall@1"],
                                                m["recall@3"] - 基["recall@3"],
                                                m["MRR"] - 基["MRR"])
            print(" " + 模.补空格(方案名, 24) + 模.补空格(名, 10)
                  + 模.补空格("%.4f" % m["recall@1"], 10)
                  + 模.补空格("%.4f" % m["recall@3"], 10)
                  + 模.补空格("%.4f" % m["recall@5"], 10)
                  + 模.补空格("%.4f" % m["MRR"], 10) + 差)
        print(" " + "-" * 100)

    # ---------- 表 2：分数级一致性 ----------
    print()
    print("=" * 104)
    print(" 表 2 · 分数级一致性（同一批块、逐题）—— 排序是否被量化扰动")
    print("=" * 104)
    print(" " + 模.补空格("题", 7) + 模.补空格("池块", 7) + 模.补空格("最大分量差", 13)
          + 模.补空格("逐位相同", 11) + 模.补空格("Top1同", 9) + 模.补空格("Top3同", 9)
          + 模.补空格("Top5同", 9) + "Spearman")
    print(" " + "-" * 100)
    全局最大差 = 0.0
    top3全同, top5全同, top1全同 = 0, 0, 0
    斯氏和, 题数计 = 0.0, 0
    for 题 in 逐题信息:
        编号 = 题["编号"]
        池 = 池表[编号]
        甲 = [分表明细[服务甲[0]][编号][i] for i in 池]
        乙 = [分表明细[服务乙[0]][编号][i] for i in 池]
        最大, 逐位同, 总 = 比分数(甲, 乙)
        全局最大差 = max(全局最大差, 最大)
        t1 = 前K集合(甲, 1) == 前K集合(乙, 1)
        t3 = 前K集合(甲, 3) == 前K集合(乙, 3)
        t5 = 前K集合(甲, 5) == 前K集合(乙, 5)
        top1全同 += 1 if t1 else 0
        top3全同 += 1 if t3 else 0
        top5全同 += 1 if t5 else 0
        ρ = 斯皮尔曼(甲, 乙)
        斯氏和 += ρ
        题数计 += 1
        print(" " + 模.补空格(编号, 7) + 模.补空格(str(len(池)), 7)
              + 模.补空格("%.4f" % 最大, 13) + 模.补空格("%d/%d" % (逐位同, 总), 11)
              + 模.补空格("✅" if t1 else "✗", 9) + 模.补空格("✅" if t3 else "✗", 9)
              + 模.补空格("✅" if t5 else "✗", 9) + "%.4f" % ρ)
    print(" " + "-" * 100)
    print(" 汇总：最大分量差 %.4f｜Top-1 集合全同 %d/%d｜Top-3 全同 **%d/%d**｜Top-5 全同 %d/%d｜"
          "Spearman 均值 **%.4f**"
          % (全局最大差, top1全同, 题数计, top3全同, 题数计, top5全同, 题数计,
             斯氏和 / max(题数计, 1)))

    # ---------- 表 3：RB50 逐题配对胜负 ----------
    print()
    print("=" * 104)
    print(" 表 3 · 推荐方案 RB50 下的逐题配对胜负（Q8_0 基线 vs FP16）")
    print("=" * 104)
    甲包装 = {"明细": [(t["编号"], t["类别"], 排名表[(服务甲[0], "RB50 重排×BM25Top50")][t["编号"]], None)
                      for t in 逐题信息]}
    乙包装 = {"明细": [(t["编号"], t["类别"], 排名表[(服务乙[0], "RB50 重排×BM25Top50")][t["编号"]], None)
                      for t in 逐题信息]}
    胜, 平, 负 = 模.配对胜负(甲包装, 乙包装)
