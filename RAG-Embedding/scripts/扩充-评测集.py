# 三、自检：题目集结构完整性
# ---------------------------------------------------------------------------

def 校验题目集结构(模):
    """题目.json 是唯一来源，所以这里检的是**它自己**有没有坏。

    检查项：① 编号唯一；② 类别合法；③ 库内题必有金标准、库外题必无；
    ④ 跨文档题必有证据组（否则「多跳」这条判据在它身上落空）；
    ⑤ 脚本读到的查询集条数与 json 一致（证明单一来源生效）。
    """
    合法类别 = {"表格", "短小关键", "长文档", "跨文档", "库外"}
    题集 = json.load(open(题目文件, encoding="utf-8"))["题目"]
    问题 = []

    if len(模.查询集) != len(题集):
        问题.append("  脚本查询集 %d 条 ≠ json %d 条（单一来源失效）"
                    % (len(模.查询集), len(题集)))

    见过 = set()
    for 题 in 题集:
        号 = 题["编号"]
        if 号 in 见过:
            问题.append("  编号重复：%s" % 号)
        见过.add(号)
        if 题["类别"] not in 合法类别:
            问题.append("  %s 类别非法：%r" % (号, 题["类别"]))
        if 题["类别"] == "库外":
            if 题.get("金标准"):
                问题.append("  %s 是库外题却有金标准" % 号)
        else:
            if not 题.get("金标准"):
                问题.append("  %s 是库内题却无金标准" % 号)
        if 题["类别"] == "跨文档" and not 题.get("证据组"):
            问题.append("  %s 是跨文档题却无证据组（多跳判据落空）" % 号)
    return 问题


