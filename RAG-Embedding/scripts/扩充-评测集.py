def 建S13块列表(模, 文档列表):
    """用确定的基座 S13 软表保-1200 建块 —— 校验必须跑在**真实分块**上。"""
    块列表 = []
    for 文档 in 文档列表:
        for 前缀, 正文 in 模.切标题结构(文档, 1200, False, 软表格=True):
            if len(正文.strip()) >= 8:
                块列表.append((文档["文号"], 前缀, 正文))
    return 块列表


def 校验新题(模, 文档列表, 块列表):
    全库文本 = "\n".join(文档["正文"] for 文档 in 文档列表)
    规范库 = 模.规范化(全库文本)
    规范块表 = [模.规范化(文) for _, _, 文 in 块列表]

    问题, 警告 = [], []
    for 题 in 新增题:
        if 题["类别"] == "库外":
            continue
        if not 题.get("金标准"):
            问题.append("  %s 是库内题却没有金标准片段" % 题["编号"])
            continue
        # 护栏 1：片段必须逐字存在
        for 片段 in 题["金标准"]:
            规范片段 = 模.规范化(片段)
            if 规范片段 not in 规范库:
                问题.append("  ✗ %s 金标准片段在语料中找不到：%r" % (题["编号"], 片段))
        # 护栏 2：合取必须能落到某一块
        片段们 = [模.规范化(x) for x in 题["金标准"]]
        命中块 = [i for i in range(len(块列表))
                  if all(p in 规范块表[i] for p in 片段们)]
        if not 命中块:
            问题.append("  ✗ %s 的片段合取在 S13 分块下凑不到同一块（结构性不可召回）" % 题["编号"])
        else:
            文号 = 排序去重([块列表[i][0] for i in 命中块])
            if 题["目标"] and not (set(文号) & set(题["目标"])):
                警告.append("  ⚠ %s 命中块文号 %s 不在目标文档 %s 内（目标只用于分组统计，不影响打分）"
                            % (题["编号"], "/".join(文号), "/".join(题["目标"])))
            # 证据组校验
            for 组 in 题.get("证据组", []):
                组片段 = [模.规范化(x) for x in 组["片段"]]
                if not any(all(p in 规范块表[i] for p in 组片段) for i in range(len(块列表))):
                    问题.append("  ✗ %s 证据组「%s」在语料中不存在" % (题["编号"], 组["名"]))
                for 片段 in 组["片段"]:
                    if 模.规范化(片段) not in 规范库:
                        问题.append("  ✗ %s 证据组「%s」片段找不到：%r"
                                    % (题["编号"], 组["名"], 片段))
    return 问题, 警告


def 排序去重(表):
    出 = []
    for x in 表:
        if x not in 出:
            出.append(x)
    return 出


# ---------------------------------------------------------------------------
# 五、主流程
# ---------------------------------------------------------------------------

def 主流程():
    落盘 = "--落盘" in sys.argv
    模 = 载入分块模块()
    模.设终端编码()

    print("=" * 92)
    print(" 扩充评测集    dry-run=%s" % (not 落盘))
    print("=" * 92)

    # --- 步骤 1：题目集结构自检 ---
    print("\n[1/4] 题目集结构自检（编号唯一 / 类别合法 / 金标准齐备 / 跨文档带证据组）…")
    问题 = 校验题目集结构(模)
    if 问题:
        print("  ✗ 题目集有问题，先修好再扩充：")
        for 行 in 问题:
            print(行)
        return 1
    print("  ✓ 通过（脚本读到 %d 条，与 json 一致）" % len(模.查询集))

    # --- 步骤 2：读语料 + 建 S13 块 ---
    print("\n[2/4] 读语料 + 建 S13 块 …")
    文档列表 = 模.读语料()
    块列表 = 建S13块列表(模, 文档列表)
    print("  ✓ %d 份语料 / %d 字符 → %d 块"
          % (len(文档列表), sum(len(d["正文"]) for d in 文档列表), len(块列表)))

    # --- 步骤 3：校验新增题 ---
    print("\n[3/4] 校验新增题（%d 条）…" % len(新增题))
    问题, 警告 = 校验新题(模, 文档列表, 块列表)
    for 行 in 警告:
        print(行)
    if 问题:
        print("  ✗ 校验失败：")
        for 行 in 问题:
            print(行)
        return 1
    print("  ✓ 全部通过")

    # --- 合并（幂等：已存在的编号只校验内容一致，不重复追加） ---
    json题集 = json.load(open(题目文件, encoding="utf-8"))["题目"]
    已有 = {题["编号"]: 题 for 题 in json题集}
    冲突, 新增数 = [], 0
    for 题 in 新增题:
        旧 = 已有.get(题["编号"])
        if 旧 is None:
            已有[题["编号"]] = 题
            新增数 += 1
        elif 旧 != 题:
            冲突.append("  %s 已存在但内容不同 —— 不能盲目覆盖，请人工确认" % 题["编号"])
    if 冲突:
        print("  ✗ 冲突：")
        for 行 in 冲突:
            print(行)
        return 1

    # 保持「原有顺序 + 新增追加」的稳定次序，便于 diff
    已有编号 = [题["编号"] for 题 in json题集]
    合并后 = [已有[号] for 号 in 已有编号] + \
             [已有[题["编号"]] for 题 in 新增题 if 题["编号"] not in 已有编号]

    from collections import Counter
    分类 = Counter(题["类别"] for 题 in 合并后)
    库内 = sum(v for k, v in 分类.items() if k != "库外")
    print("\n[4/4] 合并后：%d 条（库内 %d + 库外 %d），本次新增 %d 条"
          % (len(合并后), 库内, 分类["库外"], 新增数))
    for 类 in ("表格", "短小关键", "长文档", "跨文档", "库外"):
        if 分类.get(类):
            print("   %-8s %2d 条" % (类, 分类[类]))
    print("   库内题数 %d → 1 题 = %.2fpp（原 33 条时是 3.03pp）" % (库内, 100.0 / 库内))

    if not 落盘:
        print("\n  （dry-run，未写盘；确认无误后加 --落盘）")
        return 0

    原文说明 = json.load(open(题目文件, encoding="utf-8")).get("说明", "")
    with open(题目文件, "w", encoding="utf-8") as 文件:
        json.dump({"说明": 原文说明, "题目": 合并后}, 文件, ensure_ascii=False, indent=2)
    print("\n  ✅ 已写入 %s" % 题目文件)
    return 0


if __name__ == "__main__":
    sys.exit(主流程())
