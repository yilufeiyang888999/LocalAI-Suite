def 切二元组(文本):
    """字符级 bigram，步长 1。

    为什么不用 jieba：
      ① 保零依赖（本机没装，整套脚本都跑在标准库上）；
      ② 中文常用词多为 2 字，bigram 已能覆盖大部分语义单元；
      ③ 对「JC-GY-2026-006」这类串，bigram 会切出 jc / gy / 2026 / 006 等片段，
         比分词更不容易切错 —— 而编号类查询正是 BM25 要补的那块。

    副作用：会产生「莞精」这类噪声 bigram。不用管 —— IDF 会自动把它压下去
    （跨文档高频、区分度低）。
    """
    文本 = re.sub(r"\s+", "", 文本.lower())
    if len(文本) < 2:
        return [文本] if 文本 else []
    return [文本[i:i + 2] for i in range(len(文本) - 1)]


def 建BM25索引(块文本表):
    """一次建好：每块词频、块长、平均长、IDF。290 块量级，纯 Python 足够。"""
    N = len(块文本表)
    词频表, 长度表, df = [], [], {}
    for 文 in 块文本表:
        词列表 = 切二元组(文)
        长度表.append(len(词列表))
        频 = {}
        for 词 in 词列表:
            频[词] = 频.get(词, 0) + 1
        词频表.append(频)
        for 词 in 频:
            df[词] = df.get(词, 0) + 1
    平均长 = sum(长度表) / max(1, N)
    idf = {词: math.log(1.0 + (N - 数 + 0.5) / (数 + 0.5)) for 词, 数 in df.items()}
    return {"N": N, "词频": 词频表, "长度": 长度表, "平均长": 平均长, "idf": idf}


def BM25打分(索引, 查询文本):
    """标准 Okapi BM25。"""
    词列表 = 切二元组(查询文本)
    N, 平均长 = 索引["N"], 索引["平均长"]
    得分 = [0.0] * N
    if not 词列表 or 平均长 <= 0:
        return 得分
    for 词 in 词列表:
        该词idf = 索引["idf"].get(词)
        if 该词idf is None:
            continue
        for 序 in range(N):
            f = 索引["词频"][序].get(词)
            if not f:
                continue
            分母 = f + BM25_K1 * (1.0 - BM25_B + BM25_B * 索引["长度"][序] / 平均长)
            得分[序] += 该词idf * f * (BM25_K1 + 1.0) / 分母
    return 得分


