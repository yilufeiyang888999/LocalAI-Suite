def 向量排序(查询文本, 块向量表, 块模表, 缓存):
    """返回 (降序块序号列表, 分数列表)。查询向量按文本缓存 —— 32 次查询各算一次。"""
    if 查询文本 not in 缓存:
        查询向量 = 模.取向量(默认服务, [查询文本])[0]
        缓存[查询文本] = (查询向量, 模.求模长(查询向量))
    查询向量, 查询模 = 缓存[查询文本]
    分 = []
    for 块向量, 块模 in zip(块向量表, 块模表):
        if 查询模 <= 0 or 块模 <= 0:
            分.append(0.0)
        else:
            分.append(模.点积(查询向量, 块向量) / (查询模 * 块模))
    序 = sorted(range(len(分)), key=lambda i: -分[i])
    return 序, 分


def BM25排序(查询文本, 索引):
    分 = BM25打分(索引, 查询文本)
    序 = sorted(range(len(分)), key=lambda i: -分[i])
    return 序, 分


def 抽扩展词(候选块序, 索引, 问句, 词数=12):
    """伪相关反馈（PRF）的经典做法：从首轮 Top-N 块里挑**高 IDF、原查询里没有**的词。

    为什么这条路能走通、而 LLM 改写走不通：
        扩展词全部**来自库里已有的文本**，不依赖模型知道任何私有事实。
        「六价铬」「钝化」「变更」这些词本来就躺在正确块里，
        首轮 Top-5 已经摸到了含这些词的块 —— 只要把它们捞出来再检一次。

    打分 = IDF × log(1+在候选集内的词频)：
        IDF 保证区分度（「检验」这种万金油词权重低），
        词频保证主题一致（多块都出现的词更能代表这一簇主题）。
    """
    问句词 = set(切二元组(问句))
    词频 = {}
    for 序 in 候选块序:
        for 词, 数 in 索引["词频"][序].items():
            if 词 in 问句词:
                continue
            词频[词] = 词频.get(词, 0) + 数
    if not 词频:
        return []
    打分 = {词: 索引["idf"].get(词, 0.0) * math.log(1 + 数) for 词, 数 in 词频.items()}
    return sorted(打分, key=lambda w: -打分[w])[:词数]


def 求排名(序列表, 正确块集):
    """正确块在排序里的名次（取最靠前的那一个）。空集 = 结构性不可召回。"""
    if not 正确块集:
        return None
    for 位次, 序 in enumerate(序列表, start=1):
        if 序 in 正确块集:
            return 位次
    return None


