# 🔴 正则必须允许「中间段是数字」，否则 `JC-GY-2026-006` 会被截成 `JC-GY-2026`,
#    库内文档被误判成库外引用 → 库内题大面积误伤。（实测踩过，见 `实验-拒答规则.py` 注释）
编号模式 = re.compile(r"[A-Z]{2,6}(?:-[A-Z0-9]{1,6}){1,3}")

# 只认「本文档体系的规范性文件」：
#   QW- 作业指导 / QP- 程序文件 / JC- 变更通知 / JS- 技术协议 / CSR- 客户特殊要求
# 排除：QR-（记录表单，不入库是正常的，混进来制造假阳性）、ISO-/GB-（外部标准）
文档前缀 = ("QW-", "QP-", "JC-", "JS-", "CSR-")


def 抽文档号(文本):
    """抽文本里出现的「本体系文档编号」。记录表单与外部标准不计。"""
    出 = set()
    for m in 编号模式.finditer(文本):
        号 = m.group(0)
        if not 号.startswith(文档前缀):
            continue
        if not any(c.isdigit() for c in 号):
            continue
        出.add(号)
    return 出


def 找正确块(块列表, 查询集):
    """正确块 = **同一块内同时含全部金标准片段**（合取）。返回 {题号: set(块序号)}。"""
    正确 = {}
    for 编号, 问句, 目标, 金标准, 类别 in 查询集:
        片段 = [模.规范化(x) for x in 金标准]
        命中 = set(i for i, (_, _, 文) in enumerate(块列表)
                   if 片段 and all(p in 模.规范化(文) for p in 片段))
        正确[编号] = 命中
    return 正确


def 读证据组():
    """读 eval/题目.json 里的「证据组」（跨文档题专用）。

    金标准（合取）衡量的是「**单块可答性**」—— 同一块内含全部片段。
    但两跳题（提问讲结果、答案讲原因）本来就该按「**多跳可答性**」考核：
    Top-k 内能不能把两侧证据都捞到。证据组就是为这个加的。

    每组 = 文档约束 + 片段合取。**文档约束不能省** ——
    本语料「钝化」出现在 11 份文档、「不良率」在 6 份，不约束就是假阳性一片。
    """
    if not os.path.exists(题目文件):
        return {}
    题集 = json.load(open(题目文件, encoding="utf-8"))["题目"]
    return {题["编号"]: 题["证据组"] for 题 in 题集 if 题.get("证据组")}


def 校验证据组(块列表, 证据组表):
    """护栏：证据组里的每一组，语料里必须真有块满足（文档约束 + 片段合取）。

    不校验的话，「覆盖不到」会同时表示「检索差」和「这组证据根本不存在」——
    两者表现相同 = 没有判据。
    """
    规范表 = [模.规范化(文) for _, _, 文 in 块列表]
    问题 = []
    for 编号, 组列表 in 证据组表.items():
        for 组 in 组列表:
            片段 = [模.规范化(x) for x in 组["片段"]]
            文档 = 组.get("文档") or []
            有没有 = any(
                (not 文档 or 块列表[i][0] in 文档) and all(p in 规范表[i] for p in 片段)
                for i in range(len(块列表))
            )
            if not 有没有:
                问题.append("  %s 证据组「%s」在语料中不存在（文档 %s + 片段 %s）"
                            % (编号, 组["名"], "/".join(文档) or "不限", "/".join(组["片段"])))
    return 问题


def 算证据覆盖(证据组列表, 序, 块列表, 规范表, 上限=5):
    """统计证据组的覆盖情况，返回 (覆盖组数, 总组数, 明细, 同块齐备排名)。

    两个量各管一件事，别混：
      · **覆盖率** = Top-5 内齐备的组数 / 总组数（分母固定，「通过」与「没检查」才分得开）
        —— 衡量**多跳可答性**（两侧证据能不能都捞到）
      · **同块齐备排名** = 最靠前的「一块同时满足全部组」的名次
        —— 衡量**单块可答性**，与金标准（合取）对标，但用**语义等价片段**而不是连续串
    """
    条件 = [(组["名"], [模.规范化(x) for x in 组["片段"]], 组.get("文档") or [])
            for 组 in 证据组列表]

    def 满足(序号, 片段, 文档):
        return (not 文档 or 块列表[序号][0] in 文档) and all(p in 规范表[序号] for p in 片段)

    得 = []
    for 名, 片段, 文档 in 条件:
        排 = None
        for 位次, i in enumerate(序[:上限], start=1):
            if 满足(i, 片段, 文档):
                排 = 位次
                break
        得.append({"名": 名, "最靠前排名": 排})

    同块排 = None
    for 位次, i in enumerate(序, start=1):
        if all(满足(i, 片段, 文档) for _, 片段, 文档 in 条件):
            同块排 = 位次
            break

    return sum(1 for x in 得 if x["最靠前排名"] is not None), len(得), 得, 同块排


def 汇总(明细):
    库内 = [x for x in 明细 if x["类别"] != "库外"]
    有效 = [x for x in 库内 if x["排名"] is not None]
    总数 = len(库内)
    if not 总数:
        return {}
    命中排名 = [x["排名"] for x in 有效]
    return {
        "库内题数": 总数,
        "可召回题数": len(有效),
        "recall@1": sum(1 for r in 命中排名 if r == 1) / 总数,
        "recall@3": sum(1 for r in 命中排名 if r <= 3) / 总数,
        "recall@5": sum(1 for r in 命中排名 if r <= 5) / 总数,
        "MRR": sum(1.0 / r for r in 命中排名) / 总数,
    }


def 分类汇总(明细, 类别):
    子 = [x for x in 明细 if x["类别"] == 类别]
    if not 子:
        return None
    命中 = [x["排名"] for x in 子 if x["排名"] is not None]
    return (sum(1 for r in 命中 if r == 1) / len(子),
            sum(1 for r in 命中 if r <= 3) / len(子),
            sum(1.0 / r for r in 命中) / len(子),
            len(子))


