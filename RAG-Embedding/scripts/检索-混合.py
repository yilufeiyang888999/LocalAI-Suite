def RRF融合(排名表列表, 平滑=RRF_K):
    """Reciprocal Rank Fusion —— 只吃名次。

    为什么不用「分数加权」：两路分数量纲完全不同（余弦 ∈ [-1,1]，BM25 ∈ [0,∞)），
    归一化怎么做都带主观偏置。RRF 从根上绕开这个问题，且 k=60 是原论文取值、无需调。

    返回按融合分降序的块序号列表。
    """
    融合 = {}
    for 排名表 in 排名表列表:
        for 位次, 序 in enumerate(排名表, start=1):
            融合[序] = 融合.get(序, 0.0) + 1.0 / (平滑 + 位次)
    return [序 for 序, _ in sorted(融合.items(), key=lambda 项: -项[1])]


