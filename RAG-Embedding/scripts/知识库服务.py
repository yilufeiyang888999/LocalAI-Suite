def 检索(问句, 取块数=默认取块数, 深=池深):
    """BM25 Top-50 → 重排 → 返回全序与分数。

    `全序` = 池内按重排分降序 + 池外按 BM25 原序接在后面（与实验同口径，不丢块）。
    """
    序B, _ = 检.BM25排序(问句, 基座["BM25索引"])
    池 = 序B[:深]
    分 = 重.重排打分(重排服务, 问句,
                    [基座["嵌入文本"][i] for i in 池], 标签="服务")
    分表 = {i: s for i, s in zip(池, 分)}
    全序 = sorted(池, key=lambda i: -分表[i]) + 序B[深:]
    return {"全序": 全序, "分表": 分表, "取": 全序[:取块数],
            "最高分": max(分表.values()) if 分表 else float("-inf")}


