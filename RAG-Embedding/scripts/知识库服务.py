    新模 = 新检.载入分块模块()
    新检.模 = 新模
    新重 = 载入("实验-重排对照.py", "重排")

    文档列表 = 新模.读语料()                      # ← 最可能抛异常的一步，放在换句柄之前
    块列表 = []
