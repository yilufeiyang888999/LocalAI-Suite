def 调生成(提示文本, 超时=180):
    载荷 = json.dumps({
        "messages": [{"role": "user", "content": 提示文本}],
        "temperature": 0.1,
        "max_tokens": 400,
        "chat_template_kwargs": {"enable_thinking": False},   # Spark-X2.5 默认开 thinking
    }, ensure_ascii=False).encode("utf-8")
    请求 = urllib.request.Request(生成服务 + "/v1/chat/completions", data=载荷,
                                  headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(请求, timeout=超时) as 响应:
        d = json.loads(响应.read().decode("utf-8"))
    return (d["choices"][0]["message"].get("content") or "").strip()


def 拼资料(取块):
    """资料块带**文号 + 章节路径** —— 这就是引用溯源的物理载体。"""
    段 = []
    for i in 取块:
        文号, 前缀, 正文 = 基座["块列表"][i]
        段.append("【%s】\n%s" % (前缀, 正文))
    return "\n\n".join(段)


def 回答(问句, 取块数=默认取块数, 生成=True):
    """核心入口。验收脚本直接调它（不走 HTTP）。"""
    起 = time.time()
    检索结果 = 检索(问句, 取块数)
    检耗时 = time.time() - 起

    判 = 判拒答(检索结果)
    资料 = 拼资料(检索结果["取"])
    引用 = []
    for 位, i in enumerate(检索结果["取"], start=1):
        文号, 前缀, 正文 = 基座["块列表"][i]
        章节 = 前缀.split(">")[-1].strip() if ">" in 前缀 else 前缀
        引用.append({"rank": 位, "doc_no": 文号, "section": 章节,
                     "score": round(检索结果["分表"][i], 4),
                     "excerpt": re.sub(r"\s+", " ", 正文).strip()[:160]})

    out = {
        "question": 问句,
        "top_score": round(检索结果["最高分"], 4),
        "citations": 引用,
        "context": 资料,                 # 送进生成端的原文（前端可展示「依据」；验收用它核对数值忠实度）
        "refused": 判["refused"],
        "refusal_type": 判["type"],
        "refusal_reason": 判["reason"],
        "off_library_refs": 判["库外引用"],
        "answer": "",
        "model_refused": False,
        "timings": {"retrieve": round(检耗时, 3)},
    }

    if 判["refused"]:
        out["answer"] = "资料不足"
        out["timings"]["total"] = round(time.time() - 起, 3)
        return out

    if not 生成 or 不生成:
        out["answer"] = "(未生成)"
        out["timings"]["total"] = round(time.time() - 起, 3)
        return out

    库外信号 = bool(判["库外引用"])
    警示 = 警示模板.format(号="、".join(判["库外引用"])) if 库外信号 else ""
    引导 = "" if 库外信号 else 引导模板          # 与警示互斥：库外场景不让「直接答」抢戏
    尾注 = 尾注模板 if 库外信号 else ""
    提示 = 提示模板.format(引导=引导, 警示=警示, 资料=资料, 问句=问句, 尾注=尾注)
    起生 = time.time()
    try:
        out["answer"] = 调生成(提示)
    except Exception as 错:                                   # noqa: BLE001
        out["answer"] = "(生成失败：%s)" % 错
        out["error"] = str(错)
    生耗时 = time.time() - 起生

    # 类3：生成端自己说「资料不足」→ 也算拒答（这是兜底，能拦住类1/类2 漏掉的）
    # 判据见 `判生成端拒答()`：① 拒答词是主句（开头窗口内）∨ 答案极短；
    #                            ② **检索已提示引用了库外文档** → 承认缺资料即算拒答，不看位置。
    # 🔴 别改回「5 个词任一命中」：那会把长正常答案里的「未提及」也杀成拒答（实测 9~10/10 误杀）。
    # 🔴 也别把 ② 去掉：纯位置判会被"句序翻转"打穿（O03 实测漏网 12/12）。
    命中 = 判生成端拒答(out["answer"], bool(判["库外引用"]))
    if 命中:
        out["refused"] = True
        out["refusal_type"] = "model_refused"
        out["refusal_reason"] = "生成端判定资料不足（命中：%s）" % "、".join(命中)
        out["model_refused"] = True

    out["timings"].update({"generate": round(生耗时, 3),
                           "total": round(time.time() - 起, 3)})
    return out


