    新基座 = {
        "文档列表": 文档列表,
        "块列表": 块列表,
        "嵌入文本": 嵌入文本,
        "库内文号": {文档["文号"] for 文档 in 文档列表},
        "BM25索引": 新索引,
    }
    检, 模, 重 = 新检, 新模, 新重           # 全部成功，才换
    基座 = 新基座
    return 基座


