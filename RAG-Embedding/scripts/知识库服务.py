# ---------------------------------------------------------------------------
# 日志：**请求路径绝不直接写控制台**（2026-10-10 实测踩到，代价很大）
# ---------------------------------------------------------------------------
# 🔴 现象：服务「活着但不应答」—— 端口仍 LISTENING、CPU 0%、所有请求超时（连 /health 都挂）。
#    起因：**Windows 传统控制台(conhost)被鼠标拖选就进入「标记」模式**，
#    此时进程的**下一次控制台输出会永久阻塞**。而本服务每个请求都要往控制台打一行
#    （`log_message`）→ 窗口一旦被选中，服务就冻在那儿，看上去跟崩了没区别。
#    实测（同一个 PID、没重启）：窗口标题带 `Select ` 前缀时 `/health` 6 s 超时；
#    前缀消失后 0.03 s 返回 —— **进程没死，是被卡在控制台 I/O 上**。
#
# 🔴 对策：把「会阻塞的控制台」从**请求路径**上摘下来 —— 只把**上屏**交给后台线程。
#      · 落盘：由**调用线程**直接写。本地追加写是**有界**的、不会被窗口状态影响
#        → **日志一行不少**；进程被 kill 也不会丢掉已经发生的行。
#      · 上屏：交给一根后台守护线程。它被拖选冻住，只冻它自己，请求照常跑。
#      · 队列设上限：控制台长时间冻着就丢最旧的**屏幕**行并计数（`/health.console_dropped`），
#        既不撑爆内存，也不会「冻了却看不出来」。
#
# ⚠️ 中途踩的坑（被实测抓到的）：一开始把「落盘 + 上屏」放在**同一根线程**里（先落盘、再上屏）。
#    控制台一冻，这根线程就卡在上屏上 —— **文件也跟着不再增长**。
#    实测：控制台冻住时打 6 个请求，文件只长了 42 字节（1 行），而期望约 240 字节（6 行）。
#    「先落盘」只保证**卡住那一刻之前**的行不丢；要一行不少，落盘就不能和上屏在同一根线程上。
#
# 白捡的判据：**「窗口被拖选」不再等于「服务不可用」** —— 屏幕上不滚了，
# 但 `/health`、`/ask` 一切照常，日志文件里也一行不缺。
日志文件 = None                       # 启动时由 `开日志文件()` 定；None = 只上屏
日志队列 = queue.Queue(maxsize=2000)
控制台丢弃数 = 0                      # 控制台被冻期间丢掉的**屏幕**行（文件里不缺）
日志写锁 = threading.Lock()


def 开日志文件():
    """按天开一个日志文件。返回路径；失败返回 None（只上屏，服务照常）。"""
    global 日志文件
    try:
        目录 = os.path.join(根目录, "logs")
        os.makedirs(目录, exist_ok=True)
        日志文件 = os.path.join(目录, "知识库-%s.log" % time.strftime("%Y%m%d"))
        return 日志文件
    except OSError:
        日志文件 = None
        return None


def _落盘(行0):
    if 日志文件 is None:
        return
    try:
        with 日志写锁:
            with open(日志文件, "a", encoding="utf-8") as 文:
                文.write(行0)
    except OSError:
        pass            # 日志本身出问题，绝不能再把服务带崩


def 上屏线程():
    """**唯一**的控制台写者。它被「拖选」冻住时，只冻它自己 —— 落盘在别的线程，不受影响。"""
    while True:
        行0 = 日志队列.get()
        if 行0 is None:
            return
        try:
            sys.stdout.write(行0)                   # 全进程**唯一**可能被冻住的一步
            sys.stdout.flush()
        except Exception:                           # noqa: BLE001
            pass                                    # 控制台断了也不管：文件里已经有一份


def 日志(内容, 加时间=True):
    """**整个进程唯一的输出口**。调用线程只做两件**有界**的事：落盘 + 入队，永不阻塞。

    `加时间=False` 给启动横幅用（多行表格不需要每行一个时间戳）。
    """
    global 控制台丢弃数
    行0 = ("  %s  %s\n" % (time.strftime("%H:%M:%S"), 内容)) if 加时间 else (内容 + "\n")
    _落盘(行0)                                      # ① 落盘在**调用线程**里：不跟控制台共命运
    try:
        日志队列.put_nowait(行0)                    # ② 入队给上屏线程；满了就丢屏幕、不丢文件
    except queue.Full:
        控制台丢弃数 += 1                           # 丢屏幕、不丢文件；计数在 /health

