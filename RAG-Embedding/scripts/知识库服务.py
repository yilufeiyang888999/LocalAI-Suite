def main():
    global 监听端口, 不生成, 类2启用, 类2软, 重排服务, 生成服务
    sys.stdout.reconfigure(errors="replace")
    # 日志：先开文件 + 起**唯一**的控制台写线程，再打任何一行。
    # 之后**所有**输出都走 `日志()`（含启动横幅）—— 落盘在调用线程里，
    # 屏幕被拖选时顶多不滚，服务与日志文件都不受影响。
    文件 = 开日志文件()
    threading.Thread(target=上屏线程, name="日志-上屏", daemon=True).start()

    if "--端口" in sys.argv:
        监听端口 = int(sys.argv[sys.argv.index("--端口") + 1])
    不生成 = "--不生成" in sys.argv
    if "--宽松" in sys.argv:
        类2启用 = False
    if "--类2硬" in sys.argv:
        类2软 = False           # 切回「拦截优先」的保守配置（会误拒 P06）
    # 🔴 APP 的生成端端口是**用户可配**的（设置里的 `service_port`），本脚本默认写死 8000。
    # 两边不一致时，现象是「问什么都答资料不足 / 生成失败」——**不报错，只是没结果**，
    # 所以这两个开关必须存在。前端 `/health` 会拿 `deps.generate` 与 APP 的实际地址核对。
    if "--生成端" in sys.argv:
        生成服务 = sys.argv[sys.argv.index("--生成端") + 1].rstrip("/")
