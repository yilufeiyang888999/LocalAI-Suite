def 安全文件名(原名):
    """把上传文件名洗成**纯文件名**。非法时抛 ValueError。

    🔴 目录穿越是这类接口的头号风险：`..\\..\\eval\\题目.json` 或
    `C:\\Windows\\x.md` 都能把"保存到暂存区"变成"往任意路径写"。
    这里只取 basename，再剥掉一切分隔符与盘符冒号，最后卡扩展名白名单。
    """
    名 = os.path.basename(str(原名 or "").replace("\\", "/"))
    名 = 名.replace("/", "").replace("\\", "").replace(":", "").strip()
    if not 名 or 名 in (".", "..") or 名.startswith("."):
        raise ValueError("文件名不合法：%r" % (原名,))
    扩展 = os.path.splitext(名)[1].lower()
    if 扩展 not in 允许扩展:
        raise ValueError("不支持的扩展名 %r（允许：%s）"
                         % (扩展 or "无", "、".join(sorted(允许扩展))))
    return 名


def 解码上传(项):
    """`{"名": "...", "内容": "<base64>"}` → (安全文件名, bytes)。"""
    import base64
    名 = 安全文件名(项.get("名") or 项.get("name"))
    文本 = (项.get("内容") or 项.get("content") or "").strip()
    if not 文本:
        raise ValueError("%s：内容为空" % 名)
    try:
        数据 = base64.b64decode(文本, validate=False)
    except Exception as 错:                                    # noqa: BLE001
        raise ValueError("%s：base64 解码失败（%s）" % (名, 错))
    if len(数据) > 单件上限:
        raise ValueError("%s：超过单件上限 %d MiB" % (名, 单件上限 >> 20))
    return 名, 数据


def 语料清单():
    """现有语料一览 + 悬空引用。悬空引用是**现算的**，不是抄文档里的清单。"""
    计数 = {}
    for 号, _, _ in 基座.get("块列表", []):
        计数[号] = 计数.get(号, 0) + 1
    每份 = []
    for 文档 in 基座.get("文档列表", []):
        每份.append({"文件": 文档["文件"], "文号": 文档["文号"], "标题": 文档["标题"],
                     "字符": len(文档["正文"]), "块数": 计数.get(文档["文号"], 0)})
    引用 = set()
    for 文本 in 基座.get("嵌入文本", []):
        引用 |= 检.抽文档号(文本)
    return {"文档数": len(每份), "块数": len(基座.get("块列表", [])),
            "每份": 每份,
            "库内文号": sorted(基座.get("库内文号", [])),
            "悬空引用": sorted(引用 - 基座.get("库内文号", set())),
            "可选依赖": 可选依赖()}


def 语料预检(上传列表):
    """影子预检（只算不落盘）。返回预检报告 dict。"""
    if not 上传列表:
        raise ValueError("没有上传文件")
    合计 = sum(len(str(项.get("内容") or "")) for 项 in 上传列表)
    if 合计 > 批量上限 * 4 // 3:            # base64 比原文大约 4/3
        raise ValueError("本次上传合计过大（上限 %d MiB）" % (批量上限 >> 20))

    自检 = 取自检()
    临时 = tempfile.mkdtemp(prefix="服务预检-")
    旧输出 = 自检.输出
    自检.输出 = lambda *a, **k: None          # 🔴 请求路径不碰控制台
    try:
        路径 = []
        for 项 in 上传列表:
            名, 数据 = 解码上传(项)
            路 = os.path.join(临时, 名)
            with open(路, "wb") as 文件:
                文件.write(数据)
            路径.append(路)
        现状 = 自检.复算(自检.语料目录)
        影子, 落地 = 自检.影子预检(路径)
        报告 = 自检.预检报告(路径, 影子, 落地, 现状, 自检.读基线())
        报告["口径自证"] = {"通过": True, "问题": []}
        return 报告
    finally:
        自检.输出 = 旧输出
        shutil.rmtree(临时, ignore_errors=True)


def 语料入库(上传列表, 强制=False):
    """把上传的 .md 落进 `corpus/raw/`，然后**热重建**（不重启进程）。

    只接受**已经是 .md** 的内容：非 md 必须先经 `转换-语料.py` 转成规范 Markdown。
    这是刻意的 —— 自动转换出来的文档文号基本抽不到，直接入库就是"不报错只出错"。
    """
    if not 上传列表:
        raise ValueError("没有上传文件")

    预检 = 语料预检(上传列表)
    if not 预检.get("通过") and not 强制:
        return {"已入库": False, "原因": "预检未通过", "预检": 预检}

    def 去重(名):
        """同名不覆盖。覆盖＝静默丢数据，而且旧文档可能已被评测集引用。"""
        出 = 名
        序号 = 1
        while os.path.exists(os.path.join(语料目录, 出)):
            出 = "%s-%d.md" % (os.path.splitext(名)[0], 序号)
            序号 += 1
        return 出

    自检 = 取自检()
    os.makedirs(语料目录, exist_ok=True)
    临时 = tempfile.mkdtemp(prefix="服务入库-")
    写入 = []
    try:
        for 项 in 上传列表:
            名, 数据 = 解码上传(项)
            临时路 = os.path.join(临时, 名)
            with open(临时路, "wb") as 文件:
                文件.write(数据)

            if os.path.splitext(名)[1].lower() in (".md", ".markdown"):
                文本 = 数据.decode("utf-8")      # 🔴 非 UTF-8 会在这里抛 —— 这是预期行为
                目标名 = 去重(名)
            else:
                # 非 md：走**与影子预检同一份**转换实现（`候选转Markdown`），
                # 避免"预检看的是 A、入库写的是 B"这种分叉。
                自检.输出 = lambda *a, **k: None
                文本, 建议名 = 自检.候选转Markdown(临时路)
                目标名 = 去重(建议名)

            with open(os.path.join(语料目录, 目标名), "w", encoding="utf-8", newline="\n") as 文件:
                文件.write(文本)
            写入.append(目标名)
    except Exception:
        for 名 in 写入:                              # 写到一半失败也要回滚
            try:
                os.remove(os.path.join(语料目录, 名))
            except OSError:
                pass
        raise
    finally:
        shutil.rmtree(临时, ignore_errors=True)

    前文 = len(基座.get("文档列表", []))
    前块 = len(基座.get("块列表", []))
    try:
        with 锁:                                    # 与 /ask 互斥，见 `建基座()` 的约定
            建基座()
    except Exception as 错:                          # noqa: BLE001
        # 重建失败就把刚写进去的文件撤掉，**别让库停在半坏状态**
        for 名 in 写入:
            try:
                os.remove(os.path.join(语料目录, 名))
            except OSError:
                pass
        with 锁:
            建基座()
        raise RuntimeError("入库后重建失败，已回滚：%s" % 错)

    日志("语料入库：%s → 文档 %d→%d、块 %d→%d"
         % ("、".join(写入), 前文, len(基座["文档列表"]), 前块, len(基座["块列表"])))
    return {
        "已入库": True,
        "写入": 写入,
        "重建前": {"文档数": 前文, "块数": 前块},
        "重建后": {"文档数": len(基座["文档列表"]), "块数": len(基座["块列表"])},
        "生效判据": "看这里，不看 status: ok —— 旧基座也是 ok",
        "预检": 预检,
        "提醒": ("新文档若引用了原先故意留白的文号，对应库外拒答题会从「该拒答」"
                 "变成「该答」；66 题 / 100 题的口径已变，需要重跑并记账。"),
    }


