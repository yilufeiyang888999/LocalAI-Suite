# 🔴 类3 判据：**按位置判，不按词判**（2026-10-09 重写，依据见 `实验-类3判据.py`）
#
#    旧写法「任一拒答词命中即判拒答」错在哪（两次实测把它打穿）：
#      ① `未提及` / `资料中没有` / `没有相关` **在正常答案里也是合理表述** ——
#         问「哪家供应商处于观察期」，模型**答对了 S012**，却因对资料里缺数据的维度写了
#         「资料中未提及该供应商的不良率」，整条被判拒答 → **10/10 全被误杀**。
#      ② 连"强词一票"也扛不住：另一条 61 字的答案**前半句答对了**
#         （「记录写错后应划单横线更正」），只因污染尾巴带了「故资料不足」被判拒答。
#    共同点：**拿「会出现也会不出现的东西」当判据**（判据铁律 §9.5）。
#
#    改按**位置**判 —— 因为拒答和正常回答在形态上本来就不同：
#      · 真拒答时，拒答词是整条答案的**主句** → 必在**开头**：
#          `资料不足`（首现 0）／`资料不足。处理流程见文档 QW-DD-05…`（首现 0）
#      · 正常答案里，这类词只是**从句** → 位置靠后：
#          被误杀的 184 字、61 字两条，拒答词首现位在 42 之后
#    再加一条兜底：**答案极短**（≤ 短答案上限）时全篇都算"开头" ——
#    防「绕圈子式的拒答」把拒答词推到窗口之后（如"很抱歉，资料不足"）。
#
#    窗口取值依据（实测）：真拒答清一色首现 0；误杀样本首现 42 / 45+。
#    12 落在两者之间且靠近拒答侧 —— **窗口越大越容易误杀，越小越容易漏网**，
#    12 是"抓得住真拒答、放得过从句"的位置；短答案上限 40 见实测（拒答 ≤38、正常 ≥51）。
#
#  🔴🔴 **2026-10-09 二次重写：纯"位置判"也不够 —— 句序会翻。**
#    上面留下的"反向边界"（拒答词被推到窗口之后）我当时以为罕见、标注"未实测"就走了，
#    实测把它打穿：同一道 O03「电镀废液具体怎么处理」、同一份代码，
#    只是**生成端换了两句的顺序**：
#      · 采样甲：`资料不足。处理流程见文档 QW-DD-05…`            → 首现 0  → 判拒答 ✓
#      · 采样乙：`电镀废液处理流程见 QW-DD-05…取样送检。资料不足。` → 首现 37 → 漏网 ✗
#    连打 **12 次全是采样乙 → 漏网 12/12**。
#    教训：**判据不能依赖"模型会把哪个句子放前面"** —— 那不是稳定事实，是采样结果。
#
#    修法：**接一条确定性信号进来**。`判拒答()` 里的类2（Top-1 提到库外文档）
#    **只看检索、不看生成**，是确定的。检索已客观指出"这块资料引用了一份库外文档"，
#    此时模型承认资料不足即为拒答，**不必再要求它在开头**。
#
#    代价实测为零（离线统计全 66 题）：
#      · 库内 60 题里类2 信号非空的**只有 P06**，而它的答案是正常答案（不含任何拒答词）；
#      · 库内 60 题里"答案含拒答词"的是 **0 题** —— 这一层的固有风险面本就极小。
拒答词 = ("资料不足", "无法回答", "未提及", "没有相关", "资料中没有")
拒答词开窗 = 12      # 只在这个字数内找拒答词 = 「它是不是主句」
短答案上限 = 40      # 答案短于此 = 压根没实质内容 → 全篇都算窗口内
# 🔴 2026-10-10 三改提示词后实测补的第三组词：模型可能只声明「不在本知识库中」
#    而不带「资料不足」（O03b 实测漏 1/5）。这组词**只在有类2 信号时参与判定** ——
#    检索已客观确认该文档在库外，模型承认这一点就是拒答，与位置无关、确定性成立。
#    库内题带类2 信号的只有 P06（答案干净），误伤面为零（10-09 离线统计）。
库外拒答词 = ("不在本知识库", "不在知识库", "不在库中", "未收录")


def 判生成端拒答(答案, 有库外引用=False):
    """类3 判据。返回命中的词列表（空列表 = 不判拒答）。

    两条并列判据，任一成立即判拒答：
      ① 拒答词是**主句**（落在开头窗口内）—— 或答案极短（没有实质内容）；
      ② 检索已客观指出"Top-1 引用了库外文档"（`有库外引用=True`）——
         此时"资料不完整"是**事实**，模型承认缺资料即为拒答，**不看位置**。
         承认的表述包括通用拒答词，也包括 `库外拒答词`（"不在本知识库中"等）。

    为什么必须带 ②：纯位置判依赖"模型把拒答词放开头"，而同一道题两种句序
    都可能出现（实测 O03 连打 12 次全漏）。② 确定性来自检索结果，用来兜住句序翻转。
    """
    命 = [w for w in 拒答词 if w in 答案]
    if not 命 and 有库外引用:
        命 = [w for w in 库外拒答词 if w in 答案]
    if not 命:
        return []
    窗 = len(答案) if len(答案) <= 短答案上限 else 拒答词开窗
    if any(w in 答案[:窗] for w in 命):
        return 命
    return 命 if 有库外引用 else []

