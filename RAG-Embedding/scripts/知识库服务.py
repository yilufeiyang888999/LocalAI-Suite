def 判拒答(检索结果):
    """返回 {"refused":bool, "type":ascii|None, "reason":str, "库外引用":[...]}"""
    最高 = 检索结果["最高分"]
    if 最高 <= 分数阈值:
        return {"refused": True, "type": "score_threshold",
                "reason": "全库最高重排分 %.2f ≤ 阈值 %.2f，检索不到相关内容" % (最高, 分数阈值),
                "库外引用": []}

    if 类2启用:
        库外 = set()
        for i in 检索结果["全序"][:类2范围]:
            库外 |= (检.抽文档号(基座["嵌入文本"][i]) - 基座["库内文号"])
        if 库外:
            号 = "、".join(sorted(库外))
            if 类2软:
                # 软模式：不拦，只把「资料引用了库外文档」告诉生成端，由它判断
                return {"refused": False, "type": None, "reason": "", "库外引用": sorted(库外)}
            return {"refused": True, "type": "broken_citation_chain",
                    "reason": "最相关的资料引用了库外文档 %s（该文档未入库），答案所需信息不在库内" % 号,
                    "库外引用": sorted(库外)}

    return {"refused": False, "type": None, "reason": "", "库外引用": []}


