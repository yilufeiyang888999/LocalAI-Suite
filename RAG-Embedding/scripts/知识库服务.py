class 容忍断连的服务器(ThreadingHTTPServer):
    """客户端半途走掉**不是服务端故障**，但默认会打一整页 Traceback。

    🔴 触发场景（2026-10-09 在 8092 控制台实测到两次）：
      · 浏览器**预连接**：连上先不发请求，或发完就关（刷新 / 关标签页 / 换页都会）；
      · 调用方**只取响应头就把 response 丢下不管** —— socket 被 GC 回收时发 RST，
        而服务端此刻还在写这 14 KB 问答页（早先 `启动-服务.py --状态` 就是这么写的）。
      两种都表现为 `WinError 10053 / 10054`，**服务本身完全正常、后续请求照旧**。

    为什么要专门盖住它：默认行为是把完整堆栈打到控制台，看的人会认定服务崩了。
    「把噪声当故障」和「把日志当状态」是同一个毛病的两面 —— 一次就能让运维白排查半天。

    🔴 边界：**只**吞 `ConnectionError` 家族（含 ConnectionResetError /
    ConnectionAbortedError / BrokenPipeError）。其它异常照旧走父类的完整堆栈 ——
    真 bug 不能被这层顺手盖掉，那才是真的把判据弄丢。

    🔴 为什么要计数：吞掉堆栈之后，「服务扛住了断连」和「根本没能触发断连」在控制台上
    **长得一模一样**。所以把次数暴露到 `/health` 的 `client_aborts`，
    让判据能区分这两件事（`探测-问答页.py` 第 8 组就靠它）。
    """

    客户端断连次数 = 0        # 累计；`/health` 里可见
    已报过 = 0                # 只逐条报前几条，避免刷新页面把控制台刷满

    def handle_error(self, 请求, 客户端):
        错 = sys.exc_info()[1]
        if not isinstance(错, ConnectionError):
            return super().handle_error(请求, 客户端)          # 真异常：保留完整堆栈
        类 = type(self)
        类.客户端断连次数 += 1
        if 类.已报过 < 3:
            类.已报过 += 1
            # 带上来源地址：能一眼看出是浏览器预连接还是某个探针脚本在捣乱。
            # 走 `日志()`：这是**请求线程**，同样不能直接写控制台（同 `log_message`）。
            地址 = ("%s:%s" % 客户端[:2]) if isinstance(客户端, tuple) else str(客户端)
            日志("· 客户端提前断开（%s，来自 %s）"
                 "—— 正常：预连接 / 刷新 / 关标签页，服务不受影响"
                 % (type(错).__name__, 地址))
            if 类.已报过 == 3:
                日志("· 同类断连后续不再逐条打印（累计计数见 GET /health 的 client_aborts）")


class 处理器(BaseHTTPRequestHandler):
    # 🔴 这是 `BaseHTTPRequestHandler` 的约定属性名，只能 ASCII（写中文名会被静默忽略）
    protocol_version = "HTTP/1.1"

    def _发跨域头(self):
        """Tauri 的 webview 里，前端是**直接 fetch** 本机服务的（与它调 8000 生成端同一模式，
        见 `ChatView.vue` 的 `fetch(.../v1/chat/completions)`）。所以跨域头是**硬前提**：
        少了它，浏览器/WebView 只会抛一个笼统的 CORS 失败，既看不到状态码也看不到响应体 ——
        排查时会误以为"服务没起来"。

        放开 `*` 的理由：服务**只监听 127.0.0.1**，且不使用 cookie/凭证
        （`*` 与 `Allow-Credentials` 本就互斥）。若日后要收窄，应校验 Origin 是否为
        `tauri://localhost`（打包）或 `http://localhost:1420`（`tauri:dev`）。"""
        self.send_header("Access-Control-Allow-Origin", "*")
        self.send_header("Access-Control-Allow-Methods", "GET, POST, OPTIONS")
        self.send_header("Access-Control-Allow-Headers", "Content-Type")

    def _发(self, 码, 对象):
        体 = json.dumps(对象, ensure_ascii=False, indent=2).encode("utf-8")
        self.send_response(码)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(体)))
        self._发跨域头()
        self.end_headers()
        self.wfile.write(体)

    def do_OPTIONS(self):                                      # noqa: N802
        """预检。当前只用 `application/json`（属 CORS 的"非简单请求"），
        浏览器一定会先发 OPTIONS —— 不回它就等不到真正的 POST。"""
        self.send_response(204)
        self._发跨域头()
        self.send_header("Content-Length", "0")
        self.end_headers()

    def _发页面(self, 内容=None, 名="问答页", 文件="web/index.html"):
        """返回 Web 页面（问答页 / 管理页同一套发送逻辑）。

        页面缺失时给**明确的 503 + 原因**，不降级成 404 ——
        「打不开」和「这个路径不存在」是两种问题，混在一起排查会走弯路。
        """
        内容 = 页面内容 if 内容 is None else 内容
        if 内容 is None:
            self._发(503, {"error": "%s未就绪" % 名,
                           "hint": "%s 缺失或读取失败，见服务启动输出" % 文件})
            return
        体 = 内容.encode("utf-8")
        self.send_response(200)
        self.send_header("Content-Type", "text/html; charset=utf-8")
        self.send_header("Content-Length", str(len(体)))
        # 🔴 `no-store`：页面改动后浏览器必须重新拉。今天已栽过一次「改了没生效」，
        #    不要在上面再叠一层浏览器缓存（服务端也已改为启动时读一次）。
        self.send_header("Cache-Control", "no-store")
        self._发跨域头()
        self.end_headers()
        self.wfile.write(体)

    def do_GET(self):                                          # noqa: N802
        # 🔴 `unquote`：`self.path` 是**原始**请求行，非 ASCII 已被百分号编码
        路径 = unquote(urlparse(self.path).path)
        if 路径 in ("/", "/index.html"):                       # Web 问答页（与 /ask 同源）
            self._发页面()
            return
        if 路径 in 路由_页面:                                   # 知识库管理页
            self._发页面(管理页内容, "管理页", "web/管理.html")
            return
        if 路由_语料.get(路径) == "清单":
            try:
                self._发(200, 语料清单())
            except Exception as 错:                            # noqa: BLE001
                self._发(500, {"error": str(错)})
            return
        if 路径 == "/favicon.ico":                             # 浏览器自动请求，回它免得日志刷 404
            self.send_response(204)
            self._发跨域头()
            self.send_header("Content-Length", "0")
            self.end_headers()
            return
        if 路径 == "/health":
            self._发(200, {
                "status": "ok",
                # 客户端提前断开的累计次数（服务**吞掉**它们、不当故障；只吞 ConnectionError）。
                # 🔴 这个字段是**判据的支点**：吞掉堆栈后，「扛住了断连」和「断连没触发到」
                #    在控制台上分不出来 —— 有计数才能区分（见 `探测-问答页.py` 第 8 组）。
                "client_aborts": getattr(self.server, "客户端断连次数", None),
                # 日志落点 + 「屏幕丢行数」。`console_dropped > 0` 说明控制台有段时间写不出去
                # （窗口被拖选 / 管道断了）——**当时服务仍在正常应答**，日志文件里一行没缺。
                "log_file": 日志文件,
                "console_dropped": 控制台丢弃数,
                "docs": len(基座.get("文档列表", [])),
                "blocks": len(基座.get("块列表", [])),
                "pool": 池深, "top_k": 默认取块数,
                "score_threshold": 分数阈值,
                "class2_enabled": 类2启用, "class2_scope": 类2范围,
                "class2_soft": 类2软,
                # 类3 判据指纹：排查「改了没生效」时靠它区分新旧代码（旧版无此字段）
                # 🔴 指纹字段必须能区分**每一次**重写：一次重写（纯位置判）与二次重写
                #    （位置判 ∨ 类2 信号）的 words/open_window/short_max_len **完全相同** ——
                #    不加这条就分不出跑了哪版，而「判据不能区分新旧」＝ 没有判据。
                "class3": {"words": list(拒答词), "open_window": 拒答词开窗,
                           "short_max_len": 短答案上限,
                           "uses_class2_signal": True,
                           "off_library_words": list(库外拒答词)},
                "chain": "BM25 Top-%d -> rerank -> Top-%d" % (池深, 默认取块数),
                "deps": {"rerank": 重排服务, "generate": 生成服务},
                # 语料与热重建的判据：`docs`/`blocks` 是**唯一**能区分新旧基座的字段
                "corpus": {"dir": os.path.relpath(语料目录, 根目录).replace(os.sep, "/"),
                           "docs": len(基座.get("文档列表", [])),
                           "blocks": len(基座.get("块列表", []))},
                "manage_page": 管理页内容 is not None,
                # 格式转换的可选依赖：缺了不影响问答，只影响对应格式的入库
                "optional_deps": 可选依赖(),
            })
        else:
            self._发(404, {"error": "not found",
                           "paths": ["/", "/health", "/ask", "/manage",
                                     "GET /corpus/list", "POST /corpus/check",
                                     "POST /corpus/add"]})

    def do_POST(self):                                         # noqa: N802
        路径 = unquote(urlparse(self.path).path)
        语料动作 = 路由_语料.get(路径)
        if 路径 != "/ask" and 语料动作 is None:
            self._发(404, {"error": "not found"})
            return
        try:
            长 = int(self.headers.get("Content-Length") or 0)
            体 = json.loads(self.rfile.read(长).decode("utf-8")) if 长 else {}
        except Exception as 错:                                # noqa: BLE001
            self._发(400, {"error": "bad json: %s" % 错})
            return

        # ---------- 语料：预检 / 入库 ----------
        if 语料动作 in ("预检", "入库"):
            上传 = 体.get("文件") or 体.get("files") or []
            if not isinstance(上传, list):
                self._发(400, {"error": "'文件' 必须是数组"})
                return
            try:
                if 语料动作 == "预检":
                    出 = 语料预检(上传)
                else:
                    出 = 语料入库(上传, 强制=bool(体.get("强制") or 体.get("force")))
            except Exception as 错:                            # noqa: BLE001
                # 参数问题（文件名不合法 / 非 md / 超限）都是 400，不是 500 ——
                # 500 是"服务坏了"，400 是"你给的输入不对"，混起来排查会走弯路。
                self._发(400, {"error": str(错)})
                return
            self._发(200, 出)
            return

        # ---------- /ask ----------
        # 兼容中英文键（对外建议用 question，但别让调用方踩空）
        问句 = (体.get("question") or 体.get("问") or "").strip()
        if not 问句:
            self._发(400, {"error": "missing 'question'"})
            return
        取块数 = int(体.get("top_k") or 体.get("取块数") or 默认取块数)
        要生成 = bool(体.get("generate", True))

        try:
            with 锁:
                out = 回答(问句, 取块数, 生成=要生成)
            self._发(200, out)
        except Exception as 错:                                # noqa: BLE001
            self._发(500, {"error": str(错)})

    def log_message(self, 格式, *参数):                        # noqa: A003
        # 🔴 必须走 `日志()`（入队、不阻塞）。这里直接 `sys.stdout.write` 正是
        #    2026-10-10 那次「服务活着却全超时」的引信：窗口一被拖选，请求线程就冻在这一行。
        日志(格式 % 参数)


def 载入页面():
    """把 Web 页面读进内存（只读一次）。返回问题列表（空 = 两个页面都可用）。

    问答页与管理页**各自独立失败**：问答页缺了不影响 HTTP 接口，
    管理页缺了只影响"入库"那个界面 —— 两种"缺"都得能一眼看出来，不能静默降级。
    """
    global 页面内容, 管理页内容
    问题 = []
    for 名, 路 in (("问答页", 页面文件), ("管理页", 管理页文件)):
        try:
            with open(路, "r", encoding="utf-8") as 文:
                文本 = 文.read()
        except OSError as 错:                                  # noqa: BLE001
            文本 = None
            问题.append("  ✗ %s读不到：%s（%s）" % (名, 路, 错))
        if 名 == "问答页":
            页面内容 = 文本
        else:
            管理页内容 = 文本
    return 问题


