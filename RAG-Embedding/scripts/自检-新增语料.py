# -*- coding: utf-8 -*-
"""
自检-新增语料.py —— 入库前的「影子预检」
================================================================================

一句话：**先在影子里入一遍，看会不会出事，再决定要不要真入。**

为什么要有这一步
----------------
往 `corpus/raw/` 加一份文档，有四种失败方式，**其中三种不报错**：

  | 失败方式 | 症状 |
  |---|---|
  | 非 UTF-8 编码 | 🔴 `UnicodeDecodeError` 上抛 → **整个服务起不来**（会报错） |
  | 非 `.md` 后缀 | 静默丢弃，`/health.docs` 不涨（**不报错**） |
  | 文号抽不到 | 回退成文件名主干 → 块前缀错、跨文档线索断（**不报错**） |
  | 补上"故意留白"的文号 | 库外拒答题（O03/O03b）当场失效（**不报错**） |

后三种在界面和日志里看不出任何异常 —— 只有重跑评测才会发现分数掉了，
而那时已经很难定位是哪一步引入的。所以入库前必须有**能区分"通过"和"没检查"的判据**。

做法：影子语料目录
------------------
把 `corpus/raw/` 现有的全部语料 + 候选文件一起复制进临时目录，把 `语料目录` 指过去，
**用服务本身那套代码**（`实验-分块对照.读语料/提取文号/切标题结构`）重算一遍：

  现有库 --> 复算 --> 与基线/`/health` 比对 --> 对得上，才说明"影子里的重算可信"
  影子库 --> 复算 --> 得出新增后的 文号集合 / 悬空引用 / 块数，与现有库对比

**关键：一行代码都不复制。** 分块参数（1200 / 软表格）与文号规则都从原模块取，
否则就是"同一份数据两处定义"——改一处跑另一处，不报错只出错。

用法
----
    python scripts\\自检-新增语料.py                    # 只读现状，并与基线比对
    python scripts\\自检-新增语料.py --写基线           # 建立/刷新基线（首次或语料变更后）
    python scripts\\自检-新增语料.py --预检 a.md b.docx  # 影子预检（支持 md/docx/xlsx/pdf/txt）
    python scripts\\自检-新增语料.py --预检 corpus\\_待入库 --json 报告.json

退出码：0 = 预检通过（无 🔴）；1 = 有阻断项；2 = 预检本身不可信（口径对不上）
"""

