# ======================= 复算：与服务同一套口径 =======================

def 复算(目录):
    """按 `知识库服务.建基座()` 的口径，在一个语料目录上重算。

    返回 {"文档列表","块列表","嵌入文本","库内文号","引用","悬空","每份"}。
    """
    旧 = 分块.语料目录
    分块.语料目录 = 目录
    try:
        文档列表 = 分块.读语料()
        块列表 = []
        每份 = []
        for 文档 in 文档列表:
            本份块 = 0
            for 前缀, 正文 in 分块.切标题结构(文档, 分块上限, False, 软表格=True):
                if len(正文.strip()) >= 最短块:
                    块列表.append((文档["文号"], 前缀, 正文))
                    本份块 += 1
            每份.append({"文件": 文档["文件"], "文号": 文档["文号"],
                         "字符": len(文档["正文"]), "块数": 本份块})
    finally:
        分块.语料目录 = 旧

    嵌入文本 = [(前 + "\n" + 文) for _, 前, 文 in 块列表]
    库内文号 = {文档["文号"] for 文档 in 文档列表}
    引用 = set()
    for 文本 in 嵌入文本:
        引用 |= 检索.抽文档号(文本)
    return {
        "目录": 目录, "文档列表": 文档列表, "块列表": 块列表, "嵌入文本": 嵌入文本,
        "库内文号": 库内文号, "引用": 引用, "悬空": 引用 - 库内文号, "每份": 每份,
    }


def 影子预检(候选路径列表):
    """把现有语料 + 候选文件放进**同一个**临时目录，复算一次。

    返回 (影子结果, 落地清单)。落地清单里带上"转换失败"的候选 ——
    失败也是一条结论，不能因为没产出行就把它从报告里抹掉。
    """
    临时 = tempfile.mkdtemp(prefix="语料预检-")
    try:
        for 名 in sorted(os.listdir(语料目录)):
            if 名.lower().endswith(".md"):
                shutil.copy2(os.path.join(语料目录, 名), os.path.join(临时, 名))

        落地 = []
        for 路 in 候选路径列表:
            项 = {"候选": 路, "落地名": None, "错误": None, "编码": None, "正文": None}
            落地.append(项)
            目标 = os.path.join(临时, 独占名(os.path.basename(路), 临时))
            try:
                准备候选(路, 目标)
            except Exception as 错:                            # noqa: BLE001
                项["错误"] = "%s: %s" % (type(错).__name__, 错)
                continue

            原始 = open(目标, "rb").read()
            级别, 说明, 正文 = 判编码(原始)
            项["编码"] = {"级别": 级别, "说明": 说明}
            项["正文"] = 正文
            项["落地名"] = os.path.basename(目标)

            if 级别 == "fail":
                # 🔴 不放进影子：`读语料()` 是**无 try 的 UTF-8 读**，一份坏编码
                #    会把整次复算带崩 —— 而我们正要报告的就是这件事。
                #    留着它，预检会自己先死，反而报不出问题。
                os.remove(目标)
                项["落地名"] = None
                项["排除原因"] = "非 UTF-8，已从影子中排除（否则整次复算会直接失败）"
        return 复算(临时), 落地
    finally:
        shutil.rmtree(临时, ignore_errors=True)


def 判编码(原始):
    """返回 (级别, 说明, 文本)。

    **严格 UTF-8，不用 replace 兜底** —— 服务就是这么读的，兜底等于把问题藏起来。
    判 fail 时仍用 gb18030 解一份出来，只为让人看清内容（不参与任何判定）。
    """
    if 原始[:3] == b"\xef\xbb\xbf":
        try:
            原始[3:].decode("utf-8")
            return ("warn",
                    "带 UTF-8 BOM：能读进来，但首行 `# ` 前有不可见字符 → 文档标题会丢",
                    原始[3:].decode("utf-8"))
        except UnicodeDecodeError:
            pass
    try:
        return "ok", "UTF-8", 原始.decode("utf-8")
    except UnicodeDecodeError as 错:
        略 = 原始.decode("gb18030", errors="replace")
        return ("fail",
                "非 UTF-8（%s）→ `读语料()` 的 open 没有 try，会直接抛异常，整个服务起不来"
                % 错.reason,
                略)


def 独占名(原文件名, 目录):
    """推导影子目录里不重名的 .md 文件名。**绝不覆盖同名文件**（覆盖=静默丢数据）。"""
    基础 = os.path.splitext(原文件名)[0]
    名 = 基础 + ".md"
    序号 = 1
    while os.path.exists(os.path.join(目录, 名)):
        名 = "%s-%d.md" % (基础, 序号)
        序号 += 1
    return 名


def 准备候选(路径, 目标):
    """把一个候选文件变成影子目录里的 .md。

    · `.md` **原样复制、不动编码** —— 非 UTF-8 正是要让它原形毕露，
      在这里顺手转码等于把最危险的一类问题掩盖掉；
    · 其他格式走 `候选转Markdown()`。
    """
    扩展 = os.path.splitext(路径)[1].lower()
    if 扩展 in (".md", ".markdown"):
        shutil.copy2(路径, 目标)
        return
    文本, _ = 候选转Markdown(路径)
    with open(目标, "w", encoding="utf-8", newline="\n") as 文件:
        文件.write(文本)


def 候选转Markdown(路径):
    """把**非 md** 候选转成规范 Markdown。返回 `(文本, 建议落地 .md 文件名)`。

    抽成独立函数是为了**一处实现两处用**：影子预检要拿它填充临时目录，
    服务端入库要拿它写进 `corpus/raw/`。两处各写一份的话，
    「预检说没问题、入库写出来的却是另一份内容」这种事迟早发生。

    `.md` 刻意不走这里 —— 它必须原样复制字节，否则非 UTF-8 会被顺手"修好"，
    最危险的那类问题就被掩盖了。
    """
    global 转换
    if 转换 is None:
        转换 = 载入模块("转换-语料.py", "语料转换")
    名 = os.path.basename(路径)
    扩展 = os.path.splitext(名)[1].lower()
    正文 = ""
    if 扩展 in 转换.Markdown类:
        raise ValueError(".md 不走转换路径（原样入库即可）")
    if 扩展 in 转换.纯文本类:
        正文, _ = 转换.读文本(路径)
    elif 扩展 in 转换.转换器:
        格式, 函数 = 转换.转换器[扩展]
        正文, 统计 = 函数(路径)
        if 格式 == "PDF" and 统计.get("疑似扫描件") and not 正文.strip():
            raise RuntimeError("无文本层（%d 页、每页均 %s 字）→ 疑似扫描件，需先 OCR"
                               % (统计["页数"], 统计["每页均字"]))
    else:
        raise RuntimeError("不支持的扩展名 %s" % 扩展)
    if not 正文.strip():
        raise RuntimeError("提取到 0 字符（空文件 / 加密 / 扫描件？）")
    产物 = 转换.规范成知识库格式(
        正文, 名, 来源=名,
        提示="本文件由 %s 自动转换，文号与标题请人工核对。" % 名)
    return 产物, os.path.splitext(名)[0] + ".md"


# ======================= 单项检查 =======================

def 检查标题(正文):
    for 行 in 正文.split("\n"):
        if 行.startswith("# "):
            return "ok", "首个一级标题：%s" % 截断(行[2:].strip(), 24)
    return "warn", "没有 `# ` 一级标题 → 该文档所有块的标题前缀为空"


def 检查文号(正文, 路径, 影子):
    """返回 (级别, 说明, 文号)。

    级别口径（2026-10-12 修正）：
      · ok   文件头信息表**显式声明**，且是**本企业体系文号**（形态 + 前缀白名单都过）
      · warn 不阻断 —— 不是体系文号（参考资料），或者文号只是从文件名推来的
      · fail **本项不出** —— 「文号不合规」本身不会让检索出错

    为什么从 fail 降为 warn：白名单 `QW-/QP-/JC-/JS-/CSR-` 本身就是一句
    「本库只装本企业体系文件」的声明，但**参考资料**（外部标准、行业报告、
    客户资料、厂商手册）本来就不该有体系文号 —— 一律判 fail 是**判据越界**。
    真正会让检索出错的情形（注册文号里嵌着另一个合规号 → 类2 误拒）
    由第 ⑥ 项独立兜底，不靠这一项。
    """
    名 = os.path.basename(路径)
    显式 = re.search(r"\|\s*\*\*([^*\n]{0,8}编号)\*\*\s*\|\s*([A-Za-z0-9\-]+)\s*\|", 正文)
    文号 = 分块.提取文号(正文, 名)
    形态合规 = bool(re.match(r"^[A-Z]{2,6}(?:-[A-Z0-9]{1,6}){1,3}$", 文号))
    前缀合规 = any(文号.startswith(前) for 前 in 检索.文档前缀)
    体系 = 形态合规 and 前缀合规

    说明 = []
    if 体系:
        级别 = "ok" if 显式 else "warn"
        if 显式:
            说明.append("文件头信息表显式声明「%s」" % 显式.group(1))
        else:
            说明.append("未在文件头信息表声明 → 回退用文件名推得")
        说明.append("本企业体系文号 → 注册为「%s」" % 文号)
    else:
        级别 = "warn"
        说明.append("文件头信息表声明的编号不成体系文号形态" if 显式
                    else "未在文件头信息表声明")
        说明.append("非本企业体系文号（非 QW-/QP-/JC-/JS-/CSR-）→ 按**参考资料**处理，不阻断")
        说明.append("检索不受影响：类2「库外引用」判据本来就不认它（见第 ⑥ 项）")
        说明.append("注册为「%s」" % 文号)
    return 级别, "；".join(说明), 文号


def 检查留白冲突(文号, 基线):
    """补上"故意留白"的文号 = 废掉 O03/O03b 库外拒答题。"""
    留白 = set((基线 or {}).get("悬空文号", []))
    if 文号 in 留白:
        return "fail", ("这是**有意留白**的文号，原被库内文档引用但不在库中。"
                        "补上它会同时废掉 O03 / O03b 类库外拒答题")
    return "ok", "未撞上留下的 %d 个留白文号" % len(留白)


def 检查自身误判(影子, 文号):
    """类2 误拒的**真正**触发条件（不是"文号抽不到"那么简单）。

    `判拒答()` 类2 的口径是：**块里出现、且不在 `库内文号` 里的体系文号 = 库外引用**。
    `库内文号` 是拿每份文档**注册的**文号拼出来的，所以"注册文号不在集合里"永远不成立
    （那样写这条检查就是恒假的摆设）。真正会出事的是这一种：

      注册文号 = `19-新制度-QW-QA-01 (2)`（文件名带空格括号 → 正则整串匹配失败 → 回退取主干）
      但块文本里 `QW-QA-01` 是个**合规号**，会被 `抽文档号` 抽出来；
      而 `库内文号` 里只有 `19-新制度-QW-QA-01 (2)`，没有 `QW-QA-01`。
      → 每次检索命中这份文档，都判「引用了库外文档」→ **类2 库内误拒，且不报错。**

    所以判据是：**注册文号里是否"嵌着"另一个合规号**，且那个号不在库内。
    """
    自己文本 = "\n".join(前 + "\n" + 文 for 号, 前, 文 in 影子["块列表"] if 号 == 文号)
    if not 自己文本:
        return "warn", "影子块列表里找不到该文档的块（注册文号「%s」）" % 文号
    库外 = 检索.抽文档号(自己文本) - 影子["库内文号"]
    冒名 = sorted(号 for 号 in 库外 if 号 != 文号 and 号 in 文号)
    if 冒名:
        return "fail", ("注册文号「%s」里**嵌着**另一个合规文号 %s，而它不在库内 → "
                        "每次命中该文档都会被判「引用了库外文档」= 类2 库内误拒"
                        "（改掉文件名里的空格/括号，或在文件头信息表里写明文号即可消除）"
                        % (文号, 冒名))
    if 库外:
        return "ok", "本文档引用了库外文号 %s（属正常留白或新增线索，非自身问题）" % sorted(库外)
    return "ok", "本文档的块不会被判成「引用库外」"


# ======================= 基线与现状 =======================

def 读基线():
    if not os.path.exists(基线文件):
        return None
    try:
        return json.load(open(基线文件, encoding="utf-8"))
    except Exception:                                          # noqa: BLE001
        return None


def 服务健康():
    """活着就返回 {docs, blocks}；连不上返回 None。**绕开代理**（本机有 HTTP_PROXY）。"""
    import urllib.request
    try:
        开 = urllib.request.build_opener(urllib.request.ProxyHandler({}))
        应答 = json.load(开.open(服务地址 + "/health", timeout=服务超时))
        return {"docs": 应答.get("docs"), "blocks": 应答.get("blocks")}
    except Exception:                                          # noqa: BLE001
        return None


def 写基线():
    现状 = 复算(语料目录)
    健康 = 服务健康()
    数据 = {
        "生成时间": time.strftime("%Y-%m-%d %H:%M:%S"),
        "生成脚本": "自检-新增语料.py",
        "解释器": sys.executable,
        "语料目录": 语料目录,
        "口径": {"分块上限": 分块上限, "最短块": 最短块, "说明": "与 知识库服务.建基座() 一致"},
        "文档数": len(现状["文档列表"]),
        "块数": len(现状["块列表"]),
        "库内文号": sorted(现状["库内文号"]),
        "悬空文号": sorted(现状["悬空"]),
        "每份": 现状["每份"],
        "服务健康": 健康,
    }
    os.makedirs(输出目录, exist_ok=True)
    with open(基线文件, "w", encoding="utf-8", newline="\n") as 文件:
        json.dump(数据, 文件, ensure_ascii=False, indent=2)

    输出(" 基线已写入 %s" % 基线文件)
    输出("   文档 %d 份 / 块 %d 个 / 悬空引用 %d 个"
          % (数据["文档数"], 数据["块数"], len(数据["悬空文号"])))
    if 健康:
        一致 = (健康["docs"] == 数据["文档数"] and 健康["blocks"] == 数据["块数"])
        输出("   服务 /health：docs=%s blocks=%s → %s"
              % (健康["docs"], 健康["blocks"], "✅ 口径一致" if 一致 else "🔴 不一致，见下"))
    else:
        输出("   ⚠️ 服务未响应，未能交叉验证（基线仍可用，但只代表脚本口径）")
    return 数据


def 口径自证(现状):
    """**这一步是整个预检可信的前提。**
    复算结果必须与基线（以及运行中的服务）对得上；
    对不上说明分块口径漂了，此时预检结论一概不可信 —— 必须明说，不能装作通过。
    """
    基线 = 读基线()
    健康 = 服务健康()
    问题 = []
    if 基线:
        if 基线.get("文档数") != len(现状["文档列表"]):
            问题.append("基线文档数 %s ≠ 复算 %d（库已被改过？请刷新基线）"
                        % (基线.get("文档数"), len(现状["文档列表"])))
        if 基线.get("块数") != len(现状["块列表"]):
            问题.append("基线块数 %s ≠ 复算 %d（**分块口径可能漂了**）"
                        % (基线.get("块数"), len(现状["块列表"])))
        口径 = 基线.get("口径") or {}
        if 口径.get("分块上限") != 分块上限 or 口径.get("最短块") != 最短块:
            问题.append("基线口径 %s ≠ 脚本口径 {%s, %s}" % (口径, 分块上限, 最短块))
    if 健康:
        if 健康.get("docs") != len(现状["文档列表"]):
            问题.append("服务 docs=%s ≠ 复算 %d" % (健康.get("docs"), len(现状["文档列表"])))
        if 健康.get("blocks") != len(现状["块列表"]):
            问题.append("服务 blocks=%s ≠ 复算 %d" % (健康.get("blocks"), len(现状["块列表"])))
    return 问题, 基线, 健康


# ======================= 输出 =======================

标记 = {"ok": "✅", "warn": "⚠️", "fail": "🔴", "skip": "— "}

# 六项检查的固定顺序（报告与页面共用一份，别写两处）
检查项 = ["编码", "标题", "文号", "留白冲突", "库外引用", "类2误判"]


def 打行(符, 标题, 说明):
    输出("   %s %s %s" % (符, 补宽(标题, 11), 说明))


def 打印现状(现状, 问题, 基线, 健康):
    输出()
    输出(" 现状复算（口径：上限 %d / 软表保 / 最短块 %d）" % (分块上限, 最短块))
    输出("   文档 %d 份 ｜ 块 %d 个 ｜ 库内文号 %d 个 ｜ 悬空引用 %d 个"
          % (len(现状["文档列表"]), len(现状["块列表"]),
             len(现状["库内文号"]), len(现状["悬空"])))
    if 健康:
        输出("   服务 /health：docs=%s blocks=%s" % (健康["docs"], 健康["blocks"]))
    else:
        输出("   服务 /health：未响应")
    if 问题:
        输出()
        for 项 in 问题:
            输出("   🔴 口径自证失败：%s" % 项)
        输出("   → **本次预检结论不可信**，先刷新基线（--写基线）并排查口径漂移。")
    else:
        输出("   ✅ 口径自证通过（复算与基线/服务一致）")
    输出()
    输出(" 悬空引用（被引用但不在库内，共 %d 个）：" % len(现状["悬空"]))
    for 号 in sorted(现状["悬空"]):
        输出("   · %s" % 号)


def 预检报告(候选列表, 影子, 落地, 现状, 基线):
    """跑完六项检查，**打印给人看 + 返回给程序用**（同一份结论，不写两遍）。

    返回值是「结构化结论」，管理页直接拿它渲染；CLI 靠 `输出` 打屏。
    服务端调用前把 `输出` 换成空函数即可 —— 请求路径不许碰控制台。
    """
    前悬空 = set(现状["悬空"])
    后悬空 = set(影子["悬空"])
    新增悬空 = 后悬空 - 前悬空
    消除悬空 = 前悬空 - 后悬空

    输出()
    输出(" 影子预检：%d 个候选文件" % len(候选列表))
    输出(" " + "-" * 76)

    阻断 = 0
    警告 = 0
    报告 = []
    for 项 in 落地:
        名 = os.path.basename(项["候选"])
        记录 = {"候选": 项["候选"], "落地名": 项["落地名"], "名": 名, "检查": {}}
        输出()
        输出(" 【%s】" % 名)

        def 记账(键, 级别, 说明, **额外):
            记录["检查"][键] = dict({"级别": 级别, "说明": 说明}, **额外)
            return 级别

        # ---- 读取/转换失败：只有这一条，后面全部"未检查" ----
        if 项["错误"]:
            记账("编码", "fail", 项["错误"])
            打行(标记["fail"], "读取/转换", 项["错误"])
            for 键 in 检查项[1:]:
                记账(键, "skip", "因读取失败，未检查")
            记录["字符"] = 0
            记录["块数"] = None
            阻断 += 1
            报告.append(记录)
            continue

        正文 = 项["正文"]

        # ---- ① 编码 ----
        级, 说 = 项["编码"]["级别"], 项["编码"]["说明"]
        记账("编码", 级, 说)
        打行(标记[级], "① 编码", 说)
        if 项.get("排除原因"):
            打行("   ", "", "→ " + 项["排除原因"])

        # 🔴 判据铁律：编码不过关时，后面每一项必须写「未检查」而不是「通过」——
        #    两者在报告里长得一样，就等于没有判据。
        if 级 == "fail":
            for 键 in 检查项[1:]:
                记账(键, "skip", "因①编码未通过，未检查")
                打行(标记["skip"], 键, "未检查（编码不过关，先修编码）")
            记录["字符"] = len(正文)
            记录["块数"] = None
            阻断 += 1
            报告.append(记录)
            continue

        # ---- ② 标题 ----
        级, 说 = 检查标题(正文)
        记账("标题", 级, 说)
        打行(标记[级], "② 标题", 说)

        # ---- ③ 文号 ----
        级, 说, 文号 = 检查文号(正文, 项["候选"], 影子)
        记账("文号", 级, 说, 文号=文号)
        打行(标记[级], "③ 文号", 说)

        # ---- ④ 留白冲突 ----
        级, 说 = 检查留白冲突(文号, 基线)
        记账("留白冲突", 级, 说)
        打行(标记[级], "④ 留白冲突", 说)

        # ---- ⑤ 库外引用（本文档净新增的悬空号） ----
        # 用**影子**的库内文号做差集：这样文档自身的文号已被算作"库内"，
        # 不会被误报成"本文档引入了库外引用"。
        新号 = sorted((检索.抽文档号(正文) - 影子["库内文号"]) - 前悬空)
        级 = "warn" if 新号 else "ok"
        记账("库外引用", 级,
             ("净新增库外引用 %s" % 新号) if 新号 else "未净新增库外引用", 新号=新号)
        打行(标记[级], "⑤ 库外引用", 记录["检查"]["库外引用"]["说明"])

        # ---- ⑥ 类2 自身误判风险 ----
        级, 说 = 检查自身误判(影子, 文号)
        记账("类2误判", 级, 说)
        打行(标记[级], "⑥ 类2误判", 说)

        # ---- 容量 ----
        命中 = next((x for x in 影子["每份"] if x["文件"] == 项["落地名"]), None)
        记录["字符"] = 命中["字符"] if 命中 else 0
        记录["块数"] = 命中["块数"] if 命中 else 0
        打行("·", "容量", "%d 字 → %d 个块" % (记录["字符"], 记录["块数"]))

        for 键 in 检查项:
            值 = 记录["检查"].get(键)
            if not 值:
                continue
            if 值["级别"] == "fail":
                阻断 += 1
            elif 值["级别"] == "warn":
                警告 += 1
        报告.append(记录)

    输出()
    输出(" " + "-" * 76)
    输出(" ⑤ 汇总（影子 vs 现状）")
    输出("   文档：%d → %d   块：%d → %d"
          % (len(现状["文档列表"]), len(影子["文档列表"]),
             len(现状["块列表"]), len(影子["块列表"])))
    if 消除悬空:
        输出("   ⚠️ **消除了 %d 个原有悬空引用**：%s" % (len(消除悬空), sorted(消除悬空)))
        输出("      → 若其中有 O03/O03b 依赖的号，对应拒答题会**从「该拒答」变成「该答」**，")
        输出("        66 题 / 100 题的拒答率与分母都必须重跑并记账。")
    if 新增悬空:
        输出("   · 新增 %d 个库外引用：%s（会成为新的拒答靶子，需显式记账）"
              % (len(新增悬空), sorted(新增悬空)))
    输出()
    输出(" " + "-" * 76)
    if 阻断:
        输出(" 🔴 预检未通过：%d 个阻断项、%d 个警告 → **不要入库**，先修。" % (阻断, 警告))
    elif 警告:
        输出(" ⚠️ 预检通过但有 %d 个警告 → 可以入库，但请先人工核对上面标出的项。" % 警告)
    else:
        输出(" ✅ 预检全部通过 → 按下面的步骤入库。")
    输出()
    输出(" 入库动作（预检通过后再做）：")
    # 非 .md 候选不能直接拷 —— 服务端的入库接口会自己调转换器，CLI 得说清楚
    有非md = any(os.path.splitext(项)[1].lower() not in (".md", ".markdown", "")
                and os.path.isfile(项) for 项 in 候选列表)
    if 有非md:
        输出("   1) 候选里有非 .md 文件 → **走管理页入库**（服务端会自动转换），或先转换：")
        输出("      python scripts\\转换-语料.py <文件>      # 产物落在 %s" % 暂存目录)
        输出("   2) 用 /health 的 docs/blocks 确认生效（**不是** status: ok）")
    else:
        输出("   1) 把 %s 下的 .md 拷进 %s" % (暂存目录, 语料目录))
        输出("   2) python scripts\\启动-服务.py --重起     # 或用管理页热重建")
        输出("   3) 用 /health 的 docs/blocks 确认生效（**不是** status: ok）")

    # 结构化结论（管理页直接消费）；`通过` 只看阻断项，警告不算不通过。
    return {
        "候选": 报告,
        "阻断项": 阻断, "警告项": 警告,
        "通过": 阻断 == 0,
        "现状": {"文档数": len(现状["文档列表"]), "块数": len(现状["块列表"]),
                 "悬空": sorted(现状["悬空"])},
        "影子": {"文档数": len(影子["文档列表"]), "块数": len(影子["块列表"]),
                 "悬空": sorted(影子["悬空"])},
        "新增悬空": sorted(新增悬空),
        "消除悬空": sorted(消除悬空),
    }


# ======================= 主流程 =======================

def 解析输入(输入列表):
    出 = []
    for 项 in 输入列表:
        路 = 项 if os.path.isabs(项) else os.path.join(os.getcwd(), 项)
        if os.path.isdir(路):
            for 名 in sorted(os.listdir(路)):
                子 = os.path.join(路, 名)
                if os.path.isfile(子) and not 名.startswith("."):
                    出.append(子)
        elif os.path.isfile(路):
            出.append(路)
        else:
            输出("  ⚠️ 找不到：%s" % 项)
    return 出


def 主流程():
    解释器 = argparse.ArgumentParser(
        description="入库前影子预检：先在影子里入一遍，看会不会出事")
    解释器.add_argument("--写基线", action="store_true", help="建立/刷新 eval/语料基线.json")
    解释器.add_argument("--预检", nargs="*", default=None, help="候选文件或目录（md/docx/xlsx/pdf/txt）")
    解释器.add_argument("--json", default=None, help="把预检报告落成 JSON（供管理页用）")
    参数 = 解释器.parse_args()

    初始化()

    输出("自检-新增语料.py  —— 入库前影子预检")
    输出("=" * 78)
    输出(" 解释器：%s" % sys.executable)
    输出(" 语料目录：%s" % 语料目录)

    if 参数.写基线:
        写基线()
        return 0

    现状 = 复算(语料目录)
    问题, 基线, 健康 = 口径自证(现状)
    打印现状(现状, 问题, 基线, 健康)

    if 参数.预检 is None:
        if not 基线:
            输出()
            输出(" 提示：还没有基线。先跑一次 `--写基线`，以后才能对比出「新增了什么」。")
        return 0

    候选 = 解析输入(参数.预检)
    if not 候选:
        输出("\n 没有可预检的文件。")
        return 1

    try:
        影子, 落地 = 影子预检(候选)
    except Exception as 错:                                    # noqa: BLE001
        # 到这一步说明**连预检本身都跑不通**了 —— 必须明说，不能当成"没问题"。
        输出("\n 🔴 影子预检自身失败：%s: %s" % (type(错).__name__, 错))
        输出("    → 本次没有结论。请把上面的异常原文贴回来排查。")
        return 2

    汇总 = 预检报告(候选, 影子, 落地, 现状, 基线)
    汇总["生成时间"] = time.strftime("%Y-%m-%d %H:%M:%S")
    汇总["口径自证"] = {"通过": not 问题, "问题": 问题}
    # 「通过」要把口径自证算进去：口径对不上时，六项检查全绿也不可信。
    汇总["通过"] = 汇总["通过"] and not 问题

    if 参数.json:
        路 = 参数.json if os.path.isabs(参数.json) else os.path.join(os.getcwd(), 参数.json)
        目录 = os.path.dirname(路)
        if 目录:
            os.makedirs(目录, exist_ok=True)
        with open(路, "w", encoding="utf-8", newline="\n") as 文件:
            json.dump(汇总, 文件, ensure_ascii=False, indent=2)
        输出(" 预检报告已写入 %s" % 路)

    if 问题:
        return 2
    return 0 if 汇总["通过"] else 1


if __name__ == "__main__":
    设终端编码()
    sys.exit(主流程())
