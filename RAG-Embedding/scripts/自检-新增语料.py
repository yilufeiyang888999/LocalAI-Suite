def 设终端编码():
    for 流 in (sys.stdout, sys.stderr):
        if hasattr(流, "reconfigure"):
            流.reconfigure(errors="replace")           # 只改 errors，不改 encoding


def 显示宽(文本):
    宽 = 0
    for 字符 in str(文本):
        宽 += 2 if unicodedata.east_asian_width(字符) in ("W", "F") else 1
    return 宽


def 补宽(文本, 宽):
    文本 = str(文本)
    填充 = 宽 - 显示宽(文本)
    return 文本 + " " * 填充 if 填充 > 0 else 文本


def 截断(文本, 宽=30):
    出 = ""
    for 字符 in str(文本):
        if 显示宽(出 + 字符) > 宽:
            return 出 + "…"
        出 += 字符
    return 出


