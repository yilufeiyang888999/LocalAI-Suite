# -*- coding: utf-8 -*-
"""库外拒答率量化 + 类2 信号分布 —— 回答「拦截率到底是多少」。

为什么需要它（方法论，都是踩出来的）：
  ① **单次验收报的「库外漏网 0/6」不是拦截率**。生成端不是确定函数
     （见 `诊断-生成确定性.py`），同一道题不同采样会给出不同形态的答案。
     实测 O03：修复前连打 **12 次全漏网**，而另一次验收却判成拒答 ——
     所以必须**重复打、看分母**，不能拿一次结果当基线。
  ② **问句措辞是隐藏变量**。「电镀废液具体怎么处理」与「电镀废液应该怎么处理」
     这同一道题的两种说法，答案句序稳定不同（一个拒答词在前、一个在后）。
     内置题里的 `O03` / `O03b` 就是这个对照 —— 后者正是修复前 12/12 漏网的那个。
  ③ `--分布` 走**离线**路径（只检索 + 判拒答，不调生成端），秒级：
     用来回答「新判据会不会误伤库内题」—— 看有多少库内题带类2 信号。

用法：
  python scripts\\诊断-库外拒答率.py                   # 内置 3 题，每题 10 次
  python scripts\\诊断-库外拒答率.py 20                # 每题 20 次
  python scripts\\诊断-库外拒答率.py --问 "某个问题"   # 测任意问句
  python scripts\\诊断-库外拒答率.py --分布            # 66 题的类2 信号分布（离线，秒级）

退出码：全部稳定判拒答 → 0；有题不稳定 → 1（这样能被自检单当判据用）。
"""
import importlib.util
import io
import json
import os
import sys

sys.stdout.reconfigure(errors="replace")
脚本目录 = os.path.dirname(os.path.abspath(__file__))
根目录 = os.path.dirname(脚本目录)


def 载入(文件名, 别名):
    规范 = importlib.util.spec_from_file_location(别名, os.path.join(脚本目录, 文件名))
    模块 = importlib.util.module_from_spec(规范)
    规范.loader.exec_module(模块)
    return 模块


服 = 载入("知识库服务.py", "知识库服务")

内置题 = [
    ("O03", "电镀废液具体怎么处理",
     "**有类2 信号**（QW-DD-05）→ 应由「类2 信号 ∧ 承认缺资料」兜住"),
    ("O03b", "电镀废液应该怎么处理",
     "🔴 同一问题的另一说法 —— 修复前 12/12 漏网的就是它"),
    ("O06", "S001 东莞精诚的注册资本是多少",
     "**无类2 信号**（最高分 0.18）→ 只能靠位置判"),
]


def 跑分布():
    """离线：统计每题的类2 信号（只检索 + 判拒答，不调生成端）。"""
    路 = os.path.join(根目录, "eval", "题目.json")
    题集 = json.load(io.open(路, encoding="utf-8"))["题目"]
    行 = []
    for 题 in 题集:
        结果 = 服.检索(题["问"], 3)
        判 = 服.判拒答(结果)
        行.append({"编号": 题["编号"], "类别": 题["类别"], "问": 题["问"],
                   "最高分": round(结果["最高分"], 3),
                   "前置拒答": 判["refused"], "类型": 判["type"], "库外引用": 判["库外引用"]})
    库内 = [x for x in 行 if x["类别"] != "库外"]
    库外 = [x for x in 行 if x["类别"] == "库外"]
    库内有 = [x for x in 库内 if x["库外引用"]]
    库外有 = [x for x in 库外 if x["库外引用"]]

    print("=" * 98)
    print("  类2 信号（Top-1 是否提到库外文档）分布 ｜ 类2 范围 = Top-%d ｜ 库内文号 %d 个"
          % (服.类2范围, len(服.基座["库内文号"])))
    print("=" * 98)
    print("\n【库内 %d 题】带类2 信号的：" % len(库内))
    for x in 库内有:
        print("   %-5s 最高分 %7.3f  前置拒答=%-5s  库外引用=%s  | %s"
              % (x["编号"], x["最高分"], x["前置拒答"], ",".join(x["库外引用"]), x["问"][:26]))
    print("   → %d/%d" % (len(库内有), len(库内)))

    print("\n【库外 %d 题】逐题：" % len(库外))
    for x in 库外:
        print("   %-5s 最高分 %7.3f  前置拒答=%-5s  类型=%-20s  库外引用=%s"
              % (x["编号"], x["最高分"], x["前置拒答"], x["类型"] or "—",
                 ",".join(x["库外引用"]) or "—"))
    print("   → 带类2 信号 %d/%d" % (len(库外有), len(库外)))

    print()
    print("  判读（新判据的兜底规则 =「类2 信号非空 ∧ 答案出现拒答词」）：")
    print("    · 库内误伤面 = 带类2 信号的库内题 %d 题 —— 还要它们答案含拒答词才会误判" % len(库内有))
    print("    · 库外受益面 = 带类2 信号的库外题 %d 题" % len(库外有))
    余 = [x["编号"] for x in 库外 if not x["库外引用"] and not x["前置拒答"]]
    print("    · 其余 %s 靠类1（确定性）与生成端自觉" % (余 or "无"))
    print("=" * 98)
    return 0


def 跑拒答率(题单, 次数):
    print("=" * 98)
    print("  库外拒答率实测（每题 %d 次）｜ 判据 = 位置判 ∨（类2 信号 ∧ 出现拒答词）" % 次数)
    print("  ⚠ 单次结果不是拦截率 —— 生成端不是确定函数，必须看分母")
    print("=" * 98)
    汇总 = {}
    for 编号, 问句, 说明 in 题单:
        print("\n【%s】%s" % (编号, 问句))
        print("   %s" % 说明)
        拒 = 0
        失败 = 0
        for i in range(1, 次数 + 1):
            r = 服.回答(问句, 3)
            答 = (r.get("answer") or "").strip()
            # 🔴 生成失败（超时 / 服务不可达）**不计入分母** —— 2026-10-10 实测：
            #    两个探针并发打单槽生成端时全部超时，旧版把失败当「未拒答」，
            #    拦截率被冲成 0/6 —— 那不是漏网，是分母被污染。
            if r.get("error") or 答.startswith("(生成失败"):
                失败 += 1
                print("   %2d | ⚠️ 生成失败（已从分母剔除，勿当漏网）｜ %s"
                      % (i, 答.replace("\n", " ")[:60]))
                continue
            if r.get("refused"):
                拒 += 1
            位 = min([答.find(w) for w in 服.拒答词 if w in 答] or [-1])
            print("   %2d | refused=%-5s type=%-20s 拒答词首现=%-4s | %s"
                  % (i, r.get("refused"), r.get("refusal_type") or "—",
                     (位 if 位 >= 0 else "无"), 答.replace("\n", " ")[:48]))
        汇总[编号] = (拒, 失败)
    print("\n" + "=" * 98)
    print("  汇总（分母 = 每题 %d 次，**生成失败已剔除**）" % 次数)
    全稳 = True
    for 编号, _, _ in 题单:
        拒, 失败 = 汇总[编号]
        有效 = 次数 - 失败
        if 失败:
            全稳 = False
            print("   %-5s 判拒答 %2d/%d（⚠️ %d 次生成失败已剔除 —— 有效分母不足，**重跑**，别用这个下结论）"
                  % (编号, 拒, 有效, 失败))
            continue
        稳 = 拒 == 次数
        全稳 = 全稳 and 稳
        print("   %-5s 判拒答 %2d/%d  %s"
              % (编号, 拒, 次数, "✅ 稳定" if 稳 else "⚠️ 不稳定 —— 要看漏的那次是什么形态"))
    print("=" * 98)
    return 0 if 全稳 else 1


def 主():
    次数 = 10
    位置参数 = [x for x in sys.argv[1:] if not x.startswith("--")]
    if 位置参数 and 位置参数[0].isdigit():
        次数 = int(位置参数[0])

    print("建基座 …", flush=True)
    服.建基座()

    if "--分布" in sys.argv:
        return 跑分布()

    题单 = 内置题
    if "--问" in sys.argv:
        题单 = [("自定义", sys.argv[sys.argv.index("--问") + 1], "命令行指定")]
    return 跑拒答率(题单, 次数)


if __name__ == "__main__":
    sys.exit(主())
