def 设终端编码():
    """Windows 终端多为 cp936，中文可能编不出来；用 errors=replace 兜底（不要改 encoding）。"""
    for 流 in (sys.stdout, sys.stderr):
        if hasattr(流, "reconfigure"):
            流.reconfigure(errors="replace")


def 显示宽(文本):
    """中文字符按 2 个宽度算，否则表格会错位（f-string 的 <12 对中文无效）。"""
    宽 = 0
    for 字符 in str(文本):
        宽 += 2 if ord(字符) > 0x2E80 else 1
    return 宽


def 补空格(文本, 目标宽):
    文本 = str(文本)
    return 文本 + " " * max(0, 目标宽 - 显示宽(文本))


def 取向量(服务地址, 文本列表):
    """调用 OpenAI 兼容的 /v1/embeddings，按 index 还原顺序。"""
    载荷 = json.dumps(
        {"input": 文本列表, "model": "bge-m3"},
        ensure_ascii=False,
    ).encode("utf-8")
    请求 = urllib.request.Request(
        服务地址.rstrip("/") + "/v1/embeddings",
        data=载荷,
        headers={"Content-Type": "application/json"},
    )
    with urllib.request.urlopen(请求, timeout=180) as 响应:
        数据 = json.loads(响应.read().decode("utf-8"))
    条目 = sorted(数据["data"], key=lambda 项: 项["index"])
    return [项["embedding"] for 项 in 条目]


def 余弦(甲, 乙):
    点积 = sum(甲[i] * 乙[i] for i in range(len(甲)))
    模甲 = math.sqrt(sum(值 * 值 for 值 in 甲))
    模乙 = math.sqrt(sum(值 * 值 for 值 in 乙))
    if 模甲 == 0 or 模乙 == 0:
        return 0.0
    return 点积 / (模甲 * 模乙)


def 模长(向量):
    return math.sqrt(sum(值 * 值 for 值 in 向量))


def 主流程():
    设终端编码()
    服务地址 = sys.argv[1] if len(sys.argv) > 1 else 默认服务地址

    print("=" * 80)
    print(" bge-m3 embedding 自检   目标: " + 服务地址)
    print("=" * 80)

    # ---- 步骤 0：服务在线？ ----
    try:
        探针 = 取向量(服务地址, ["探针"])
    except urllib.error.URLError as 错:
        print("[X] 连不上服务：" + str(错))
        print("    请先启动：llama-server.exe --model <bge-m3 路径> --embedding --pooling cls --port 8081")
        return 2
    except Exception as 错:
        print("[X] 调用失败：" + repr(错))
        return 2

    维度 = len(探针[0])
    print("[1] 服务在线，向量维度 = " + str(维度))
    if 维度 != 1024:
        print("    [!] bge-m3 官方维度是 1024，实测 " + str(维度) + " —— 配置可疑，继续跑但结论存疑")
    else:
        print("    维度正确（bge-m3 官方 1024 维）")

    # ---- 步骤 1：归一化检查 ----
    甲 = 取向量(服务地址, ["归一化检查"])
    实测模长 = 模长(甲[0])
    print("[2] 向量模长 = " + "%.6f" % 实测模长)
    if abs(实测模长 - 1.0) < 0.02:
        print("    已做 L2 归一化（llama.cpp 默认 --embd-normalize 2）→ 余弦可直接用点积")
        归一化正常 = True
    else:
        print("    [!] 模长偏离 1.0 较多；余弦仍按公式算，但值得确认 --embd-normalize")
        归一化正常 = False

    # ---- 步骤 2：四档区分度 ----
    所有句 = []
    for 档, 句甲, 句乙 in 测试句对:
        所有句.append(句甲)
        所有句.append(句乙)
    向量表 = 取向量(服务地址, 所有句)

    结果 = []
    for 序, (档, 句甲, 句乙) in enumerate(测试句对):
        结果.append((档, 句甲, 句乙, 余弦(向量表[序 * 2], 向量表[序 * 2 + 1])))

    print()
    print("[3] 四档相似度")
    print("    " + 补空格("档", 4) + 补空格("余弦", 8) + "句子对")
    print("    " + "-" * 72)
    for 档, 句甲, 句乙, 值 in 结果:
        print("    " + 补空格(档, 4) + 补空格("%.4f" % 值, 8) + 句甲 + "  ↔  " + 句乙)

    分档 = {}
    for 档, _, _, 值 in 结果:
        分档.setdefault(档, []).append(值)
    A组 = 分档.get("A", [])
    B组 = 分档.get("B", [])
    C组 = 分档.get("C", [])
    D组 = 分档.get("D", [])
    A最小 = min(A组) if A组 else 0.0
    A最大 = max(A组) if A组 else 0.0
    B最大 = max(B组) if B组 else 0.0
    C最大 = max(C组) if C组 else 0.0
    D最大 = max(D组) if D组 else 0.0
    间隔AC = A最小 - C最大
    间隔AD = A最小 - D最大

    print()
    print("[4] 汇总（判据是相对间隔，不是单点绝对值）")
    print("    A 同义改写      最小 = %.4f  (期望 >= %.2f)" % (A最小, 档位期望["A"][0]))
    if B组:
        print("    B 同业务线异题  范围 = %.4f ~ %.4f  (参考，不判定)" % (min(B组), B最大))
    print("    C 同企业跨业务线 最大 = %.4f  (期望 <= %.2f)" % (C最大, 档位期望["C"][1]))
    print("    D 跨领域完全无关 最大 = %.4f  (期望 <= %.2f)" % (D最大, 档位期望["D"][1]))
    print("    间隔1  min(A)-max(C) = %.4f  (期望 >= %.2f)" % (间隔AC, 间隔期望["A-C"]))
    print("    间隔2  min(A)-max(D) = %.4f  (期望 >= %.2f)" % (间隔AD, 间隔期望["A-D"]))
    层级对 = [("A", A最大), ("B", B最大), ("C", C最大), ("D", D最大)]
    层级串 = " >= ".join("%s %.4f" % (n, v) for n, v in 层级对 if v > 0)
    层级OK = all(层级对[i][1] >= 层级对[i + 1][1] - 1e-9
                 for i in range(len(层级对) - 1) if 层级对[i][1] > 0 and 层级对[i + 1][1] > 0)
    print("    层级  max(A) >= max(B) >= max(C) >= max(D)：%s  [%s]"
          % ("满足" if 层级OK else "不满足", 层级串))

    # ---- 步骤 3：长文本 ----
    print()
    print("[5] 长文本（约 %d 字）" % len(长文本样例))
    try:
        长向量 = 取向量(服务地址, [长文本样例])[0]
        print("    返回维度 = %d，模长 = %.4f  → 未报错" % (len(长向量), 模长(长向量)))
        长文本正常 = True
    except Exception as 错:
        print("    [X] 长文本失败：" + repr(错))
        长文本正常 = False

    # ---- 判定 ----
    print()
    print("=" * 80)
    问题 = []
    警告 = []
    if A最小 < 档位期望["A"][0]:
        问题.append("A 组同义改写偏低（%.4f < %.2f）→ 同义捕捉能力不足" % (A最小, 档位期望["A"][0]))
    if C最大 > 档位期望["C"][1]:
        问题.append("C 组同域跨业务线偏高（%.4f > %.2f）→ 向量空间可能塌缩" % (C最大, 档位期望["C"][1]))
    if D最大 > 档位期望["D"][1]:
        问题.append("D 组跨领域偏高（%.4f > %.2f）→ 无关文本没拉开" % (D最大, 档位期望["D"][1]))
    if 间隔AC < 间隔期望["A-C"]:
        问题.append("间隔1 不足（%.4f < %.2f）→ 同义句没有压过同域异题句" % (间隔AC, 间隔期望["A-C"]))
    if 间隔AD < 间隔期望["A-D"]:
        问题.append("间隔2 不足（%.4f < %.2f）" % (间隔AD, 间隔期望["A-D"]))
    if not 层级OK:
        警告.append("层级非单调（相邻档最大值未递减）—— 单独看可能只是样本边界问题，"
                    "若同时间隔不足则一并视为异常")
    if not 归一化正常:
        问题.append("模长未归一化")
    if not 长文本正常:
        问题.append("长文本调用失败")

    for 项 in 警告:
        print(" [警告] " + 项)
    if 问题:
        print(" 结论：判为【不通过】—— 向量质量有问题")
        for 项 in 问题:
            print("   - " + 项)
        print()
        print(" 排查顺序：")
        print("   ① 直读 GGUF 元数据确认 bert.pooling_type 与启动参数 --pooling 是否一致")
        print("   ② 确认 --embd-normalize 未被人为改过")
        print("   ③ 换 bge-m3-FP16.gguf 对照，排除量化损伤")
        return 1

    print(" 结论：判为【通过】—— pooling / 归一化表现正常，可用于建库")
    print(" 注：本判据只证明『成对相似度分层健康』，不证明『排序效果好』。")
    print("     排序能力请跑 验证-检索排序.py（那才是 RAG 的入场券）。")
    return 0


if __name__ == "__main__":
    sys.exit(主流程())
