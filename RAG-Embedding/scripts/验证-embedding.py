# -*- coding: utf-8 -*-
"""
bge-m3 embedding 服务自检
========================

为什么需要这个脚本
------------------
embedding 的 **pooling 类型**或**归一化**设错了**不会报错**，只会让向量质量悄悄变差 ——
表现是「检索结果莫名其妙」，而不是「启动失败」。这跟 P1-8 是同一种病：

    失败会报警，这个不会；所以必须有判据。

本脚本把「看起来正常运行」翻译成可判定的数字。


判据设计的一个教训（2026-10-08 第一版判错，此处留痕）
---------------------------------------------------
第一版把测试对分成 **A 同义 / B 同主题 / C 完全无关** 三档，要求「C 组最大 <= 0.45」。
实测 C 组出现 0.5179 —— 于是判「不通过」，怀疑 pooling 有问题。

**这是判据设计错误，不是模型的问题。** 两处证据：

1. 直读 GGUF 元数据：`bert.pooling_type = 2`（= CLS，与官方一致）、
   `bert.attention.causal = False`（双向注意力）。配置本来就是对的。
2. 回看那两条「C 组」句子：「镀层厚度标准」↔「供应商准入评级办法」、
   「安全库存设定规则」↔「电镀槽液温度控制」——
   **它们是同一家企业里的不同业务线，不是「完全无关」**。
   中文短句本身语义信息少，领域词汇高度重叠时余弦到 0.5 上下是正常的。

真正的跨领域对照（「今天天气真不错」↔「螺纹钢的抗拉强度等级」）只有 **0.2864**。

**教训**：绝对值阈值一旦脱离句子对的「领域接近度」这个变量，就会误报。
改成**四档分层 + 相对间隔**作判据 —— 相对关系与模型/语料无关，稳定得多。


判据（四档 + 两条间隔）
------------------------
    A 同义改写        最小 应 >= 0.80     （同一个意思的两种说法）
    B 同业务线异问题   不分档判定，仅打印   （最容易混的一类）
    C 同企业跨业务线   最大 应 <= 0.65     （同域不同主题，允许偏高）
    D 跨领域完全无关   最大 应 <= 0.40     （不同域，必须低）
    ----------------------------------------------------------
    间隔1 = min(A) - max(C)  应 >= 0.20    （同义必须压过同域异题）
    间隔2 = min(A) - max(D)  应 >= 0.40    （两端必须拉开）
    层级  = max(A) >= max(B) >= max(C) >= max(D)，不满足仅警告

任一硬判据不过才判不通过。**排序能力的最终判据在 `验证-检索排序.py`。**

用法
----
    python 验证-embedding.py
    python 验证-embedding.py http://127.0.0.1:8081

零第三方依赖（只用标准库）。
"""

import json
import math
import sys
import urllib.error
import urllib.request

默认服务地址 = "http://127.0.0.1:8081"

# ---- 四档测试句对 ----
