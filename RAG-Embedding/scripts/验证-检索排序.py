def 设终端编码():
    """Windows 终端多为 cp936；用 errors=replace 兜底（不要改 encoding）。"""
    for 流 in (sys.stdout, sys.stderr):
        if hasattr(流, "reconfigure"):
            流.reconfigure(errors="replace")


def 显示宽(文本):
    """中文按 2 宽度算，否则表格对齐会错（f-string 的 <12 对中文无效）。"""
    宽 = 0
    for 字符 in str(文本):
        宽 += 2 if ord(字符) > 0x2E80 else 1
    return 宽


def 补空格(文本, 目标宽):
    文本 = str(文本)
    return 文本 + " " * max(0, 目标宽 - 显示宽(文本))


def 截断(文本, 目标宽):
    """按显示宽截断并加省略号。"""
    出 = ""
    宽 = 0
    for 字符 in str(文本):
        宽 += 2 if ord(字符) > 0x2E80 else 1
        if 宽 > 目标宽 - 2:
            return 出 + "…"
        出 += 字符
    return 出


def 取向量(服务地址, 文本列表):
    """调用 OpenAI 兼容的 /v1/embeddings，按 index 还原顺序。"""
    载荷 = json.dumps(
        {"input": 文本列表, "model": "bge-m3"}, ensure_ascii=False
    ).encode("utf-8")
    请求 = urllib.request.Request(
        服务地址.rstrip("/") + "/v1/embeddings",
        data=载荷,
        headers={"Content-Type": "application/json"},
    )
    with urllib.request.urlopen(请求, timeout=300) as 响应:
        数据 = json.loads(响应.read().decode("utf-8"))
    条目 = sorted(数据["data"], key=lambda 项: 项["index"])
    return [项["embedding"] for 项 in 条目]


def 余弦(甲, 乙):
    点积 = sum(甲[i] * 乙[i] for i in range(len(甲)))
    模甲 = math.sqrt(sum(值 * 值 for 值 in 甲))
    模乙 = math.sqrt(sum(值 * 值 for 值 in 乙))
    if 模甲 == 0 or 模乙 == 0:
        return 0.0
    return 点积 / (模甲 * 模乙)


def 跑一遍(服务地址, 标签):
    """对一个服务跑完整套排序测试，返回统计字典。"""
    print()
    print("=" * 86)
    print(" 检索排序验证  " + (("[" + 标签 + "] ") if 标签 else "") + "目标: " + 服务地址)
    print("=" * 86)

    # ---- 语料与查询一起送，减少往返 ----
    素材文本 = [正文 for _, _, 正文 in 候选池] + [问句 for _, 问句, _ in 查询集]
    向量表 = 取向量(服务地址, 素材文本)
    语料向量 = 向量表[: len(候选池)]
    查询向量 = 向量表[len(候选池):]

    命中排名 = []          # 每条库内查询：正确项排在第几（1 起）
    库外最高分 = []        # 每条库外查询：候选池里的最高相似度
    库内正确分 = []        # 每条库内查询：正确项的相似度
    域外闯入 = []          # 库内查询的前三中混入域外段（X 开头）的次数
    明细 = []

    print()
    print(" " + 补空格("查询", 30) + 补空格("目标", 6) + 补空格("排名", 6)
          + 补空格("正确项分", 10) + "Top-1（截断）")
    print(" " + "-" * 84)

    for 序, (编号, 问句, 目标) in enumerate(查询集):
        分列表 = []
        for i, (段号, _, _) in enumerate(候选池):
            分列表.append((余弦(查询向量[序], 语料向量[i]), 段号))
        分列表.sort(key=lambda 项: (-项[0], 项[1]))

        最高分, 最高段 = 分列表[0]

        if 目标 is None:
            库外最高分.append(最高分)
            print(" " + 补空格(截断(问句, 28), 30) + 补空格("库外", 6)
                  + 补空格("—", 6) + 补空格("—", 10)
                  + "%s(%.4f)" % (最高段, 最高分))
            明细.append((编号, 问句, 目标, None, 分列表))
            continue

        排名 = [段号 for _, 段号 in 分列表].index(目标) + 1
        正确分 = next(分 for 分, 段号 in 分列表 if 段号 == 目标)
        命中排名.append(排名)
        库内正确分.append(正确分)
        # 域外段闯进前三 = 语义空间混入了不该有的吸引点
        for 分, 段号 in 分列表[:3]:
            if 段号.startswith("X"):
                域外闯入.append((编号, 段号, 分))

        标记 = "OK " if 排名 == 1 else ("~  " if 排名 <= 3 else "X  ")
        print(" " + 补空格(截断(问句, 28), 30) + 补空格(目标, 6)
              + 补空格(标记 + str(排名), 6) + 补空格("%.4f" % 正确分, 10)
              + "%s(%.4f)" % (最高段, 最高分))
        明细.append((编号, 问句, 目标, 排名, 分列表))

    # ---- 汇总 ----
    总数 = len(命中排名)
    命中1 = sum(1 for r in 命中排名 if r == 1)
    命中3 = sum(1 for r in 命中排名 if r <= 3)
    recall1 = 命中1 / 总数
    recall3 = 命中3 / 总数
    mrr = sum(1.0 / r for r in 命中排名) / 总数

    print()
    print(" [汇总]  " + "库内查询 %d 条 / 库外查询 %d 条" % (总数, len(库外最高分)))
    print("   recall@1 = %.4f  (%d/%d)   期望 >= %.2f   %s"
          % (recall1, 命中1, 总数, 阈值["recall1"],
             "OK" if recall1 >= 阈值["recall1"] else "低于阈值"))
    print("   recall@3 = %.4f  (%d/%d)   期望 >= %.2f   %s"
          % (recall3, 命中3, 总数, 阈值["recall3"],
             "OK" if recall3 >= 阈值["recall3"] else "低于阈值"))
    print("   MRR      = %.4f           期望 >= %.2f   %s"
          % (mrr, 阈值["mrr"], "OK" if mrr >= 阈值["mrr"] else "低于阈值"))

    if 库外最高分 and 库内正确分:
        库外均值 = sum(库外最高分) / len(库外最高分)
        库内均值 = sum(库内正确分) / len(库内正确分)
        留白 = 库内均值 - 库外均值
        print("   库内正确项均分 = %.4f   库外查询最高分均值 = %.4f   间隔 = %.4f"
              % (库内均值, 库外均值, 留白))
        print("      → 间隔为正说明「库内有答案」与「库里没答案」在分数上可区分，"
              "这是 10-12 做拒答的检索侧前提")

    print("   域外段闯入前三次数 = %d   （域内提问不该被生活类文本吸引，期望 0）"
          % len(域外闯入))
    for 编号, 段号, 分 in 域外闯入:
        print("       %s 的前三里混入了 %s(%.4f)" % (编号, 段号, 分))

    print()
    print(" [逐条命中]")
    for 编号, 问句, 目标, 排名, 分列表 in 明细:
        前三 = "  ".join("%s:%.3f" % (段号, 分) for 分, 段号 in 分列表[:3])
        print("   %s %s" % (补空格(编号, 5), 前三))
    print()

    通过 = (recall1 >= 阈值["recall1"] and recall3 >= 阈值["recall3"]
            and mrr >= 阈值["mrr"])
    if 通过:
        print(" 结论：判为【通过】—— 向量排序能力达到 RAG 可用水平")
        if 域外闯入:
            print(" [警告] 域外段闯入 %d 次 —— 不影响 recall，但说明域外干扰偏强"
                  % len(域外闯入))
        print(" 注：这是 baseline，不含量化分块与重排的增益。")
    else:
        print(" 结论：判为【不通过】—— 排序能力不足，先别急着建库")
        print(" 排查顺序：① 是否 --pooling 与 GGUF 元数据 bert.pooling_type 不一致；")
        print("            ② 是否漏了 --embd-normalize；")
        print("            ③ 换 FP16 版对照，排除量化损伤。")

    返回 = {
        "地址": 服务地址, "标签": 标签 or 服务地址,
        "recall@1": recall1, "recall@3": recall3, "mrr": mrr, "通过": 通过,
    }
    if 库外最高分 and 库内正确分:
        返回["库内正确项均分"] = sum(库内正确分) / len(库内正确分)
        返回["库外最高分均值"] = sum(库外最高分) / len(库外最高分)
    return 返回


def 拆目标(目标串):
    """支持 http://host:port[:标签]。标签可选，用最后一个冒号后无斜杠的部分判定。"""
    去掉协议 = 目标串.split("://", 1)[1] if "://" in 目标串 else 目标串
    if ":" in 去掉协议:
        主机端口, 尾 = 去掉协议.rsplit(":", 1)
        # 尾是纯数字 → 视为端口，无标签
        if 尾.isdigit():
            return 目标串, ""
        return (目标串.split(":", 2)[0] + "://" + 主机端口), 尾
    return 目标串, ""


def 主流程():
    设终端编码()
    参数 = sys.argv[1:]
    if not 参数:
        参数 = [默认服务地址]

    目标们 = []
    for 项 in 参数:
        地址, 标签 = 拆目标(项)
        目标们.append((地址, 标签))

    结果集 = []
    for 地址, 标签 in 目标们:
        try:
            结果集.append(跑一遍(地址, 标签))
        except urllib.error.URLError as 错:
            print("[X] 连不上 " + 地址 + "：" + str(错))
            return 2
        except Exception as 错:
            print("[X] " + 地址 + " 调用失败：" + repr(错))
            return 2

    # ---- 多服务对照表 ----
    if len(结果集) > 1:
        print("=" * 86)
        print(" 多服务对照")
        print("=" * 86)
        print(" " + 补空格("实现", 18) + 补空格("recall@1", 12)
              + 补空格("recall@3", 12) + 补空格("MRR", 10) + "判定")
        print(" " + "-" * 70)
        最优 = max(结果集, key=lambda r: r["mrr"])
        for r in 结果集:
            标记 = "  ← MRR 最高" if r is 最优 else ""
            print(" " + 补空格(r["标签"], 18)
                  + 补空格("%.4f" % r["recall@1"], 12)
                  + 补空格("%.4f" % r["recall@3"], 12)
                  + 补空格("%.4f" % r["mrr"], 10)
                  + ("通过" if r["通过"] else "不通过") + 标记)
        print()

    return 0 if all(r["通过"] for r in 结果集) else 1


if __name__ == "__main__":
    sys.exit(主流程())
