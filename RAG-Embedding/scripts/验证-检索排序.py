"""
检索排序验证（RAG 的入场券）
============================

为什么不满足于「相似度看起来正常」
----------------------------------
`验证-embedding.py` 测的是**成对相似度的分层**，能发现「向量空间塌缩」这类粗故障。
但它**不测 RAG 真正依赖的能力：排序**。

反例：若所有向量都被叠加了同一个方向偏移，成对相似度的分档可能还看得过去，
而「给定一句提问，从一堆候选里把正确那段排到第一」可能已经崩了 ——
这个崩法**同样不报错**，只会在演示时表现为「答非所问」。

所以这里直接跑**它最终要干的活**：query → 候选池 → 排序 → 命中。

判据
----
    recall@1   >= 0.75   正确段落排第一的比例
    recall@3   >= 0.90   排进前三的比例
    MRR        >= 0.85   平均倒数排名
    拒答对照   库外问题的最高分，应明显低于库内问题正确项的平均分

这三个数字**只由向量质量决定**，与分块策略、重排无关 —— 它们是 baseline。
10-09 的分块对照、10-10 的重排效果，都要拿这组数字做参照。

用法
----
    python 验证-检索排序.py
    python 验证-检索排序.py http://127.0.0.1:8081
    # 多服务对照（如验证不同 pooling）：
    python 验证-检索排序.py http://127.0.0.1:8081:CLS http://127.0.0.1:8082:MEAN

零第三方依赖（只用标准库）。
"""

